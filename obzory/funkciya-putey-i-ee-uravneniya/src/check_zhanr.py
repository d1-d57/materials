#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ГЕЙТ ЖАНРА математического текста: судит, ЧЕМ записаны утверждения.

    python3 check_zhanr.py <файл.md>          # rc=0 зелёный, rc=1 красный

🔴 ЗАЧЕМ. Существующие гейты умеют СЧИТАТЬ (блоки, ссылки, случаи) и не умеют
СУДИТЬ (жанр, порядок, смысл). За сессию 2026-08-25 документ переписывался
ЧЕТЫРЕЖДЫ, и каждый раз дефект находил владелец глазами, ни разу — гейт:
все были зелёными, включая `build_doc` rc=0, `check_view` ✅ и счёт «28 из 28».
Этот гейт закрывает три класса из четырёх — те, что счётны.

Что судит (и чего НЕ судит — сказано честно):
  Ж1  доля блоков с ВЫКЛЮЧНОЙ формулой ($$…$$). Утверждение, по сути которого
      стоит равенство, обязано это равенство ПОКАЗАТЬ. Владелец: «по сути
      утверждение сводится к одной формуле; здесь этой формулы нет».
  Ж2  доля блоков, чьё тело начинается УСЛОВИЕМ («Пусть», «Для», «При», «Если»)
      либо сразу формулой — а не прозой. Форма утверждения: условие → вывод.
  Ж3  служебные слова отчётности («проверено», «сверено», «расхождений») ВНУТРИ
      тела утверждения. Охват проверки — отчётность приёмки, а не часть
      математического факта; его место в скрипте и в `## ОТЧЁТ`.

⚠ ОБЪЯВЛЕННАЯ СЛЕПАЯ ЗОНА. Гейт НЕ судит: верна ли математика, на месте ли
утверждение по смыслу, не выдана ли мотивировка за факт (У19), не оформлено ли
отрицание как утверждение (У20). Это суждения — их выносит владелец или
свежий читатель, и зелёный этого гейта их не заменяет.
"""
import re
import sys
from pathlib import Path

ZHANRY = r"(?:Определение|Утверждение|Теорема|Лемма|Предложение|Следствие)"
USLOVIE = re.compile(r"^\s*(?:Пусть|Для |При |Если |Возьмём|Обозначим|\$)")
OTCHET = re.compile(r"(?i)(проверено|сверено|расхождений|охват)")

# Пороги — не абсолютная истина, а граница, ниже которой текст перестаёт быть
# набором утверждений и становится конспектом. Подняты из замера живого файла
# на четвёртом круге: было 6/36 с формулой и 17/36 с условием — то есть текст,
# который владелец забраковал, лежал глубоко под обоими порогами.
PORog_FORMULA = 0.60
PORог_USLOVIE = 0.70


def razobrat(text):
    """Тело каждого блока: от жирного заголовка до строки `опирается:` или до
    следующего заголовка. Определения судятся наравне с утверждениями — у них
    та же болезнь (Опр. 2 «подъём стоит q^{p-x}, спуск бесплатен»)."""
    parts = re.split(r"\n(?=\*\*%s\s+\d+)" % ZHANRY, text)
    out = []
    for p in parts:
        m = re.match(r"\*\*(%s)\s+(\d+)\s*\(([^)]*)\)" % ZHANRY, p)
        if not m:
            continue
        body = p.split("опирается:")[0]
        # первая строка — сам заголовок; тело начинается со второй
        tail = body.split("\n", 1)[1] if "\n" in body else ""
        out.append((m.group(2), m.group(3), body, tail.strip()))
    return out


def main(argv):
    if not argv:
        print(__doc__)
        return 0
    put = Path(argv[0])
    if not put.is_file():
        print("НЕ НАЙДЕН: %s" % put)
        return 2
    bloki = razobrat(put.read_text(encoding="utf-8"))
    if not bloki:
        print("❌ блоков вида `**%s N (…)**` не найдено — судить нечего" % ZHANRY)
        return 1

    n = len(bloki)
    s_formula = [b for b in bloki if "$$" in b[2]]
    s_uslovie = [b for b in bloki if USLOVIE.match(b[3])]
    s_otchet = [b for b in bloki if OTCHET.search(b[2])]

    d_f, d_u = len(s_formula) / n, len(s_uslovie) / n
    print("── ГЕЙТ ЖАНРА (check_zhanr) ──")
    print("  блоков: %d" % n)
    print("  Ж1 с выключной формулой:      %2d (%.0f%%), порог %.0f%%  %s"
          % (len(s_formula), 100 * d_f, 100 * PORog_FORMULA,
             "✅" if d_f >= PORog_FORMULA else "❌"))
    print("  Ж2 начинается условием:       %2d (%.0f%%), порог %.0f%%  %s"
          % (len(s_uslovie), 100 * d_u, 100 * PORог_USLOVIE,
             "✅" if d_u >= PORог_USLOVIE else "❌"))
    print("  Ж3 отчётность внутри тела:    %2d (норма 0)             %s"
          % (len(s_otchet), "✅" if not s_otchet else "❌"))

    for imya, spisok in (("без формулы", [b for b in bloki if b not in s_formula]),
                         ("не с условия", [b for b in bloki if b not in s_uslovie]),
                         ("с отчётностью", s_otchet)):
        if spisok:
            print("     %s: %s" % (imya, ", ".join("№" + b[0] for b in spisok[:14])))

    krasnye = (d_f < PORog_FORMULA) + (d_u < PORог_USLOVIE) + bool(s_otchet)
    print("  ⚠ НЕ судит: верность математики, место блока по смыслу,")
    print("    мотивировку под видом факта (У19), отрицание под видом утверждения (У20).")
    print("%s ЖАНР: красных %d из 3" % ("✅" if not krasnye else "❌", krasnye))
    return 0 if not krasnye else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
