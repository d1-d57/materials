def doska(r, c, k=None, tl=None, dom=None, label=''):
    """Доска r×c. k×k с левой верхней клеткой tl=(ряд, столбец) от 0 залит, левая верхняя клетка выделена;
    dom=((ряд, столбец), 'г'|'в') — доминошка."""
    a, x0, y0 = 28, 8, 8
    zal = set()
    if k:
        zal = {(tl[0] + i, tl[1] + j) for i in range(k) for j in range(k)}
    if dom:
        (i, j), t = dom
        zal = {(i, j), (i, j + 1)} if t == 'г' else {(i, j), (i + 1, j)}
    s = ''
    for i in range(r):
        for j in range(c):
            kl = 's-fill-need' if (k and (i, j) in zal) else 's-fill-warm' if (dom and (i, j) in zal) else 's-fill-skip'
            s += f'<rect class="{kl}" x="{x0+j*a}" y="{y0+i*a}" width="{a}" height="{a}"/>'
    for i in range(r):
        for j in range(c):
            s += f'<rect class="s-frame" x="{x0+j*a}" y="{y0+i*a}" width="{a}" height="{a}"/>'
    if k:
        s += f'<rect class="s-car-r" x="{x0+tl[1]*a+6}" y="{y0+tl[0]*a+6}" width="{a-12}" height="{a-12}" rx="3"/>'
    return svg(x0 * 2 + c * a, y0 * 2 + r * a, s, label)


def troiki(palochki):
    """{самая длинная: [(a, b), …]} — пары двух других палочек, из которых и самой длинной складывается треугольник."""
    p = sorted(palochki)
    return {m: [(a, b) for a, b in combinations([x for x in p if x < m], 2) if a + b > m] for m in p}


def stroki_troek(palochki):
    return [[str(m), ', '.join(f'{a}–{b}' for a, b in pary) or 'нет', str(len(pary))] for m, pary in troiki(palochki).items() if pary]


