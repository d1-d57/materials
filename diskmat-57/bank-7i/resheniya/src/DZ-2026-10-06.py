def etazhi(n, vydeleny, label):
    """Этажи 1…n квадратиками в ряд; между соседними — пролёт (линия), под пролётом его номер."""
    x0, st, w = 12, 50, 28
    s = ''
    for i in range(n):
        x = x0 + i * st
        s += f'<rect class="{"s-fill-need" if (i + 1) in vydeleny else "s-fill-skip"}" x="{x}" y="6" width="{w}" height="30" rx="4"/>'
        s += f'<text class="s-big" x="{x+w/2}" y="27" text-anchor="middle">{i+1}</text>'
        if i < n - 1:
            s += f'<line class="s-line-a" x1="{x+w+3}" y1="21" x2="{x+st-3}" y2="21"/>'
            s += f'<text class="s-txt-m" x="{x+(w+st)/2}" y="56" text-anchor="middle">{i+1}</text>'
    return svg(x0 * 2 + (n - 1) * st + w, 64, s, label)


