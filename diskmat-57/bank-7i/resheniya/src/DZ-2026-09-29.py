def pentamino_risunok(label):
    a, g, x0 = 13, 22, 10
    s, W = '', 0
    for ryad_, fig in enumerate((PENT[:6], PENT[6:])):
        x, y = x0, 8 + ryad_ * 92
        for t, kl in fig:
            w = (max(c for _, c in kl) + 1) * a
            for r, c in kl:
                s += f'<rect class="s-car" x="{x+c*a}" y="{y+r*a}" width="{a}" height="{a}"/>'
            s += f'<text class="s-txt-m" x="{x+w/2}" y="{y+4*a+16}" text-anchor="middle">{t}</text>'
            x += w + g
        W = max(W, x - g + x0)
    return svg(W, 190, s, label)


def chk_pent():
    def norm(c):
        m, n = min(r for r, _ in c), min(x for _, x in c)
        return tuple(sorted((r - m, x - n) for r, x in c))

    def canon(c):
        out, c = set(), list(c)
        for _ in range(4):
            c = [(x, -r) for r, x in c]
            out |= {norm(c), norm([(r, -x) for r, x in c])}
        return min(out)

    def run(c):
        s, b = set(c), 1
        for r, x in c:
            for d in ((0, 1), (1, 0)):
                k = 0
                while (r + d[0] * k, x + d[1] * k) in s:
                    k += 1
                b = max(b, k)
        return b
    assert len({canon(k) for _, k in PENT}) == 12
    assert all(str(run(k)) == t for t, k in PENT)
    cur = {norm([(0, 0)])}
    for _ in range(4):
        cur = {norm(list(f) + [q]) for f in cur for r, c in f for q in ((r + 1, c), (r - 1, c), (r, c + 1), (r, c - 1)) if q not in f}
    assert {canon(f) for f in cur} == {canon(k) for _, k in PENT}


