def doska(r, c, k=None, tl=None, label=''):
    """Доска r×c; квадрат k×k с левой верхней клеткой tl=(ряд, столбец) от 0 залит, его левая верхняя клетка выделена."""
    a, x0, y0 = 28, 8, 8
    zal = {(tl[0] + i, tl[1] + j) for i in range(k) for j in range(k)} if k else set()
    s = ''.join(f'<rect class="{"s-fill-need" if (i, j) in zal else "s-fill-skip"}" x="{x0+j*a}" y="{y0+i*a}" width="{a}" height="{a}"/>'
                for i in range(r) for j in range(c))
    s += ''.join(f'<rect class="s-frame" x="{x0+j*a}" y="{y0+i*a}" width="{a}" height="{a}"/>' for i in range(r) for j in range(c))
    if k:
        s += f'<rect class="s-car-r" x="{x0+tl[1]*a+6}" y="{y0+tl[0]*a+6}" width="{a-12}" height="{a-12}" rx="3"/>'
    return svg(x0 * 2 + c * a, y0 * 2 + r * a, s, label)


def razlozheniya(n, mx=None):
    """Все разложения n в сумму натуральных слагаемых по убыванию, слагаемые не больше mx; списки в порядке перебора."""
    mx = mx or n
    if n == 0:
        return [[]]
    return [[k] + p for k in range(min(n, mx), 0, -1) for p in razlozheniya(n - k, k)]


def zapis(p):
    return '+'.join(map(str, p))


