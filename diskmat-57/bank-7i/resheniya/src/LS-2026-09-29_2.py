def setka(rows, podpisi, label, k=22):
    """Клетчатая фигура по строкам: '#' — заштрихована, 'o' — клетка вырезанной части, 'c' — незаштрихованная клетка,
    '.' — пусто. podpisi — список (столбец, ряд, текст, жирный?) в клетках от 0."""
    s = ''
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == '.':
                continue
            cls = {'#': 's-fill-need', 'o': 's-fill-skip', 'c': 's-fill-skip'}[ch]
            s += f'<rect class="{cls}" x="{c*k}" y="{r*k}" width="{k}" height="{k}"/>'
            s += f'<rect class="s-frame" x="{c*k}" y="{r*k}" width="{k}" height="{k}"/>'
    for c, r, t, big in podpisi:
        s += f'<text class="{"s-num" if big else "s-txt-m"}" x="{(c+0.5)*k}" y="{(r+0.5)*k+6}" text-anchor="middle">{t}</text>'
    return svg(len(rows[0]) * k, len(rows) * k, s, label)


