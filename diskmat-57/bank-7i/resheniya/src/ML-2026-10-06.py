z.ol(['Возьмём число 3. Оно стоит на костях 3–0, 3–1, 3–2, 3–4, 3–5, 3–6 — по одному разу, и на дубле 3–3 — два раза, на обеих половинках. Всего 6 + 2 = 8 раз.',
    'То же для любого числа от 0 до 6: шесть костей с другими числами и дубль с двумя половинками. Каждое число встречается 8 раз.',
    'Число 0 даёт 0 точек, число 1 — 8 точек, число 2 — 16, и так далее. Всего точек (0 + 1 + 2 + 3 + 4 + 5 + 6) · 8 = 21 · 8 = 168.'])
def _domino(n, k):
    c, h, x0, y0 = 46, 28, 28, 22
    s = ''
    for j in range(n):
        s += f'<text class="s-txt-m" x="{x0+j*c+c/2-3}" y="14" text-anchor="middle">{j}</text>'
    for i in range(n):
        s += f'<text class="s-txt-m" x="12" y="{y0+i*h+h/2+5}" text-anchor="middle">{i}</text>'
        for j in range(i + 1):
            cls = 's-fill-need' if k in (i, j) else 's-fill-skip'
            s += f'<rect class="{cls}" x="{x0+j*c}" y="{y0+i*h}" width="{c-6}" height="{h-4}" rx="4"/>'
            s += f'<text class="s-txt" x="{x0+j*c+(c-6)/2}" y="{y0+i*h+h/2+3}" text-anchor="middle">{i}–{j}</text>'
    return svg(x0 + n * c, y0 + n * h, s, f'Таблица костей домино от 0–0 до {n-1}–{n-1}: в строке i стоят кости i–0, …, i–i; залиты все кости с числом {k}')
