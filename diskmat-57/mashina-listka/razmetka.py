# -*- coding: utf-8 -*-
"""ЗАДАНИЕ РАЗМЕТЧИКАМ сканов сдачи (Ф12) — печатает готовый текст задания субагенту из канона листка.
Запуск:  python3 razmetka.py <папка итерации> <скан.pdf> <страницы, напр. 1-8> <файл-выход.jsonl>
Разметчиков — по 4–5 работ на одного (Sonnet); сверка с эталоном ДО свода — в svod.py (верный ответ при кресте → флаг).
"""
import json, sys
from pathlib import Path
SLOVAR = """Коды: '+' — плюс принимающего; 'x' — крест или минус; 'z' — что-то написано, отметки нет; '.' — пусто.
Формы плюса (всё это ПЛЮС): «+», «†», «t», «P»-образный знак, плюс с точкой, галочка. Сомневаешься — плюс.
Плюс на пустом поле — ответ принят устно, это '+'. Много раз зачёркнутый ответ, потом плюс — '+'.
Пусто ≠ крест: пустое поле — '.', не 'x'."""
def main(it, scan, pages, out):
    K = json.load(open(Path(it) / 'out' / 'kanon.json', encoding='utf-8'))
    spisok = {v: ', '.join(p['punkt'] for p in P) for v, P in K['punkty'].items()}
    klyuch = {v: '; '.join(f"{p['punkt']}: {p['otvet']}" for p in P) for v, P in K['punkty'].items()}
    print(f"""Разметь сдачу листка по скану {scan}, страницы {pages}. Работ ~4–5; каждая работа — две страницы (одна двусторонняя).
Для каждой работы: имя (как написано), вариант (А/Б — в шапке справа), по каждому пункту — код и записанный ответ.
Пункты варианта А (ровно эти, в этом порядке): {spisok['А']}
Пункты варианта Б: {spisok['Б']}
{SLOVAR}
Эталон (для сверки, не для подмены кода): А — {klyuch['А']}
Б — {klyuch['Б']}
Если ответ совпал с эталоном, а стоит крест, — поставь код как видишь, а в поле "flag" напиши номер пункта.
Формат: по строке JSON на работу, СРАЗУ дописывай в файл {out} после каждой работы (не в конце):
{{"imya": "...", "var": "А", "o": {{"1": "+", "2а": ".", ...}}, "n": {{"2а": "10·10 − 6·6 = 64", ...}}, "flag": []}}
В чат — одна строка: сколько работ записано. Добычу в чат не печатай.""")
if __name__ == '__main__':
    main(*sys.argv[1:])
