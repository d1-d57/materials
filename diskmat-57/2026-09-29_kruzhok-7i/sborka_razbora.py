def usloviya(path):
    """Все \\zad{…}{…}{…} после \\begin{document}: список (звёздочка?, текст условия)."""
    s = path.read_text(encoding='utf-8')
    s = s[s.index('\\begin{document}'):]
    s = '\n'.join(l for l in s.split('\n') if not l.lstrip().startswith('%'))
    out, i = [], 0
    while True:
        i = s.find('\\zad{', i)
        if i < 0:
            return out
        args, j = [], i + 4
        for _ in range(3):
            assert s[j] == '{', 'ожидалась {'
            d, k = 0, j
            while True:
                if s[k] == '{': d += 1
                elif s[k] == '}':
                    d -= 1
                    if d == 0: break
                k += 1
            args.append(s[j + 1:k]); j = k + 1
        out.append((bool(args[0].strip()), args[2].replace('\\newline', '\\par').strip()))
        i = j


