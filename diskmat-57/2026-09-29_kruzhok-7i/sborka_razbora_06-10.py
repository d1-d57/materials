def usloviya(path):
    """Все \\zad{знак}{плюсы}{условие}{рисунок} после \\begin{document}: (звёздочка?, условие + рисунок)."""
    s = path.read_text(encoding='utf-8')
    s = s[s.index('\\begin{document}'):]
    out, i = [], 0
    while True:
        i = s.find('\\zad{', i)
        if i < 0:
            return out
        args, j = [], i + 4
        for _ in range(4):
            assert s[j] == '{', 'ожидалась {'
            d, k = 0, j
            while True:
                if s[k] == '{': d += 1
                elif s[k] == '}':
                    d -= 1
                    if d == 0: break
                k += 1
            args.append(s[j + 1:k]); j = k + 1
        txt = args[2].strip() + (('\\par\\vspace{3pt}' + args[3].strip()) if args[3].strip() else '')
        znachok = lambda t: t.replace("current bounding box.north", "current bounding box.south")
