"""Свод ДЗ к 6.10 (и сданного заодно ДЗ к 29.09) по разметке распознавателя + перечтения.
Вердикт по пункту выставлен АНАЛИТИКОМ вручную (поле V ниже) по ответу из n, правилам Р231/Р232:
верный ответ в любой форме (2,25 мин = 135 с = 2 мин 15 с) — плюс; обсчёт при верном ходе — плюс.
Скрипт только считает и печатает охват; '?' — пункт не решён (по Р287 '?' не остаётся: не разобрать → '-'), нужен владелец/пересъёмка (не плюс и не минус)."""
import json, collections
K610 = {'1':'2 мин 15 с','2':'12 кг','3':'50','4':'33','5':'140','6':'45'}
K2909 = {'1':'8','2':'14','3':'34','4':'22','5':'12'}  # svod_dz.py 29.09
# foto -> вердикты по задачам: + верно, - неверно, . пусто, ? не решено
V = {
 'dz01':'++++++',                     # Карцев: досъёмка 22:20, ход верный везде (Р232: обсчёт при верном ходе — плюс)
 'dz02':'+++-+-', 'dz03':'+++-+-', 'dz04':'++++++',  # dz04/3: «Т0» — 5 без нижней дуги, по Р287 (все 18 решивших №3 дали 50)
 'dz05':'+++-+-', 'dz06':'++++++', 'dz07':'--++++', 'dz08':'--++++',
 'dz09':'+-++++', 'dz11':'++++++', 'dz12':'+++++.',
 'dz13':'-++-+.',                     # 2: «112 кг» = 12 кг с лишней чертой (Р287, владелец)
 'dz14':'+++++-',                     # 1: «за 135 сек» — досъёмка 22:20
 'dz15':'-++-+.', 'dz16':'+-+++-', 'dz17':'++++++', 'dz18':'++++++',
 'dz19':'++++++', 'dz20':'-++++-', 'dz23':'++++++',
 'dz10':'++--+', 'dz21':'++--+', 'dz22':'+++++',  # ДЗ к 29.09
}
rows=[json.loads(l) for l in open('RAZMETKA-DZ-k-6-10.jsonl',encoding='utf-8') if l.strip()]
Y=len(rows); print(f'строк разметки: {Y}; с вердиктом: {sum(r["foto"][0][:4] in V for r in rows)} из {Y}')
by=collections.Counter()
for dz,K in (('6.10',K610),('29.09',K2909)):
    print(f'\n== ДЗ к {dz} ==')
    sel=[r for r in rows if r.get('dz')==dz]
    for r in sorted(sel,key=lambda r:r['imya'] or ''):
        v=V[r['foto'][0][:4]]; p=v.count('+')
        print(f"{(r['imya'] or '?'):26} {v}  плюсов {p} из {len(K)}" + ('  ⚠ есть ?' if '?' in v else ''))
    print('по задачам (+/−/./?):')
    for i,k in enumerate(K):
        c=collections.Counter(V[r['foto'][0][:4]][i] for r in sel)
        print(f'  {k}: +{c["+"]} −{c["-"]} .{c["."]} ?{c["?"]}   ключ {K[k]}')
