import json, re, io, subprocess
from collections import Counter
P_ALL = json.load(open('/tmp/pul.json'))
P = [c for c in P_ALL if c.get('keep')]   # второй просев: только те, где в решении считают мощность
def g(c,*p):
    for k,v in c.items():
        if any(k.startswith(x) for x in p): return v
    return ''
def cl(s,n=100000): return re.sub(r'\s+',' ',s).strip()[:n]

SRC = {'shen':'Шень, «Комбинаторика», 8 листков (маткласс онлайн, TeX в spetsmat_db)',
 'raskina-1':'Раскина–Шаповалов, «Комбинаторика», ШМК вып. 20, МЦНМО 2024',
 'raskina-2':'Раскина–Шаповалов, «Комбинаторика: заседание продолжается», ШМК вып. 24',
 'trudnye':'Шаповалов «Конструкции» + Канель-Белов–Ковальджи «Как решают нестандартные задачи»',
 'matshkola':'Выездная матшкола 5–6 кл., М. Корсаков (_fond/chuzhoe)',
 'nlogn-manzhina':'NLOGN 6–7 кл. (Буфеев) + летняя школа 6 кл. (О. Манжина)',
 'bank-babicheva':'Банк задач _fond/zadachi/bank + Бабичева «Олимпиадная математика» А1',
 'ksenia-1':'Листки от Ксении: МЦНМО 6 зан. 15, МММФ-4 зан. 13',
 'ksenia-2':'Листки от Ксении: МЦНМО 6 зан. 16 и 23 (сочетания)'}

o = io.StringIO()
w = o.write
w('---\ntab: Каталог пула задач к 22.09\nstatus: каталог\nporyadok: 0\n---\n\n')
w('# Каталог пула — комбинаторика, блок «Перебор и правило суммы»\n\n')
w('Дата данных: 2026-09-21. Собран скриптом из девяти файлов `SYRYO-22-09_*.md`; числа ниже пересчитываются командой `python3 /tmp/katalog.py`, руками не правятся.\n\n')
w(f'**Два просева.** Выемка из источников дала {len(P_ALL)} карточек по отрицательному фильтру (нет правила произведения). Затем положительный просев оставил **{len(P)}**: только те задачи, в РЕШЕНИИ которых есть шаг «сколько элементов в таком-то множестве». Выброшенные {len(P_ALL)-len(P)} — логика и рыцари, обратный ход, игры на чётность позиции, инварианты-не-количества, делимость — в каталог не входят; они с причинами лежат во вкладке «Выброшено» HTML-версии и в файлах `VERDIKT_*.jsonl`.\n\n')
w('**Жёсткий фильтр, по которому шла выемка:** правило произведения запрещено (цепочки выборов, дерево, перестановки, факториалы, 2ⁿ, сочетания); умножение равных групп как подсчёт клеток прямоугольной таблицы разрешено. Запрещены дроби и проценты, геометрия, текстовые задачи, двойной подсчёт как основной метод, подсчёт рёбер, Евклид и НОД, Дирихле как основной метод.\n\n')

w('## Источники и выход\n\n| источник | карточек |\n|---|---|\n')
for k,n in Counter(c['src'] for c in P).most_common():
    w(f'| {SRC.get(k,k)} | {n} |\n')
w(f'| **всего** | **{len(P)}** |\n\n')

w('## Раскладка по типам — механическая, по критериям владельца\n\n')
w('Правило разметки: доля «единицы/никто» → ГРОБ · «меньше половины» + есть пункты → РОМБ · «почти все/больше половины» + ход виден сразу → КРУЖОК · то же, но ход не виден → ТРЕУГОЛЬНИК.\n\n')
w('| тип | в пуле | надо в листок | запас |\n|---|---|---|---|\n')
need = {'КРУЖОК':5,'ТРЕУГОЛЬНИК':5,'РОМБ':7,'ГРОБ':3}
cnt = Counter(c['tip'] for c in P)
for t in ['КРУЖОК','ТРЕУГОЛЬНИК','РОМБ','ГРОБ']:
    w(f'| {t} | {cnt[t]} | {need[t]} | ×{cnt[t]//need[t]} |\n')
w(f'| ромб-монолит (не делится на пункты) | {cnt["ромб-монолит"]} | — | в резерв |\n')
w(f'| не разметилось | {cnt["?"]} | — | разобрать руками |\n\n')

w('## Разрезы пула\n\n')
for title, key in [('По методу','metod'),('По доле класса','dolya'),('Ход виден сразу','hod'),('Не выглядит комбинаторной','neko')]:
    w(f'**{title}:** ' + ' · '.join(f'{k} — {n}' for k,n in Counter(c[key] for c in P).most_common()) + '\n\n')
w(f'**Разбивается на пункты:** да — {sum(1 for c in P if c["punkty"])} · монолит — {sum(1 for c in P if not c["punkty"])}\n\n')

w('---\n\n# Карточки по типам\n\n')
for t in ['КРУЖОК','ТРЕУГОЛЬНИК','РОМБ','ГРОБ','ромб-монолит','?']:
    sel = [c for c in P if c['tip']==t]
    if not sel: continue
    w(f'\n## {t} — {len(sel)} шт.\n\n')
    sel.sort(key=lambda c:(c['src'], c['id']))
    for c in sel:
        w(f"### {c['id']}\n\n")
        w(f"*{SRC.get(c['src'],c['src'])}* · **роль подсчёта: {c.get('rol','')}** · метод: {c['metod']} · доля: {c['dolya']} · ход виден: {c['hod']} · некомбинаторная на вид: {c['neko']}\n\n")
        if c.get('why'): w(f"**Что именно считается.** {cl(c['why'])}\n\n")
        w(f"**Условие.** {cl(g(c,'УСЛОВИЕ'))}\n\n")
        ans = cl(g(c,'ОТВЕТ'))
        if ans: w(f"**Ответ и идея.** {ans}\n\n")
        pk = cl(g(c,'ПУНКТЫ'))
        if c['punkty'] and pk: w(f"**Пункты.** {pk}\n\n")
        pr = cl(g(c,'ПРИМЕЧАНИЕ'))
        if pr: w(f"> Примечание выемщика: {pr}\n\n")
open('KATALOG-pula-22-09.md','w',encoding='utf-8').write(o.getvalue())
print('KATALOG-pula-22-09.md:', len(o.getvalue()), 'знаков')
