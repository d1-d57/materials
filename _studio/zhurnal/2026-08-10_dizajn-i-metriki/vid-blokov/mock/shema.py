def overlay(v, kommentarij=True):
    """вариант → CSS-оверлей. Один источник и для кадра, и для итогового фрагмента."""
    L, D, Z = LINEJKA[v["l"]], DOKAZ[v["d"]], ZAGOLOVOK[v["z"]]
    S, O = SODERZHIMOE[v["s"]], OTSTUP[v["o"]]
    sh = O.get("sh", 0.0)
    # линейка в поле (pole=1) не сдвигает текст вовсе — цена по горизонтали
    # ноль; со сдвигом (pole=0) текст ужимается на ширину линейки и зазор.
    pad = 0.0 if L["pole"] else (L["w"] + L["gap"])
    sme = -(L["w"] + L["gap"]) if L["pole"] else 0.0
    css = []
    if kommentarij:
        css.append("/* вариант: %s */" % " · ".join("%s=%s" % (k, v[k]) for k in "ldzso"))
    # Отступ ужимается ТОЛЬКО перед блоком, который реально несёт строку-заголовок
    # (правило С2: заголовок садится ЗА СЧЁТ отступа). Блок без заголовка платить
    # не должен — иначе вариант «ничего не печатаем» дешевел бы даром и сравнение
    # осей поехало бы. Список типов — статусные из §5 спецификации.
    STAT = ", ".join('.blk + .blk[data-tip="%s"]' % t
                     for t in ("opredelenie", "utverzhdenie", "primer"))
    css.append("""
.blk { position: relative; }
.blk + .blk { margin-top: var(--blok); }
""")
    if S != "net":
        css.append("%s { margin-top: calc(var(--blok) * %.3f); }" % (STAT, O["g"]))
    # ── тихий заголовок ──
    if S == "net":
        css.append(".blk-h { display: none; }")
    else:
        css.append("""
.blk-h { font-size: %(fs)s; line-height: 1.15; color: %(c)s; opacity: %(op).2f;
         margin-top: calc(var(--blok) * %(sh).3f); margin-bottom: %(gap).3fem;
         font-family: var(--font-body); letter-spacing: .01em; }
.h-%(off)s { display: none; }
""" % dict(fs=("max(%dpx, %.3fem)" % (Z["pol"], Z["k"])) if Z.get("pol")
                   else ("%.3fem" % Z["k"]),
           c=Z["cvet"], op=Z["op"], gap=Z["gap"] * O.get("n", 1.0), sh=sh,
           off=("mysl" if S == "slovo" else "slovo")))
    # ── линейка центрального блока (правило С4) ──
    css.append("""
.blk[data-central="1"] { padding-left: %(pad).3fem; }
.blk[data-central="1"]::before {
  content: ''; position: absolute; left: %(sme).3fem;
  top: %(vrez).3fem; bottom: %(vrez).3fem;
  width: %(w).3fem; background: %(c)s; opacity: %(op).2f; }
""" % dict(pad=pad, sme=sme, vrez=L["vrez"], w=L["w"], c=L["cvet"], op=L["op"]))
    # ── доказательство (правила С5–С6) ──
    css.append("""
.blk[data-tip="dokazatelstvo"] { font-size: %(k).3fem; line-height: calc(var(--lh) * %(lh).3f);
                                 padding-left: %(ind).3fem; }
""" % dict(k=D["k"], lh=D["lh"], ind=D["ind"]))
    return "\n".join(css)


def imya(v):
    return "-".join(v[k] for k in "ldzso")
