def _sredstva(b, fs_sosed):
    """сколько средств применено к блоку — считается по отрисованному кадру."""
    n = 0
    if b.get("rule") and b["rule"]["w"] > 0.5 and b["rule"]["op"] > 0.02:
        n += 1
    if b.get("padLeft", 0) > 2:
        n += 1
    if fs_sosed and abs(b["fs"] / fs_sosed - 1) > 0.02:
        n += 1
    if b.get("zag") and b["zag"]["h"] > 1:
        n += 1
    return n


