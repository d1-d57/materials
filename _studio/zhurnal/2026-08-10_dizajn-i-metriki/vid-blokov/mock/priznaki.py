def p8(kadry):
    otn = []
    for k in kadry:
        # ПЕРВЫЙ блок слайда исключён: воздух над ним даёт заголовок СЛАЙДА, а не
        # межблочный отступ, и мерить там нечего. Без этого исключения признак
        # уходил в 0 у всех вариантов подряд — считался несуществующий зазор.
        for b in k["bloki"][1:]:
            z = b.get("zag")
            if not z or z["h"] < 1:
                continue
            # зазор НАД заголовком = собственный margin блока + margin заголовка;
            # зазор ПОД = margin-bottom заголовка. Обе величины сняты с кадра.
            nad = b.get("marginTop", 0) + z.get("mt", 0)
            pod = z.get("mb", 0)
            if pod > 0.01:
                otn.append(nad / pod)
    if not otn:
        return None, {"заголовков": 0}
    # По ХУДШЕМУ заголовку считать нельзя: солвер ужимает `--blok` до 3 px на
    # отдельных слайдах, и один такой слайд обнулял бы признак у любого варианта
    # (проверено прогоном — П8 вышел 0 у всех 26 вариантов подряд, то есть был
    # мёртв не по сути, а по статистике). Считается ДОЛЯ здоровых заголовков.
    hud = min(otn)
    sr = sum(otn) / len(otn)
    dolya = sum(1 for x in otn if x >= 1.5) / len(otn)
    ball = 3 if dolya >= 0.90 else (2 if dolya >= 0.70 else (1 if dolya >= 0.40 else 0))
    return ball, {"доля заголовков с воздухом над/под ≥ 1.5": round(dolya, 3),
                  "воздух над/под, худший": round(hud, 2),
                  "воздух над/под, средний": round(sr, 2),
                  "заголовков": len(otn)}


def _slova(s):
    return [w for w in ''.join(c.lower() if c.isalnum() else ' ' for c in (s or '')).split()
            if len(w) > 3]


STATUSNYE = ("opredelenie", "utverzhdenie", "primer")


def p7(kadry, tolko_narrativ):
    """Помечено РОВНО то, что должно: фигура помечена, фон — нет.

    Признак сведён из двух после первого прогона, и вот почему. Отдельный
    контроль «фон не помечен» оказался мёртв (все варианты его соблюдают по
    построению), а шкала без него не ловила ГЛАВНОГО: вариант «ничего не
    печатать» набирал по общим признакам БОЛЬШЕ всех — просто потому, что
    ничего не стоит. Шкала, в которой «не делать ничего» выигрывает у «сделать
    задачу», меряет цену вместо пользы. Здесь обе половины в одном признаке:
    ноль средств на нарративе — условие допуска, доля помеченных статусных
    блоков — сам балл.
    """
    gr = [k for k in kadry if k["id"] in tolko_narrativ]
    hud = 0
    for k in gr:
        for b in k["bloki"]:
            hud = max(hud, _sredstva(b, k["fsZone"]))
    vsego = pomecheno = 0
    for k in kadry:
        for b in k["bloki"]:
            if b["tip"] in STATUSNYE:
                vsego += 1
                if _sredstva(b, k["fsZone"]) > 0:
                    pomecheno += 1
    if not gr or not vsego:
        return None, {"нарративных кадров": len(gr), "статусных блоков": vsego}
    dolya = pomecheno / vsego
    if hud > 0:
        ball = 0
    elif dolya >= 0.99:
        ball = 3
    elif dolya >= 0.5:
        ball = 2
    elif dolya > 0:
        ball = 1
    else:
        ball = 0
    return ball, {"нарративных кадров": len(gr), "средств на нарративе": hud,
                  "статусных блоков": vsego, "из них помечено": pomecheno,
                  "доля": round(dolya, 3)}


def shtrih_iz_skrinshota(png, oblast=None, porog=140):
    """медианная толщина штриха шрифта тела — по пикселям кадра, а не по таблице
    гарнитуры. Скан горизонтальными строками, длины тёмных пробегов 1–12 px."""
    from PIL import Image
    import numpy as np
    im = Image.open(png).convert("L")
    a = np.asarray(im)
    if oblast:
        x0, y0, x1, y1 = oblast
        a = a[y0:y1, x0:x1]
    dl = []
    for row in a:
        t = row < porog
        if not t.any():
            continue
        d = np.diff(np.concatenate(([0], t.view(np.int8), [0])))
        nach = np.where(d == 1)[0]
        kon = np.where(d == -1)[0]
        dl.extend([int(x) for x in (kon - nach) if 1 <= x <= 12])
    if not dl:
        return None
    dl.sort()
    return dl[len(dl) // 2]
