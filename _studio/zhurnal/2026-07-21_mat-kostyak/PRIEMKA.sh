#!/usr/bin/env bash
# ПРИЁМЩИК арки «2026-07-21_mat-kostyak» — независимая проверка КРИТЕРИЯ ГОТОВНОСТИ
# (kod_mat-kostyak.md §КРИТЕРИЙ, 9 пунктов).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ, а не «посмотреть счётчик исполнителя»:
# счётчик из §2.6 пишет тот же, кого он проверяет. Судья своим числом не пользуется
# (RUKOVODSTVO §Приёмка: «объективные гейты Cowork перегоняет САМ на живых файлах, не на слово»).
# Маркеры взяты из ПЛАНа исполнителя П1.6 — если он их поменял, скрипт краснеет на П0,
# а не молча считает ноль (греп-ноль ничего не доказывает, §ГРЕП).
#
# Запуск из корня materials/:  bash _studio/zhurnal/2026-07-21_mat-kostyak/PRIEMKA.sh

set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
# MK_DOC — только для самопроверки приёмщика на фикстуре; в приёмке не задавать.
DOC="${MK_DOC:-$ROOT/teorkat-vvedenie/MAT-KOSTYAK.md}"
FAIL=0
ok(){ printf '  ✅ %s\n' "$1"; }
no(){ printf '  ❌ %s\n' "$1"; FAIL=1; }
hm(){ printf '  ⚠  %s\n' "$1"; }

echo "═══ ПРИЁМЩИК mat-kostyak ═══"; echo "док: $DOC"; echo

# ── П0. Артефакт вообще есть? Без него остальные пункты — не «зелено», а «нечего мерить».
if [ ! -f "$DOC" ]; then
  no "П0: MAT-KOSTYAK.md НЕ СУЩЕСТВУЕТ — прогон не завершён, критерий не применим."
  echo; echo "ВЕРДИКТ: приёмка невозможна (нет артефакта)."; exit 2
fi
ok "П0: файл на месте"

# ── П0'. Маркеры те, что объявлены в ПЛАНе П1.6. Иначе все счётчики ниже врут нулями.
P=$(grep -cE '^### П[0-9]+\.' "$DOC")
U=$(grep -cE '^### У[0-9]+\.' "$DOC")
[ "$P" -gt 0 ] || no "П0': маркеров '### П<N>.' ноль — формат разошёлся с ПЛАНом П1.6, ЧИТАТЬ ГЛАЗАМИ"
[ "$U" -gt 0 ] || no "П0': маркеров '### У<N>.' ноль — то же"
echo "  ▸ понятий: $P · утверждений: $U   ← ГЛАВНЫЙ ОТВЕТ АРКИ («мало» vs «полсотни»)"

# ── 1. Сборка и гейт отрисовки.
if [ -d "$ROOT/teorkat-vvedenie/MAT-KOSTYAK" ]; then
  ( cd "$ROOT" && python3 _generator/build_doc.py teorkat-vvedenie/MAT-KOSTYAK >/dev/null 2>&1 ) \
    && ok "1a: build_doc.py отработал" || no "1a: build_doc.py упал"
  ( cd "$ROOT" && python3 _generator/tools/check_view.py teorkat-vvedenie/MAT-KOSTYAK ) \
    && ok "1b: check_view.py зелёный" || no "1b: check_view.py КРАСНЫЙ (текст съеден при отрисовке)"
else
  no "1: папки teorkat-vvedenie/MAT-KOSTYAK/ нет — движку нечего собирать (ПЛАН Р7: симлинк)"
fi

# ── 2. Понятий без пометки зоны — 0. Считаем НЕ пометки, а разрыв: блоков минус блоков-с-зоной.
ZONA=$(awk '/^### П[0-9]+\./{b=1;z=0} /^> поле:зона /{if(b)z=1} /^### У[0-9]+\./{b=0}
            /^### П[0-9]+\./{if(prev&&!pz)n++; prev=1; pz=0} {if(b&&/^> поле:зона /)pz=1}
            END{if(prev&&!pz)n++; print n+0}' "$DOC")
[ "${ZONA:-1}" -eq 0 ] && ok "2: понятий без зоны 0 из $P" || no "2: понятий без зоны ${ZONA} из $P"

# ── 3. Шесть полей у каждого понятия.
# ⚠ ПОЧИНЕНО ПРИ ПРИЁМКЕ 21.07 (урок исполнителя, В7): два поля из шести НЕ могут быть `> поле:` —
# формат `03-matbaza`, назначенный заданием §2.0, требует имя заголовком `### П<N>. <имя>`,
# а определение врезкой `**Определение N (имя).**`, иначе движок не сделает врезку.
# Прежняя версия скрипта ждала `> поле:название`/`> поле:определение` и печатала два ❌
# на верном документе. Инструмент был написан под ПЛАН исполнителя и не сверен с заданием.
NAM=$(grep -cE '^### П[0-9]+\. +\S' "$DOC")
[ "$NAM" -ge "$P" ] && ok "3.название: $NAM ≥ $P (заголовком блока)" || no "3.название: только $NAM из $P"
OPR=$(grep -cE '^\*\*Определение [0-9]+' "$DOC")
[ "$OPR" -ge "$P" ] && ok "3.определение: $OPR ≥ $P (врезкой)" || no "3.определение: только $OPR из $P"
for f in зона зависимости оправдание не-говорим; do
  c=$(grep -cE "^> поле:${f} " "$DOC")
  [ "$c" -ge "$P" ] && ok "3.${f}: $c ≥ $P" || no "3.${f}: только $c из $P понятий — ЧИТАТЬ ГЛАЗАМИ (может быть иное имя поля)"
done

# ── 4. Вердикт у каждого утверждения. Якорь строки целиком: 'тривиально' — подстрока 'нетривиально'.
T=$(grep -cE '^> поле:вердикт тривиально[[:space:]]*$' "$DOC")
N=$(grep -cE '^> поле:вердикт нетривиально[[:space:]]*$' "$DOC")
echo "  ▸ тривиально: $T · нетривиально: $N · сумма: $((T+N)) при $U утверждениях"
[ $((T+N)) -eq "$U" ] && ok "4: вердикт у всех утверждений" || no "4: без вердикта $((U-T-N)) утверждений"

# ── 5. Открытых флагов 0.
# ⚠ ПОЧИНЕНО ПРИ ПРИЁМКЕ Ф2.1: без якоря начала строки греп ловил маркер ВНУТРИ команды,
# которую §2.6 требует держать в шапке, — и печатал «открытых флагов -2» на здоровом документе.
# Диагноз выдан исполнителем вместе с готовой починкой; проверено — 5/5 и на HEAD, и на новой версии.
FO=$(grep -cE '^⚑ Флаг' "$DOC" || true); FC=$(grep -cE '^Флаг закрыт:' "$DOC" || true)
[ "$FO" -eq "$FC" ] && ok "5: флагов $FO, закрыто $FC" || no "5: открытых флагов $((FO-FC))"

# ── 6. В шапке КОМАНДА, а не число (KONSTITUCIYA §10 — тут врали пять раз).
head -40 "$DOC" | grep -qE 'grep|awk|python3' && ok "6a: в шапке есть команда" || no "6a: команды в шапке нет"
head -40 "$DOC" | grep -qE '^[^`]*(понятий|утверждений)[^`]*[0-9]+' \
  && hm "6b: в шапке похоже на вписанное руками число — ПРОВЕРИТЬ ГЛАЗАМИ" || ok "6b: голого числа в шапке не видно"

# ── 7. Отвергнутая опция на месте.
grep -q 'функторы после CCC' "$DOC" && ok "7: опция «функторы после CCC» записана" || no "7: отвергнутой опции нет (§2.5)"

# ── 8. Запрет не обоснован через «лектор не знает» — греп ловит только грубый случай.
if grep -nE 'лектор (не знает|не уверен|плохо понимает)' "$DOC" | grep -v 'SPEKA' ; then
  no "8: обоснование через незнание лектора (см. строки выше)"
else ok "8: грубых формулировок нет (⚠ греп не доказывает отсутствие — п.8 дочитать глазами)"; fi

# ── 9. Ни лекций, ни назначенного порядка.
# ⚠ без символьных классов кириллицы: [^а-яё] в этой локали даёт «Invalid collation character»,
# и греп падал, а ветка || печатала ЗЕЛЁНОЕ на упавшей проверке. Поймано на фикстуре.
HITS=$(grep -nE 'Лекци(я|ю|и|ей) [0-9]|Л[123]( |\.|,|:|;|\)|$)|порядок изложения курса' "$DOC"); RC=$?
HITS=$(printf '%s\n' "$HITS" | grep -v 'НЕ назнач' | grep -v '^$')
if [ "$RC" -gt 1 ]; then no "9: греп упал (rc=$RC) — проверка НЕ выполнена, читать глазами"
elif [ -n "$HITS" ]; then printf '%s\n' "$HITS"; no "9: похоже на распределение по лекциям (строки выше)"
else ok "9: распределения по лекциям не найдено"; fi

echo; [ "$FAIL" -eq 0 ] && echo "ВЕРДИКТ ПРИЁМЩИКА: машинная часть зелёная. Ручное — гейты §Приёмка: охват в отрицательных вердиктах · время+токены · нет тихого недобора · УРОКИ ФАБРИКЕ · верификатор §3." \
  || echo "ВЕРДИКТ ПРИЁМЩИКА: КРАСНОЕ — вернуть на точечную дочистку."
exit "$FAIL"
