# `КРТ-РАЗН · <фаза>` — подгруппа «Разное» KRATNOST.md: 131 находка, механизм каждой свой,
# в источнике они НЕ сведены. Классифицировать их одной буквой значило бы придумать. Честный
# исход — отдельная клетка «не сведено в источнике», и она печатается наравне с классами.
NE_SVEDENO = "?"

FAZY = ("06-tekst", "05-raskadrovka")


def _srez():
    spec = importlib.util.spec_from_file_location(
        "srez", os.path.join(KART, "srez_po_faze.py"))
    srez = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(srez)
    return srez.parse()


def _korpus(path, regexp):
    d = {}
    with open(os.path.join(KART, path), encoding="utf-8") as f:
        for ln in f:
            m = re.match(regexp, ln)
            if m:
                d[int(m.group(1))] = m.group(2)
    return d


def razobrat():
    """→ список записей (фаза, id, кратность, симптом, класс)."""
    _, rows_by_phase = _srez()
    krt = _korpus("KRATNOST.md", r"^## (\d+)\. (.*?) — (\d+) вхожд")
    krv = _korpus("KRATNOST-vladelca.md", r"^### (\d+)\. (.*?) — (\d+) вхожд")
    zapisi = []
    for faza in FAZY:
        for ln in rows_by_phase.get(faza, []):
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            ident, krat = cells[0], int(cells[2]) if cells[2].isdigit() else 1
            m = re.match(r"^(КРТ-\d+)", ident)
            v = re.match(r"^(КРВ-\d+)", ident)
            if m:
                simptom = krt.get(int(m.group(1)[4:]), "??")
                klass = PO_ID.get(m.group(1), NE_SVEDENO)
            elif v:
                simptom = krv.get(int(v.group(1)[4:]), "??")
                klass = PO_ID.get(v.group(1), NE_SVEDENO)
            elif ident.startswith("КРТ-РАЗН"):
                simptom = "«Разное» KRATNOST.md — механизм в источнике не сведён"
                klass = NE_SVEDENO
            else:
                simptom = ident
                klass = PO_SIMPTOMU.get(ident, NE_SVEDENO)
            zapisi.append((faza, ident, krat, simptom, klass))
    return zapisi


def main():
    zapisi = razobrat()
    po_klassam = collections.Counter()
    strok = collections.Counter()
    for _f, _i, krat, _s, k in zapisi:
        po_klassam[k] += krat
        strok[k] += 1
    vsego = sum(po_klassam.values())

    if "--neraskryt" in sys.argv:
        for f, i, krat, s, k in zapisi:
            if k == NE_SVEDENO or s == "??":
                print("%-28s %-16s k=%-3d %s" % (i, f, krat, s))
        return
    if "--stroki" in sys.argv:
        for f, i, krat, s, k in sorted(zapisi, key=lambda z: (z[4], -z[2])):
            print("%s %-26s %-16s k=%-3d %-12s %s"
                  % (k, i, f, krat, RYCHAG.get(k, "—")[:12], s))
        return

    print("СРЕЗ КАРТОТЕКИ ПО ФАЗЕ ЛЕНТЫ — распределение по классам отказов")
    print("источник: %s/KARTOTEKA-problem.md · фазы: %s" % (os.path.basename(KART), ", ".join(FAZY)))
    print("строк-групп: %d · Σ кратности: %d\n" % (len(zapisi), vsego))
    print("%-3s %-6s %-7s %s" % ("кл", "Σ крат", "строк", "что ломается"))
    print("─" * 100)
    for k, n in po_klassam.most_common():
        imya = KLASSY.get(k, "НЕ СВЕДЕНО В ИСТОЧНИКЕ — механизм каждой находки свой")
        print("%-3s %-6d %-7d %s" % (k, n, strok[k], imya))
    print("─" * 100)
    print("%-3s %-6d %-7d %s" % ("Σ", vsego, len(zapisi), "все классы"))

    print("\nРАСПРЕДЕЛЕНИЕ ПО ВИДАМ РЫЧАГА (Σ кратности)")
    po_vidam = collections.Counter()
    for k, n in po_klassam.items():
        r = RYCHAG.get(k, "не классифицировано")
        vid = ("НЕТ РЫЧАГА" if r.startswith("НЕТ РЫЧАГА")
               else "ГЕЙТ" if r.startswith("ГЕЙТ")
               else "строка ZAHOD" if r.startswith("строка ZAHOD")
               else "проза DOK" if r.startswith("проза DOK")
               else "не классифицировано")
        po_vidam[vid] += n
    for vid, n in po_vidam.most_common():
        print("  %-22s %4d  (%.0f %%)" % (vid, n, 100.0 * n / vsego))

    zhivye = [k for k in po_klassam if k != NE_SVEDENO]
    bez = [k for k in zhivye if RYCHAG.get(k, "").startswith("НЕТ РЫЧАГА")]
    print("\nЖИВЫХ КЛАССОВ: %d (плюс клетка «%s» — не сведено в источнике, записей %d)"
          % (len(zhivye), NE_SVEDENO, strok[NE_SVEDENO]))
    print("КЛАССОВ БЕЗ РЫЧАГА: %d из %d — %s"
          % (len(bez), len(zhivye), ", ".join(sorted(bez))))
    print("ПУСТЫХ КЛЕТОК (класс объявлен, а записей нет): %s"
          % (", ".join(sorted(set(KLASSY) - set(po_klassam))) or "нет"))


if __name__ == "__main__":
    main()
