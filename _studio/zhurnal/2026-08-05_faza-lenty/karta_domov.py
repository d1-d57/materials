def atoms_06tekst():
    """Фаза `06-tekst` → список атомов (одно вхождение = один атом).

    Атом берётся из колонки адресов картотеки: `файл:строки` через `;`, внутри — через `,`.
    Маркер `(×N)` внутри токена означает N вхождений по одному адресу (иначе Σ атомов не сойдётся
    с Σ кратности: четыре строки фазы несут такие маркеры и дают ровно недостающие 7 вхождений).
    Ключ атома — сырой текст адреса, БЕЗ нормализации: в `КРВ-26a` два разных вхождения стоят по
    одной строке и различаются только пометкой в скобках (`230(осмысление)` / `230(манифест)`).
    """
    out = []
    for r in extract_groups("06-tekst"):
        if "adres" not in r:  # КРТ-РАЗН-* — агрегат без своей колонки адресов
            out.append({"id": r["id"], "kluch": "*", "kratnost": r["kratnost"],
                        "simptom": r["simptom"]})
            continue
        for part in r["adres"].split(";"):
            part = part.strip()
            m = re.match(r'^(.*?):(.*)$', part)
            if not m:
                continue
            fname, lines = m.groups()
            for tok in lines.split(","):
                tok = tok.strip()
                mult = re.search(r'×(\d+)', tok)
                out.append({"id": r["id"], "kluch": f"{fname.strip()}:{tok}",
                            "kratnost": int(mult.group(1)) if mult else 1,
                            "simptom": r["simptom"]})
    return out


def classify_06tekst():
    """Атом → дом. Падает, если строка фазы не размечена или Σ атомов разошлась с Σ фазы."""
    atoms = atoms_06tekst()
    unknown = sorted({a["id"] for a in atoms if a["id"] not in DOM_06TEKST})
    if unknown:
        raise SystemExit(f"❌ `06-tekst`: строки без разметки §C: {unknown}")
    for a in atoms:
        default, exceptions = DOM_06TEKST[a["id"]]
        a["dom"] = exceptions.get(a["kluch"], default)
        a["po_umolchaniyu"] = a["kluch"] not in exceptions
    # исключение, промахнувшееся мимо адреса, молча превратилось бы в «дом по умолчанию»
    for ident, (_d, exceptions) in DOM_06TEKST.items():
        live = {a["kluch"] for a in atoms if a["id"] == ident}
        promah = [k for k in exceptions if k not in live]
        if promah:
            raise SystemExit(f"❌ `06-tekst`: исключение {ident} не нашло адрес: {promah}")
    return atoms


def classify_vnefaz():
    rows = extract_groups("вне-фаз")
    for r in rows:
        if r["razdel"] == "4":
            KLASS_VNEFAZ[r["id"]] = "коммиты и git"
    return rows


def classify_intervyu():
    rows = extract_groups("04.5-intervyu")
    for r in rows:
        if r["razdel"] == "3":
            dom = PODKLASS_I_TO_DOM.get(r["podklass"], "СПОРНО")
            KLASS_INTERVYU[r["id"]] = dom
            if dom == "СПОРНО":
                KLASS_INTERVYU_WHY[r["id"]] = PODKLASS_I_WHY.get(r["podklass"], "?")
    return rows


def main():
    srez = _srez()
    counts, _ = srez.parse()

    dom_totals = collections.Counter()
    for phase, dom in PHASE_TO_DOM.items():
        dom_totals[dom] += counts.get(phase, 0)

    vnefaz_rows = classify_vnefaz()
    intervyu_rows = classify_intervyu()
    atoms06 = classify_06tekst()

    # Элемент `spornye`: (группа, id, симптом, причина, Σ кратности). Кратность носит сам элемент —
    # спорные приходят из трёх источников с РАЗНОЙ единицей (строка-группа у `вне-фаз` и `04.5`,
    # вхождение у `06-tekst`), и обратный поиск по строке для атомов уже не работает.
    spornye = []
    split06 = collections.Counter()
    for a in atoms06:
        split06[a["dom"]] += a["kratnost"]
        if a["dom"] == "СПОРНО":
            kluch = f"{a['id']}|{a['kluch']}"
            spornye.append(("06-tekst", kluch, a["simptom"],
                            SPORNO_06TEKST_WHY.get(kluch, "не классифицировано"), a["kratnost"]))
        else:
            dom_totals[a["dom"]] += a["kratnost"]
    if sum(split06.values()) != counts.get("06-tekst", 0):
        raise SystemExit(f"❌ `06-tekst`: Σ атомов {sum(split06.values())} "
                         f"!= Σ фазы {counts.get('06-tekst', 0)}")

    poddom_totals = collections.Counter()
    for r in vnefaz_rows:
        cls = KLASS_VNEFAZ.get(r["id"])
        if cls is None:
            spornye.append(("вне-фаз", r["id"], r["simptom"], KLASS_VNEFAZ_WHY.get(r["id"], "не классифицировано"), r["kratnost"]))
        elif cls == "СПОРНО":
            spornye.append(("вне-фаз", r["id"], r["simptom"], KLASS_VNEFAZ_WHY.get(r["id"], "?"), r["kratnost"]))
        else:
            poddom_totals[cls] += r["kratnost"]
            dom_totals["МЕТА"] += r["kratnost"]

    intervyu_split = collections.Counter()
    for r in intervyu_rows:
        cls = KLASS_INTERVYU.get(r["id"])
        if cls is None or cls == "СПОРНО":
            spornye.append(("04.5-intervyu", r["id"], r["simptom"], KLASS_INTERVYU_WHY.get(r["id"], "не классифицировано"), r["kratnost"]))
        else:
            intervyu_split[cls] += r["kratnost"]
            dom_totals[cls] += r["kratnost"]

    total_corpus = sum(counts.values())
    total_domov = sum(dom_totals.values())
    # Σ кратности спорных (не строк) — для сверки с total_corpus
    spornye_sum = sum(n for *_rest, n in spornye)

    if "--06tekst" in sys.argv:
        print(f"ФАЗА `06-tekst` — раздвоение по артефакту, позаписно "
              f"({len(atoms06)} атомов, Σ кратности {sum(split06.values())})")
        print(f"{'дом':10} {'Σ кратности':>12}")
        for dom in ("СЛАЙДЫ", "ЛЕНТА", "СПОРНО"):
            print(f"{dom:10} {split06[dom]:>12}")
        print(f"{'ИТОГО':10} {sum(split06.values()):>12}   (Σ фазы по srez: {counts.get('06-tekst', 0)})\n")
        cur = None
        for a in atoms06:
            if a["id"] != cur:
                cur = a["id"]
                print(f"\n{a['id']} — {a['simptom']}")
            mark = "" if a["po_umolchaniyu"] else "  ← поимённо"
            mult = f" ×{a['kratnost']}" if a["kratnost"] > 1 else ""
            print(f"   {a['dom']:8} {a['kluch']}{mult}{mark}")
        return

    if "--spornye" in sys.argv:
        for grp, ident, simptom, why, n in spornye:
            print(f"[{grp}] {ident} (кратность {n}): {simptom!r} — СПОРНО: {why}")
        print(f"\nВсего спорных записей: {len(spornye)}, Σ кратности: {spornye_sum}", file=sys.stderr)
        return

    if "--poddoma" in sys.argv:
        print("МЕТА (вне-фаз) по под-домам:")
        for pd in PODDOMA_VNEFAZ:
            print(f"  {pd:22} {poddom_totals[pd]:>6}")
        print(f"  {'СПОРНО (вне-фаз)':22} {sum(1 for g,*_ in spornye if g=='вне-фаз'):>6} строк")
        print(f"\n04.5-intervyu: СЛАЙДЫ={intervyu_split['СЛАЙДЫ']} МЕТА={intervyu_split['МЕТА']} "
              f"СПОРНО={sum(1 for g,*_ in spornye if g=='04.5-intervyu')} строк")
        print(f"06-tekst: СЛАЙДЫ={split06['СЛАЙДЫ']} ЛЕНТА={split06['ЛЕНТА']} "
              f"СПОРНО={split06['СПОРНО']} (Σ кратности; позаписно — `--06tekst`)")
        return

    print("КАРТА ДОМОВ — Σ кратности по прогону этого скрипта")
    print(f"{'дом':16} {'записей':>10}")
    for dom in DOMA:
        print(f"{dom:16} {dom_totals[dom]:>10}")
    # Решение 7 (2026-08-07) слило дома РЕСЁРЧ и ЛЕНТА в один дом плагина `reserch-cikl`.
    # Карта продолжает считать их раздельно (иначе теряется раскладка по фазам); сумма — здесь.
    print(f"{'  = reserch-cikl':16} {dom_totals['РЕСЁРЧ'] + dom_totals['ЛЕНТА']:>10}   (РЕСЁРЧ + ЛЕНТА, решение 7)")
    print(f"{'СПОРНЫЕ (записей)':16} {len(spornye):>10}   (Σ кратности спорных: {spornye_sum})")
    print(f"{'ИТОГО (дома+спорн)':16} {total_domov + spornye_sum:>10}")
    print(f"{'корпус (srez)':16} {total_corpus:>10}")
    if total_domov + spornye_sum != total_corpus:
        print(f"\n⚠ РАСХОЖДЕНИЕ: {total_domov + spornye_sum} != {total_corpus}", file=sys.stderr)


if __name__ == "__main__":
    main()
