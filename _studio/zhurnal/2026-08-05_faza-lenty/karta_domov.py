def _korpus(path, regexp):
    d = {}
    with open(os.path.join(KART, path), encoding="utf-8") as f:
        for ln in f:
            m = re.match(regexp, ln)
            if m:
                d[m.group(1)] = m.group(2).strip()
    return d


def _raznoe_bullets():
    """`## Разное` KRATNOST.md — 131 несведённых находки, каждая со своим симптомом+адресом."""
    text = open(os.path.join(KART, "KRATNOST.md"), encoding="utf-8").read()
    sec = text.split("## Разное", 1)[1]
    entries = []
    for symptom, addr in re.findall(r'^- \*\*(.+?)\*\* — (.+)$', sec, re.M):
        m = re.match(r'^(.*?)/([^/]+\.md)#([^,]+), строк[аи]\s+(.+)$', addr)
        if not m:
            continue
        folder, fname, anchor, lines = m.groups()
        # ';' режет составной адрес одного пункта на несколько мест (напр. "42; #ОТЧЁТ, строка
        # 125") — без него firstline ловит хвост второго анкора и не матчится ни с одной строкой.
        firstline = re.split(r'[–\-,(;]', lines.strip())[0].strip()
        entries.append({"folder": folder, "file": fname, "anchor": anchor.strip(),
                         "line": firstline, "symptom": symptom})
    return entries


def _expand_raznoe(adres_str, kratnost, raznoe):
    """КРТ-РАЗН · вне-фаз — один агрегат на 85 разнородных находок (метод: 'механизм каждой
    уникален', KARTOTEKA §94-96). Разворачиваем в кратность отдельных строк по адресу, а не
    оставляем одним неклассифицируемым комом — иначе 12% дома МЕТА ушло бы в СПОРНО оптом."""
    out = []
    for a in [x.strip() for x in adres_str.split(";")]:
        m2 = re.match(r'^([\w.\-]+\.md)\(([\w\-]+)\)#(.+)$', a)
        if m2:
            fname, arka, rest = m2.groups()
            anchor_part, lines_part = ("УРОКИ ФАБРИКЕ", rest) if ':' not in rest else rest.split(':', 1)
            cands = [e for e in raznoe if e["file"] == fname and e["folder"].endswith(arka)
                     and e["anchor"] == anchor_part.strip()]
        else:
            m = re.match(r'^([\w.\-]+\.md)#([^:]+):(.+)$', a)
            if not m:
                continue
            fname, anchor, lines_part = m.groups()
            cands = [e for e in raznoe if e["file"] == fname and e["anchor"] == anchor.strip()]
        for tok in re.split(r',', lines_part):
            fl = re.split(r'[–\-(]', tok.strip())[0].strip()
            for c in cands:
                if c["line"] == fl:
                    out.append({"symptom": c["symptom"], "adres": a})
    # добор известного ×2 (kod_bootstrap-guard.md#ЗАДАНИЕ:42) — источник размечает кратность 2
    # на этот адрес явно, второй экземпляр той же находки текстуально идентичен первому.
    dup = [e for e in out if "42" in e["adres"] and "bootstrap-guard" in e["adres"]]
    if dup and len(out) < kratnost:
        out.append(dict(dup[0]))
    return out


def extract_groups(phase_filter):
    """Строки-группы (все 5 разделов KARTOTEKA) с фазой == phase_filter, симптом резолвлен."""
    text = open(os.path.join(KART, "KARTOTEKA-problem.md"), encoding="utf-8").read()
    sections = re.split(r'\n(?=## Раздел \d)', text)
    krt = _korpus("KRATNOST.md", r"^## (\d+)\. (.*?) — \d+ вхожд")
    krv = _korpus("KRATNOST-vladelca.md", r"^### (\d+)\. (.*?) — \d+ вхожд")
    raznoe = _raznoe_bullets()
    rows = []
    r5_counter = [0]  # Раздел 5 не несёт id-колонки — нумеруем независимо от Разделов 1/2/4
    for sec in sections:
        head = sec.split("\n", 1)[0]
        if not head.startswith("## Раздел"):
            continue
        num = re.match(r'## Раздел (\d)', head).group(1)
        for ln in sec.split("\n"):
            if num == "3":
                m = ROW_R3.match(ln)
                if not m:
                    continue
                ident, phase, podklass, simptom = m.groups()
                if phase.split("/")[0] != phase_filter:
                    continue
                rows.append({"razdel": "3", "id": ident, "kratnost": 1,
                             "simptom": simptom.strip(), "podklass": podklass.strip()})
            elif num == "4":
                m = ROW_R4.match(ln)
                if not m:
                    continue
                ident, simptom, n, phase = m.groups()
                if phase.split("/")[0] != phase_filter:
                    continue
                rows.append({"razdel": "4", "id": ident, "kratnost": int(n), "simptom": simptom.strip()})
            else:
                m = ROW4.match(ln)
                if not (m and not ln.startswith("| id |") and not ln.startswith("|---")):
                    continue
                ident, phase, n, addr = m.groups()
                if phase.split("/")[0] != phase_filter:
                    continue
                if ident.startswith("КРТ-РАЗН"):
                    for i, e in enumerate(_expand_raznoe(addr, int(n), raznoe), 1):
                        rows.append({"razdel": "1-raznoe", "id": f"КРТ-РАЗН-{i}", "kratnost": 1,
                                     "simptom": e["symptom"]})
                    continue
                if ident.startswith("КРТ-"):
                    num_id = re.match(r"КРТ-0*(\d+)", ident).group(1)
                    simptom = krt.get(num_id, "??")
                elif ident.startswith("КРВ-"):
                    num_id = re.match(r"КРВ-0*(\d+)", ident).group(1)
                    simptom = krv.get(num_id, "??")
                else:
                    r5_counter[0] += 1
                    ident, simptom = f"Р5-{r5_counter[0]}", ident  # Раздел 5: id-колонка = симптом
                rows.append({"razdel": num, "id": ident, "kratnost": int(n),
                             "simptom": simptom, "adres": addr})
    return rows


