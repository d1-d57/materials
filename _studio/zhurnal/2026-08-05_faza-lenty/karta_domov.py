def main():
    srez = _srez()
    counts, _ = srez.parse()

    dom_totals = collections.Counter()
    for phase, dom in PHASE_TO_DOM.items():
        dom_totals[dom] += counts.get(phase, 0)

    vnefaz_rows = classify_vnefaz()
    intervyu_rows = classify_intervyu()

    spornye = []
    poddom_totals = collections.Counter()
    for r in vnefaz_rows:
        cls = KLASS_VNEFAZ.get(r["id"])
        if cls is None:
            spornye.append(("вне-фаз", r["id"], r["simptom"], KLASS_VNEFAZ_WHY.get(r["id"], "не классифицировано")))
        elif cls == "СПОРНО":
            spornye.append(("вне-фаз", r["id"], r["simptom"], KLASS_VNEFAZ_WHY.get(r["id"], "?")))
        else:
            poddom_totals[cls] += r["kratnost"]
            dom_totals["МЕТА"] += r["kratnost"]

    intervyu_split = collections.Counter()
    for r in intervyu_rows:
        cls = KLASS_INTERVYU.get(r["id"])
        if cls is None or cls == "СПОРНО":
            spornye.append(("04.5-intervyu", r["id"], r["simptom"], KLASS_INTERVYU_WHY.get(r["id"], "не классифицировано")))
        else:
            intervyu_split[cls] += r["kratnost"]
            dom_totals[cls] += r["kratnost"]

    total_corpus = sum(counts.values())
    total_domov = sum(dom_totals.values())
    total_spornye = sum(1 for _ in spornye)
    # Σ кратности спорных (не строк) — для сверки с total_corpus
    spornye_sum = 0
    for grp, ident, _s, _w in spornye:
        src = vnefaz_rows if grp == "вне-фаз" else intervyu_rows
        row = next(r for r in src if r["id"] == ident)
        spornye_sum += row["kratnost"]

    if "--spornye" in sys.argv:
        for grp, ident, simptom, why in spornye:
            print(f"[{grp}] {ident}: {simptom!r} — СПОРНО: {why}")
        print(f"\nВсего спорных строк: {len(spornye)}, Σ кратности: {spornye_sum}", file=sys.stderr)
        return

    if "--poddoma" in sys.argv:
        print("МЕТА (вне-фаз) по под-домам:")
        for pd in PODDOMA_VNEFAZ:
            print(f"  {pd:22} {poddom_totals[pd]:>6}")
        print(f"  {'СПОРНО (вне-фаз)':22} {sum(1 for g,_,_,_ in spornye if g=='вне-фаз'):>6} строк")
        print(f"\n04.5-intervyu: СЛАЙДЫ={intervyu_split['СЛАЙДЫ']} МЕТА={intervyu_split['МЕТА']} "
              f"СПОРНО={sum(1 for g,_,_,_ in spornye if g=='04.5-intervyu')} строк")
        return

    print("КАРТА ДОМОВ — Σ кратности по прогону этого скрипта")
    print(f"{'дом':16} {'записей':>10}")
    for dom in DOMA:
        print(f"{dom:16} {dom_totals[dom]:>10}")
    print(f"{'СПОРНЫЕ (строк)':16} {len(spornye):>10}   (Σ кратности спорных: {spornye_sum})")
    print(f"{'ИТОГО (дома+спорн)':16} {total_domov + spornye_sum:>10}")
    print(f"{'корпус (srez)':16} {total_corpus:>10}")
    if total_domov + spornye_sum != total_corpus:
        print(f"\n⚠ РАСХОЖДЕНИЕ: {total_domov + spornye_sum} != {total_corpus}", file=sys.stderr)


