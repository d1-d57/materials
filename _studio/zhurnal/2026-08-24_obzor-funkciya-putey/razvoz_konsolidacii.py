import re, sys
done = []
buf = {}


def rd(p):
    if p not in buf:
        buf[p] = open(p, encoding='utf-8').read()
    return buf[p]


def wr(p, s):
    buf[p] = s
    done.append(p)


def one(s, a, p):
    c = s.count(a)
    if c != 1:
        sys.exit(f"ЯКОРЬ ×{c} в {p}: {a[:70]}")


def ins_before(p, a, t):
    s = rd(p); one(s, a, p); wr(p, s.replace(a, t + a))


def ins_after_line(p, a, t):
    s = rd(p); one(s, a, p); i = s.index(a); j = s.index('\n', i)
    wr(p, s[:j + 1] + t + s[j + 1:])


def app_line(p, a, t):
    s = rd(p); one(s, a, p); i = s.index(a); j = s.index('\n', i)
    wr(p, s[:j] + t + s[j:])


def rep(p, a, b, cnt=1):
    s = rd(p); c = s.count(a)
    if c != cnt:
        sys.exit(f"ЗАМЕНА ×{c}≠{cnt} в {p}: {a[:70]}")
    wr(p, s.replace(a, b))


def before_next_heading(p, head, t):
    s = rd(p); one(s, head, p); i = s.index(head) + len(head)
    m = re.search(r'\n(#{2,3} )', s[i:])
    j = i + m.start() + 1 if m else len(s)
    wr(p, s[:j] + t + s[j:])


