#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ДВИЖКИ ПО ИМЕНИ — единственная дверь к `_generator` для тех, кто снаружи.

    python3 -m dvizhki doc <src-dir>     # build_doc.py        — документ-вид
    python3 -m dvizhki dek <src-dir>     # build_deck.py       — слайд-колода
    python3 -m dvizhki vid <src-dir>     # tools/check_view.py — гейт выхода
    python3 -m dvizhki --spisok          # что вообще есть

ЗАЧЕМ. Движок адресовался МЕСТОМ: одиннадцать скриптов курсов вычисляли путь к
нему, поднимаясь вверх от себя (`ROOT = Path(__file__).parents[N]`, дальше
`ROOT / "_generator" / "build_doc.py"`). Пока это так, вынести папку нельзя —
сломаются все разом, и сломаются у курсов, а не у фабрики. Владелец
сформулировал лечение сам: «ей не нужно расположение знать, а нужно просто в
системе знать её название».

Здесь оно и выдано: знание о месте движков переезжает из ОДИННАДЦАТИ чужих
файлов в ОДИН свой, который лежит с движками в одной папке и потому знает их
адрес даром — `Path(__file__).resolve().parent`. Тот же приём само-наведения,
что у `tools/korni.py` (`Path(__file__).resolve().parents[2]`).

25.08.2026 движки `doc`/`dek` переехали в плагин disciplina
(`../disciplina/_generator/`, решение владельца), дверь осталась здесь —
зовущие её по имени модуля правиться не должны. `put()` ищет файл двигателя
сначала рядом с дверью, затем в соседнем доме; `vid` живёт здесь же, как и
прежде.

🔴 ВТОРОЙ ПЕРЕМЕННОЙ ОКРУЖЕНИЯ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ.
`korni.py` держит `GIT_ZONA_REPO`, потому что его наводят на ЧУЖОЙ репозиторий:
фикстуры копируют инструменты в одноразовый каталог. Диспетчер наводить некуда —
он физически лежит среди движков, и переменная, которая ничего не меняет, была бы
не переиспользованием приёма, а второй конвенцией на пустом месте.

🔴 ПОЧЕМУ `runpy`, А НЕ `import` И НЕ `subprocess`. Задача — сменить адресацию,
не тронув поведение. `runpy.run_path(..., run_name="__main__")` исполняет ТОТ ЖЕ
файл, оставляя движку всё, на что он опирается:
  · `__file__` — настоящий путь движка. Несуще: `build_deck.py` ищет
    `skeleton/sluzhebnye` относительно `__file__`, и подмена сломала бы служебные
    слайды молча;
  · `sys.argv[0]` — путь к движку, значит `prog` у argparse тот же, значит текст
    `--help` и диагностика ошибок аргументов не меняются ни на символ;
  · код возврата — `SystemExit` из `sys.exit(main())` движка пролетает насквозь.
Ни один байт `build_doc.py` / `build_deck.py` / `check_view.py` не правится.

УСТАНОВКА — `_generator/README.md`, раздел «Установка (один раз)».
"""
import runpy
import sys
from pathlib import Path

# Дом движков — папка, в которой лежит этот файл. После `git mv _generator …`
# всё едет вместе с ним, и ни один вызывающий не правится: в этом вся цель.
DOM = Path(__file__).resolve().parent

# Соседний дом — куда уехали `doc`/`dek` 25.08. Вычисляется от двери, не
# вписывается рукой: оба репозитория лежат рядом, переезд пары едет вместе.
SOSEDI = DOM.parents[1] / "disciplina" / "_generator"

# Имя движка → файл внутри дома. Это ДАННЫЕ: новый движок — одна строка здесь и
# ноль правок где-либо ещё. Имена короткие и русские, потому что их набирают
# руками: `doc` — документ-вид, `dek` — слайд-колода, `vid` — гейт выхода.
DVIZHKI = {
    "doc": "build_doc.py",
    "dek": "build_deck.py",
    "vid": "tools/check_view.py",
}


def put(imya_fajla):
    """Абсолютный путь к файлу движка по его ИМЕНИ («build_doc.py»).

    Дверь для тех, кому нужен не запуск, а сам файл. Падаем громко: молчаливое
    None здесь означало бы «прочитали пустоту» у зовущего.
    """
    # Локальный дом первым: здесь живут `vid` и любые будущие местные движки,
    # соседний — только если файла здесь нет. Ни дома, ни порядка поиска зовущий
    # не видит.
    for dom in (DOM, SOSEDI):
        p = dom / imya_fajla
        if p.is_file():
            return p
    raise FileNotFoundError(
        "в движке нет файла «%s» (дома: %s)"
        % (imya_fajla, ", ".join(str(d) for d in (DOM, SOSEDI)))
    )


def ishodnik(imya_fajla):
    """Текст файла движка по имени — для тех, кто читает исходник, а не зовёт.

    Такой зовущий есть, и он ровно один: рендер иллюстраций обзора вынимает из
    `build_doc.py` блок CSS словаря примитивов, чтобы отрисовать SVG теми же
    классами, какими их отрисует движок. Ему нужен не запуск, а текст.
    """
    return put(imya_fajla).read_text(encoding="utf-8")


# `or ""`, а не голое `__doc__`: под `python3 -OO` докстринги вырезаются, `__doc__`
# становится None, и `import dvizhki` падал бы с AttributeError ещё до первой строки
# работы — то есть ронял бы вызывающего по причине, не имеющей к нему отношения.
# Поймано прогоном `python3 -OO -c "import dvizhki"`, а не рассуждением.
SPRAVKA = (__doc__ or "python3 -m dvizhki <движок> <аргументы>").split("ЗАЧЕМ.")[0].strip() \
    + "\n\nдвижки: " + " · ".join("%s → %s" % (k, v) for k, v in DVIZHKI.items())


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ("-h", "--help", "--spisok"):
        print(SPRAVKA)
        return 0
    imya = argv[0]
    if imya not in DVIZHKI:
        print("✗ движка «%s» нет. Есть: %s" % (imya, " ".join(DVIZHKI)), file=sys.stderr)
        return 2
    fajl = put(DVIZHKI[imya])
    # argv движка — ровно тот, что был у него при запуске путём: argv[0] = его
    # собственный путь, дальше аргументы зовущего без единой добавки.
    sys.argv = [str(fajl)] + argv[1:]
    # 🔴 ПАПКА ДВИЖКА — В sys.path[0], КАК ПРИ ЗАПУСКЕ ПУТЁМ. `python3 <файл>` кладёт
    # туда папку файла, а `runpy.run_path` — НЕ кладёт. Сегодня разницы не видно: все
    # три движка на чистой stdlib и соседей не импортируют (проверено). Но это
    # неявное условие, а не свойство: первый же движок, которому понадобится сосед,
    # работал бы путём и падал по имени — и падал бы у курса, не у фабрики. Дешевле
    # снять расхождение сейчас, чем ловить его тогда. Найдено верификатором захода.
    papka = str(fajl.parent)
    if not sys.path or sys.path[0] != papka:
        sys.path.insert(0, papka)
    runpy.run_path(str(fajl), run_name="__main__")
    # сюда попадаем только если движок завершился БЕЗ sys.exit (так делает
    # check_view.py при зелёном) — это успех, и код возврата у него был 0.
    return 0


if __name__ == "__main__":
    sys.exit(main())
