# HEAD. Флаг превратил бы каждую из этих строк в развилку внутри функции, которую
# канон объявил «единственной законной дверью» и которой пользуются все заходы, —
# цена ошибки легла бы на общий путь. Отдельная подкоманда не трогает работающий
# путь ни строкой, а её имя выдаётся субагенту гит-контура КАК ПРАВО («тебе можно
# `vlit-v-osnovnuyu` и `vyvezti`, и ничего сверх»).
#
# ПОЧЕМУ ЭТО БЕЗОПАСНО ПРИ ЖИВЫХ СОСЕДЯХ. Операция меняет файлы ГЛАВНОЙ папки —
# там основная ветка и стоит. Соседние worktree стоят на СВОИХ ветках, их рабочие
# деревья не трогаются вовсе. Опасностей ровно три, и все три закрыты ниже
# механизмом: грязь главной папки (считается В НЕЙ, а не здесь), её `index.lock`
# (у неё свой), и чужая/отцепленная ветка в ней (отказ, а не влитие куда попало).


def osnovnaya_vetka(koren=None):
    """(имя основной ветки, None) либо (None, причина) — СНЯТО КОМАНДОЙ.

    `koren` — судить ДРУГОЙ репозиторий (соседний, не свой). По умолчанию свой:
    источники 1–2 спрашиваются у `REPO`, источник 3 — у главной рабочей копии.
    Параметр заведён ради `dolg_repozitoriev.py`, который считает долг по
    СОСЕДНИМ репозиториям и держал ЧЕТВЁРТУЮ копию этого определения — ту же
    HEAD-овую и с тем же дефектом. Копию убрали, дом остался один.

    🔴 ЭТО ДОМ ОТВЕТА, И ОН ОДИН. Тот же вопрос задают `priyomka.py` (Г12, Г14) и
    `bootstrap_zahod.py` (сторож невлитых веток) — оба зовут ЭТУ функцию, своей
    копии определения не заводят. Три копии и были дефектом: один и тот же
    неверный ответ приезжал в трёх местах, и чинить его пришлось бы трижды.
    Фикстура держит это машинно (`fixtures/topologiya/PROGNAT.sh`, ловушка
    `M-07-pod-mutaciej-storozh-vrjot-i-dom-otveta-odin`): подменяется ДОМ, и
    если вызывающий перестанет спрашивать дом, подмена его не достанет и
    ловушка покраснеет.

    🔴 ИМЯ НЕ ВПИСЫВАЕТСЯ В КОД. `arka/mat-kostyak` в `materials` и `main` в
    `disciplina` — разные, и захардкоженное имя сделало бы подкоманду
    однорепозиторной ровно в тот момент, когда её зовут во втором репозитории.

    🔴 ОТ РЕПОЗИТОРИЯ, А НЕ ОТ `HEAD` — И ВОТ ПОЧЕМУ ЭТО ПЕРЕПИСАНО. Прежнее
    определение («основная ветка — та, что стоит в ГЛАВНОЙ рабочей копии»)
    верно РОВНО в многопапочной топологии: там заходы живут в worktree, а
    главная папка стоит на основной ветке. В ОДНОПАПОЧНОМ репозитории (Матлас, и
    вообще любой обычный проект) главная папка — единственная, и в ней стоит
    ветка захода. Функция отвечала «основная ветка = ветка захода», после чего:
      · `vlit-v-osnovnuyu` отказывался вливать «саму в себя» — и с `rc=0`;
      · Г14 приёмки печатал ✅ «ВЛИТА», сравнив ветку С СОБОЙ. Это единственный
        гейт, стерегущий «отчёт приехал без кода», и в той топологии он не мог
        покраснеть НИКОГДА — зелёный гейт, который ничего не проверяет, хуже
        отсутствующего: рецензент перестаёт смотреть;
      · сторож невлитых веток не давал собрать заход, считая невлитым влитое.
    Замер — `ot-maksa/BACKLOG_MATLAS.md`, M-01/M-02/M-07, живой прогон 23.08.

    ПОРЯДОК ИСТОЧНИКОВ — СВЕРХУ ВНИЗ, ПЕРВЫЙ ОТВЕТИВШИЙ ВЫИГРЫВАЕТ:
      1. `git symbolic-ref refs/remotes/origin/HEAD` — что удалённый репозиторий
         САМ считает своей веткой по умолчанию. Самый сильный источник: это факт
         о репозитории, а не о том, где кто стоит.
      2. настроенный дефолт `init.defaultBranch` — **только `--local`**, то есть
         настройка ЭТОГО репозитория. Глобальную намеренно не читаем: она
         описывает МАШИНУ, а не репозиторий, и на машине владельца ответила бы
         `main` для `materials`, чья основная ветка — `arka/mat-kostyak`. Взять
         её значило бы сломать ровно ту топологию, ради которой написано (3).
      3. ветка ГЛАВНОЙ рабочей копии — прежнее поведение, последним запасом.
         В многопапочной топологии оно верно и остаётся ответом по умолчанию,
         когда репозиторий о себе ничего не сообщил.

    🔴 ИСТОЧНИК ПРИНИМАЕТСЯ, ТОЛЬКО ЕСЛИ НАЗВАННАЯ ИМ ВЕТКА СУЩЕСТВУЕТ ЛОКАЛЬНО.
    Без этой проверки порядок источников сделал бы ХУЖЕ, чем было: влить,
    сравнить `--merged`, посчитать `--no-merged` можно лишь по существующей
    ветке, и ответ-призрак означал бы отказ на ровном месте там, где сегодня
    работает. Не существует — падаем к следующему источнику, а не отказываем.

    Отцепленный HEAD в главной папке — это НЕ имя ветки, и вливать в него
    нельзя: отказ (и только если до (3) вообще дошло).
    """
    # Одна дверь к git на всю функцию: свой репозиторий или названный чужой.
    def _g(*a):
        return (git(*a, check=False) if koren is None
                else git_tam(koren, *a, check=False))

    def _est(name):
        return bool(name) and _g("rev-parse", "--verify", "--quiet",
                                 f"refs/heads/{name}").returncode == 0

    # 1. Что репозиторий сам объявил своей веткой по умолчанию.
    # 🔴 ХВОСТ БЕРЁТСЯ ПО ПРЕФИКСУ, А НЕ ПО ПОСЛЕДНЕМУ СЛЭШУ. Имя основной ветки
    # в этой фабрике содержит слэш (`arka/mat-kostyak`), и `rsplit("/", 1)[-1]`
    # отдал бы `mat-kostyak` — ветку, которой нет. Проверка существования это
    # поймала бы и увела к следующему источнику, но ответ был бы верным
    # СЛУЧАЙНО, а не по построению.
    PREFIKS_ORIGIN = "refs/remotes/origin/"
    r = _g("symbolic-ref", "--quiet", PREFIKS_ORIGIN + "HEAD")
    polnoe = r.stdout.strip() if r.returncode == 0 else ""
    if polnoe.startswith(PREFIKS_ORIGIN):
        imya = polnoe[len(PREFIKS_ORIGIN):]
        if _est(imya):
            return imya, None

    # 2. Настроенный дефолт ЭТОГО репозитория (не машины — см. докстринг).
    r = _g("config", "--local", "--get", "init.defaultBranch")
    if r.returncode == 0 and _est(r.stdout.strip()):
        return r.stdout.strip(), None

    # 3. Прежнее поведение: ветка главной рабочей копии (у чужого репозитория —
    #    его собственный HEAD: понятия «главная копия» снаружи у нас нет).
    glav = Path(koren) if koren is not None else glavnaya_rabochaya()
    r = git_tam(glav, "rev-parse", "--abbrev-ref", "HEAD", check=False)
    if r.returncode != 0:
        return None, f"главная рабочая копия {glav} не отвечает на rev-parse"
    name = r.stdout.strip()
    if not name or name == "HEAD":
        return None, (f"в главной рабочей копии {glav} ОТЦЕПЛЕННЫЙ HEAD, а "
                      f"репозиторий не объявил ветку по умолчанию ни через "
                      f"`origin/HEAD`, ни через `init.defaultBranch` — "
                      f"имени основной ветки нет, вливать не во что")
    return name, None


def _git_dir_tam(cwd):
    """Личный служебный каталог ДРУГОЙ рабочей копии (её `index.lock` живёт там).

    У каждой рабочей копии он свой: ждать СВОЙ лок, собираясь писать в ЧУЖОЕ
    дерево, — значит не ждать ничего (`wait_for_lock` это уже знает про себя,
    см. её докстроку; здесь тот же факт, но про соседа).
    """
    r = git_tam(cwd, "rev-parse", "--git-dir", check=False)
    p = Path(r.stdout.strip() or ".git")
    return p if p.is_absolute() else Path(cwd) / p


def _zhdat_lok_tam(gitdir, limit=LOCK_WAIT_SEC):
    """Тот же ретрай с отступом, что у `wait_for_lock`, но по ЧУЖОМУ каталогу.

    Лок не удаляем никогда и здесь: в главной папке коммитит владелец, и снести
    лок у работающего git — испортить его индекс.
    """
    lock = Path(gitdir) / "index.lock"
    if not lock.exists():
        return True
    print(f"⏳ {lock} занят — в главной папке кто-то коммитит. Жду до {limit} с…")
    waited, step = 0, 2
    while waited < limit:
        time.sleep(step)
        waited += step
        if not lock.exists():
            print(f"   лок отпущен через {waited} с — продолжаю.")
            return True
    print(f"⛔ Лок главной папки держат дольше {limit} с. Ничего не делаю.\n"
          "   Это НЕ поломка: рядом идёт длинный коммит. Подожди и повтори ту же\n"
          "   команду. Лок руками НЕ удалять.")
    return False


def _gryaz_tam(cwd):
    """[(код, путь)] вне git в ДРУГОЙ рабочей копии — её грязь, не своя."""
    r = git_tam(cwd, "status", "--porcelain", "--untracked-files=all", check=False)
    rows = []
    for line in r.stdout.splitlines():
        if not line.strip():
            continue
        path = line[3:].strip()
        if path.startswith('"') and path.endswith('"'):
            path = path[1:-1].encode().decode("unicode_escape").encode("latin-1").decode("utf-8")
        rows.append((line[:2], path))
    return rows


def _vse_rabochie_papki():
    """{ветка: путь} по ВСЕМ рабочим папкам, включая СВОЮ.

    🔴 ПОЧЕМУ НЕ `worktree_branches()` — НАЙДЕНО СОБСТВЕННЫМ ПРОГОНОМ ДО ПЕРВОГО
    БОЕВОГО ВЫЗОВА. Та функция нарочно исключает папку вызывающего: для `merge`
    это верно, там своя ветка — это `head`, и её защищает отдельная проверка
    «сливать в себя нечего». Здесь цель ДРУГАЯ (основная ветка), поэтому своя
    ветка перестаёт быть целью и становится обычным источником — и отказ
    «вычекаучена в рабочей папке» на ней НЕ срабатывал: субагент, стоящий в
    папке захода, молча влил бы в основную СВОЮ ЖЕ ветку вместе с
    недокоммиченным состоянием вокруг. Проверено на синтетическом репозитории:
    вызов без `--vsyo-ravno` проходил там, где обязан был отказать.

    Главная папка в исключении не нуждается: ветка, стоящая в ней, — это и есть
    основная, а влитие основной в себя отсекается раньше отдельной проверкой.
    """
    res, path = {}, None
    for line in git("worktree", "list", "--porcelain", check=False).stdout.splitlines():
        if line.startswith("worktree "):
            path = line[len("worktree "):].strip()
        elif line.startswith("branch ") and path:
            res[line[len("branch "):].strip().replace("refs/heads/", "", 1)] = path
            path = None
    return res


def cmd_vlit_v_osnovnuyu(args):
    """Влить ветку в ОСНОВНУЮ ветку, в главной рабочей папке.

    Отличие от `merge` в одной фразе: `merge` вливает в ТЕБЯ, эта — в ОСНОВНУЮ.
    Полное «зачем» и почему это отдельная подкоманда — в комментарии выше.

    Конфликт НЕ разрешает, как и `merge`: печатает пути и останавливается.
    Дальше `vlit-v-osnovnuyu --continue` или `--abort` — обе работают в ГЛАВНОЙ
    папке, а не здесь; своих одноимённых хвостов у `merge` они не трогают.
    """
    glav = glavnaya_rabochaya()
    gd = _git_dir_tam(glav)

    # --abort / --continue: хвосты незаконченного слияния В ГЛАВНОЙ ПАПКЕ.
    if args.abort or args.cont:
        if in_sandbox():
            return refuse_write("vlit-v-osnovnuyu --abort/--continue",
                                suggest="vlit-v-osnovnuyu "
                                        + ("--abort" if args.abort else "--continue"))
        if not (gd / "MERGE_HEAD").exists():
            print(f"⚠ В главной папке {glav} незаконченного слияния нет — "
                  "отменять/продолжать нечего.")
            return 1
        if args.abort:
            r = git_tam(glav, "merge", "--abort", check=False)
            if r.returncode != 0:
                print(f"❌ merge --abort в главной папке упал (rc={r.returncode}):\n"
                      f"   {r.stderr.strip()}")
                return 1
            print(f"✅ Слияние в главной папке отменено, дерево вернулось к состоянию до него.")
            return 0
        unmerged = [l for l in git_tam(glav, "diff", "--name-only",
                                       "--diff-filter=U").stdout.splitlines() if l]
        if unmerged:
            print(f"⛔ Ещё {len(unmerged)} путей с неразрешённым конфликтом — не завершаю:")
            for p in unmerged:
                print(f"   {p}")
            return 1
        nv, rc = flagi_obhoda_sliyaniya(
            getattr(args, "no_verify", None),
            'vlit-v-osnovnuyu --continue --no-verify "чужой долг: <что именно покраснело>"')
        if rc is not None:
            return rc
        if not _zhdat_lok_tam(gd):
            return 2
        r = git_tam(glav, "commit", "--no-edit", *nv, check=False)
        if r.returncode != 0:
            out = (r.stderr.strip() + "\n" + r.stdout.strip()).strip().splitlines()
            print(f"❌ merge-коммит в главной папке упал (rc={r.returncode}):")
            for l in (out[-5:] or ["(вывод пуст)"]):
                print(f"   {l}")
            if not nv:
                print("   Красное на ЧУЖОМ долге (фикстура/гейт чужой зоны) — обход законен,\n"
                      "   но только с причиной:\n"
                      '     vlit-v-osnovnuyu --continue --no-verify "чужой долг: <что покраснело>"')
            log_incident("vlit-v-osnovnuyu --continue: коммит слияния не прошёл",
                         "смотреть вывод хука и `doctor` в главной папке")
            return 1
        print(f"✅ Слияние завершено: "
              f"{git_tam(glav, 'log', '-1', '--oneline').stdout.strip()}")
        return 0

    if not args.branch:
        sys.exit("❌ Нужна ветка: `git_zona.py vlit-v-osnovnuyu <ветка> [--zone <путь>]`")
    branch = args.branch
    if git("rev-parse", "--verify", "--quiet", f"refs/heads/{branch}",
           check=False).returncode != 0:
        sys.exit(f"❌ Ветки нет: {branch}")

    osn, err = osnovnaya_vetka()
    if err:
        print(f"⛔ {err}.\n"
              "   Вливать в основную не во что — поставь главную папку на её ветку\n"
              "   и повтори. Ничего не сделано.")
        log_incident("vlit-v-osnovnuyu: основной ветки нет", err)
        return 1
    if osn == branch:
        print(f"❌ `{branch}` — это и есть основная ветка. Сливать нечего.")
        return 1
    if (gd / "MERGE_HEAD").exists():
        print(f"⛔ В главной папке {glav} уже идёт незаконченное слияние — второе не начинаю.\n"
              "   Завершить: `vlit-v-osnovnuyu --continue` · отменить: `--abort`")
        return 1

    base = git_tam(glav, "merge-base", osn, branch).stdout.strip()
    commits = [l for l in git_tam(glav, "log", "--oneline",
                                  f"{osn}..{branch}").stdout.splitlines() if l]
    touched = [l for l in git_tam(glav, "diff", "--name-only",
                                  f"{osn}...{branch}").stdout.splitlines() if l]
    novye_instrumenty = [l.split("\t", 1)[1] for l in
                         git_tam(glav, "diff", "--name-status", "--diff-filter=A",
                                 f"{base}...{branch}").stdout.splitlines()
                         if l and (l.endswith(".py") or l.endswith(".sh"))]

    # 🔴 ЦЕЛЬ ПЕЧАТАЕТСЯ ДО РАБОТЫ, ПАПКОЙ И ВЕТКОЙ. Команда пишет в дерево, в
    # котором вызывающий не стоит, — единственный дешёвый способ не влить в
    # неожиданное место — назвать его вслух раньше, чем что-то произошло.
    print(f"═══ vlit-v-osnovnuyu: `{branch}` → `{osn}` ═══\n"
          f"Главная рабочая папка: {glav}\n")
    if not commits:
        print(f"✅ Всё, что есть в `{branch}`, уже в `{osn}` — сливать нечего.")
        return 0
    print(f"База слияния: {base[:7]}  "
          f"({git_tam(glav, 'log', '-1', '--format=%s', base).stdout.strip()})")
    print(f"\nПриедет коммитов: {len(commits)}")
    for l in commits:
        print(f"   {l}")
    print(f"\nЗатронет путей: {len(touched)}")
    for p in touched[:40]:
        print(f"   {p}")
    if len(touched) > 40:
        print(f"   … ещё {len(touched) - 40}")

    if args.zone:
        outside = [p for p in touched if not any(in_zone(p, z) for z in args.zone)]
        if outside:
            print(f"\n⛔ Слияние выходит за зон{'ы' if len(args.zone) > 1 else 'у'} "
                  f"({', '.join(args.zone)}) — не сливаю НИЧЕГО.")
            for p in outside[:20]:
                print(f"     {p}")
            if len(outside) > 20:
                print(f"     … ещё {len(outside) - 20}")
            log_incident(f"vlit-v-osnovnuyu {branch} выходит за зону",
                         "назвать все зоны повторным --zone либо звать без --zone осознанно")
            return 1

    # 🔴 ГРЯЗЬ СЧИТАЕТСЯ В ГЛАВНОЙ ПАПКЕ, А НЕ ЗДЕСЬ. Это не педантизм: у
    # worktree свой индекс и своё дерево, и «у меня чисто» не говорит ровно
    # ничего о том, что слияние собирается переписать ТАМ. Проверка по своей
    # грязи была бы зелёной ровно в опасном случае.
    dirty_rows = _gryaz_tam(glav)
    collision = sorted({p for _, p in dirty_rows if p in touched})
    other = sorted({p for _, p in dirty_rows if p not in touched})
    if collision:
        print(f"\n⛔ В главной папке {len(collision)} путей ОДНОВРЕМЕННО грязные и "
              "участвуют в слиянии — не сливаю:")
        for p in collision:
            print(f"   {p}")
        print("   Сперва закоммить их (`commit --zone <зона> -m …` ИЗ ГЛАВНОЙ ПАПКИ)\n"
              "   или откати — иначе слияние их затрёт.")
        log_incident(f"vlit-v-osnovnuyu {branch}: грязь главной папки пересекается со сливаемым",
                     "закоммитить или откатить эти пути в главной папке и повторить")
        return 1
    if other:
        print(f"\n⚠ Вне слияния грязных путей в главной папке: {len(other)}. В merge-коммит "
              "они НЕ поедут (индекс не трогаю), но и не защищены.")

    put_wt = _vse_rabochie_papki().get(branch)
    if put_wt:
        svoya = Path(put_wt).resolve() == REPO.resolve()
        if not args.vsyo_ravno:
            print(f"\n⛔ `{branch}` вычекаучена в рабочей папке — не сливаю:\n"
                  f"   {put_wt}{'   ← ЭТО ТВОЯ СОБСТВЕННАЯ ПАПКА' if svoya else ''}\n"
                  + ("   Своя ветка не исключение: вокруг неё может лежать "
                     "недокоммиченное,\n   и в основную уедет состояние, которого "
                     "ты не собирался отдавать.\n" if svoya else
                     "   Там может идти живой заход, и слияние притащит недоделанное.\n"
                     "   Сперва спроси того, кто в ней работает, либо повтори с\n")
                  + "   `--vsyo-ravno \"<причина>\"`.")
            return 1
        print(f"\n⚠ --vsyo-ravno: сливаю `{branch}` несмотря на живую рабочую папку "
              f"{put_wt}. Причина: {args.vsyo_ravno}")
        log_incident(f"vlit-v-osnovnuyu {branch}: ветка с живой рабочей папкой --vsyo-ravno",
                     f"причина: {args.vsyo_ravno} — работа папки {put_wt} могла разойтись")

    if in_sandbox():
        return refuse_write("Влитие в основную ветку",
                            suggest=f"vlit-v-osnovnuyu {branch}")

    if not _zhdat_lok_tam(gd):
        log_incident("vlit-v-osnovnuyu: лок главной папки держится дольше 90 с",
                     "подождать и повторить ту же команду")
        return 2

    # 🔴 ГЛАВНАЯ ПАПКА МОЖЕТ СТОЯТЬ НЕ НА ОСНОВНОЙ ВЕТКЕ — И ТОГДА `merge` ВЛИВАЕТ
    # НЕ ТУДА, МОЛЧА. `git merge` вливает в то, что ВЫЧЕКАУЧЕНО, а не в то, что
    # названо: в однопапочном репозитории (Матлас) главная папка стоит на ветке
    # захода, и `merge zahod/proba` из неё даёт «Already up to date», rc=0 — а
    # печаталось при этом «✅ Влито в `main`». Вершина `main` не двигалась.
    # Вторая половина M-01, найденная фикстурой `fixtures/topologiya/PROGNAT.sh`
    # уже ПОСЛЕ починки определения основной ветки: verное имя цели ничего не
    # стоит, если запись идёт в другое место.
    # 🔴 ПОЧЕМУ НЕ `checkout` ОСНОВНОЙ И ОБРАТНО. В общей рабочей папке checkout
    # МОЛЧА откатывает дерево к состоянию ветки, и следа в git не остаётся —
    # оплаченная цена 27→28.07 (файл откатился ночью, поймал владелец вручную).
    # Инструмент, чинящий потерю работы, не имеет права её устраивать.
    # `git fetch . <ветка>:<основная>` двигает ССЫЛКУ, не трогая ни дерево, ни
    # индекс, и по построению отказывается от всего, что не fast-forward, — то
    # есть переписать историю им нельзя. Он же отказывается писать в ветку,
    # вычекаученную в ЛЮБОЙ рабочей папке, так что чужой заход в безопасности.
    # Не fast-forward — честный отказ: настоящее слияние требует дерева, а
    # дерева основной ветки здесь нет ни у кого.
    tekushchaya = git_tam(glav, "rev-parse", "--abbrev-ref", "HEAD",
                          check=False).stdout.strip()
    if tekushchaya != osn:
        print(f"\n⚠ Главная папка стоит на `{tekushchaya}`, а не на `{osn}` — "
              f"дерева основной ветки нет ни в одной рабочей папке.\n"
              f"   Двигаю ССЫЛКУ `{osn}` (`git fetch . {branch}:{osn}`): дерево и "
              f"индекс не трогаются, не-fast-forward отвергается.")
        r = git_tam(glav, "fetch", ".", f"{branch}:{osn}", check=False)
        if r.returncode == 0:
            novaya = git_tam(glav, "rev-parse", osn, check=False).stdout.strip()
            print(f"\n✅ Влито в `{osn}` перемоткой: {novaya[:7]} "
                  f"({git_tam(glav, 'log', '-1', '--format=%s', osn).stdout.strip()})")
            _obyavit_ne_vstroennoe(novye_instrumenty, koren=glav)
            return 0
        print(f"\n❌ Перемотка `{osn}` не прошла (rc={r.returncode}):")
        for l in ((r.stderr.strip() + "\n" + r.stdout.strip()).strip().splitlines()[:5]
                  or ["(вывод пуст)"]):
            print(f"   {l}")
        print(f"\n   Скорее всего `{osn}` ушла вперёд и перемоткой не берётся — "
              f"нужно НАСТОЯЩЕЕ слияние,\n   а для него нужна рабочая папка, стоящая "
              f"на `{osn}`. Завести её: `git_zona.py worktree add …`,\n   слить там и "
              f"повторить. Ветка `{branch}` остаётся невлитой — это честный отказ.")
        log_incident(f"vlit-v-osnovnuyu {branch}: перемотка {osn} отвергнута",
                     f"основная ветка {osn} не вычекаучена нигде, а fast-forward "
                     f"невозможен — нужна рабочая папка на {osn} и настоящее слияние")
        return otkaz_stop(
            f"влитие ветки {branch} в основную {osn} перемоткой",
            f"git_zona.py vlit-v-osnovnuyu {branch}", r.returncode,
            (r.stderr.strip() + " " + r.stdout.strip()).strip(),
            f"завести рабочую папку на {osn}, слить там по существу; "
            f"до этого ветка {branch} остаётся невлитой")

    # 🔴 ФАНТОМНЫЙ DIRECTORY-RENAME НА ПУТЯХ ОЧЕРЕДИ — ОТКЛЮЧАЕМ RENAME-DETECTION.
    # Случай `dolg-git` 23.08 (заявка 2230): ветка переносила каталог очереди
    # `na-zahod/* → sdelano/*`, а main только что ДОБАВИЛ новый файл в
    # `na-zahod/`; rename-detection git решил, что этот файл «переехал» вместе с
    # каталогом, и перенаправил его в `sdelano/` — влитие встало на конфликт,
    # которого не существует (блоб стадии 2 совпадал байт-в-байт с
    # `main:na-zahod/…`). Стоило остановленного влития и ручного разбора стадий.
    # Лечение: когда слияние затрагивает пути очереди, переезды там честно
    # выглядят удалением+добавлением (`-X no-renames`) — фантом не возникает.
    # Цена осознана и принята: настоящий переезд файла внутри очереди встанет
    # как delete/add-конфликт вместо тихого автослияния — редкий случай, и он
    # ДОСТОВЕРНЕЙ фантома.
    strategiya = ["--no-edit"]
    if any(p == ZAYAVKI_DIR or p.startswith(ZAYAVKI_DIR + "/") for p in touched):
        strategiya += ["-X", "no-renames"]
        print("\n⚠ В слиянии пути очереди заявок (" + ZAYAVKI_DIR + ") — "
              "rename-detection ОТКЛЮЧЁН (-X no-renames):\n"
              "   иначе добавленный в старый каталог файл git «переименует» следом "
              "за переносом каталога\n"
              "   и влитие встанет на фантомный конфликт (случай dolg-git 23.08, "
              "заявка 2230).\n")
    r = git_tam(glav, "merge", *strategiya, branch, check=False)
    if r.returncode == 0:
        print(f"\n✅ Влито в `{osn}` без конфликтов: "
              f"{git_tam(glav, 'log', '-1', '--oneline').stdout.strip()}")
        _obyavit_ne_vstroennoe(novye_instrumenty, koren=glav)
        return 0

    conflicts = [l for l in git_tam(glav, "diff", "--name-only",
                                    "--diff-filter=U").stdout.splitlines() if l]
    if not conflicts:
        out = (r.stderr.strip() + "\n" + r.stdout.strip()).strip().splitlines()
        print(f"\n❌ Слияние не прошло (rc={r.returncode}):")
        for l in (out[:5] or ["(вывод пуст)"]):
            print(f"   {l}")
        log_incident(f"vlit-v-osnovnuyu {branch} не прошло",
                     "смотреть вывод команды и `doctor` в главной папке")
        return otkaz_stop(
            f"влитие ветки {branch} в основную {osn}",
            f"git_zona.py vlit-v-osnovnuyu {branch}", r.returncode,
            (r.stderr.strip() + " " + r.stdout.strip()).strip(),
            "разобрать причину отказа и вернуть заходу замечание; "
            f"до этого ветка {branch} остаётся невлитой")
    print(f"\n🔴 КОНФЛИКТ в {len(conflicts)} путях — слияние ОСТАНОВЛЕНО, "
          "сама не разрешаю (это смысловое решение):")
    for p in conflicts:
        print(f"   {p}")
    print("\n   Разрешает человек или исполнитель захода. Дальше:\n"
          "     завершить — `git_zona.py vlit-v-osnovnuyu --continue`\n"
          "     откатить целиком — `git_zona.py vlit-v-osnovnuyu --abort`")
    log_incident(f"vlit-v-osnovnuyu {branch}: конфликт в {len(conflicts)} путях",
                 "разрешить конфликты, затем vlit-v-osnovnuyu --continue (или --abort)")
    # 🔴 КОНФЛИКТ — ТОЖЕ ОТКАЗ, И ЭТО НЕ ПРИДИРКА. Задание захода прямо
    # называет конфликт законной причиной идти дальше — но «законная причина»
    # значит «названа поимённо», а не «пропущена молча». Стоп здесь даёт ровно
    # то: слияние остановлено, заявка заведена, разрешает человек.
    return otkaz_stop(
        f"влитие ветки {branch} в основную {osn} — конфликт в {len(conflicts)} путях",
        f"git_zona.py vlit-v-osnovnuyu {branch}", 1,
        "конфликтуют: " + ", ".join(conflicts[:10]),
        "решить, чьей стороной разрешать конфликт (это смысловое решение, "
        "инструмент его не принимает), затем vlit-v-osnovnuyu --continue или --abort")


