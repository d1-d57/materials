def find_locks():
    """(локи, мусорные объекты) — то, что мешает записи или копится в .git.

    🔴 ДВА каталога, не один (часть A захода 2026-08-03): верхнеуровневые локи
    (`index.lock`, `HEAD.lock`) — ЛИЧНЫЕ (`git_dir()`), у каждой рабочей папки
    свои; `objects/**` — ОБЩИЙ склад (`git_common_dir()`), один на все worktree.
    В основной (не-worktree) папке они совпадают, разница не видна.
    """
    gd, gcd = git_dir(), git_common_dir()
    return (sorted(gd.glob("*.lock")) + sorted(gcd.glob("objects/*.lock")),
            sorted(gcd.glob("objects/*/tmp_obj_*")))


DEAD_LOCK_SEC = 300


def sweep_dead_locks(quiet=False):
    """Снять МЁРТВЫЕ локи (старше 5 мин). Свежие не трогать — там живой коммит.

    Почему это делает инструмент, а не человек командой из чата: команда
    `rm -f .git/*.lock` в zsh ПАДАЕТ целиком, если ни один файл не совпал
    (`no matches found`), и владелец остаётся и без уборки, и без диагноза.
    Цена 22.07: мёртвый `maintenance.lock` и 103 мусорных объекта пережили
    две выданные команды уборки — обе не выполнились.
    """
    locks, _ = find_locks()
    now, killed, alive = time.time(), [], []
    for p in locks:
        try:
            if now - p.stat().st_mtime < DEAD_LOCK_SEC:
                alive.append(p)
                continue
            p.unlink()
            killed.append(p)
        except OSError:
            alive.append(p)
    if killed and not quiet:
        print(f"🧹 Снято мёртвых локов: {len(killed)} "
              f"({', '.join(p.name for p in killed)}).")
    return killed, alive


def cmd_clean(args):
    if in_sandbox():
        return refuse_write("Уборка .git", suggest="clean")
    locks, junk = find_locks()
    if not locks and not junk:
        print("✅ В .git чисто: ни локов, ни мусорных объектов.")
        return 0

    killed, alive = sweep_dead_locks()
    if alive:
        print(f"⏳ Оставил {len(alive)} свежих лок(ов) — младше 5 мин, рядом может\n"
              "   идти живой коммит. Снимать их опасно: испортишь индекс.\n"
              "   Подожди и повтори `clean`.")
        for p in alive:
            # Полный путь, не `relative_to(REPO)` — см. find_locks().
            print(f"   {p}")

    removed = 0
    failed = []
    for p in junk:
        try:
            os.chmod(p, stat.S_IWUSR)
            p.unlink()
            removed += 1
        except OSError as e:
            failed.append((p.name, str(e)))
    if removed:
        print(f"🧹 Убрано мусорных объектов (`tmp_obj_*`): {removed}.")
    if failed:
        print(f"❌ Не удалось убрать мусорных объектов: {len(failed)}.")
        for name, err in failed:
            print(f"   {name}: {err}")

    locks2, junk2 = find_locks()
    if not locks2 and not junk2:
        print("✅ Готово: .git чист.")
        return 0
    if alive and not junk2:
        return 0
    print(f"⚠ Осталось: локов {len(locks2)}, мусора {len(junk2)}.")
    return 1


def zona_sushchestvuet(zone):
    """Сама зона — до её чистоты. `(ok, зона_для_dirty, сообщение)`.

    🔴 ЗАЧЕМ (заход `gejty-ne-tuda`, П1; замер приёмки 2026-08-14). `dirty()`
    фильтрует строки `git status --porcelain` префиксом `in_zone(path, zone)`.
    Зона, которой на диске нет (опечатка в имени), и зона в ЧУЖОМ репозитории
    (`--zone ~/Documents/GitHub/disciplina`) ни с одной строкой не совпадают —
    строк ноль, и `check` печатал «✅ работа доехала в git, вне git ничего нет»
    с `rc=0`. То есть первый гейт ритуала приёмки, с которого начинается приём
    КАЖДОГО отчёта, был зелен на пустом месте: «проверено» и «проверять было
    нечего» выглядели одинаково.

    ⚠ ЗАКОННЫЕ СЛУЧАИ, КОТОРЫЕ ОБЯЗАНЫ ОСТАТЬСЯ ЗЕЛЁНЫМИ:
      · зона существует и ПУСТА (папка без изменений) — пустоту судит `dirty()`,
        не эта проверка;
      · зона, которую заход СНОСИТ: на диске её уже нет, но git о ней помнит
        (`git ls-files`) — там есть настоящая работа (удаления), и решать
        обязан `dirty()`, а не отказ «зоны нет».
    Резолв относительной зоны — от КОРНЯ РЕПОЗИТОРИЯ, а не от `cwd`: зона по
    смыслу репозиторно-относительна (`_generator/tools/`), и именно так её
    подставляют все гейты. Обе стороны сравнения резолвятся (`.resolve()`) —
    иначе фикстурный `GIT_ZONA_REPO=/tmp/…` против macOS-реального
    `/private/tmp/…` дал бы ложное «зона в другом репозитории».
    """
    if not zone:
        return True, zone, None
    p = Path(zone).expanduser()
    if not p.is_absolute():
        p = REPO / p
    p = p.resolve()
    koren = REPO.resolve()
    try:
        rel = p.relative_to(koren)
    except ValueError:
        return False, zone, (f"❌ зона в другом репозитории — проверь его отдельно.\n"
                             f"   зона:        {p}\n"
                             f"   репозиторий: {koren}\n"
                             f"   → там свой git: `cd {p}` и `git status --porcelain`, "
                             f"этот инструмент судит только своё дерево.")
    # 🔴 `as_posix()`, А НЕ `str()` — ИНАЧЕ ГЕЙТ 0 ПРИЁМКИ ЗЕЛЕНЕЕТ НА НЕСОХРАНЁННОЙ
    # РАБОТЕ. `relative_to` отдаёт путь СВОЕЙ платформы: на Windows `str(rel)` даёт
    # `ot-maksa\predlozheniya`, а `git status --porcelain` всегда печатает пути через
    # `/`. Префиксное сравнение в `in_zone()` не совпадает НИ С ОДНОЙ строкой —
    # строк ноль — и `check --zone` печатает «✅ работа доехала в git» с `rc=0`.
    # То есть ровно тот отказ, ради которого эта функция и написана (см. шапку),
    # возвращался здесь же, внутри неё, на второй платформе.
    #
    # Ломались ТОЛЬКО вложенные зоны (`ot-maksa/predlozheniya`, `_studio/zhurnal/<арка>`),
    # то есть обычный случай; односоставная зона (`ot-maksa`) разделителя не содержит
    # и потому работала — поэтому дефект и не бросался в глаза.
    # Замер 23.08: файл вне git внутри зоны → `check` без зоны красный, `--zone ot-maksa`
    # красный, `--zone ot-maksa/predlozheniya` ЗЕЛЁНЫЙ на том же файле.
    #
    # ⚠ `rel_str` уходит ещё и в `git ls-files -- <rel_str>`. ПРОВЕРЕНО ПРОГОНОМ
    # 23.08: git для Windows обратные слэши в pathspec понимает сам, так что ЭТА
    # половина не ломалась. Правка нужна ровно ради `in_zone()` — сравнения строк
    # на стороне Python, где никто ничего не нормализует.
    rel_str = rel.as_posix()
    if rel_str == ".":
        return True, None, None          # зона = корень репозитория ⇒ всё дерево
    if not p.exists():
        izvestno_git = git("ls-files", "--", rel_str, check=False).stdout.strip()
        if not izvestno_git:
            return False, zone, (f"❌ такой зоны здесь нет: {p}\n"
                                 f"   ни на диске, ни в git (`git ls-files -- {rel_str}` пусто).\n"
                                 f"   → опечатка в имени зоны: зелёный отсюда означал бы "
                                 f"«проверять было нечего», а не «всё чисто».")
    return True, rel_str, None


