            # 🔴 ГОТОВАЯ СТРОКА, А НЕ СОВЕТ «назови все зоны». Инструмент их уже
            # знает — ровно такую подсказку он пишет в автолог. Пока её приходилось
            # собирать руками из простыни путей, зона получалась НЕПОЛНОЙ, и
            # следующий прогон отказывал снова: ветка трогала 20 путей, зону
            # назвали по видимой половине (урок 6 арки `2026-08-05_faza-lenty`).
            # Это НЕ «сливай всё»: строка называет ровно те зоны, которые ветка
            # действительно трогает, — решение расширить зону остаётся осознанным.
            все_зоны = sorted({zone_of(p) for p in touched})
