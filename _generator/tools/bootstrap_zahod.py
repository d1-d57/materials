def validate_slug(name, chto):
    """Кривой вход обязан ГРОМКО падать, а не тихо создать файл не с тем именем.

    Тот же класс, что закрыт в bootstrap_arka.py (инцидент 23.07 с `--help`):
    имя, которое станет путём на диске, не валидируется. Здесь `tema` → имя файла
    `kod_<tema>.md`; ведущий `-`, слэш, пустое, ведущая точка — не слаг. argparse
    отбивает опции-позиции сам, но НЕ пустое/со слэшем — их ловит эта проверка.
    Дублируется сознательно (общий модуль лёг бы вне зоны — см. kod_bootstrap-guard).
    """
    if name.startswith("-"):
        raise SystemExit(
            f"❌ «{name}» похоже на флаг, а не {chto}. Имя — слаг вида "
            "`2026-07-23_tema`, без ведущего дефиса.")
    if (not name) or any(c.isspace() for c in name) or "/" in name \
            or "\\" in name or name.startswith("."):
        raise SystemExit(
            f"❌ «{name}» не годится как {chto}: нужен слаг вида "
            "`2026-07-23_tema` — без пробелов, слэшей и ведущей точки.")


def _git(*args):
    return subprocess.run(["git", "--no-optional-locks", *args],
                          cwd=REPO_ROOT, capture_output=True, text=True)


def ensure_worktree(name, branch):
    """Заводит рабочую папку захода (идемпотентно). Возвращает (путь, код-возврата).

    Почему через git_zona.py, а не своим `git worktree add`: там уже лежит
    вся дисциплина — куда класть папки, как называть ветку, отказ снимать
    папку с незакоммиченной работой. Второй реализации быть не должно.
    """
    wt_home = REPO_ROOT.parent / f"{REPO_ROOT.name}-wt"
    path = wt_home / name
    if path.is_dir():
        # 🔴 Взять папку — не значит взять её МОЛЧА. Ветку в ней надо сверить: заход
        # утверждает «`<ветка>` в ней уже стоит» и «`git checkout` ЗАПРЕЩЁН», и если
        # там стоит другая ветка, исполнитель работает не там, где думает, при
        # полностью зелёном выводе генератора. Пока файл ложился в основную папку,
        # исполнитель просто не находил захода — теперь заход лежит в worktree и
        # уверенно называет неверную ветку. Найдено верификатором.
        r = subprocess.run(["git", "--no-optional-locks", "rev-parse",
                            "--abbrev-ref", "HEAD"],
                           cwd=path, capture_output=True, text=True)
        stoit = r.stdout.strip()
        if r.returncode == 0 and stoit and stoit != branch:
            print(f"ОШИБКА: рабочая папка {path} стоит на ветке `{stoit}`, "
                  f"а заходу нужна `{branch}`.", file=sys.stderr)
            print("  Заход НЕ создаю: он написал бы «ветка уже стоит, checkout "
                  "запрещён» про ветку, которой там нет — исполнитель работал бы "
                  "не там, где думает, при зелёном выводе.", file=sys.stderr)
            print(f"  Либо возьми другое имя папки, либо сними эту: "
                  f"`git_zona.py worktree drop {name}`.", file=sys.stderr)
            return path, 1
        print(f"Рабочая папка уже есть, беру её: {path} (ветка `{stoit}` сходится)")
        return path, 0
    r = subprocess.run([sys.executable, str(GIT_ZONA), "worktree", "add", name,
                        "--branch", branch], capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode != 0:
        print("ОШИБКА: рабочая папка не завелась — заход НЕ создаю.", file=sys.stderr)
        print("  Заход с несуществующей папкой хуже отсутствующего: исполнитель "
              "пойдёт работать в основную и подменит файлы соседям.", file=sys.stderr)
        return path, 1
    return path, 0


def main(argv):
    p = argparse.ArgumentParser(
        description="Генерит kod_<тема>.md с вшитым контрактом зоны.",
        epilog="--branch и --zone обязательны: контракт зоны — не опция.",
    )
    p.add_argument("arka_dir", help="папка арки (относительно корня репо или абсолютная)")
    p.add_argument("tema", help="короткий слаг темы → имя файла kod_<тема>.md")
    p.add_argument("--branch", required=True, help="ветка, на которой работает заход")
    p.add_argument("--zone", required=True, help="пути зоны (что МОЖНО менять), одной строкой")
    p.add_argument("--model", default="Sonnet", help="модель (по умолчанию Sonnet)")
    # ФЛАГ, а не третий позиционный: позиционных уже два, и третий сделал бы
    # «описание не задано» неотличимым от «аргументы поехали» — опечатка в
    # порядке молча родила бы `kod_<описание>.md`. Флаг необязателен по природе
    # и виден в --help.
    p.add_argument("--opisanie", metavar="ТЕКСТ",
                   help="описание захода одной фразой — уходит в KARTA.md §6 "
                        "тем же ходом; не задан → в индекс уйдёт явная пометка")
    p.add_argument("--kanal", choices=["terminal", "app"], default="terminal",
                   help="канал запуска: terminal (по умолчанию, печатает командную "
                        "строку для системного Терминала) или app (Claude Code в "
                        "десктопе) — см. RUKOVODSTVO §Два канала запуска")
    p.add_argument("--worktree", metavar="ИМЯ",
                   help="ПАРАЛЛЕЛЬНЫЙ заход: своя рабочая папка. Заводит её "
                        "`git_zona.py worktree add ИМЯ` и вписывает `cd` вместо checkout")
    a = p.parse_args(argv)
    validate_slug(a.tema, "тема захода (→ имя файла kod_<тема>.md)")  # ДО любой записи
    # 🔴 Имя рабочей папки — ТОЖЕ путь на диске, и до этой строки оно не
    # проверялось вовсе. `--worktree "../../pobeg"` уводил папку ЗА пределы дома
    # `<репо>-wt`, и заход создавался и регистрировался там — тот самый класс, для
    # которого validate_slug и заводился (инцидент 23.07 с `bootstrap_arka --help`).
    # Пока файл ложился в основную папку, промах был безобиден; с починкой пути он
    # стал означать заход в произвольном месте ФС. Найдено верификатором.
    if a.worktree is not None:
        validate_slug(a.worktree, "имя рабочей папки (→ папка <репо>-wt/<имя>)")

    if not TEMPLATE.is_file():
        print(f"ОШИБКА: шаблон не найден — {TEMPLATE}", file=sys.stderr)
        return 1

    arka = Path(a.arka_dir)
    if not arka.is_absolute():
        arka = REPO_ROOT / arka
    if not arka.is_dir():
        print(f"ОШИБКА: папка арки не найдена — {arka}", file=sys.stderr)
        return 1

    # 🔴 Путь арки держим РЕПО-ОТНОСИТЕЛЬНЫМ. Он одинаков в основной папке и в
    # рабочей папке worktree (это одно дерево, разные копии), и именно им заход
    # входит в свою зону — зона задаётся git-путями, а не путями машины.
    try:
        arka_rel = arka.resolve().relative_to(REPO_ROOT.resolve())
    except ValueError:
        print(f"ОШИБКА: папка арки вне репозитория — {arka}", file=sys.stderr)
        print("  Заход обязан лежать ВНУТРИ репо: иначе он не входит в свою зону "
              "и физически не может закоммитить сам себя.", file=sys.stderr)
        return 1
    own_rel = (arka_rel / f"kod_{a.tema}.md").as_posix()

    # Отказ ДО заведения рабочей папки. Копия в основном дереве означает, что заход
    # уже собирали без флага; вторая копия в worktree — это ровно та «тень», из
    # которой рождается расхождение двух версий одного файла (§4 канона, `adopt`).
    if (REPO_ROOT / own_rel).exists():
        print(f"ОШИБКА: заход уже существует — {REPO_ROOT / own_rel} (не затираю)",
              file=sys.stderr)
        return 1

    # 🔴 ФАЙЛ-ЗАХОД — В ОДНОМ ЭКЗЕМПЛЯРЕ, ВСЕГДА В ОСНОВНОЙ ПАПКЕ (часть D захода
    # `kod_dobivka-vetok.md`, урок 23 «перевернулся»). Было: `dst = rabochaya`,
    # и при `--worktree` файл рождался ТОЛЬКО в рабочей папке — исполнитель,
    # придя в основную (куда его отправляет нынешний контракт: «ПЛАН/ВОПРОСЫ/
    # ОТЧЁТ… в ОСНОВНОЙ папке… файл коммитит аналитик при приёмке»), не находил
    # там ничего. `arka.is_dir()` уже провалидирован выше от REPO_ROOT, значит
    # `dst.parent` гарантированно существует — прежний фолбэк на «арки на ветке
    # не было» относился к СТАРОМУ `dst=rabochaya` и здесь не нужен.
    dst = REPO_ROOT / own_rel

    # 🔴 Развилку «worktree или checkout» решает ГЕНЕРАТОР, а не исполнитель.
    # Заход обязан быть самоценным: исполнитель работает с пустым контекстом, и
    # инструкция вида «дали папку — cd, не дали — checkout» заставляет его гадать
    # о том, чего он знать не может. Поэтому в файл уходит РОВНО ОДИН вариант.
    # `rabochaya` — МЕСТО РАБОТЫ ДЛЯ КОДА (worktree, если задан); файла там нет.
    if a.worktree:
        wt_path, rc = ensure_worktree(a.worktree, a.branch)
        if rc:
            return rc
        mesto = (f"**рабочая папка `{wt_path}`** — ТОЛЬКО ДЛЯ КОДА (worktree захода, "
                 f"ветка `{a.branch}` в ней уже стоит). 🔴 `git checkout` в основной "
                 f"папке ЗАПРЕЩЁН: рядом идут другие заходы, переключение подменит "
                 f"файлы у них под ногами. 🔴 Этот файл-заход — В ОДНОМ ЭКЗЕМПЛЯРЕ, "
                 f"здесь же, в ОСНОВНОЙ папке (не в рабочей папке кода): его самого "
                 f"НЕ коммитить — это делает аналитик при приёмке.")
        pervyj = (f"- `cd {wt_path}` — рабочая папка ДЛЯ КОДА. Ветку НЕ переключай: "
                  f"`{a.branch}` в ней уже стоит.\n"
                  f"- Проверить, что на месте: `git rev-parse --abbrev-ref HEAD` "
                  f"→ должно быть `{a.branch}`.\n"
                  f"- ПЛАН/ВОПРОСЫ/ОТЧЁТ/УРОКИ ФАБРИКЕ пиши в ЭТОТ файл — он в "
                  f"основной папке, не копируй его в рабочую.")
        start_line = f"cd {wt_path}"
        rabochaya = wt_path
    else:
        mesto = (f"ветка `{a.branch}` в основной папке. 🔴 Она должна УЖЕ стоять. "
                 f"НЕ на ней — СТОП, НЕ делай `git checkout`: в общей папке он МОЛЧА "
                 f"откатывает дерево к состоянию ветки (цена 27→28.07: файл сильно "
                 f"откатился ночью, поймал владелец вручную; след в git НЕ остаётся). "
                 f"Тогда заход пересобрать с `--worktree`. Ветку не переключай, в другие НЕ коммить.")
        pervyj = (f"- Проверь ветку: `git branch --show-current` — обязано быть `{a.branch}`. "
                  f"Не она — СТОП, `git checkout` НЕ делай (§4 GIT-disciplina), нужен `--worktree`.")
        start_line = "git branch --show-current"
        rabochaya = REPO_ROOT

    if dst.exists():
        print(f"ОШИБКА: заход уже существует — {dst} (не затираю)", file=sys.stderr)
        return 1

    # 🔴 Заход обязан входить в СОБСТВЕННУЮ зону — иначе его же отчёт физически
    # лежит вне того, что коммитит `git_zona.py check --zone`, и заход не может
    # закоммитить сам себя. Аналитик про это помнить не обязан: путь дописывается
    # сюда, а не в задание. Задан аналитиком вручную (уже есть в `--zone`) —
    # не удваиваем.
    #
    # 🔴 В `--worktree`-режиме `own_rel` НЕ добавляется (часть D, тот же заход).
    # Файл живёт ТОЛЬКО в основной папке, а `git_zona.py check --zone`, запущенный
    # из рабочей папки кода, находит `REPO` от СВОЕГО `__file__` — то есть от
    # рабочей папки. Путь файла-захода там никогда не появится: включать его в
    # зону было бы фикцией (а по контракту зоны файл и не должен коммититься
    # исполнителем — это делает аналитик при приёмке). В checkout-режиме дерево
    # одно, и это поведение НЕ меняю — вне цели части D.
    if a.worktree:
        zone = a.zone
    else:
        zone = a.zone if own_rel in a.zone.split() else f"{a.zone} {own_rel}"

