    invlitye, invlitye_err = nevlityje_vetki()
    vlit_vetki = a.vlit or []
    # 🔴 Блок собирается ВСЕГДА и всегда непуст — четыре исхода сторожа различимы
    # внутри слота 1, а слоты 2 и 3 либо несут конкретику аналитика, либо явный
