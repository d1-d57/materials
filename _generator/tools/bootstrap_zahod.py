def nevlityje_vetki():
    """(список невлитых `zahod/*`-веток, причина отказа|None).

    🔴 СТОРОЖ §2.3 — единственное место захода с суждением, решённое ЗДЕСЬ:
    список печатается ПРЕДУПРЕЖДЕНИЕМ, не отказом (§79 канона: невлитая ветка —
    законное состояние, рядом может идти чужой заход). Функция сама НЕ решает
    ничего — только докладывает факт `git branch --no-merged`; кто с этим
    фактом что делает, решает вызывающий (§3: сборка не должна зависеть от
    того, ответил git или нет).

    Причина не None → git не ответил (detached HEAD, чужой лок, нет веток) —
    вызывающий обязан собрать заход всё равно, просто без сторожа.
    """
    cur = _git("rev-parse", "--abbrev-ref", "HEAD")
    if cur.returncode != 0 or not cur.stdout.strip():
        return None, (cur.stderr.strip() or "не удалось определить текущую ветку")
    # 🔴 ИМЕНА БЕРЁМ `--format`, А НЕ ОБРЕЗКОЙ УКРАШЕНИЙ. `git branch` метит
    # ветку, вычекаученную в ДРУГОЙ рабочей папке, префиксом `+`, и прежний
    # `lstrip("* ")` его не снимал: строка оставалась `+ zahod/имя`, фильтр
    # `startswith("zahod/")` её отвергал, список выходил ПУСТЫМ, и в каждый
    # заход печаталось «вливать нечего, невлитых 0». Заходы фабрики работают в
    # worktree ПО ПОСТРОЕНИЮ (`GIT-disciplina §4`) — значит слеп сторож был не
    # изредка, а ровно на том единственном классе веток, ради которого его
    # завели. Замер 16.08 в живом репозитории: прямой `git branch --no-merged`
    # даёт две ветки (`+ zahod/vid-blokov-vnedrenie`, `+ zahod/vlitie-i-vitrina-kursa`),
    # эта функция возвращала []. Тот же дефект был найден и починен 14.08 в
    # `git_zona.py vyvezti --zahody` (там из 26 локальных `zahod/*` пропускалось
    # 24) — здесь он дожил до 16.08, потому что чинили место, а не класс.
    # Ловушка на все три префикса (`*`, `+`, голое имя) — `fixtures/nevlitye/`.
    r = _git("branch", "--no-merged", cur.stdout.strip(),
             "--format=%(refname:short)")
    if r.returncode != 0:
        return None, (r.stderr.strip() or "git branch --no-merged упал")
    imena = [l.strip() for l in r.stdout.splitlines() if l.strip()]
    return [b for b in imena if b.startswith(ZAHOD_VETKA_PREFIX)], None


