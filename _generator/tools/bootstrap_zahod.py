_GIT_ZONA_MOD = None


def _git_zona():
    """Модуль `git_zona.py`, загруженный по пути (`tools/` — не пакет).

    Один загрузчик на все обращения: модуль тяжёлый (4000+ строк), а звали его
    отсюда уже дважды — за `in_sandbox()` и за адресом очереди заявок. Третья
    копия трёх строк importlib означала бы третье место, где путь к инструменту
    можно опечатать молча.
    """
    global _GIT_ZONA_MOD
    if _GIT_ZONA_MOD is None:
        import importlib.util
        spec = importlib.util.spec_from_file_location("_gz", GIT_ZONA)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        _GIT_ZONA_MOD = mod
    return _GIT_ZONA_MOD


