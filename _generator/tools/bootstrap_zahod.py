def sostoyanie_vetok():
    """Печать ДО заведения новой ветки: сколько открыто и где неперенесённое.

    🔴 ЗАЧЕМ ИМЕННО ЗДЕСЬ. Это момент, когда владелец решает «запускать или
    ждать», — его слова. Ветки заводятся ровно этим скриптом и не закрываются
    никогда: замер 04.08 — 18 веток при пяти живых заходах. Печать перед
    заведением девятнадцатой — единственное место, где число видно ДО того,
    как оно вырастет.

    Печать, а не отказ: заводить заход при десяти открытых ветках законно
    (они могут быть все зелёные и ждать подметания), а гейт, запрещающий
    работу из-за незакрытой уборки, отключат первым же вечером.
    """
    # 🔴 Печать не смеет уронить генератор. Соседняя фикстура (`fixtures/dvizhok`,
    # ловушка 17 этого же файла) копирует к себе НЕ ВСЕ инструменты — там
    # `git_zona.py` рядом может не лежать вовсе, и жёсткий вызов превратил бы
    # справочную строку в стоп-кран для создания захода.
    if not GIT_ZONA.is_file():
        return
    try:
        r = subprocess.run([sys.executable, str(GIT_ZONA), "poteri"],
                           cwd=REPO_ROOT, capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return
    vyvod = (r.stdout or "") + (r.stderr or "")
    vsego = [l for l in vyvod.splitlines() if l.strip().startswith("Охват: проверено")]
    poteri = [l.strip() for l in vyvod.splitlines()
              if l.strip().startswith("· ") and "пропадёт файлов" in l]
    print("── ветки ДО заведения новой (печать, ничего не меняет) ──")
    print("   " + (vsego[0].strip() if vsego else "состояние снять не удалось"))
    if poteri:
        print(f"   🔴 с НЕПЕРЕНЕСЁННОЙ работой — {len(poteri)}:")
        for l in poteri:
            print("      " + l)
        print("   Это не запрет заводить новый заход — это то, что пропадёт, "
              "если те ветки удалить.")
    else:
        print("   ✅ веток с неперенесённой работой нет")
    print("   Подмести отработавшие: python3 _generator/tools/git_zona.py "
          "zakryt-vetku --vse-zelenye")
    print()


