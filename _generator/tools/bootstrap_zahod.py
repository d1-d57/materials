def _zone_bez_backtick(zone):
    """Пути зоны БЕЗ markdown-разметки — для команд, не для текста.

    🔴 `--zone` приходит обёрнутым в backtick-и: этого требует структурный
    линтер входа, и в ПРОЗЕ захода так и надо. Но в КОМАНДУ такая строка ехать
    не может: `git_zona.py` судит пути буквально и `` `_generator/tools/` ``
    для него — путь с обратными кавычками в имени, которого нет; команда
    ответила бы «слияние выходит за зону» и не сделала бы ничего. Ошибка была бы
    тихой в худшем смысле: строка выглядит правильной, отказ выглядит
    содержательным («ветка тащит чужое»), а на деле не совпало имя.
    """
    if not zone:
        return []
    # str — от сборки (одна строка `--zone`), list — от режима
    # `--zadanie-subagentu`, где флаг повторяемый: собранная команда печатает
    # `--zone` на КАЖДЫЙ корень зоны, и непорвторяемый парсер оставил бы от них
    # только последний. Зона молча сузилась бы до одного пути, а слияние, которое
    # обязано было отказать на чужом, прошло бы (найдено живым прогоном 14.08:
    # из двух корней в команду доехал один).
    toks = zone if isinstance(zone, list) else [zone]
    return [z for tok in toks for z in tok.replace("`", "").split()]


