def _v_pesochnice():
    """Признак песочницы Cowork — берётся у `git_zona.py`, своей копии не заводим.

    Второй реализации детекта быть не должно: там он выверен (тип монтирования,
    без следов на диске). Импорт по пути, потому что `tools/` — не пакет.
    """
    import importlib.util
    spec = importlib.util.spec_from_file_location("_gz", GIT_ZONA)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.in_sandbox()


def ensure_worktree(name, branch):
    """Заводит рабочую папку захода (идемпотентно). Возвращает (путь, код-возврата).

    Код возврата: 0 — папка на месте · 1 — ошибка, заход не создавать ·
    2 — папку заведёт САМ ИСПОЛНИТЕЛЬ первым ходом (мы в песочнице).

    Почему через git_zona.py, а не своим `git worktree add`: там уже лежит
    вся дисциплина — куда класть папки, как называть ветку, отказ снимать
    папку с незакоммиченной работой. Второй реализации быть не должно.
    """
    wt_home = REPO_ROOT.parent / f"{REPO_ROOT.name}-wt"
    path = wt_home / name
    # 🔴 Из песочницы Cowork `worktree add` запрещён (git при записи оставляет
    # локи, снять которые отсюда нечем). Раньше это роняло сборку целиком, и
    # цепочка выходила такая: Cowork пробует → генератор отказывает → команда
    # уходит владельцу → владелец её выполняет → Cowork собирает заново. Четыре
    # хода и живой человек в середине ради операции, которую исполнитель делает
    # у себя за секунду. Решение владельца 2026-08-05: папку заводит САМ ЗАХОД
    # первым ходом, а генератор просто вписывает ему команду.
    if not path.is_dir() and _v_pesochnice():
        print(f"Песочница: папку {path} заведёт САМ ИСПОЛНИТЕЛЬ первым ходом "
              f"(команда вписана в заход).")
        return path, 2
    if path.is_dir():
        # 🔴 Взять папку — не значит взять её МОЛЧА. Ветку в ней надо сверить: заход
        # утверждает «`<ветка>` в ней уже стоит» и «`git checkout` ЗАПРЕЩЁН», и если
        # там стоит другая ветка, исполнитель работает не там, где думает, при
        # полностью зелёном выводе генератора. Пока файл ложился в основную папку,
        # исполнитель просто не находил захода — теперь заход лежит в worktree и
        # уверенно называет неверную ветку. Найдено верификатором.
        r = subprocess.run(["git", "--no-optional-locks", "rev-parse",
                            "--abbrev-ref", "HEAD"],
                           cwd=path, capture_output=True, text=True)
        stoit = r.stdout.strip()
        if r.returncode == 0 and stoit and stoit != branch:
            print(f"ОШИБКА: рабочая папка {path} стоит на ветке `{stoit}`, "
                  f"а заходу нужна `{branch}`.", file=sys.stderr)
            print("  Заход НЕ создаю: он написал бы «ветка уже стоит, checkout "
                  "запрещён» про ветку, которой там нет — исполнитель работал бы "
                  "не там, где думает, при зелёном выводе.", file=sys.stderr)
            print(f"  Либо возьми другое имя папки, либо сними эту: "
                  f"`git_zona.py worktree drop {name}`.", file=sys.stderr)
            return path, 1
        print(f"Рабочая папка уже есть, беру её: {path} (ветка `{stoit}` сходится)")
        return path, 0
    # 🔴 `cwd=REPO_ROOT` ОБЯЗАТЕЛЕН (заход `gejty-vrut`, побочный эффект починки
    # Г3). `git_zona.py` теперь резолвит СВОЙ репозиторий по МЕСТУ ВЫЗОВА
    # (`git rev-parse --show-toplevel` от cwd), а не по расположению файла —
    # без явного `cwd` дочерний процесс наследует cwd ЭТОГО скрипта, который
    # может стоять где угодно (например, в фикстуре, копирующей инструменты в
    # одноразовый репозиторий и зовущей `bootstrap_zahod.py` из боевой папки).
    # Тогда worktree завёлся бы в чужом дереве молча — ровно тот класс дефекта,
    # который Г3 и чинит.
    r = subprocess.run([sys.executable, str(GIT_ZONA), "worktree", "add", name,
                        "--branch", branch], cwd=REPO_ROOT,
                       capture_output=True, text=True)
    print(r.stdout.strip() or r.stderr.strip())
    if r.returncode != 0:
        print("ОШИБКА: рабочая папка не завелась — заход НЕ создаю.", file=sys.stderr)
        print("  Заход с несуществующей папкой хуже отсутствующего: исполнитель "
              "пойдёт работать в основную и подменит файлы соседям.", file=sys.stderr)
        return path, 1
    return path, 0


ZAHOD_VETKA_PREFIX = "zahod/"


def nevlityje_vetki():
    """(список невлитых `zahod/*`-веток, причина отказа|None).

    🔴 СТОРОЖ §2.3 — единственное место захода с суждением, решённое ЗДЕСЬ:
    список печатается ПРЕДУПРЕЖДЕНИЕМ, не отказом (§79 канона: невлитая ветка —
    законное состояние, рядом может идти чужой заход). Функция сама НЕ решает
    ничего — только докладывает факт `git branch --no-merged`; кто с этим
    фактом что делает, решает вызывающий (§3: сборка не должна зависеть от
    того, ответил git или нет).

    Причина не None → git не ответил (detached HEAD, чужой лок, нет веток) —
    вызывающий обязан собрать заход всё равно, просто без сторожа.
    """
    cur = _git("rev-parse", "--abbrev-ref", "HEAD")
    if cur.returncode != 0 or not cur.stdout.strip():
        return None, (cur.stderr.strip() or "не удалось определить текущую ветку")
    r = _git("branch", "--no-merged", cur.stdout.strip())
    if r.returncode != 0:
        return None, (r.stderr.strip() or "git branch --no-merged упал")
    imena = [l.strip().lstrip("* ").strip() for l in r.stdout.splitlines() if l.strip()]
    return [b for b in imena if b.startswith(ZAHOD_VETKA_PREFIX)], None


