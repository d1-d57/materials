def slot_vlitie(vlit_vetki, zone, invlitye, invlitye_err):
    """Слот 1 «ВЛИТЬ ПЕРЕД РАБОТОЙ» — команды `merge` + проверка фактом на диске.

    `zone` — СЫРАЯ строка `--zone` (до обёртки backtick-ами): `git_zona.py
    merge` сам судит пути без markdown-разметки.

    Четыре исхода, и все четыре РАЗЛИЧИМЫ (§2.2): ветки названы · невлитых нет ·
    невлитые есть, но не названы · сторож не отработал. Прежняя редакция
    схлопывала два последних в пустую строку.
    """
    if vlit_vetki:
        zony = zone.split() if zone else []
        stroki = ["```"]
        for v in vlit_vetki:
            cmd = f"python3 _generator/tools/git_zona.py merge {v}"
            for z in zony:
                cmd += f" --zone {z}"
            stroki.append(cmd)
        stroki.append("```")
        stroki.append("")
        stroki.append("Проверка фактом на диске, а не словом инструмента — для каждой ветки:")
        stroki.append("```")
        stroki.append("git log --oneline")
        for v in vlit_vetki:
            stroki.append(f"# обязан быть виден коммит ветки `{v}`")
        stroki.append("```")
        stroki.append("Не сошлось хоть для одной — СТОП, в `## ВОПРОСЫ`, дальше не иди. "
                      "Ветки НЕ удаляй.")
        return "\n".join(stroki)
    if invlitye_err is not None:
        return NE_ZAPOLNENO % (
            f"сторож невлитого не отработал при сборке ({invlitye_err}); состояние "
            f"чужих веток НЕ проверено — снять руками `git branch --no-merged` и "
            f"вписать сюда результат")
    if invlitye == []:
        return ("вливать нечего, проверено командой `git branch --no-merged` при сборке: "
                "невлитых веток 0.")
    return NE_ZAPOLNENO % (
        "невлитых `zahod/*`-веток при сборке — {n}: {spisok}. Назвать нужные флагом "
        "`--vlit <ветка>` (генератор впишет сюда `merge` и проверку фактом) либо "
        "вписать строкой, почему вливать не надо".format(
            n=len(invlitye), spisok=", ".join(f"`{b}`" for b in invlitye)))


