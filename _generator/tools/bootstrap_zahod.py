    if not vlit_vetki:
        return (NE_ZAPOLNENO % (
            "чем заполнять: ветки, которые надо влить в ОСНОВНУЮ, флагом "
            "`--vlit <ветка>`. Вливать нечего — так и вписать явно")).replace("\n", " ")
    zony = _zone_bez_backtick(zone)
