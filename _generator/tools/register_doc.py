def _git(папка, что):
    """`git rev-parse <что>` из папки — Path либо None (git нет / не репозиторий)."""
    try:
        out = subprocess.run(
            ["git", "--no-optional-locks", "-C", str(папка), "rev-parse", что],
            capture_output=True, text=True, check=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return None
    return Path(os.path.realpath(Path(папка) / out)) if out else None


def корень_файла(сырой):
    """Корень рабочей копии, в которой ФИЗИЧЕСКИ лежит файл; иначе `REPO`.

    🔴 ДЕФЕКТ Д1, РАДИ КОТОРОГО ЭТА ФУНКЦИЯ СУЩЕСТВУЕТ. Корень брался у ПРОЦЕССА
    (константа `REPO` = папка инструмента либо `GIT_ZONA_REPO`), а контракт зоны
    предписывает каждому параллельному заходу worktree. Заход зовёт дверь по
    абсолютному пути (`python3 $MAT/_generator/tools/register_doc.py …`) — то
    есть инструмент из ОСНОВНОЙ папки, а файл лежит в worktree, физически вне
    неё. `relative_to()` бросал, дверь отвечала «путь вне репозитория», и
    указание «завёл `.md` — зарегистрируй тем же ходом» становилось неисполнимым
    для КАЖДОГО worktree-захода (урок 59 арки `2026-08-05_faza-lenty`).

    Лечение — спросить корень у САМОГО ФАЙЛА: `git rev-parse --show-toplevel` от
    его папки. Worktree честно называет себя, и путь внутри него принимается.

    🔴 Проверяем `--git-common-dir`, а не только наличие git: у worktree того же
    репозитория общий git-каталог совпадает с `REPO`, у ЧУЖОГО репозитория —
    нет. Без этой проверки дверь взялась бы регистрировать файл соседнего
    проекта в наш индекс.

    🔴 Git нет вовсе → возвращаем `REPO`, как было. Свойство несущее: фикстуры
    копируют инструменты в `$T/_generator/tools/` и гоняют их ДО `git init`
    (`korni.py`, комментарий к `REPO`). Определение только через git убило бы
    каждую такую фикстуру.
    """
    p = Path(сырой)
    папка = (p if p.is_absolute() else (Path.cwd() / p)).parent
    if not папка.is_dir():
        return REPO
    верх = _git(папка, "--show-toplevel")
    if верх is None:
        return REPO
    if _git(папка, "--git-common-dir") != _git(REPO, "--git-common-dir"):
        return REPO
    return верх


def отн_путь(сырой, база=None):
    """Путь относительно корня рабочей копии (posix), либо None — если он вне неё.

    `база` по умолчанию — корень рабочей копии САМОГО ФАЙЛА (см. `корень_файла`),
    а не корень процесса: иначе дверь не работает ни в одном worktree.

    Принимаем и абсолютный, и относительный от текущей папки: исполнитель
    зовёт дверь из корня, а генератор захода — из любого места.

    🔴 Симлинк НЕ разыменовываем. Развернули бы папки (это безобидно), но не
    последний компонент: ворота 5 судят путь, КОТОРЫМ файл лежит в индексе, а
    `resolve()` подменил бы его путём цели. Итог был бы худшим из возможных —
    ворота краснеют на симлинке, дверь отказывается его регистрировать, и
    легального хода не остаётся вовсе (найдено верификатором, дыра Д6).
    """
    p = Path(сырой)
    p = p if p.is_absolute() else (Path.cwd() / p)
    p = Path(os.path.realpath(p.parent)) / p.name
    try:
        return p.relative_to(Path(os.path.realpath(база or корень_файла(сырой)))).as_posix()
    except ValueError:
        return None


def формы_папки(rel):
    """Хвосты пути папки, которыми раздел `§6` мог назвать её, от длинного к короткому.

    `_studio/zhurnal/A/f.md` → `_studio/zhurnal/A/`, `zhurnal/A/`.
    Длинный пробуем первым: в `§6` папки названы по-разному (`docs/kak-delat/`,
    `../zhurnal/<арка>/`), потому что ссылки там относительные от `_studio/docs/`.

    🔴 ОДНОКОМПОНЕНТНЫЙ хвост берём, только если сама папка однокомпонентная
    внутри `_studio/` (`docs/`, `konvejer/`). Иначе он ловит чужой раздел: в §6
    живут 26 одиноких токенов-папок (`src/`, `content/`, `skeleton/`…), и
    документ из `…/<арка>/src/` уезжал записью в строку про `_generator/skeleton/`
    — индекс не молчал, а ВРАЛ о месте (найдено верификатором, дыра Д7).
    Не нашли раздела — заводим новую строку; это честнее мисфайлинга.
    """
    части = Path(rel).parent.as_posix().split("/")
    предел = len(части) - 1 if len(части) > 2 else len(части)
    return ["/".join(части[i:]) + "/" for i in range(предел)]


def найти_раздел(строки, rel):
    """Индекс строки `§6`, к которой дописывается запись, либо None.

    🔴 Ищем ОБРАТНО-КАВЫЧЕННЫЙ ТОКЕН, оканчивающийся на хвост папки, — а не
    вхождение имени папки в строку. Разница не косметическая: строка арки
    `2026-07-30_dovodka-fabriki` уже на 110-м символе упоминает
    `2026-07-28_konspekt-l1` как предшественницу, и наивный поиск по имени
    отправил бы запись в чужой раздел. Проверено на живом файле: для арки
    попадание ровно одно, для `docs/kak-delat/` — ровно одно.
    """
    for форма in формы_папки(rel):
        for i, строка in enumerate(строки):
            for токен in re.findall(r"`([^`]+)`", строка):
                if токен.endswith(форма):
                    return i
    return None


def точно_зарегистрирован(раздел, rel):
    """Названа ли в `§6` ИМЕННО эта строка про ИМЕННО этот документ.

    🔴 Зачем дверь строже ворот. Предикат ворот 5 — подстрочный (`имя in раздел`),
    и это не описка, а его давнее поведение, которое заход запрещает менять. Но
    для ДВЕРИ подстроки мало: имя `PLAN.md` встречается в §6 (план соседней
    арки), поэтому на `PLAN.md` новой арки дверь печатала бы «уже
    зарегистрирован», rc=0, и не писала бы НИЧЕГО. Исполнитель, честно
    выполнивший инструкцию, получал бы успех и пустой индекс — то есть дверь
    производила бы ровно тех сирот, ради которых заводилась (верификатор, Д1;
    так молчали все пять файлов, которые плодит `bootstrap_arka.py`).

    🔴 И почему это НЕ разъезд ядра. Строгое ВЛОЖЕНО в грубое: раз токен с этим
    именем в §6 есть, то `имя in раздел` истинно тем более. Значит опасное
    направление («дверь сказала готово, а хук краснеет») невозможно по
    построению — а безопасное («дверь пишет лишний раз») стоит одной строки.

    Засчитываем два случая: токен содержит ПОЛНЫЙ путь (регистрация по пути,
    в §6 таких много), либо токен с этим именем стоит в строке того раздела,
    куда документ и относится.
    """
    имя = Path(rel).name
    строки = раздел.split("\n")
    for строка in строки:
        for токен in re.findall(r"`([^`]+)`", строка):
            if токен.endswith(rel):
                return True
    i = найти_раздел(строки, rel)
    if i is None:
        return False
    return any(т.endswith(имя) for т in re.findall(r"`([^`]+)`", строки[i]))


def вписать(текст, rel, описание):
    """(новый текст, номер строки, что дописано). Правка ЛОКАЛЬНАЯ — ровно одна строка.

    🔴 ГРАНИЦЫ `§6` БЕРЁМ У САМИХ ВОРОТ (`вырезать_раздел_6`), а не ищем заново.
    Своя реализация границы уже разошлась с воротами и дала самый дорогой класс
    дефекта: ворота режут от ПЕРВОГО `## §6.`, а самодельный поиск брал
    ПОСЛЕДНИЙ. Хватало одной строки `## §6.` в примере формата внутри самого
    индекса — и дверь писала в настоящий раздел с `rc=0`, а хук краснел на том
    же файле; повторный вызов печатал «уже зарегистрирован», и легального хода
    не оставалось: `--no-verify` возвращался штатным (верификатор, Д5).
    Теперь граница физически одна, и разойтись ей не с чем.

    Работаем построчно ВНУТРИ вырезанного раздела, а не регекспом по всему
    файлу: `KARTA.md` — 210 КБ, где отдельные строки-разделы длиной под 45 000
    знаков. Замена по всему тексту — самый вероятный способ незаметно переписать
    чужой раздел; склейка «до + раздел + после» оставляет всё нетронутое
    байт-в-байт прежним.
    """
    раздел = вырезать_раздел_6(текст)
    if not раздел:
        return None, None, None
    начало = текст.index(раздел)
    до, после = текст[:начало], текст[начало + len(раздел):]
    смещение = текст.count("\n", 0, начало)
    строки = раздел.split("\n")
    запись = f"`{Path(rel).name}` ({описание})"
    i = найти_раздел(строки, rel)
    if i is None:
        # Раздела под эту папку в §6 нет — заводим отдельную строку в конце §6.
        # Путь целиком, а не имя: у одинокой строки нет соседей, из которых
        # читается, где документ лежит. Пустая строка перед ней обязательна —
        # без неё markdown приклеит абзац к предыдущему.
        запись = f"**`{rel}`** ({описание})"
        хвост = len(строки)
        while хвост > 0 and not строки[хвост - 1].strip():
            хвост -= 1
        строки[хвост:хвост] = ["", запись]
        i = хвост + 1
    else:
        строки[i] = строки[i].rstrip() + " · " + запись
    return до + "\n".join(строки) + после, смещение + i + 1, запись


def registrate(путь, описание, тихо=False):
    """Зарегистрировать `путь` с `описанием`. Возвращает код возврата.

    Один вход и для двери (`__main__`), и для генератора захода
    (`bootstrap_zahod.py` импортирует ЭТУ функцию). Второй реализации быть не
    должно: шаг A и шаг B обязаны писать в §6 одинаково, иначе строки
    разъедутся и разъезд будет виден только через неделю.
    """
    описание = re.sub(r"\s+", " ", (описание or "")).strip()
    # Порог грубый и ОТСЕИВАЮЩИЙ: пустое, пробелы, `-`, одинокое эмодзи. Такая
    # строка выглядит как выполненная регистрация и несёт ноль — это хуже её
    # отсутствия, потому что ворота 5 после неё замолчат навсегда.
    if len(re.findall(r"[^\W_]", описание, re.UNICODE)) < 2:
        print("❌ Пустое или бессодержательное описание. Описание — единственное, "
              "ради чего индекс существует; строка без него хуже её отсутствия, "
              "потому что ворота 5 после неё замолчат навсегда.", file=sys.stderr)
        return 2

    # 🔴 База — рабочая копия САМОГО ФАЙЛА, а не процесса (дефект Д1, см.
    # `корень_файла`). Всё ниже считается от неё: и проверка «файл на диске», и
    # индекс. Считать индекс от `REPO`, а файл от worktree — значит вписать
    # строку регистрации в ЧУЖУЮ рабочую копию: у исполнителя она не попадёт в
    # коммит, а у соседа появится строка про документ, которого он не видит.
    база = корень_файла(путь)
    rel = отн_путь(путь, база)
    if rel is None:
        print(f"❌ Путь вне репозитория: {путь} (рабочая копия: {база})",
              file=sys.stderr)
        return 2
    if not korni.дверь_принимает(rel):
        корни = "`, `".join(korni.префиксы_двери())
        print(f"❌ Не регистрирую «{rel}»: дверь судит только `{корни}`. "
              f"Документы проектов живут в своих индексах — у курса, у лекции, "
              f"у арки. Если это самостоятельный обзор, а не часть проекта, его "
              f"место в `obzory/<slug>/src/` (см. `obzory/README.md`).",
              file=sys.stderr)
        return 2
    if not (база / rel).is_file():
        print(f"❌ Файла нет на диске: {rel}. Регистрация несуществующего "
              f"документа — запись о том, чего нет.", file=sys.stderr)
        return 2

    # Индекс — ТОГО корня, которому путь принадлежит.
    # 🔴 Инвариант «дверь принимает ⇒ индекс назван» ПРОВЕРЯЕТСЯ, а не заявляется
    # комментарием: строка реестра с `регистрация != "нет"` и `карта=None`
    # законна по типам и даёт `REPO / None` → TypeError, то есть падение стеком
    # вместо диагноза. Сегодня такой строки нет; проверка стоит ради завтрашней
    # (найдено верификатором захода).
    KARTA_REL = korni.карта_для(rel)
    if not KARTA_REL:
        print(f"❌ Корень пути «{rel}» дверью принимается, но индекс для него в "
              f"_generator/tools/korni.py не назван (`карта=None`). Чинить реестр: "
              f"строка корня обязана называть, в какой `KARTA.md` писать.",
              file=sys.stderr)
        return 2
    карта = база / KARTA_REL
    if not карта.is_file():
        print(f"❌ Не нашёл индекс: {KARTA_REL}", file=sys.stderr)
        return 2
    текст = карта.read_text(encoding="utf-8")
    раздел = вырезать_раздел_6(текст)
    if not раздел:
        print(f"❌ В {KARTA_REL} нет раздела `## §6.` — индекс сломан, "
              f"вписывать некуда.", file=sys.stderr)
        return 2

    if точно_зарегистрирован(раздел, rel):
        if not тихо:
            print(f"Уже зарегистрирован — второй строки не завожу: {rel}")
        return 0

    новый, строка, запись = вписать(текст, rel, описание)
    if новый is None:
        print(f"❌ Границы `§6` в {KARTA_REL} не читаются", file=sys.stderr)
        return 2

    # 🔴 СВЕРКА С ВОРОТАМИ ДО ЗАПИСИ НА ДИСК. Спрашиваем сам предикат ворот 5:
    # засчитают ли они то, что мы собираемся вписать. Отказ здесь дешевле, чем
    # сговор, сломавшийся молча: «дверь напечатала ✅, хук остановил коммит» —
    # это состояние без легального хода, из которого выходят только
    # `--no-verify`, то есть ровно тем, что заход закрывает.
    if not зарегистрирован(rel, вырезать_раздел_6(новый)):
        print(f"❌ Вписал бы, но ворота 5 этого НЕ засчитают — файл не тронут. "
              f"Так бывает, когда в {KARTA_REL} появился второй заголовок "
              f"`## §6.` и раздел режется не там, где кажется. Чинить индекс, "
              f"а не обходить хук.", file=sys.stderr)
        return 3

    карта.write_text(новый, encoding="utf-8")

    # Печатаем РОВНО вписанное: исполнителю это цитировать в отчёте, а
    # приёмке — сверять с файлом, не веря на слово.
    print(f"✅ Зарегистрирован: {rel}")
    print(f"   {KARTA_REL}:{строка} — вписано: {запись}")
    # 🔴 Ворота 5 читают §6 С ДИСКА, а не из индекса. Значит коммит, в котором
    # нет самого `KARTA.md`, пройдёт ЗЕЛЁНЫМ, а документ уедет сиротой — и
    # строка умрёт при первом `checkout` этого файла. Названо верификатором
    # (дыра Д2) и вылечено пока только громкостью: путь печатается, чтобы его
    # добавили в тот же коммит.
    print(f"🔴 {KARTA_REL} обязан уехать в ТОТ ЖЕ коммит — допиши его к своим "
          f"путям и в add, и в commit. Иначе документ уедет сиротой при "
          f"зелёном хуке: ворота 5 читают §6 с диска, а не из индекса.")
    return 0


