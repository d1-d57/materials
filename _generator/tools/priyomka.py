#       больше пяти — каждая живая ветка это один идущий заход. Больше пяти
#       означает не «много работы в полёте», а «ветки перестали закрывать».
#
# 🔴 ЧЕГО ЭТОТ ГЕЙТ НЕ ВИДИТ — названо здесь, потому что молчание о слепоте
# читается как её отсутствие:
