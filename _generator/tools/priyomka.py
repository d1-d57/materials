SUBAGENT_RE = re.compile(r'субагент', re.I)

# 🔴 ОТРИЦАНИЯ ВЫРЕЗАЮТСЯ, И СПИСОК УМЫШЛЕННО УЗКИЙ. «Субагентов не запускал» —
