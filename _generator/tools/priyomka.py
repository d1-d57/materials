# Слова, которыми отчёт заявляет вердикт о проверке — не только «зелёный»/
# «красный», а сам факт: что-то было проверено/прогнано/обработано и дан
# результат. Список снят грепом по живому корпусу `_studio/zhurnal/*/kod_*.md`
# (КРТ-062, Р5-72): «проверен(о/а/ы)», «прогнан(о/а/ы)», «обработан(о/а/ы)»,
# «отрендерен(о/а/ы)», «разобран(о/а/ы)», «просмотрен(о/а/ы)», «дыр не
# найдено», «все/всё зелён(ые/ое)».
# 🔴 «провер\w*» БЕЗ ОГРАНИЧЕНИЯ НА ПРИЧАСТИЕ/ПРОШЕДШЕЕ ВРЕМЯ ловил
# инфинитив/настоящее время («проверить» как пункт очереди, «не
# проверяется» как описание границы охвата) — это не вердикт о ЗАВЕРШЁННОЙ
# проверке, а план или отрицание. Найдено калибровкой 15.08:
# `kod_vneshnyaya-merka.md` краснел единственно на «не проверяется» —
# ложное. Сужено до причастия (`провер-ен…`) и прошедшего личного
# (`провер-ил…`) — «проверить»/«проверяется»/«проверяю» больше не триггер.
VERDIKT_PROVERKI_RE = re.compile(
    r'провер(?:ен\w*|ил\w*)'
    r'|прогнан\w*'
    r'|обработан\w*'
    r'|отрендерен\w*'
    r'|разобран\w*'
    r'|просмотрен\w*'
    r'|дыр\s+не\s+найдено'
    r'|все?\s+зел[её]н\w*',
    re.I)

# Форма охвата рядом с вердиктом: «N из M» в любой обвязке («проверено 21 из
# 21», «5 из 5 держится», «N из M пунктов», «просмотрено N кадров из M»),
# либо дробью «N/M» (`10/10 станций`, `5/5`, `9/9 ✅`) — калибровка 15.08
# нашла её в `kod_katalog.md`, где я сперва ошибочно счёл дробь
# невстречающейся; либо глагол-корень вплотную с числом без «из» («прогнано
# 23 файла», такую форму КРТ-062 называет законной).
# 🔴 `(?<![.\d])` / `(?![.\d])` ВОКРУГ ДРОБИ ОБЯЗАТЕЛЬНЫ — без них «N/M»
# ловит номер секции вида `§1.4/1.6` (совпадение «4/1» изнутри дробных
# номеров): найдено той же калибровкой на `kod_riehl-lccc.md`, где дробь
# section-ref давала ложный зелёный при заведомом отсутствии охвата.
# Граница — не десятичная точка и не другая цифра сразу снаружи дроби.
# ⚠ СЛЕПАЯ ЗОНА: числа словами («пять из пяти») не покрыты — не
# встретились в корпусе на замере 15.08, добавить при первом живом случае.
OHVAT_VERDIKTA_RE = re.compile(
    r'\d+[^\n]{0,60}?\bиз\s+\d+'
    r'|(?<![.\d])\d+\s*/\s*\d+(?![.\d])'
    r'|(?:провер\w*|прогнан\w*|обработан\w*|отрендерен\w*|разобран\w*|просмотрен\w*)[^\n]{0,20}?\d+',
    re.I)


