def parse_ochered(voprosy_tekst: str):
    """Пункты `## ВОПРОСЫ` с полями `ДОМ:`/`ДОСТАВЛЕНО:` (Ф1 этого захода).

    Формат пункта (шапка секции документирует его для исполнителя):
        N. <текст находки>
           ДОМ: <путь от корня репо | владелец>
           ДОСТАВЛЕНО: нет | <метка>

    Пункт без `ДОМ:` — обычный вопрос без чужого дома, очередь его не касается.
    Возвращает список dict: {"n": int, "tekst": str, "dom": str, "dostavleno": str}.
    """
    if not voprosy_tekst:
        return []
    punkty = re.split(r'^(\d+)\.\s+', voprosy_tekst, flags=re.M)
    # re.split с группой отдаёт [преамбула, num1, telo1, num2, telo2, ...]
    ochered = []
    for i in range(1, len(punkty), 2):
        n = int(punkty[i])
        telo = punkty[i + 1]
        # тело пункта — до следующего пронумерованного пункта (уже отрезано split)
        m_dom = re.search(r'^\s*ДОМ:\s*(.+)$', telo, re.M)
        if not m_dom:
            continue  # обычный вопрос без адреса — не пункт очереди
        m_dost = re.search(r'^\s*ДОСТАВЛЕНО:\s*(.+)$', telo, re.M)
        tekst_nahodki = telo.split('\n', 1)[0].strip()
        ochered.append({
            "n": n,
            "tekst": tekst_nahodki,
            # 🔴 АДРЕС НОРМАЛИЗУЕТ КАНАЛ, А НЕ `.strip()`. Поле `ДОМ:` — живой
            # текст: путь пишут голым, в бэктиках и с пояснением после него
            # (`` `путь` (следующий заход очереди) ``). Взятый как есть, он не
            # совпадает ни с одним файлом, и Г7 краснел на ВЕРНОЙ доставке —
            # живой прогон по 37 заходам арки дал 12 таких ложно-красных
            # из 12 сработавших.
            "dom": dostavit_urok.адрес_из(m_dom.group(1)),
            "dostavleno": m_dost.group(1).strip() if m_dost else "нет",
        })
    return ochered


def gate_g7(ochered, arka=None):
    """Красный ТОЛЬКО когда пункт помечен доставленным, а по адресу нет метки.

    Ложное «сделано» опаснее честного «не сделано» (Ф1, часть B): недоставленный
    пункт (`ДОСТАВЛЕНО: нет`) не гейт вообще — он в печати для рук ниже. Дом
    «владелец» — не файл, факт передачи механически не проверить (Ф1 вопрос 2:
    у этого типа находки адрес — человек, а не путь) — вне гейта принципиально,
    тоже только печать.
    """
    problemy = []
    arka = arka or REPO
    for p in ochered:
        if p["dostavleno"].strip().lower() == "нет":
            continue
        if p["dom"].strip().lower() == "владелец":
            continue
        # 🔴 РЕЗОЛВ ДОМА БЕРЁТСЯ У КАНАЛА, А НЕ СЧИТАЕТСЯ ЗДЕСЬ ОТ `REPO`.
        # Свой резолв знал одну базу — корень репозитория. Живой прогон на
        # `kod_hvosty.md` дал из-за этого ТРИ ЛОЖНО-КРАСНЫХ: дом записан
        # `<эта арка>/UROKI-FABRIKE.md` — конвенцией шаблона, которую канал
        # подставляет, а Г7 читал буквально и объявлял «дом не найден» на
        # верной доставке. Ложно-красный гейт отключают так же быстро, как
        # ложно-зелёный, только злее.
        put_doma, _baza = dostavit_urok.резолв(p["dom"], arka, REPO)
        if put_doma is None:
            problemy.append(f"пункт {p['n']} помечен доставленным (`{p['dostavleno']}`), "
                             f"а дом `{p['dom']}` не найден на диске "
                             f"(пробованы базы: папка арки, корень репо, _studio/zhurnal)")
            continue
        if p["dostavleno"] not in read(put_doma):
            problemy.append(f"пункт {p['n']} помечен доставленным (`{p['dostavleno']}`), "
                             f"а метки в доме `{p['dom']}` нет")
    if problemy:
        return False, "; ".join(problemy)
    if not ochered:
        return True, "пунктов очереди (ДОМ/ДОСТАВЛЕНО) нет"
    return True, f"{len(ochered)} пункт(ов) очереди, ложной доставки не найдено"


def gate_g8(zahod_path: Path, arka: Path):
    """Очередь захода: красный по СОСТОЯНИЮ и по ПОРОГУ, а не по факту.

    🔴 ПОЧЕМУ НЕ «ЕСТЬ НЕДОСТАВЛЕННОЕ → КРАСНЫЙ». Пункты копятся по замыслу:
    их разносят на консолидации, а не в каждом заходе. Гейт на факте покрасил бы
    33 из 37 заходов живой арки — то есть почти каждый честный отчёт. Такой гейт
    отключают первым, и это в репозитории уже случалось.

    Поэтому красным становятся ровно два случая, и оба чинятся действием:
      * **дом ЕСТЬ, а пункт не доставлен** — чинится одной командой `--dostavit`;
        на 37 заходах арки таких пунктов 29 суммарно, то есть у большинства
        заходов их нет вовсе, и гейт молчит;
      * **очередь захода перевалила порог** (`dostavit_urok.ПОРОГ_ОЧЕРЕДИ`) —
        число снято с корпуса, обоснование в самом канале.
    «Дома нет» и `ДОМ: владелец` гейту не подсудны никогда: они не чинятся
    командой, их место — печать ниже и `--gejt --zakrytie` при закрытии арки.

    🔴 РАЗБОР БЕРЁТСЯ У КАНАЛА, А НЕ У `parse_ochered` ЭТОГО ЖЕ ФАЙЛА. Замер по
    37 файлам арки: `parse_ochered` (якорь — номер в начале строки) видит 127
    пунктов из 199. Гейт на нём молчал бы на трети очереди — ровно на той трети,
    где номер записан жирным или секция названа иначе.
    """
    if not zahod_path.name.startswith("kod_"):
        return True, "файл-заход не вида `kod_*.md` — Г8 неприменим"
    spisok = dostavit_urok.punkty_zahoda(zahod_path)
    bez = [n for n in spisok if not n["метка"]]
    koren = arka.resolve().parent.parent.parent
    zhivoj_dom = [n for n in bez
                  if dostavit_urok.класс_адреса(n, arka.resolve(), koren)[0] == "дом есть"]
    porog = dostavit_urok.ПОРОГ_ОЧЕРЕДИ
    problemy = []
    # 🔴 «ДОМ ЕСТЬ, А НЕ ДОСТАВЛЕНО» — ПЕЧАТЬ, А НЕ КРАСНОЕ, И ЭТО ОПЛАЧЕНО
    # ПРОГОНОМ. Сперва это было вторым красным правилом Г8; живой прогон по
    # СВЕЖЕМУ отчёту (этого самого захода) показал, чего стоит такая
    # конструкция: перенос пункта в дом делает АНАЛИТИК на приёмке — значит на
    # каждом первом прогоне пункты ещё не перенесены по построению, и гейт
    # краснеет на любом честном отчёте, где исполнитель назвал живой дом.
    # Гейт, красный на каждой первой приёмке, отключат первым — ровно то, от
    # чего §2.4 захода и предостерегал: «краснеет по порогу или стадии, а не
    # по факту». Поэтому здесь остаётся ОДНО красное правило — порог, — а
    # доставимое печатается готовой командой: это подсказка тому, кто как раз
    # сейчас переносит, а не приговор отчёту.
    podskazka = ""
    if zhivoj_dom:
        imena = "; ".join(f"пункт {n['номер']} → `{n['дом']}`" for n in zhivoj_dom[:5])
        podskazka = (f"; доставимо командой прямо сейчас: {len(zhivoj_dom)} "
                     f"({imena}) — dostavit_urok.py --dostavit N {zahod_path.name}")
    if len(bez) > porog:
        problemy.append(f"очередь захода {len(bez)} > порога {porog} — "
                        f"разносить пора сейчас, а не на закрытии арки")
    if problemy:
        return False, "; ".join(problemy) + podskazka
    if not spisok:
        return True, "пунктов очереди в заходе нет"
    return (True, f"{len(bez)} недоставленных из {len(spisok)} — в пределах нормы "
                  f"(порог {porog})" + (podskazka or
                  ", доставить некуда: дома нет или решение за человеком"))


# ── Г9: субагент отчитался, а охвата в его ответе нет (Р5-6, КРТ-020a) ───────
# Корень «субагент» — единственная форма, которой отчёт ЗАЯВЛЯЕТ, что канал
# субагента вообще был. Ищется ПО СТРОКАМ и только внутри `## ОТЧЁТ`.
SUBAGENT_RE = re.compile(r'субагент', re.I)

# 🔴 ОТРИЦАНИЯ ВЫРЕЗАЮТСЯ, И СПИСОК УМЫШЛЕННО УЗКИЙ. «Субагентов не запускал» —
# самая частая фраза отчёта БЕЗ субагента, и она содержит корень «субагент»:
# без этого фильтра клауза краснела бы ровно на тех отчётах, ради которых её и
# ограничивали. Узкий список (а не любое `не` в строке) — потому что широкий
# глотал бы и честные заявки вида «субагент отработал, необратимого не было».
SUBAGENT_NE_BYLO_RE = re.compile(
    r'без\s+субагент'
    r'|субагент\w*\s+(?:не|нет)\b'
    r'|ни\s+одного\s+субагент'
    r'|(?:не\s+было|нет)\s+(?:никаких\s+)?субагент'
    r'|не\s+(?:запускал|звал|поднимал|привлекал|использовал|порождал)\w*',
    re.I)

# Каноническая форма охвата, которую вшивает `bootstrap_zahod.py` в промпт
# субагента: «выдано N позиций из M найденных». Хвост между числами свободный —
# отчёты пишут «выдано 12 позиций из 37 найденных» и «выдал 3 из 5» вперемешку.
OHVAT_SUBAGENTA_RE = re.compile(r'выдан\w*\s+\d+[^\n]{0,120}?\bиз\s+\d+', re.I)

# Строка, по которой видно, что ЗАХОД предписывал субагента (блок §0.1
# генератора). Гейтом это НЕ становится — см. докстринг `gate_g9`.
# 🔴 СОБРАН ИЗ ПОЛОВИНОК НАРОЧНО — тот же приём, что у `GNU_PAIRS`. Записанный
# целиком, этот флаг стоял бы буквально в прозе инструмента, который его же
# и ИЩЕТ в проверяемом тексте, — гейт находил бы сам себя (`Р5-27`,
# `КРТ-РАЗН-32`). Поймано не глазами: расширенный `check_tool_contract.py`
# покраснел на этой строке внутри pre-commit и не пустил коммит.
PREDPISAN_SUBAGENT = "--zadanie" + "-subagentu"

# Дословная формулировка требования, которую `bootstrap_zahod.py` вписывает в
# промпт субагента и в блок §0.1 каждого свежего захода. Служит ОТМЕТКОЙ
# ВРЕМЕНИ: есть в тексте захода — правило для него действовало (см. `gate_g9`).
# 🔴 МАРКЕР — НЕ САМА ФОРМУЛИРОВКА ТРЕБОВАНИЯ, А ФРАЗА, КОТОРУЮ ПИШЕТ ТОЛЬКО
# ГЕНЕРАТОР. Первая редакция границы искала строку «выдано N позиций из M
# найденных» — и ловила заходы, которые правило ЦИТИРУЮТ, не будучи по нему
# собранными: на них Г9 давала ложное (замер ведущего: 4 красных, из них
# `kod_rychagi.md` ложное — там «дело субагента» мимоходом в строке про
# коммит). Тот же класс, что чинили в З15: присутствие слова вместо его роли.
# Эта фраза уезжает в §0.1 из `bootstrap_zahod.git_kontur_blok()` и в старых
# заходах не встречается ни разу.
TREBOVANIE_OHVATA = "ОТВЕТ ЛЮБОГО"


def gate_g9(tekst):
    """Субагент в отчёте есть, а охвата в его ответе нет → красное (Р5-6, КРТ-020a).

    ЧТО ЛОВИТ. Ответ субагента мог быть УСЕЧЁН — лимитом, обрывом канала,
    смертью самого субагента, — и снаружи усечение неотличимо от честного «мало
    нашлось»: аналитик видит короткий список и принимает его за полный. Дешёвый
    признак целости ровно один — охват, записанный В САМОМ ответе последней
    строкой («выдано N позиций из M найденных»): она доезжает только вместе со
    всем, что перед ней. Требование вшито в промпт субагента
    (`bootstrap_zahod.py --zadanie-subagentu`) и в блок §0.1 КАЖДОГО захода —
    здесь стоит то, что покраснеет, когда его не выполнили (`KONSTITUCIYA §11`).

    🔴 ГЛАВНОЕ ОГРАНИЧЕНИЕ, И ОНО ЖЕ ЕДИНСТВЕННАЯ ПРИЧИНА, ПО КОТОРОЙ КЛАУЗУ
    МОЖНО ДЕРЖАТЬ ВКЛЮЧЁННОЙ. Клауза СНАЧАЛА устанавливает, что субагент был, и
    только потом требует охват. Признак «был» — строка внутри `## ОТЧЁТ`, где
    отчёт САМ называет субагента (за вычетом отрицаний). Отчётов без субагентов
    большинство; на них Г9 не применяется вовсе и молчит. Безусловный вариант
    («в заходе есть блок §0.1 → требуй охват») отвергнут: блок печатается в
    КАЖДЫЙ свежий заход, то есть гейт краснел бы на любом отчёте, где субагента
    не звали по существу дела, — а гейт, красный на здоровом, обходят вместе со
    всей защитой (Р31, и в этом репозитории это уже случалось).

    🔴 ЧЕСТНАЯ ДЫРА, КОТОРУЮ КЛАУЗА НЕ ЗАКРЫВАЕТ И НЕ ПРИТВОРЯЕТСЯ. Признак
    берётся из отчёта, значит отчёт, УМОЛЧАВШИЙ про субагента вовсе, для Г9
    невидим. Закрыть это красным нечем: «субагента не звали» и «звали, но не
    сказали» снаружи одинаковы. Поэтому случай, когда заход предписывал
    субагента (§0.1), а отчёт его не называет, уходит в ЗЕЛЁНОЕ СООБЩЕНИЕ
    строкой для рук — печать видна аналитику, но работу не останавливает.
    """
    otchet = sekciya(tekst, "ОТЧЁТ")
    if not otchet:
        return True, "## ОТЧЁТ пуста — Г9 неприменим (пустоту судит Г4)"
    # 🔴 ГРАНИЦА ПО ВРЕМЕНИ, БЕЗ КОТОРОЙ КЛАУЗУ НЕЛЬЗЯ ДЕРЖАТЬ ВКЛЮЧЁННОЙ.
    # Найдено КАЛИБРОВКОЙ ведущего захода `rychagi-3` на живом корпусе (291
    # файл): без этой проверки Г9 краснела на **179 отчётах из 291** — то есть
    # на большинстве здоровых. Причина не в регекспе и сужением словаря не
    # лечится: требование «выдано N позиций из M найденных» вшито в промпт
    # субагента ТОЛЬКО 14.08 (этим же заходом), и ни один отчёт, написанный
    # раньше, физически не мог его выполнить. Гейт, требующий задним числом
    # того, чего правило не требовало, красит всю историю разом — а такой
    # обходят `--no-verify` вместе со всей защитой.
    # Признак «правило действовало для ЭТОГО захода» — сама формулировка
    # требования в тексте захода: `bootstrap_zahod.py` вписывает её и в промпт
    # субагента, и в блок §0.1 КАЖДОГО свежего захода. Нет её — заход собран до
    # правила, и спрашивать не за что.
    if TREBOVANIE_OHVATA not in tekst:
        return True, ("заход собран ДО того, как требование охвата вшили в промпт "
                      "субагента (14.08) — Г9 неприменим: правило не действовало, "
                      "спрашивать за его невыполнение не за что")
    zayavki = [ln.strip() for ln in otchet.splitlines()
               if SUBAGENT_RE.search(ln) and not SUBAGENT_NE_BYLO_RE.search(ln)]
    if not zayavki:
        if PREDPISAN_SUBAGENT in tekst:
            return True, ("субагент в `## ОТЧЁТ` не назван — Г9 неприменим; "
                          "заход при этом предписывает субагента (§0.1 гит-контура) — "
                          "спросить руками, был он или нет: молчание отчёта гейту "
                          "неотличимо от «не звали»")
        return True, "субагент в `## ОТЧЁТ` не назван — Г9 неприменим"
    if OHVAT_SUBAGENTA_RE.search(otchet):
        return True, (f"субагент назван в {len(zayavki)} строке(ах) отчёта, "
                      f"охват «выдано N … из M …» на месте")
    imena = "; ".join(f"«{s[:120]}»" for s in zayavki[:3])
    hvost = f" (и ещё {len(zayavki) - 3})" if len(zayavki) > 3 else ""
    return False, (f"отчёт называет субагента ({len(zayavki)} строк(и)): {imena}{hvost} — "
                   f"а строки охвата «выдано N позиций из M найденных» в `## ОТЧЁТ` нет. "
                   f"Ответ субагента мог быть усечён каналом, и короткий список "
                   f"неотличим от полного. Перезапросить у субагента финальную строку "
                   f"охвата и вставить её в отчёт дословно")


ЛIMIT_VOZRASTA_CH = 24


def gate_l1():
    """Заявка открыта дольше 24 ч → красный (`GIT-disciplina §4г`, ловушка Л1).

    Механизм заявок (`_studio/zhurnal/2026-08-11_ochered-zayavok/PROEKT.md §4`)
    работает только пока очередь кто-то читает. Написанная и забытая заявка
    сегодня НЕ видна ничем — этот гейт делает её видимой на приёмке, а не
    только в печати `git_zona.py doctor`.

    🔴 ПОСТОЯННЫЕ ИСКЛЮЧЕНИЯ (`СРОЧНОСТЬ: postoyannaya`) ВОЗРАСТОМ НЕ СУДЯТСЯ.
    Иначе гейт красил бы каждую приёмку арки, где висит намеренно долгоживущая
    заявка, и его отключили бы первым же вечером (§4 PROEKT.md).

    🔴 ПУТЬ ОЧЕРЕДИ — У `git_zona.zayavki_dir()`, второй реализации не заводим:
    два разных ответа на «где очередь» разъедутся молча (задание Ш3 этого захода).
    """
    stroki = git_zona._zayavki_otkrytyye()
    sudimyje = [s for s in stroki if s[3].strip().lower() != "postoyannaya"]
    prosrochennyje = [s for s in sudimyje if s[2] > ЛIMIT_VOZRASTA_CH]
    if prosrochennyje:
        imena = "; ".join(f"{zid} ({vozrast} ч)" for zid, _p, vozrast, _s, _t in prosrochennyje)
        return (False, f"{len(prosrochennyje)} заявка(и) старше {ЛIMIT_VOZRASTA_CH} ч: {imena} "
                       f"— написали и забыли (постоянные исключения возрастом не судятся)")
    return (True, f"проверено {len(stroki)} заявок, просроченных (>{ЛIMIT_VOZRASTA_CH} ч, "
                  f"кроме постоянных исключений) нет")


KONTRAKTNAYA_ZONA_RE = re.compile(r'^-\s*\*?\*?ЗОНА[^:]*:\*?\*?\s*(.+)$', re.M)


def granicy_zony(tekst: str, khash: str):
    """Печать (НЕ гейт): пути коммита за пределами `## КОНТРАКТ ЗОНЫ`.

    Формат контракта неоднороден (Ф1/часть C1) — ложное красное здесь дороже
    пропуска, поэтому только печать для рук, не гейт.
    """
    m = KONTRAKTNAYA_ZONA_RE.search(tekst)
    if not m:
        return "строка «ЗОНА» в контракте не найдена — сверка границ пропущена"
    prefiksy = [p.strip('`').strip() for p in re.findall(r'`([^`]+)`', m.group(1))]
    if not prefiksy:
        return "в строке «ЗОНА» нет путей в backticks — сверка границ пропущена"
    r = subprocess.run(["git", "--no-optional-locks", "show", "--stat", "--format=", khash],
                        cwd=REPO, capture_output=True, text=True)
    if r.returncode != 0:
        return f"git show --stat {khash} упал — сверка границ пропущена"
    puti = [ln.split('|')[0].strip() for ln in r.stdout.splitlines() if '|' in ln]
    za_predelami = [p for p in puti if not any(p == pref or p.startswith(pref.rstrip('/') + '/')
                                                for pref in prefiksy)]
    if not za_predelami:
        return f"все пути коммита внутри зоны ({len(puti)} из {len(puti)})"
    return (f"ВНЕ зоны контракта: {', '.join(za_predelami)} "
            f"(зона по контракту: {', '.join(prefiksy)})")


def izvlech_vetku(tekst: str):
    """Ветка захода — из контракта зоны («…worktree add <имя> --branch <ветка>»).

    🔴 `[^\\s`]+`, а не `\\S+` — по той же оплаченной причине, что в
    `izvlech_zonu`: в контракте команда стоит в backticks без пробела перед
    закрывающим, и `\\S+` утащил бы backtick В СОСТАВ имени ветки. Имя с лишним
    символом не совпало бы ни с одной живой веткой, и вердикт печатался бы
    «ветки нет» на исправной работе.
    Резерв — checkout-режим захода, где `--branch` не встречается вовсе: там
    генератор пишет «обязано быть `<ветка>`».
    """
    m = re.search(r'--branch\s+([^\s`]+)', tekst)
    if m:
        return m.group(1)
    m = re.search(r'обязано быть\s+`([^`]+)`', tekst)
    return m.group(1) if m else None


def pechat_zhizni_vetki(vetka):
    """Печать (НЕ гейт): что делать с веткой принятого захода.

    🔴 ПОЧЕМУ ВЕРДИКТ, А НЕ БЕЗУСЛОВНАЯ СТРОКА `zakryt-vetku` (Ф0 захода
    `zhizn-vetki`, вопрос 3 — возражение к точке вызова). Приёмка переноса НЕ
    делает: Г0 (`check --zone`) судит ЧИСТОТУ рабочего дерева и зеленеет даже
    когда весь код захода остался на ветке — это болезнь, оплаченная ТРИЖДЫ
    (`storozh-vetok`, `dobivka-vetok` и блокер первого хода самого
    `zhizn-vetki`: канон и отчёт перенесены, код — нет). Значит в момент
    зелёных гейтов ветка захода ЕЩЁ НЕ перенесена, и готовая строка закрытия
    привела бы владельца к отказу — шум в 100 % случаев, а шумящую печать
    перестают читать (`Р31`). Поэтому печатается ВЕРДИКТ метрики:
      · зелёная  ⇒ готовая строка закрытия — ветка своё отработала;
      · красная  ⇒ ЧТО именно не перенесено + команда переноса.
    В таком виде печать сама ловит «перенос забыт», то есть закрывает причину,
    а не добавляет ещё одну строку в вывод.

    🔴 НЕ ЗАПУСКАЕТ ЗАКРЫТИЕ САМА. Приёмка идёт под аналитиком; удаление ветки
    в середине чужого прогона — не его дело (и `poteri` здесь read-only).
    """
    print("\n-- Жизнь ветки захода (печать, не гейт; ничего не удаляет) --")
    if not vetka:
        print("   ветка захода не найдена в контракте зоны — сверка пропущена")
        return
    r = subprocess.run(
        ["python3", str(TOOLS / "git_zona.py"), "poteri", "--branch", vetka],
        cwd=REPO, capture_output=True, text=True,
    )
    vyvod = (r.stdout.strip() + "\n" + r.stderr.strip()).strip()
    if "нет среди" in vyvod or "текущая ветка" in vyvod:
        print(f"   `{vetka}`: {vyvod.splitlines()[0] if vyvod else '(вывод пуст)'}")
        return
    if r.returncode == 0:
        print(f"   ✅ `{vetka}` — метрика зелёная: содержимое ветки никуда не пропадёт.")
        print("   Ветка своё отработала — закрыть её (надгробие + снос папки, "
              "обратимо):")
        print(f"     python3 _generator/tools/git_zona.py zakryt-vetku --branch {vetka}")
        return
    print(f"   🔴 `{vetka}` — метрика КРАСНАЯ: работа захода ещё НЕ перенесена. "
          "Закрывать нельзя,\n      сперва перенос — иначе повторится "
          "«приёмка привезла отчёт без кода» (оплачено трижды):")
    for stroka in vyvod.splitlines():
        print(f"      {stroka}")


def tihij_nedobor(otchet_tekst):
    """Печать (НЕ гейт): формы «не успел/частично/осталось/не сделал» в ## ОТЧЁТ."""
    if not otchet_tekst:
        return []
    return [ln.strip() for ln in otchet_tekst.splitlines()
            if re.search(r'не успел|частично|осталось|не сделал', ln, re.I) and ln.strip()]


def ohvat_polozhitelnogo(otchet_tekst):
    """True, если среди числовых строк отчёта есть форма «X из Y» (охват)."""
    if not otchet_tekst:
        return False
    return re.search(r'\d+\s+из\s+\d+', otchet_tekst) is not None


