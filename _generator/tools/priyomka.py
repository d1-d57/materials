#       над наблюдавшимся здоровым максимумом и всё ещё срабатывает на больном:
#       запас в сторону молчания выбран сознательно, потому что ложное красное
#       здесь дороже пропуска — его обходят вместе со всеми воротами.
#   невлитых    > 5  → красное. Здоровое измеренное — 1 и 0. Порог взят не из
#       середины, а из УСТРОЙСТВА работы: фабрика держит ≤5 параллельных
