#   · ветки, живущие ТОЛЬКО на origin (счёт идёт по локальным);
#   · `git stash` — спрятанное не считается ни грязным, ни закоммиченным;
#   · другие машины владельца: «вывезено» здесь значит «есть на origin», а не
#     «есть у всех»;
#   · чужие рабочие папки worktree со своим грязным деревом — они судятся
#     собственным `git status`, а не этим (`git_zona.py poteri` их печатает).

PORG_VNE_GIT = 15        # замер: здоровое 11, больное 23
PORG_NEVLITYH = 5        # замер: здоровое 1 и 0, больное 14; потолок — ≤5 заходов


def _dolg_repozitoriya(koren: Path):
    """Три числа git-долга одного репозитория + КОМАНДА, которой снято каждое.

    Возвращает dict или None, если это не git-репозиторий.

    🔴 ПОРЯДОК АРГУМЕНТОВ `rev-list` — НЕ КОСМЕТИКА. `rev-list --count --not
    --remotes HEAD` даёт ВСЕГДА 0: `--not` действует на всё, что идёт следом,
    и исключает сам `HEAD` вместе с remotes. Правильно `rev-list --count HEAD
    --not --remotes`. Пойман живым замером 2026-08-14: неверная форма печатала
    «невывезено 0» на репозитории `disciplina`, где невывезенный коммит был.
    Гейт с этой опечаткой молчал бы ровно на том, ради чего заведён.

    🔴 ПОЧЕМУ `HEAD --not --remotes`, А НЕ `@{u}..HEAD`. Мера риска — «переживёт
    ли работа смерть диска», а коммит, лежащий на origin под ЛЮБОЙ ссылкой, её
    переживает. `@{u}..HEAD` считает и то, что уже вывезено под другим именем:
    на том же замере он дал 13 против настоящей 1.
    """
    if not (koren / ".git").exists():
        return None

    def git(*args):
        r = subprocess.run(["git", "--no-optional-locks", *args],
                           cwd=koren, capture_output=True, text=True)
        return r.returncode, r.stdout.strip()

    rc, vetka = git("symbolic-ref", "--short", "HEAD")
    if rc != 0:
        vetka = "(detached HEAD)"

    # 🔴 РЕПОЗИТОРИЙ БЕЗ УДАЛЁННЫХ ВООБЩЕ — ОТДЕЛЬНЫЙ ДИАГНОЗ, А НЕ КРАСНОЕ.
    # Формально там невывезено ВСЁ, и первая редакция гейта честно краснела —
    # в том числе на одноразовом репозитории фикстуры `fixtures/priyomka`, где
    # удалённого нет по устройству. Гейт, красный на всяком временном репо, —
    # ровно тот шум, ради которого гейты отключают. Поэтому: удалённых нет →
    # число не считается, печатается «непроверяемо» и называется причина.
    rc, remotes = git("remote")
    est_remote = bool(remotes.strip())
    if est_remote:
        rc, nevyvezeno = git("rev-list", "--count", "HEAD", "--not", "--remotes")
    else:
        nevyvezeno = "-"
    kmd_nevyvezeno = "git rev-list --count HEAD --not --remotes"

    rc2, gryaz = git("status", "--porcelain")
    vne_git = len([l for l in gryaz.splitlines() if l.strip()])
    kmd_vne_git = "git status --porcelain | wc -l"

    rc3, vetki = git("branch", "--no-merged", vetka)
    nevlityh = [l.strip().lstrip("+* ").strip() for l in vetki.splitlines() if l.strip()]
    kmd_nevlityh = f"git branch --no-merged {vetka} | wc -l"

    return {
        "koren": koren, "vetka": vetka,
        "est_remote": est_remote,
        "nevyvezeno": int(nevyvezeno) if nevyvezeno.isdigit() else -1,
        "kmd_nevyvezeno": kmd_nevyvezeno,
        "vne_git": vne_git, "kmd_vne_git": kmd_vne_git,
        "nevlityh": nevlityh, "kmd_nevlityh": kmd_nevlityh,
    }


def repozitorii_zony(zona_stroka: str):
    """Репозитории под судом: наш `REPO` + корни путей зоны, лежащих ВНЕ него.

    Второй репозиторий гейт не угадывает и не хардкодит — его называет САМ
    контракт зоны захода (`ЗОНА (можно менять):` перечисляет абсолютные пути,
    когда работа выходит за `materials`). Значит гейт настраивается тем же
    текстом, который исполнитель и так обязан заполнить, и не разъедется с ним.
    """
    korni = [REPO.resolve()]
    for kus in re.findall(r'`([^`]+)`', zona_stroka or ""):
        p = Path(kus.strip().rstrip("/"))
        if not p.is_absolute():
            continue
        try:
            p.resolve().relative_to(REPO.resolve())
            continue          # внутри нашего репозитория — уже посчитан
        except ValueError:
            pass
        # подняться до корня репозитория (там, где лежит .git)
        kandidat = p.resolve()
        while kandidat != kandidat.parent and not (kandidat / ".git").exists():
            kandidat = kandidat.parent
        if (kandidat / ".git").exists() and kandidat not in korni:
            korni.append(kandidat)
    return korni


def gate_g10(zona_stroka: str):
    """Г10 — накопление git-долга по всем репозиториям зоны (см. врезку выше).

    🔴 `PRIYOMKA_BEZ_G10=1` — ВЫКЛЮЧАТЕЛЬ ДЛЯ ФИКСТУР, И ОН ГРОМКИЙ. Г10
    единственный в семье судит ОКРУЖАЮЩИЙ РЕПОЗИТОРИЙ, а не отчёт. Фикстура
    `fixtures/priyomka` проверяет отчёты и ловушки; её ловушка «здоровый отчёт →
    exit 0» без выключателя начинала бы краснеть у КАЖДОГО исполнителя, у
    которого в середине работы есть незапушенный коммит, — то есть почти всегда.
    Красная фикстура на здоровом коде — ровно та причина, по которой ворота
    обходят `--no-verify` (замер: 28 обходов из 56 срывов коммита). Поэтому
    сцепление разорвано явным флагом, а не тем, что гейт ослаблен.
    Выключатель ПЕЧАТАЕТ СЕБЯ в вердикте: в живом прогоне это видно сразу.
    """
    if os.environ.get("PRIYOMKA_BEZ_G10") == "1":
        return True, ("Г10 ОТКЛЮЧЁН переменной `PRIYOMKA_BEZ_G10=1` — окружающий "
                      "репозиторий НЕ судился. Это форма для фикстур; в живой "
                      "приёмке флага быть не должно")
    korni = repozitorii_zony(zona_stroka)
    stroki, krasnoe = [], []
    for koren in korni:
        d = _dolg_repozitoriya(koren)
        if d is None:
            stroki.append(f"{koren} — не git-репозиторий, пропущен")
            continue
        stroki.append(
            f"{koren.name} (ветка {d['vetka']}):\n"
            + (f"      невывезено {d['nevyvezeno']}  ← {d['kmd_nevyvezeno']}\n"
               if d["est_remote"] else
               "      невывезено НЕПРОВЕРЯЕМО — у репозитория нет ни одного удалённого "
               "(`git remote` пуст): вывозить некуда, значит и долга такого вида нет\n")
            + f"      вне git    {d['vne_git']}  ← {d['kmd_vne_git']}  (порог {PORG_VNE_GIT})\n"
            f"      невлитых   {len(d['nevlityh'])}  ← {d['kmd_nevlityh']}  (порог {PORG_NEVLITYH})"
            + (f"\n      невлитые поимённо: {', '.join(d['nevlityh'])}" if d["nevlityh"] else ""))
        if d["est_remote"] and d["nevyvezeno"] > 0:
            krasnoe.append(f"{koren.name}: невывезено {d['nevyvezeno']} — работа есть только "
                           f"на этом диске (`{d['kmd_nevyvezeno']}`); вывезти: "
                           f"`python3 _generator/tools/git_zona.py vyvezti`")
        if d["vne_git"] > PORG_VNE_GIT:
            krasnoe.append(f"{koren.name}: вне git {d['vne_git']} > {PORG_VNE_GIT} "
                           f"(`{d['kmd_vne_git']}`)")
        if len(d["nevlityh"]) > PORG_NEVLITYH:
            krasnoe.append(f"{koren.name}: невлитых веток {len(d['nevlityh'])} > "
                           f"{PORG_NEVLITYH} (`{d['kmd_nevlityh']}`)")

    slepota = ("не видит: чужие репозитории вне зоны · ветки только на origin · "
               "репозитории без удалённых (вывезенность непроверяема) · "
               "`git stash` · другие машины · чужие рабочие папки worktree")
    telo = "\n   ".join(stroki)
    if krasnoe:
        return False, (f"🔴 ПОРА ЗВАТЬ УБОРКУ — гейт судит РЕПОЗИТОРИЙ, а не тебя: долг ниже "
                       f"мог накопить любой заход, ты просто пришёл последним. "
                       f"Брака работы это НЕ означает.\n   "
                       + "\n   ".join(f"· {k}" for k in krasnoe)
                       + f"\n   {telo}\n   {slepota}")
    return True, f"{telo}\n   {slepota}"


KONTRAKTNAYA_ZONA_RE = re.compile(r'^-\s*\*?\*?ЗОНА[^:]*:\*?\*?\s*(.+)$', re.M)


def granicy_zony(tekst: str, khash: str):
    """Печать (НЕ гейт): пути коммита за пределами `## КОНТРАКТ ЗОНЫ`.

    Формат контракта неоднороден (Ф1/часть C1) — ложное красное здесь дороже
    пропуска, поэтому только печать для рук, не гейт.
    """
    m = KONTRAKTNAYA_ZONA_RE.search(tekst)
    if not m:
        return "строка «ЗОНА» в контракте не найдена — сверка границ пропущена"
    prefiksy = [p.strip('`').strip() for p in re.findall(r'`([^`]+)`', m.group(1))]
    if not prefiksy:
        return "в строке «ЗОНА» нет путей в backticks — сверка границ пропущена"
    r = subprocess.run(["git", "--no-optional-locks", "show", "--stat", "--format=", khash],
                        cwd=REPO, capture_output=True, text=True)
    if r.returncode != 0:
        return f"git show --stat {khash} упал — сверка границ пропущена"
    puti = [ln.split('|')[0].strip() for ln in r.stdout.splitlines() if '|' in ln]
    za_predelami = [p for p in puti if not any(p == pref or p.startswith(pref.rstrip('/') + '/')
                                                for pref in prefiksy)]
    if not za_predelami:
        return f"все пути коммита внутри зоны ({len(puti)} из {len(puti)})"
    return (f"ВНЕ зоны контракта: {', '.join(za_predelami)} "
            f"(зона по контракту: {', '.join(prefiksy)})")


def izvlech_vetku(tekst: str):
    """Ветка захода — из контракта зоны («…worktree add <имя> --branch <ветка>»).

    🔴 `[^\\s`]+`, а не `\\S+` — по той же оплаченной причине, что в
    `izvlech_zonu`: в контракте команда стоит в backticks без пробела перед
    закрывающим, и `\\S+` утащил бы backtick В СОСТАВ имени ветки. Имя с лишним
    символом не совпало бы ни с одной живой веткой, и вердикт печатался бы
    «ветки нет» на исправной работе.
    Резерв — checkout-режим захода, где `--branch` не встречается вовсе: там
    генератор пишет «обязано быть `<ветка>`».

    🔴 ХВОСТОВАЯ ПУНКТУАЦИЯ СРЕЗАЕТСЯ (заход `gejty-ne-tuda`, П3, ⚠). Первое
    `--branch` в файле — в СТАРТОВОМ СООБЩЕНИИ владельца, где команда стоит
    внутри фразы: «…worktree add kanon-put --branch zahod/kanon-put, затем
    чтение захода». Запятая уезжала В СОСТАВ имени, и печать жизни ветки
    честно сообщала «Ветки `zahod/kanon-put,` нет среди 20 проверяемых» — то
    есть вердикт о живой ветке подменялся вердиктом об опечатке разбора. В
    именах веток этого репозитория `,;:.` не встречается (`zahod/<слаг>`),
    поэтому срез хвостовой пунктуации ничего законного не портит.
    """
    m = re.search(r'--branch\s+([^\s`]+)', tekst)
    if m:
        return m.group(1).rstrip(",;:.")
    m = re.search(r'обязано быть\s+`([^`]+)`', tekst)
    return m.group(1).rstrip(",;:.") if m else None


def pechat_zhizni_vetki(vetka):
    """Печать (НЕ гейт): что делать с веткой принятого захода.

    🔴 ПОЧЕМУ ВЕРДИКТ, А НЕ БЕЗУСЛОВНАЯ СТРОКА `zakryt-vetku` (Ф0 захода
    `zhizn-vetki`, вопрос 3 — возражение к точке вызова). Приёмка переноса НЕ
    делает: Г0 (`check --zone`) судит ЧИСТОТУ рабочего дерева и зеленеет даже
    когда весь код захода остался на ветке — это болезнь, оплаченная ТРИЖДЫ
    (`storozh-vetok`, `dobivka-vetok` и блокер первого хода самого
    `zhizn-vetki`: канон и отчёт перенесены, код — нет). Значит в момент
    зелёных гейтов ветка захода ЕЩЁ НЕ перенесена, и готовая строка закрытия
    привела бы владельца к отказу — шум в 100 % случаев, а шумящую печать
    перестают читать (`Р31`). Поэтому печатается ВЕРДИКТ метрики:
      · зелёная  ⇒ готовая строка закрытия — ветка своё отработала;
      · красная  ⇒ ЧТО именно не перенесено + команда переноса.
    В таком виде печать сама ловит «перенос забыт», то есть закрывает причину,
    а не добавляет ещё одну строку в вывод.

    🔴 НЕ ЗАПУСКАЕТ ЗАКРЫТИЕ САМА. Приёмка идёт под аналитиком; удаление ветки
    в середине чужого прогона — не его дело (и `poteri` здесь read-only).
    """
    print("\n-- Жизнь ветки захода (печать, не гейт; ничего не удаляет) --")
    if not vetka:
        print("   ветка захода не найдена в контракте зоны — сверка пропущена")
        return
    r = subprocess.run(
        ["python3", str(TOOLS / "git_zona.py"), "poteri", "--branch", vetka],
        cwd=REPO, capture_output=True, text=True,
    )
    vyvod = (r.stdout.strip() + "\n" + r.stderr.strip()).strip()
    if "нет среди" in vyvod or "текущая ветка" in vyvod:
        print(f"   `{vetka}`: {vyvod.splitlines()[0] if vyvod else '(вывод пуст)'}")
        return
    if r.returncode == 0:
        print(f"   ✅ `{vetka}` — метрика зелёная: содержимое ветки никуда не пропадёт.")
        print("   Ветка своё отработала — закрыть её (надгробие + снос папки, "
              "обратимо):")
        print(f"     python3 _generator/tools/git_zona.py zakryt-vetku --branch {vetka}")
        return
    print(f"   🔴 `{vetka}` — метрика КРАСНАЯ: работа захода ещё НЕ перенесена. "
          "Закрывать нельзя,\n      сперва перенос — иначе повторится "
          "«приёмка привезла отчёт без кода» (оплачено трижды):")
    for stroka in vyvod.splitlines():
        print(f"      {stroka}")


