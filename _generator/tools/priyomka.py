#       невлитая ветка и грязный файл лежат на диске и никуда не денутся,
#       невывезенный коммит умирает вместе с диском. Порога у необратимого нет.
#   вне git     > 15 → красное. Здоровое измеренное — 11 (файлы-заходы, дневники
#       приёмки, удаления, ждущие коммита приёмки: они грязны ЗАКОННО, их
