#!/usr/bin/env python3
"""ГЕНЕРАТОР ХЭНДОФФА — собирает вход в следующую сессию из ПАРАМЕТРОВ.

    python3 _generator/tools/sdelat_handoff.py <папка-арки> \
        --chto-delaem "первый узел: дек → вёрстка" \
        --gde "Cowork, эта же папка" \
        --pervyj-hod "интервью по параметрам лекции" \
        --gotovo "паспорт лекции существует и сборка идёт по ролям" \
        --ne-delat "не строить дерево целиком; не писать канон прозой" \
        --chislo "455 записей из 1379 (33%)" \
        --dolg "H3 не перезапущен" --dolg "style/ не в репозитории"

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ (причина дороже кода — не удалять).

Владелец: *«я часто говорю: сделай хэндофф… но из-за проблем диктовки или моих
формулировок он искажается. Собирается не так, как хочется. Я запускаю новую
сессию, она очень долго работает, делает что-то не то»*.

Хэндофф, написанный прозой, — это пересказ по памяти в конце длинной сессии,
когда аналитик устал сильнее всего. Отсюда два дефекта, оба оплаченные:
хэндофф 31.07 утверждал, что ночные заходы отработали, — они не запускались
(поймано первым же грепом следующей сессии); и он же не называл, ГДЕ запускать
работу, из-за чего вопрос «где я её запускаю» пришлось задавать голосом.

Лечение: хэндофф собирается из параметров, и **обязательные поля нельзя
пропустить** — без них скрипт не соберёт файл. Плюс в него ВШИТЫ два интервью,
которых владелец требовал прямо:

  · перед сборкой хэндоффа — проговорить, что делаем дальше, вопросами да/нет;
  · в начале следующей сессии — проговорить план и первые шаги, тоже да/нет.

Только stdlib.
"""
import argparse
import subprocess
import sys
from datetime import datetime, timedelta
from pathlib import Path


def zhivoe_chislo(arka: Path) -> str:
    """Снять состояние арки командой, а не памятью (KONSTITUCIYA §10)."""
    try:
        out = subprocess.run(
            ["bash", "-lc",
             f"cd {arka!s} && ls *.md 2>/dev/null | wc -l && "
             f"(grep -c '^### ' UROKI-FABRIKE.md 2>/dev/null || echo 0) && "
             f"(grep -c '^ВЕРДИКТ: ' UROKI-FABRIKE.md 2>/dev/null || echo 0)"],
            capture_output=True, text=True, timeout=20).stdout.split()
        return f"файлов `.md` в арке **{out[0]}** · уроков **{out[1]}**, из них с вердиктом **{out[2]}**"
    except Exception:
        return "*(состояние снять не удалось — снять руками командой)*"


def sostoyanie_vetok() -> str:
    """Строка состояния веток для хэндоффа — снятая КОМАНДОЙ, не памятью.

    🔴 ЗАЧЕМ (часть B захода `zhizn-vetki`). Без неё следующая сессия начинает
    вслепую: ветки заводятся заходом и не закрываются никогда (замер 04.08 —
    18 веток при пяти живых), а хэндофф — единственный вход, который она
    читает целиком. Число в файле — это снимок (`KONSTITUCIYA §10`), поэтому
    рядом с ним печатается и команда, которой оно пересчитывается, и дата
    данных (её ставит вызывающий, тем же абзацем, что у `zhivoe_chislo`).
    """
    tools = Path(__file__).resolve().parent
    gz = tools / "git_zona.py"
    if not gz.is_file():
        return "*(состояние веток снять не удалось: `git_zona.py` не найден)*"
    try:
        r = subprocess.run(["python3", str(gz), "poteri"], cwd=tools.parent.parent,
                           capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return "*(состояние веток снять не удалось — снять руками: `git_zona.py poteri`)*"
    vyvod = (r.stdout or "") + (r.stderr or "")
    ohvat = [l.strip() for l in vyvod.splitlines() if l.strip().startswith("Охват: проверено")]
    poteri = [l.strip().lstrip("· ") for l in vyvod.splitlines()
              if l.strip().startswith("· ") and "пропадёт файлов" in l]
    vsego = "?"
    if ohvat:
        chasti = ohvat[0].split()
        if len(chasti) > 4:
            vsego = chasti[4]
    stroki = [f"веток открыто **{vsego}**, из них с НЕПЕРЕНЕСЁННОЙ работой "
              f"**{len(poteri)}**"]
    for p in poteri:
        stroki.append(f"- 🔴 {p.split(';')[0].strip()}")
    stroki.append("")
    stroki.append("Пересчитать: `python3 _generator/tools/git_zona.py poteri` · "
                  "подмести отработавшие: "
                  "`python3 _generator/tools/git_zona.py zakryt-vetku --vse-zelenye`")
    return "\n".join(stroki)


def main():
    ap = argparse.ArgumentParser(description="Собрать хэндофф из параметров")
    ap.add_argument("arka")
    ap.add_argument("--chto-delaem", required=True, help="задача следующей сессии, одной фразой")
    ap.add_argument("--gde", required=True, help="ГДЕ запускать: Cowork / Claude Code / терминал, какая папка")
    ap.add_argument("--pervyj-hod", required=True, help="первое действие, конкретное")
    ap.add_argument("--gotovo", required=True, help="критерий готовности, который может ПРОВАЛИТЬСЯ")
    ap.add_argument("--chislo", default="", help="сколько инцидентов корпуса закрывает эта работа")
    ap.add_argument("--ne-delat", default="", help="чего НЕ делать, через `;`")
    ap.add_argument("--reshено", "--resheno", dest="resheno", default="",
                    help="решения, не подлежащие пересмотру, через `;`")
    ap.add_argument("--dolg", action="append", default=[], help="долг (можно повторять)")
    ap.add_argument("--grabli", action="append", default=[], help="грабли сессии (можно повторять)")
    ap.add_argument("--dalshe", default="",
                    help="что за СЛЕДУЮЩЕЙ сессией — её задача формулируется в ней же")
    ap.add_argument("--imya", default="",
                    help="своё имя файла, если HANDOFF-<завтра>.md уже занят")
    ap.add_argument("--zamenit", action="store_true",
                    help="пересобрать поверх файла, СГЕНЕРИРОВАННОГО этим же скриптом "
                         "(рукописный файл не тронет — в нём может лежать знание)")
    args = ap.parse_args()

    arka = Path(args.arka).resolve()
    if not arka.is_dir():
        sys.exit(f"❌ нет папки арки: {arka}")

    zavtra = (datetime.now() + timedelta(days=1)).strftime("%Y-%m-%d")
    segodnya = datetime.now().strftime("%Y-%m-%d")
    out = arka / (args.imya or f"HANDOFF-{zavtra}.md")
    MARKER = "<!-- собран sdelat_handoff.py -->"
    if out.exists():
        moj = MARKER in out.read_text(encoding="utf-8", errors="ignore")
        if not (args.zamenit and moj):
            sys.exit(
                f"❌ {out.name} уже есть. Удалять не буду: в нём может лежать не перенесённое знание.\n"
                + ("   Он собран этим же скриптом — пересобрать: добавь --zamenit.\n" if moj else
                   "   Он написан РУКАМИ. Перечитай, перенеси нужное и убери сам; --zamenit его не тронет.\n"))

    def spisok(s: str) -> list[str]:
        return [x.strip() for x in s.split(";") if x.strip()]

    # Стартовая строка — то, что владелец копирует в НОВЫЙ чат. Требование
    # владельца 03.08: «каждый раз надо выписывать очень чётко короткий вводный
    # текст про то, где мы сейчас находимся и что мы делаем… сказать чату, где он
    # должен поискать информацию». Без неё новый чат начинает с угадывания.
    try:
        rel = out.relative_to(Path.cwd())
    except ValueError:
        rel = out
    start = (f"Открой файл {rel} — это твой вход, читай его ПЕРВЫМ и целиком. "
             f"Дальше — то, что он называет поимённо; проект сверх этого не изучай. "
             f"Задача: {args.chto_delaem}. "
             f"🔴 Работу НЕ начинай, пока не задашь мне четыре вопроса из раздела "
             f"«ПЕРВЫЙ ХОД» и не получишь ответы.")

    L = [f"---", f"tab: Хэндофф — вход в сессию {zavtra}", "status: handoff", "poryadok: 0", "---",
         MARKER, "",
         f"# ХЭНДОФФ {segodnya} → {zavtra}", "",
         "## 🔴 СТАРТОВАЯ СТРОКА — скопировать в новый чат первым сообщением", "",
         "```", start, "```", "",
         "*Одна строка вместо пересказа: новый чат не должен угадывать, где лежит "
         "контекст и что делать. Если работа переезжает в другой проект — путь выше "
         "остаётся абсолютным ориентиром, назови его целиком.*", "",
         "> Собран `sdelat_handoff.py` из параметров, а не написан прозой по памяти. "
         "Причина — в докстринге скрипта: хэндофф, написанный в конце длинной сессии, "
         "врёт о состоянии и забывает назвать, где запускать работу.", "",
         "## 🔴 ПЕРВЫЙ ХОД СЛЕДУЮЩЕЙ СЕССИИ — ИНТЕРВЬЮ, а не работа", "",
         "Прежде чем что-либо делать, задай владельцу эти вопросы и получи «да» или поправку. "
         "**Формат — вопрос, на который можно ответить да/нет** (требование владельца: "
         "*«должно быть в виде интервью, в смысле в виде поставленного вопроса, на который "
         "я могу ответить да или нет»*).", "",
         f"1. Задача сессии — **{args.chto_delaem}**. Верно?",
         f"2. Первый ход — **{args.pervyj_hod}**. Начинаем с него?",
         f"3. Готово — это когда **{args.gotovo}**. Такой критерий принимаем?",
         "4. Что-то изменилось со вчера, чего я не знаю?", "",
         "**Пока на все четыре нет ответа — работу не начинать.** Цена нарушения названа "
         "владельцем: *«я запускаю новую сессию, она очень долго работает, делает что-то не то»*.", "",
         "## ГДЕ ЭТО ЗАПУСКАТЬ", "", f"**{args.gde}**", "",
         "## ЗАДАЧА", "", f"**{args.chto_delaem}**", "",
         f"**Критерий готовности (может ПРОВАЛИТЬСЯ):** {args.gotovo}", ""]

    if args.chislo:
        L += [f"**Сколько закрывает:** {args.chislo}. "
              "Шаг без названного числа — надежда, а не шаг.", ""]

    L += ["## СОСТОЯНИЕ АРКИ — снято командой в момент сборки", "",
          zhivoe_chislo(arka), "",
          "**Ветки:** " + sostoyanie_vetok(), "",
          f"*Дата данных: {segodnya}. Числа в этом файле — снимок; живое состояние "
          f"снимается командами из `KARTA-ZNANIYA.md §1`.*", ""]

    if args.resheno:
        L += ["## 🔴 РЕШЕНО РАНЬШЕ — не обсуждать заново", ""]
        L += [f"{i}. {x}" for i, x in enumerate(spisok(args.resheno), 1)] + [""]

    if args.ne_delat:
        L += ["## ЧЕГО НЕ ДЕЛАТЬ", ""] + [f"- {x}" for x in spisok(args.ne_delat)] + [""]

    if args.grabli:
        L += ["## ГРАБЛИ, ОПЛАЧЕННЫЕ В ЭТОЙ СЕССИИ", ""] + [f"- {x}" for x in args.grabli] + [""]

    if args.dolg:
        L += ["## ДОЛГИ", ""] + [f"- {x}" for x in args.dolg] + [""]

    if args.dalshe:
        L += ["## ЧТО ЗА ЭТОЙ СЕССИЕЙ — задание для той, что будет после", "",
              args.dalshe, "",
              "*Формулируется В следующей сессии, а не сейчас: сейчас про неё известно "
              "меньше, чем будет известно тогда. Здесь — только направление, чтобы оно "
              "не потерялось.*", ""]

    L += ["## 🔴 ПЕРЕД СЛЕДУЮЩИМ ХЭНДОФФОМ — тоже интервью", "",
          "Закрывая ту сессию, **до** сборки хэндоффа проговори с владельцем, что делаем "
          "дальше, и получи подтверждение. Хэндофф собирается ПОСЛЕ этого разговора и по "
          "его результатам, а не вместо него.", "",
          "Порядок закрытия сессии целиком:", "",
          "```",
          "1. python3 _generator/tools/zakryt_sessiyu.py <арка>   # выгрузка транскрипта, 0 токенов",
          "2. разнести выгрузку по дневнику и домам, ответить на все вопросы владельца",
          "3. поставить в дневнике отсечку <!-- РАЗНЕСЕНО ДО СЮДА: ГГГГ-ММ-ДД -->",
          "4. интервью с владельцем: что делаем дальше (вопросы да/нет)",
          "5. python3 _generator/tools/sdelat_handoff.py <арка> --chto-delaem ... --gde ...",
          "```", "",
          "---",
          f"*Собран {segodnya}. Карта знания — `KARTA-ZNANIYA.md`. Дневник — `SESSIYA.md`.*"]

    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"✅ {out}")
    print("\n🔴 СТАРТОВАЯ СТРОКА — скопируй её в новый чат первым сообщением:\n")
    print(start)
    print()
    print("🔴 Зарегистрируй его тем же ходом:")
    print(f"   python3 _generator/tools/register_doc.py "
          f"{out.relative_to(Path.cwd()) if str(out).startswith(str(Path.cwd())) else out} "
          f'"Хэндофф в сессию {zavtra}"')


if __name__ == "__main__":
    main()
