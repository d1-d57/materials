def cmd_volna(папка):
    """Всё накопившееся по ВСЕЙ арке, сгруппированное ПО ДОМАМ.

    🔴 Это ВХОД В РАБОТУ, а не отчёт о ней. Владелец приходит раз в неделю с
    вопросом «что накопилось» и должен увидеть не 37 файлов, а список по домам —
    и рядом с каждым то, ЧЕМ эту порцию закрывать.
    """
    папка = Path(папка)
    if not папка.is_dir():
        print(f"❌ Папки нет: {папка}", file=sys.stderr)
        return 2
    корень = папка.resolve().parent.parent.parent

    файлы = sorted(папка.glob("kod_*.md"))
    уроки_файл = папка / "UROKI-FABRIKE.md"
    if уроки_файл.is_file():
        файлы.append(уроки_файл)

    все, брака = [], 0
    for f in файлы:
        _, список = наблюдения(f)
        брака += len([н for н in список if н["вид"] == "брак"])
        все += живые(список)

    без = [н for н in все if not н["метка"]]
    по_домам, по_классам = {}, {}
    for н in без:
        кл, _p = класс_адреса(н, папка.resolve(), корень)
        по_классам.setdefault(кл, []).append(н)
        ключ = ("владелец" if н["владелец"]
                else (н["дом"] or "— адрес не назван —"))
        по_домам.setdefault(ключ, []).append((кл, н))

    print(f"ВОЛНА НАКОПИВШЕГОСЯ — {папка}")
    print(f"файлов просмотрено: {len(файлы)} · наблюдений всего: {len(все)} · "
          f"доставлено: {len(все) - len(без)} · ЖДУТ: {len(без)}\n")

    print("── ПО ДОМАМ (сначала то, что чинится доставкой) " + "─" * 40)
    порядок = {кл: i for i, кл in enumerate(КЛАССЫ)}
    for дом, записи in sorted(по_домам.items(),
                              key=lambda kv: (порядок.get(kv[1][0][0], 9),
                                              -len(kv[1]))):
        кл = записи[0][0]
        видов = sorted({н["вид"] for _, н in записи})
        print(f"\n  {дом}")
        print(f"    ждут: {len(записи)} · {кл} · виды: {', '.join(видов)}")
        print(f"    чем закрывать: {ЧЕМ_ЗАКРЫВАТЬ[кл]}")
        for _, н in записи[:4]:
            print(f"      · {н['файл'].name}#{н['номер']}: "
                  f"{_обрез(н['заголовок'], 84)}")
        if len(записи) > 4:
            print(f"      … и ещё {len(записи) - 4}")

    print("\n── ИТОГ ПО КЛАССАМ " + "─" * 60)
    for кл in КЛАССЫ:
        свои = по_классам.get(кл, [])
        if свои:
            print(f"  {кл:<22} {len(свои):>4}   {ЧЕМ_ЗАКРЫВАТЬ[кл]}")
    if брака:
        print(f"\n  ⚠ строк `ДОСТАВЛЕНО:` без своего `ДОМ:` (проза, не запись): "
              f"{брака} — на счёт не влияют, но глазами проверить стоит")
    return 0


