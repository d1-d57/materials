def _блок_пункта(н, заход, сегодня):
    """Текст, который уезжает в дом: пункт ДОСЛОВНО плюс строка-метка.

    🔴 ЗАГОЛОВОК — ЧЕТВЁРТОГО УРОВНЯ (`####`), И ЭТО НЕСУЩЕЕ. Цена оплачена
    прогоном 07.08: заголовок `### ` сделал каждый доставленный пункт УРОКОМ в
    глазах `check_uroki.py` (`HEADING = ^### (.+)$`), тот потребовал у него
    `ЦЕНА:` — и гейт уроков покраснел (rc=1) на 27 верных доставках, заблокировав
    коммит. У пункта очереди цены нет по форме: его порог — адрес, а не цена.
    `####` не совпадает с признаком урока, и дом уроков остаётся домом уроков.

    🔴 ЗАГОЛОВОК НЕ ПОВТОРЯЕТ ПЕРВУЮ СТРОКУ ПУНКТА, и это не косметика. У урока
    заголовок — отдельное поле (`### N. …`), и тело берётся с `тело[1:]`. У
    пункта очереди отдельного заголовка нет: первая строка и есть находка,
    часто длиной в абзац. Сложи её в заголовок и оставь в теле — содержание
    удвоится в доме; обрежь её под заголовок — доставка перестанет быть
    дословной, а дословность здесь единственная гарантия, что при схлопывании
    ничего не подменено. Поэтому заголовок несёт ТОЛЬКО адрес-источник, а тело
    едет целиком, байт-в-байт.
    """
    тело = [s for s in н["тело"] if not ПОЛЕ_ДОСТ.match(s)]
    while тело and not тело[-1].strip():
        тело.pop()
    тело = сбалансировать_ограду(тело)
    return (["", f"#### {заход}#{н['номер']}", ""]
            + тело + [f"ДОСТАВЛЕНО: {заход}#{н['номер']} · {сегодня}"])


