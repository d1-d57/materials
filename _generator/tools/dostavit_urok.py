def класс_адреса(н, арка_папка, корень):
    """Один из `КЛАССЫ` — и от него зависит СУДЬБА записи, а не только печать.

    🔴 «Дома нет» и «решение за человеком» — разные вещи, и заход требовал их
    развести. Первое чинится тем, что дом заводят; второе — тем, что человек
    принимает решение. Слить их в «недоставлено» — значит потерять ровно тот
    класс, который сегодня потерялся весь.
    """
    if н.get("владелец"):
        return "решение за человеком", None
    if not н.get("дом"):
        return "адрес не разобран", None
    p, база = резолв(н["дом"], арка_папка, корень)
    if p is None:
        # `резолв` проверяет `is_file()`; папка-адрес («дом — следующий заход
        # очереди») туда не попадает, а это законный живой случай.
        for б in (арка_папка, корень):
            if (Path(б) / н["дом"]).is_dir():
                return "дом — папка", None
        return "дома нет", None
    if p.suffix == ".md" and указатель(p):
        return "дом — указатель", p
    try:
        p.resolve().relative_to(Path(корень).resolve())
    except ValueError:
        # 🔴 ДОМ ЗА ПРЕДЕЛАМИ ЭТОГО РЕПОЗИТОРИЯ. В корпусе такие адреса есть —
        # абсолютным путём в соседний репозиторий `disciplina/`. Файл существует,
        # путь резолвится, доставка прошла бы успешно и записала бы в ЧУЖОЙ
        # проект, чей коммит делает не этот заход: содержание уехало, а метка
        # в источнике осталась здесь — расхождение, которое никто не увидит,
        # пока чужой репозиторий не откатят.
        return "дом вне репозитория", p
    if p.suffix in (".py", ".sh"):
        # 🔴 ДОСТАВКА В ИСПОЛНЯЕМЫЙ КОД ЛОМАЕТ ЕГО, И МОЛЧА. Доставка дописывает
        # markdown в КОНЕЦ файла-дома; в конце `.py` это `SyntaxError` — проверено
        # прогоном на копии `check_termin.py`. По обоим машинным признакам такой
        # дом «живой» (путь резолвится, файл существует), поэтому до этой
        # проверки он попадал в класс «дом есть» и доставка бы прошла успешно.
        # На живой арке так адресованы 15 записей: пятнадцать сломанных
        # инструментов фабрики за один прогон миграции.
        # Что делать с такой записью, решает человек: урок про инструмент едет
        # либо в докстринг (руками, осмысленно), либо в канон рядом.
        return "дом — исполняемый код", p
    return "дом есть", p


