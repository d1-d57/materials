#!/usr/bin/env python3
"""КАНАЛ НАБЛЮДЕНИЙ — транспорт наблюдения из места, где оно записано, в его ДОМ.

    python3 _generator/tools/dostavit_urok.py --plan     <файл>
    python3 _generator/tools/dostavit_urok.py --dostavit N <файл>
    python3 _generator/tools/dostavit_urok.py --gejt     <файл> [--zakrytie]
    python3 _generator/tools/dostavit_urok.py --volna    <папка-арки>

НАБЛЮДЕНИЕ — одно понятие на два вида записи, потому что путь у них один:
разобрать → назвать дом → доставить дословно → пометить → покраснеть на
недоставленном. Различаются они ТОЛЬКО полем вида и тем, чем записаны:

    вид `urok`   — `### N.` + `ЦЕНА:` + `ВЕРДИКТ:` в `UROKI-FABRIKE.md`,
                   дом стоит внутри вердикта прозой;
    вид `punkt`  — пункт очереди в `## ВОПРОСЫ` файла-захода `kod_*.md`,
                   дом стоит отдельным полем `ДОМ:`, доставка — полем `ДОСТАВЛЕНО:`.

Вид определяется по имени файла и НЕ требуется в команде: `UROKI-FABRIKE.md` →
`urok`, `kod_*.md` → `punkt`. Прежние вызовы двери уроков работают дословно как
работали — это условие расширения, а не удобство (см. ниже).

🔴 ПОЧЕМУ ЭТО РАСШИРЕНИЕ, А НЕ ВТОРОЙ ИНСТРУМЕНТ. Второй парсер той же вещи в
этом репозитории уже расходился с первым, и расхождение было видно только на
новом файле. Здесь один разбор, один резолв дома, один формат метки, один гейт.

🔴 ЧЕМ РАЗБОР ПУНКТА ОТЛИЧАЕТСЯ ОТ РАЗБОРА `priyomka.parse_ochered`, И ПОЧЕМУ.
`priyomka` ищет пункт по НОМЕРУ в начале строки (`^(\\d+)\\.`). Живой замер по
37 файлам арки `2026-08-05_faza-lenty`: строк `ДОСТАВЛЕНО: нет` вне цитат — 199,
парсер по номеру находит 127. **Теряется 72 из 199, то есть больше трети.**
Причины, все три подтверждены на файлах:
  * пункт пронумерован жирным (`**2. ✅ ОТВЕЧЕН ВЛАДЕЛЬЦЕМ…**`) или не имеет
    номера вовсе — `kod_etap-20-i-perenos.md` даёт 9 пунктов и 0 разобранных;
  * пункты живут в секции с другим именем — `## ВТОРАЯ ПАЧКА ВОПРОСОВ` в
    `kod_evals.md` и `kod_nochnaya-sborka.md`, это 18 пунктов, невидимых для
    поиска по точному имени `ВОПРОСЫ`;
  * шапка-подсказка секции несёт ОБРАЗЕЦ формы с `ДОСТАВЛЕНО: нет` внутри
    blockquote, и он считается пунктом — 72 ложных строки на 37 файлов.
Поэтому здесь якорь пункта — не номер, а САМА ПАРА ПОЛЕЙ `ДОМ:` + `ДОСТАВЛЕНО:`:
номер в этих файлах пишут как придётся, а пару полей — всегда, она и есть форма.
Строки внутри blockquote (`>`) не считаются никогда: это шапка, а не запись.

🔴 ГЕЙТ РАЗЛИЧАЕТ ДВА СОСТОЯНИЯ НЕДОСТАВЛЕННОГО, И ЭТО НЕСУЩЕЕ РАЗЛИЧЕНИЕ.
«Не доставлено, хотя дом есть» чинится одной командой — краснеет всегда.
«Дома нет» и «решение за человеком» (`ДОМ: владелец`) командой не чинятся:
краснеть на них каждую приёмку — значит красить каждый заход, а такой гейт
отключают первым. Они краснеют только на `--gejt --zakrytie`, то есть при
закрытии арки, когда «потом разберём» кончилось. Без этого различения гейт
на живой арке не может стать зелёным НИКОГДА: пунктов `ДОМ: владелец` больше
половины, и доставить их некуда по определению.

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ (причина дороже кода — не удалять).

`UROKI-FABRIKE.md` объявлен «локальной памятью арки, ephemeral»: при закрытии
арка умирает, а уроки обязаны уехать в канон. Механизма переезда не было —
была прозаическая инструкция «разнести по домам руками». По закону
`KONSTITUCIYA §11` такое правило нарушается молча, и оно нарушалось: из ~12
уроков трёх суток до канона дошёл один (цена записана в шапке `check_uroki.py`).
Здесь переезд становится командой, а «не разнесли» — красным кодом возврата.

🔴 ЧТО ЭТОТ ИНСТРУМЕНТ НЕ ДЕЛАЕТ (клауза 3 гейта — говорить о своих слепых зонах).
  * Не судит, НАСТОЯЩАЯ ли цена и честен ли вердикт. Он переносит текст дословно;
    правду ловит владелец и свежая сессия.
  * Не понимает `§раздел` в адресе дома: урок дописывается в КОНЕЦ дома, а не в
    названную секцию. Секцию выбирает человек при консолидации.
  * Не чинит адрес. Дома нет на диске — отказ с названной причиной; файл наугад
    не создаётся, потому что придуманный дом хуже отсутствующего.

🔴 ПОЧЕМУ КЛЮЧ `ДОСТАВЛЕНО-В-ДОМ:`, А НЕ `ДОСТАВЛЕНО:`. В живом файле арки
`2026-08-05_faza-lenty` 37 уроков из 60 УЖЕ несут строку `ДОСТАВЛЕНО: <заход>#<N>`,
и она значит ПРОТИВОПОЛОЖНОЕ — «эта запись ПРИЕХАЛА сюда из ВОПРОСОВ такого-то
захода» (конвенция `## ВОПРОСЫ` в шаблоне захода: аналитик ставит одну и ту же
метку и в источнике, и в доме). Ни один из этих 37 в канон не доставлен. Возьми
гейт тот же ключ — и он промолчал бы на 37 уроках из 60, объявив доставленным то,
чего не было. Ложно-зелёный гейт опаснее отсутствующего, поэтому ключи разведены.

🔴 МЕТКА И СОДЕРЖАНИЕ — ОДНИМ ХОДОМ, И ПОРЯДОК НЕСУЩИЙ. Сначала пишется ДОМ,
только потом метка в урок. Оборвись работа между ходами — получится содержание
без метки: гейт останется КРАСНЫМ, то есть ошибка в безопасную сторону. Обратный
порядок дал бы метку без содержания — ровно тот ложно-зелёный Г7, который в этом
репозитории уже оплачен.

Разбор уроков берётся у `check_uroki.py` (`lessons_in`), а не пишется заново:
второй парсер той же вещи разойдётся с первым, и расхождение будет видно только
на новом файле. Здесь поверх его разбора — ровно три вещи, которых он не знает:
```-забор, адрес дома и метка доставки.

Только stdlib. Код возврата: 0 — сделано/чисто, 1 — гейт красный, 2 — отказ.
"""
import argparse
import re
import sys
from datetime import date
from pathlib import Path

# Ядро «что такое урок» живёт у ГЕЙТА, а не здесь — см. шапку.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_uroki  # noqa: E402

МЕТКА = "ДОСТАВЛЕНО-В-ДОМ:"
РАЗДЕЛ = "## Уроки арок, доставленные `dostavit_urok.py`"
РАМКА = ("> Дословные записи из `UROKI-FABRIKE.md` закрывающихся арок — голос "
         "источника, не редактора. Консолидирует их человек: переносит в нужный "
         "раздел, сливает с существующим правилом, слабую формулировку "
         "переписывает. До консолидации они лежат здесь, а не пропадают вместе с аркой.\n"
         "> 🔴 **Задачами борда они не становятся сами.** Вердикт урока часто "
         "содержит невыполненную работу, но чекбокса у неё здесь нет и по скану "
         "борда её не видно: пункт `- [ ]` заводит человек при консолидации.")

# Адрес дома стоит в ВЕРДИКТЕ и написан четырьмя разными оборотами — это живой
# текст, а не поле формы. Словарь снят с корпуса 60 уроков; что им не
# разбирается, печатается строкой «адрес НЕ разобран», а не пропускается молча.
МАРКЕР = re.compile(r"(?:Дом\s*[—–-]|[Вв]писан[оаы]?\s*→|[Зз]аписан[оаы]?\s+в"
                    r"|[Вв]писать\s+в|[Вв]писано\s+в)")
ТОКЕН = re.compile(r"`([^`]+)`")
ЗАГОЛОВОК = re.compile(r"^(\d+)\.\s*(.+)$")
ЦЕНА = re.compile(r"^\*{0,2}ЦЕНА(?!\w)")
ВЕРДИКТ = re.compile(r"^\*{0,2}ВЕРДИКТ(?!\w)")


def _строки(путь):
    return Path(путь).read_text(encoding="utf-8").splitlines()


def в_заборе(строки):
    """Номера строк (1-based) внутри ```-забора.

    🔴 Зачем это здесь. В шапке каждого `UROKI-FABRIKE.md` лежит ОБРАЗЕЦ формы
    урока — `### N. <что произошло>` / `ЦЕНА:` / `ВЕРДИКТ:` — внутри забора.
    Греп-гейты шапки его считают, и все три сходятся (61/61/61) именно потому,
    что образец несёт и цену, и вердикт: они сходятся, не видя, что считают.
    Инструмент, взявший это число за охват, никогда не досчитает до 100 %.
    """
    внутри, res = False, set()
    for n, s in enumerate(строки, 1):
        if s.lstrip().startswith("```"):
            внутри = not внутри
            res.add(n)
            continue
        if внутри:
            res.add(n)
    return res


def дом_из(вердикт):
    """Путь дома из строки ВЕРДИКТА, либо None — адрес не разобран."""
    m = МАРКЕР.search(вердикт)
    if not m:
        return None
    for токен in ТОКЕН.findall(вердикт[m.end():]):
        # `RUKOVODSTVO-zahodami.md §4` — номер раздела живёт ВНУТРИ бэктиков;
        # инструмент секций не понимает (см. шапку), поэтому отрезает.
        кандидат = re.split(r"\s*§", токен)[0].strip().rstrip(",;")
        if "/" in кандидат or кандидат.endswith((".md", ".py", ".sh")):
            return кандидат
    return None


def вид_дома(дом):
    """канон · инструмент · скилл — они ведут себя по-разному (§2.1 захода)."""
    if дом.endswith((".py", ".sh")):
        return "инструмент"
    if дом.startswith("disciplina/") or "/skills/" in дом:
        return "скилл"
    return "канон"


def резолв(дом, арка_папка, корень):
    """(Path, имя базы) — либо (None, None). Две базы, потому что база не объявлена.

    🔴 В наших документах относительный путь не говорит, откуда он считается:
    в одном файле соседствуют `../../docs/KARTA.md` (от папки арки) и
    `_studio/zhurnal/…` (от корня репозитория). Чекер, написанный по одной базе,
    даёт списки почти целиком ложные — это уже измерено (урок 52 арки
    `faza-lenty`: 22 «пропажи» от одной базы и 24 от другой, обе ложные).
    Поэтому пробуем обе и ПЕЧАТАЕМ, какая сработала.
    """
    # 🔴 `<эта арка>` — НЕ ОПЕЧАТКА, А КОНВЕНЦИЯ ШАБЛОНА. Шапка секции
    # `## ВОПРОСЫ` в каждом файле-заходе прямо говорит: «для урока фабрике дом
    # почти всегда `<эта арка>/UROKI-FABRIKE.md`», и исполнители пишут этот
    # адрес дословно — на живой арке так записаны 9 находок. Дом при этом
    # существует; не подставить имя папки — значит объявить «дома нет» там,
    # где дом назван ровно так, как велел шаблон.
    дом = re.sub(r"^<\s*эта\s+арка\s*>/", f"{Path(арка_папка).name}/", дом)
    # Третья база — `_studio/zhurnal/`: в корпусе 4 адреса записаны от неё
    # (`2026-08-05_faza-lenty/UROKI-FABRIKE.md`). Причина та же, по которой баз
    # изначально две: база в наших документах не объявлена, и перечислить её
    # честнее, чем считать такой адрес битым. Какая база сработала — печатается.
    журнал = Path(корень) / "_studio" / "zhurnal"
    for база, имя in ((арка_папка, "арка"), (корень, "корень"), (журнал, "журнал")):
        p = (Path(база) / дом)
        try:
            if p.is_file():
                return p, имя
        except OSError:
            continue
    return None, None


def указатель(p):
    """Файл-указатель («… → ПЕРЕЕХАЛ») — дом, из которого содержание уехало.

    После выноса `_meta` четыре канонных файла `_studio/docs/kak-delat/` стали
    редиректами. Адрес урока туда РАЗБИРАЕТСЯ и файл СУЩЕСТВУЕТ — то есть по
    обоим машинным признакам дом «живой», а содержания там нет. Доставка в
    редирект тихо кладёт урок мимо канона; поэтому это отдельный вид отказа.
    """
    первая = (p.read_text(encoding="utf-8").splitlines() or [""])[0]
    return первая.startswith("# ") and первая.rstrip().endswith("ПЕРЕЕХАЛ")


def уроки(путь):
    """Разбор файла уроков. Список словарей, по одному на настоящий урок."""
    путь = Path(путь)
    строки = _строки(путь)
    забор = в_заборе(строки)
    сырые = check_uroki.lessons_in(путь)          # авторитетный разбор гейта
    начала = [l["line"] for l in сырые] + [len(строки) + 1]

    итог = []
    for i, l in enumerate(сырые):
        if l["line"] in забор:                    # образец формы — не урок
            continue
        тело = строки[l["line"] - 1:начала[i + 1] - 1]
        while тело and not тело[-1].strip():
            тело.pop()
        m = ЗАГОЛОВОК.match(l["title"])
        вердикт = next((s for s in тело if ВЕРДИКТ.match(s)), "")
        дом = дом_из(вердикт) if вердикт else None
        итог.append({
            "номер": int(m.group(1)) if m else None,
            "заголовок": m.group(2) if m else l["title"],
            "строка": l["line"],
            "конец": l["line"] + len(тело) - 1,
            "тело": тело,
            "цена": next((s for s in тело if ЦЕНА.match(s)), ""),
            "вердикт": вердикт,
            "дом": дом,
            "метка": any(s.startswith(МЕТКА) for s in тело),
        })
    return итог


def контекст(путь):
    """(папка арки, корень репозитория) для резолва домов."""
    арка = Path(путь).resolve().parent
    return арка, арка.parent.parent.parent


# ── ВИД `punkt`: пункт очереди из `## ВОПРОСЫ` файла-захода ─────────────────
ПОЛЕ_ДОМ = re.compile(r"^\s*(?:[-*+]\s+)?\*{0,2}ДОМ:\*{0,2}\s*(.+?)\s*$")
ПОЛЕ_ДОСТ = re.compile(r"^\s*(?:[-*+]\s+)?\*{0,2}ДОСТАВЛЕНО:\*{0,2}\s*(.+?)\s*$")
НОМЕР_ПУНКТА = re.compile(r"^\s*\*{0,2}(\d+)[.)]")
СЕКЦИЯ = re.compile(r"^##\s+(.*)$")
# Расстояние от `ДОСТАВЛЕНО:` вверх до своего `ДОМ:`. Три — с запасом: в живом
# корпусе они стоят соседними строками у 198 из 198, но между ними встречается
# пустая строка и хвост markdown-списка.
ОКНО_ДОМА = 3


def вид_по_имени(путь):
    """`urok` или `punkt` — по имени файла. Вид в команде не спрашивается.

    🔴 Автоопределение здесь не удобство, а условие обратной совместимости:
    живые команды в документах и в `zakryt_sessiyu.py:459` зовут `--plan
    UROKI-FABRIKE.md` без всякого вида, и обязаны работать дословно как раньше.
    """
    имя = Path(путь).name
    if имя.startswith("kod_") and имя.endswith(".md"):
        return "punkt"
    return "urok"


def адрес_из(значение):
    """Значение поля `ДОМ:` → путь. Хвост-пояснение отрезается.

    🔴 Поле `ДОМ:` — живой текст, а не форма. В корпусе оно пишется четырьмя
    способами: голым путём, путём в бэктиках, путём в бэктиках с пояснением
    (`` `_studio/zhurnal/<арка>/` (следующий заход очереди) ``) и словом
    `владелец`. Взять строку целиком — значит получить адрес с пояснением
    внутри, который не резолвится ни в одну базу; такой пункт попадёт в класс
    «дома нет» и будет объявлен непочинимым, хотя дом есть.
    """
    значение = значение.strip()
    в_бэктиках = ТОКЕН.findall(значение)
    if в_бэктиках:
        return re.split(r"\s*§", в_бэктиках[0])[0].strip().rstrip(",;")
    return re.split(r"\s+\(", значение)[0].strip().rstrip(",;")


def секции_вопросов(строки):
    """[(имя, начало, конец)] секций, чьё имя содержит «ВОПРОС».

    🔴 Не точное имя `ВОПРОСЫ`, а вхождение: 18 живых пунктов лежат в секции
    `## ВТОРАЯ ПАЧКА ВОПРОСОВ — накоплена этапами 3–8`, заведённой исполнителем
    по ходу работы. Поиск по точному имени их не видит, и они не печатались
    приёмкой ни разу.
    """
    головы = [(i, m.group(1).strip()) for i, s in enumerate(строки)
              if (m := СЕКЦИЯ.match(s))]
    res = []
    for k, (i, имя) in enumerate(головы):
        if "ВОПРОС" not in имя.upper():
            continue
        конец = головы[k + 1][0] if k + 1 < len(головы) else len(строки)
        res.append((имя, i, конец))
    return res


def пункты(путь):
    """Разбор пунктов очереди файла-захода. Форма списка — как у `уроки()`.

    Якорь — пара полей `ДОМ:`/`ДОСТАВЛЕНО:`, а не номер (почему — в шапке).
    """
    путь = Path(путь)
    строки = _строки(путь)
    итог = []
    for имя_секции, начало, конец in секции_вопросов(строки):
        предыдущий_конец = начало  # тело пункта начинается после прошлого пункта
        порядковый = 0
        for i in range(начало, конец):
            стр = строки[i]
            if стр.lstrip().startswith(">"):     # шапка-подсказка, не запись
                continue
            m_дост = ПОЛЕ_ДОСТ.match(стр)
            if not m_дост:
                continue
            дом = None
            for j in range(i - 1, max(предыдущий_конец, i - 1 - ОКНО_ДОМА) - 1, -1):
                if j < начало or строки[j].lstrip().startswith(">"):
                    continue
                m_дом = ПОЛЕ_ДОМ.match(строки[j])
                if m_дом:
                    дом = адрес_из(m_дом.group(1))
                    break
            if дом is None:
                # `ДОСТАВЛЕНО:` без своего `ДОМ:` — это не пункт, а проза
                # (обсуждение самой формы: «заменены на метки», «оба
                # `ДОСТАВЛЕНО: нет`»). Молча не глотаем: считаем и печатаем.
                итог.append({"вид": "брак", "номер": None,
                             "заголовок": _обрез(стр.strip(), 90),
                             "строка": i + 1, "конец": i + 1, "тело": [стр],
                             "дом": None, "доставлено": None, "файл": путь,
                             "секция": имя_секции})
                предыдущий_конец = i + 1
                continue
            тело = строки[предыдущий_конец:i + 1]
            # Ведущий мусор блока: заголовок самой секции и её шапка-подсказка
            # (blockquote). Внутренние `>`-строки НЕ трогаем — они бывают частью
            # находки, а тело обязано уехать в дом дословно.
            while тело and (not тело[0].strip()
                            or тело[0].lstrip().startswith((">", "## "))):
                тело.pop(0)
                предыдущий_конец += 1
            порядковый += 1
            непустые = [s for s in тело if s.strip()]
            первая = непустые[0] if непустые else ""
            # 🔴 НОМЕР ИЩЕТСЯ ГЛУБЖЕ ПЕРВОЙ СТРОКИ, А ЕГО ОТСУТСТВИЕ НЕ
            # ДОДУМЫВАЕТСЯ. Цена найдена верификатором: fallback «порядковый
            # внутри секции» выдумывал номера 1, 4, 9 для пунктов, физически
            # подписанных 7, 10 и 15 (их первая строка — ```-ограда или
            # подзаголовок пачки, а не номер). Выдуманные номера СТАЛКИВАЛИСЬ
            # с настоящими: инструмент объявлял коллизию адреса там, где в
            # файле все 24 номера уникальны, и предлагал «перенумеровать файл»
            # — то есть чинить здоровое по показаниям сломанного.
            m_ном = next((m for s in непустые[:5] if (m := НОМЕР_ПУНКТА.match(s))),
                         None)
            заголовок = re.sub(r"^\s*\*{0,2}\d+[.)]\s*", "", первая).strip()
            итог.append({
                "вид": "punkt",
                # Номера нет вовсе — адресуем по СТРОКЕ поля `ДОСТАВЛЕНО:`:
                # она уникальна по построению, а придуманный порядковый — нет.
                "номер": int(m_ном.group(1)) if m_ном else i + 1,
                "номер_явный": bool(m_ном),
                "заголовок": заголовок or _обрез(первая.strip(), 90),
                "строка": предыдущий_конец + 1,
                "конец": i + 1,               # 1-based номер строки `ДОСТАВЛЕНО:`
                "тело": тело,
                "дом": None if дом.lower() == "владелец" else дом,
                "владелец": дом.lower() == "владелец",
                "доставлено": m_дост.group(1).strip(),
                "метка": m_дост.group(1).strip().lower() != "нет",
                "файл": путь,
                "секция": имя_секции,
            })
            предыдущий_конец = i + 1
    return итог


