#!/usr/bin/env python3
"""ДВЕРЬ УРОКОВ — транспорт урока из `UROKI-FABRIKE.md` арки в его ДОМ.

    python3 _generator/tools/dostavit_urok.py --plan     <UROKI-FABRIKE.md>
    python3 _generator/tools/dostavit_urok.py --dostavit N <UROKI-FABRIKE.md>
    python3 _generator/tools/dostavit_urok.py --gejt     <UROKI-FABRIKE.md>

ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ (причина дороже кода — не удалять).

`UROKI-FABRIKE.md` объявлен «локальной памятью арки, ephemeral»: при закрытии
арка умирает, а уроки обязаны уехать в канон. Механизма переезда не было —
была прозаическая инструкция «разнести по домам руками». По закону
`KONSTITUCIYA §11` такое правило нарушается молча, и оно нарушалось: из ~12
уроков трёх суток до канона дошёл один (цена записана в шапке `check_uroki.py`).
Здесь переезд становится командой, а «не разнесли» — красным кодом возврата.

🔴 ЧТО ЭТОТ ИНСТРУМЕНТ НЕ ДЕЛАЕТ (клауза 3 гейта — говорить о своих слепых зонах).
  * Не судит, НАСТОЯЩАЯ ли цена и честен ли вердикт. Он переносит текст дословно;
    правду ловит владелец и свежая сессия.
  * Не понимает `§раздел` в адресе дома: урок дописывается в КОНЕЦ дома, а не в
    названную секцию. Секцию выбирает человек при консолидации.
  * Не чинит адрес. Дома нет на диске — отказ с названной причиной; файл наугад
    не создаётся, потому что придуманный дом хуже отсутствующего.

🔴 ПОЧЕМУ КЛЮЧ `ДОСТАВЛЕНО-В-ДОМ:`, А НЕ `ДОСТАВЛЕНО:`. В живом файле арки
`2026-08-05_faza-lenty` 37 уроков из 60 УЖЕ несут строку `ДОСТАВЛЕНО: <заход>#<N>`,
и она значит ПРОТИВОПОЛОЖНОЕ — «эта запись ПРИЕХАЛА сюда из ВОПРОСОВ такого-то
захода» (конвенция `## ВОПРОСЫ` в шаблоне захода: аналитик ставит одну и ту же
метку и в источнике, и в доме). Ни один из этих 37 в канон не доставлен. Возьми
гейт тот же ключ — и он промолчал бы на 37 уроках из 60, объявив доставленным то,
чего не было. Ложно-зелёный гейт опаснее отсутствующего, поэтому ключи разведены.

🔴 МЕТКА И СОДЕРЖАНИЕ — ОДНИМ ХОДОМ, И ПОРЯДОК НЕСУЩИЙ. Сначала пишется ДОМ,
только потом метка в урок. Оборвись работа между ходами — получится содержание
без метки: гейт останется КРАСНЫМ, то есть ошибка в безопасную сторону. Обратный
порядок дал бы метку без содержания — ровно тот ложно-зелёный Г7, который в этом
репозитории уже оплачен.

Разбор уроков берётся у `check_uroki.py` (`lessons_in`), а не пишется заново:
второй парсер той же вещи разойдётся с первым, и расхождение будет видно только
на новом файле. Здесь поверх его разбора — ровно три вещи, которых он не знает:
```-забор, адрес дома и метка доставки.

Только stdlib. Код возврата: 0 — сделано/чисто, 1 — гейт красный, 2 — отказ.
"""
import argparse
import re
import sys
from datetime import date
from pathlib import Path

# Ядро «что такое урок» живёт у ГЕЙТА, а не здесь — см. шапку.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_uroki  # noqa: E402

МЕТКА = "ДОСТАВЛЕНО-В-ДОМ:"
РАЗДЕЛ = "## Уроки арок, доставленные `dostavit_urok.py`"
РАМКА = ("> Дословные записи из `UROKI-FABRIKE.md` закрывающихся арок — голос "
         "источника, не редактора. Консолидирует их человек: переносит в нужный "
         "раздел, сливает с существующим правилом, слабую формулировку "
         "переписывает. До консолидации они лежат здесь, а не пропадают вместе с аркой.\n"
         "> 🔴 **Задачами борда они не становятся сами.** Вердикт урока часто "
         "содержит невыполненную работу, но чекбокса у неё здесь нет и по скану "
         "борда её не видно: пункт `- [ ]` заводит человек при консолидации.")

# Адрес дома стоит в ВЕРДИКТЕ и написан четырьмя разными оборотами — это живой
# текст, а не поле формы. Словарь снят с корпуса 60 уроков; что им не
# разбирается, печатается строкой «адрес НЕ разобран», а не пропускается молча.
МАРКЕР = re.compile(r"(?:Дом\s*[—–-]|[Вв]писан[оаы]?\s*→|[Зз]аписан[оаы]?\s+в"
                    r"|[Вв]писать\s+в|[Вв]писано\s+в)")
ТОКЕН = re.compile(r"`([^`]+)`")
ЗАГОЛОВОК = re.compile(r"^(\d+)\.\s*(.+)$")
ЦЕНА = re.compile(r"^\*{0,2}ЦЕНА(?!\w)")
ВЕРДИКТ = re.compile(r"^\*{0,2}ВЕРДИКТ(?!\w)")


def _строки(путь):
    return Path(путь).read_text(encoding="utf-8").splitlines()


def в_заборе(строки):
    """Номера строк (1-based) внутри ```-забора.

    🔴 Зачем это здесь. В шапке каждого `UROKI-FABRIKE.md` лежит ОБРАЗЕЦ формы
    урока — `### N. <что произошло>` / `ЦЕНА:` / `ВЕРДИКТ:` — внутри забора.
    Греп-гейты шапки его считают, и все три сходятся (61/61/61) именно потому,
    что образец несёт и цену, и вердикт: они сходятся, не видя, что считают.
    Инструмент, взявший это число за охват, никогда не досчитает до 100 %.
    """
    внутри, res = False, set()
    for n, s in enumerate(строки, 1):
        if s.lstrip().startswith("```"):
            внутри = not внутри
            res.add(n)
            continue
        if внутри:
            res.add(n)
    return res


def дом_из(вердикт):
    """Путь дома из строки ВЕРДИКТА, либо None — адрес не разобран."""
    m = МАРКЕР.search(вердикт)
    if not m:
        return None
    for токен in ТОКЕН.findall(вердикт[m.end():]):
        # `RUKOVODSTVO-zahodami.md §4` — номер раздела живёт ВНУТРИ бэктиков;
        # инструмент секций не понимает (см. шапку), поэтому отрезает.
        кандидат = re.split(r"\s*§", токен)[0].strip().rstrip(",;")
        if "/" in кандидат or кандидат.endswith((".md", ".py", ".sh")):
            return кандидат
    return None


def вид_дома(дом):
    """канон · инструмент · скилл — они ведут себя по-разному (§2.1 захода)."""
    if дом.endswith((".py", ".sh")):
        return "инструмент"
    if дом.startswith("disciplina/") or "/skills/" in дом:
        return "скилл"
    return "канон"


def резолв(дом, арка_папка, корень):
    """(Path, имя базы) — либо (None, None). Две базы, потому что база не объявлена.

    🔴 В наших документах относительный путь не говорит, откуда он считается:
    в одном файле соседствуют `../../docs/KARTA.md` (от папки арки) и
    `_studio/zhurnal/…` (от корня репозитория). Чекер, написанный по одной базе,
    даёт списки почти целиком ложные — это уже измерено (урок 52 арки
    `faza-lenty`: 22 «пропажи» от одной базы и 24 от другой, обе ложные).
    Поэтому пробуем обе и ПЕЧАТАЕМ, какая сработала.
    """
    for база, имя in ((арка_папка, "арка"), (корень, "корень")):
        p = (Path(база) / дом)
        try:
            if p.is_file():
                return p, имя
        except OSError:
            continue
    return None, None


def указатель(p):
    """Файл-указатель («… → ПЕРЕЕХАЛ») — дом, из которого содержание уехало.

    После выноса `_meta` четыре канонных файла `_studio/docs/kak-delat/` стали
    редиректами. Адрес урока туда РАЗБИРАЕТСЯ и файл СУЩЕСТВУЕТ — то есть по
    обоим машинным признакам дом «живой», а содержания там нет. Доставка в
    редирект тихо кладёт урок мимо канона; поэтому это отдельный вид отказа.
    """
    первая = (p.read_text(encoding="utf-8").splitlines() or [""])[0]
    return первая.startswith("# ") and первая.rstrip().endswith("ПЕРЕЕХАЛ")


def уроки(путь):
    """Разбор файла уроков. Список словарей, по одному на настоящий урок."""
    путь = Path(путь)
    строки = _строки(путь)
    забор = в_заборе(строки)
    сырые = check_uroki.lessons_in(путь)          # авторитетный разбор гейта
    начала = [l["line"] for l in сырые] + [len(строки) + 1]

    итог = []
    for i, l in enumerate(сырые):
        if l["line"] in забор:                    # образец формы — не урок
            continue
        тело = строки[l["line"] - 1:начала[i + 1] - 1]
        while тело and not тело[-1].strip():
            тело.pop()
        m = ЗАГОЛОВОК.match(l["title"])
        вердикт = next((s for s in тело if ВЕРДИКТ.match(s)), "")
        дом = дом_из(вердикт) if вердикт else None
        итог.append({
            "номер": int(m.group(1)) if m else None,
            "заголовок": m.group(2) if m else l["title"],
            "строка": l["line"],
            "конец": l["line"] + len(тело) - 1,
            "тело": тело,
            "цена": next((s for s in тело if ЦЕНА.match(s)), ""),
            "вердикт": вердикт,
            "дом": дом,
            "метка": any(s.startswith(МЕТКА) for s in тело),
        })
    return итог


def контекст(путь):
    """(папка арки, корень репозитория) для резолва домов."""
    арка = Path(путь).resolve().parent
    return арка, арка.parent.parent.parent


def _обрез(s, n):
    return s if len(s) <= n else s[:n - 1] + "…"


# ── РЕЖИМ 1: --plan ─────────────────────────────────────────────────────────
def cmd_plan(путь):
    """Таблица «что где живёт и что не доехало». Ничего не меняет."""
    список = уроки(путь)
    арка_папка, корень = контекст(путь)
    арка = арка_папка.name
    всего_заголовков = len(check_uroki.lessons_in(Path(путь)))

    print(f"ПЛАН ДОСТАВКИ УРОКОВ — {Path(путь)}")
    print(f"арка: {арка}\n")
    print(f"{'№':>3}  {'урок':<52} {'вид':<11} {'дост':<5} {'дом'}")
    print("─" * 118)

    разобран = вид_счёт = 0
    неразобран, нет_дома, указатели, недоставлено = [], [], [], []
    for u in список:
        ном = str(u["номер"]) if u["номер"] is not None else "—"
        дост = "✅" if u["метка"] else "—"
        if not u["метка"]:
            недоставлено.append(ном)
        if not u["дом"]:
            неразобран.append(ном)
            print(f"{ном:>3}  {_обрез(u['заголовок'], 52):<52} {'—':<11} {дост:<5} "
                  f"⚠ адрес НЕ разобран")
            continue
        разобран += 1
        вид = вид_дома(u["дом"])
        p, база = резолв(u["дом"], арка_папка, корень)
        if p is None:
            пометка = "❌ дома нет на диске"
            нет_дома.append(ном)
        elif p.suffix == ".md" and указатель(p):
            пометка = "⚠ файл-указатель (содержание переехало)"
            указатели.append(ном)
        else:
            пометка = f"(база: {база})"
        print(f"{ном:>3}  {_обрез(u['заголовок'], 52):<52} {вид:<11} {дост:<5} "
              f"{u['дом']}  {пометка}")

    n = len(список)
    print("─" * 118)
    print(f"заголовков `### ` в файле: {всего_заголовков} · из них образец формы "
          f"внутри ```-забора: {всего_заголовков - n} · настоящих уроков: {n}")
    print(f"адрес дома разобран: {разобран} из {n} · НЕ разобран: {n - разобран}"
          + (f" (уроки {', '.join(неразобран)})" if неразобран else ""))
    print(f"дом не существует на диске: {len(нет_дома)}"
          + (f" (уроки {', '.join(нет_дома)})" if нет_дома else ""))
    print(f"дом — файл-указатель, содержание переехало: {len(указатели)}"
          + (f" (уроки {', '.join(указатели)})" if указатели else ""))
    print(f"НЕ доставлено в дом: {len(недоставлено)} из {n}")
    if недоставлено:
        print(f"  доставить: python3 _generator/tools/dostavit_urok.py "
              f"--dostavit {недоставлено[0]} {путь}")
    return 0


# ── РЕЖИМ 2: --dostavit N ───────────────────────────────────────────────────
def _блок(u, арка, сегодня):
    """Текст, который уезжает в дом: урок ДОСЛОВНО плюс строка-метка."""
    return (["", f"### {u['номер']}. {u['заголовок']}"] + u["тело"][1:]
            + [f"{МЕТКА} {арка}#{u['номер']} · {сегодня}"])


def cmd_dostavit(путь, номер, сегодня=None):
    сегодня = сегодня or date.today().isoformat()
    путь = Path(путь)
    арка_папка, корень = контекст(путь)
    арка = арка_папка.name
    список = уроки(путь)

    u = next((x for x in список if x["номер"] == номер), None)
    if u is None:
        есть = ", ".join(str(x["номер"]) for x in список if x["номер"] is not None)
        print(f"❌ Урока {номер} в файле нет. Есть: {есть}", file=sys.stderr)
        return 2

    if u["метка"]:
        print(f"Уже доставлен — второй раз не пишу: урок {номер} ({арка})")
        return 0
    if not u["дом"]:
        print(f"❌ У урока {номер} адрес дома не разобран. ВЕРДИКТ говорит:\n"
              f"   {_обрез(u['вердикт'], 300)}\n"
              f"   Дом называется оборотом «Дом — `путь`»; поправь вердикт, а не "
              f"инструмент — угадывать дом он не будет.", file=sys.stderr)
        return 2

    дом, база = резолв(u["дом"], арка_папка, корень)
    if дом is None:
        print(f"❌ Дом урока {номер} не существует: `{u['дом']}`. Пробовал две базы: "
              f"папку арки ({арка_папка}) и корень репозитория ({корень}). "
              f"Файл наугад НЕ создаю: придуманный дом хуже отсутствующего — он "
              f"выглядит доставкой.", file=sys.stderr)
        return 2
    if дом.suffix == ".md" and указатель(дом):
        print(f"❌ Дом урока {номер} — файл-указатель: {дом}\n"
              f"   Его первая строка говорит «ПЕРЕЕХАЛ», содержание живёт в другом "
              f"файле. Доставка сюда положила бы урок мимо канона и выглядела бы "
              f"успешной. Чинить адрес в вердикте урока, а не обходить.",
              file=sys.stderr)
        return 2

    текст_дома = дом.read_text(encoding="utf-8")
    якорь = f"{МЕТКА} {арка}#{номер} ·"

    # 🔴 ПОРЯДОК ХОДОВ НЕСУЩИЙ — сначала дом, потом метка (см. шапку файла).
    if якорь in текст_дома:
        # Содержание на месте, метки в уроке нет — дописываем только её. Это НЕ
        # ложно-зелёный случай: метка ставится по факту найденного содержания.
        print(f"   Содержание уже в доме — ставлю только метку в уроке.")
    else:
        куски = []
        if РАЗДЕЛ not in текст_дома:
            куски += ["", "---", "", РАЗДЕЛ, "", РАМКА]
        куски += _блок(u, арка, сегодня)
        новый = текст_дома.rstrip("\n") + "\n" + "\n".join(куски) + "\n"
        дом.write_text(новый, encoding="utf-8")

    строки = _строки(путь)
    строки.insert(u["конец"], f"{МЕТКА} {сегодня} → {u['дом']}")
    путь.write_text("\n".join(строки) + "\n", encoding="utf-8")

    print(f"✅ Урок {номер} доставлен: {арка}#{номер}")
    print(f"   дом:   {дом.resolve()}  (база: {база})")
    print(f"   метка: {путь}:{u['конец'] + 1} — {МЕТКА} {сегодня} → {u['дом']}")
    print(f"🔴 Оба файла обязаны уехать в ОДИН коммит: содержание в доме и метка в "
          f"уроке порознь — это ложно-зелёный гейт при первом же `checkout`.")
    return 0


# ── РЕЖИМ 3: --gejt ─────────────────────────────────────────────────────────
def cmd_gejt(путь):
    """Красный, пока есть уроки без `ДОСТАВЛЕНО-В-ДОМ`. Не даёт закрыть арку молча."""
    список = уроки(путь)
    без = [u for u in список if not u["метка"]]
    if без:
        print(f"❌ УРОКИ НЕ ДОСТАВЛЕНЫ В ДОМА — арка закроется, и они умрут вместе "
              f"с ней:\n", file=sys.stderr)
        for u in без[:12]:
            ном = u["номер"] if u["номер"] is not None else "—"
            print(f"  {ном:>3}. {_обрез(u['заголовок'], 88)}", file=sys.stderr)
        if len(без) > 12:
            print(f"  … и ещё {len(без) - 12}", file=sys.stderr)
        print(f"\nНе доставлено {len(без)} из {len(список)}. "
              f"Что где живёт: --plan {путь}", file=sys.stderr)
        print("Проскочить: git commit --no-verify (можно; но уже не молча).",
              file=sys.stderr)
        return 1
    print(f"✅ Все {len(список)} уроков доставлены в дома.")
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(
        description="Транспорт урока из UROKI-FABRIKE.md арки в его дом.",
        epilog="Дом читается из ВЕРДИКТА урока (оборот «Дом — `путь`»). "
               "Инструмент не создаёт домов и не понимает `§раздел`.")
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--plan", action="store_true",
                   help="таблица: урок · дом · вид дома · доставлен · разобран ли адрес")
    g.add_argument("--dostavit", metavar="N", type=int,
                   help="дописать урок N в его дом дословно и пометить его доставленным")
    g.add_argument("--gejt", action="store_true",
                   help="rc=1, пока есть уроки без ДОСТАВЛЕНО-В-ДОМ")
    p.add_argument("fajl", metavar="UROKI-FABRIKE.md", help="файл уроков арки")
    a = p.parse_args(argv)

    путь = Path(a.fajl)
    if not путь.is_file():
        print(f"❌ Файла нет: {путь}", file=sys.stderr)
