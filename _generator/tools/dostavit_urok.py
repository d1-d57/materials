def _обрез(s, n):
    return s if len(s) <= n else s[:n - 1] + "…"


def сбалансировать_ограду(тело):
    """Тело с чётным числом ```-оград — иначе доставка съедает ХВОСТ ДОМА.

    🔴 ЦЕНА ЭТОГО МЕСТА ОПЛАЧЕНА ВЕРИФИКАТОРОМ, А НЕ РАССУЖДЕНИЕМ. Пункты
    очереди в живых файлах часто обёрнуты одной ```-оградой на несколько
    записей сразу (`kod_gejt-vhozhdeniya.md`: ограда открыта на 228-й строке и
    закрыта на 248-й, внутри пункты 1–3). Доставка одного такого пункта уносит
    в дом ОТКРЫВАЮЩУЮ ограду без закрывающей: байты целы, `diff` показывает
    ноль удалений, все гейты зелёные — а в доме `UROKI-FABRIKE.md` 22 заголовка
    и весь хвост файла после неё в любом просмотрщике становятся кодом.
    Порча, невидимая всем машинным проверкам, которые у нас есть.

    Балансируем по признаку происхождения: ведущая ограда — часть чужого
    обрамления, её отбрасываем; всё прочее закрываем в конце, потому что
    оборвать чужой блок хуже, чем закрыть свой.
    """
    if sum(1 for s in тело if s.lstrip().startswith("```")) % 2 == 0:
        return тело
    первая = next((i for i, s in enumerate(тело) if s.strip()), None)
    if первая is not None and тело[первая].lstrip().startswith("```"):
        return тело[:первая] + тело[первая + 1:]
    return тело + ["```"]


def имя_zahoda(путь):
    """`kod_vynos-meta.md` → `vynos-meta` — то, что стоит в метке `<заход>#<N>`.

    Метку читает Г7 `priyomka.py`: он ищет ЗНАЧЕНИЕ поля `ДОСТАВЛЕНО:` как
    подстроку в файле-доме. Формат обязан совпасть с конвенцией аналитика
    (`## ВОПРОСЫ` шаблона захода), иначе гейт покраснеет на верной доставке.
    """
    return re.sub(r"^kod_|\.md$", "", Path(путь).name)


def наблюдения(путь, вид=None):
    """(вид, список наблюдений одной формы) — единственный вход для всех режимов.

    Уроки приводятся к той же форме, что пункты: остальной код видит одно
    понятие и не знает, чем запись была записана.
    """
    вид = вид or вид_по_имени(путь)
    if вид == "punkt":
        return вид, пункты(путь)
    список = уроки(путь)
    for u in список:
        u.update(вид="urok", владелец=False, файл=Path(путь),
                 секция="УРОКИ ФАБРИКЕ",
                 доставлено=("да" if u["метка"] else "нет"))
    return вид, список


def punkty_zahoda(путь):
    """Пункты очереди файла-захода, без брака разбора — публичный вход для Г8.

    Приёмка обязана звать ЭТОТ разбор, а не писать свой: два парсера одной вещи
    в этом репозитории уже разошлись, и разошлись молча.
    """
    return живые(наблюдения(путь, "punkt")[1])


def живые(список):
    """Наблюдения без брака разбора (`ДОСТАВЛЕНО:` без своего `ДОМ:`)."""
    return [н for н in список if н["вид"] != "брак"]


