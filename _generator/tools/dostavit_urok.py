ПОРОГ_ОЧЕРЕДИ = 12
"""Сколько недоставленных пунктов в ОДНОМ заходе перестают быть нормой.

🔴 ЧИСЛО СНЯТО С КОРПУСА, А НЕ НАЗНАЧЕНО. Распределение недоставленных по 37
заходам живой арки `2026-08-05_faza-lenty`: медиана 4, среднее 4.2, p75 = 5,
p90 = 8, максимум 24. Плотная часть кончается на 9; дальше в корпусе ровно два
значения — 11 и 24, и между ними разрыв. Порог 12 стоит в этом разрыве: он
краснеет на 1 заходе из 37 (`kod_nochnaya-sborka.md`, 24 пункта) и молчит на
36 остальных. Копить по 4–5 пунктов за заход — замысел, их разносят на
консолидации; сложить 24 — это уже не очередь, а перекладывание работы.

Порог ниже (скажем, 6) покрасил бы 7 заходов из 37, то есть каждый пятый; гейт,
который краснеет на каждом пятом честном заходе, отключают первым — это в
репозитории уже случалось, и ровно поэтому здесь порог, а не факт.
"""


def cmd_gejt_punkt(путь, закрытие=False):
    """Красный на недоставленном, у которого дом ЕСТЬ. Остальное — по стадии.

    Почему не «любое недоставленное» — в шапке файла: гейт, красный всегда,
    отключают первым.
    """
    if Path(путь).is_dir():
        return _gejt_arki(Path(путь), закрытие)
    арка_папка, корень = контекст(путь)
    список = живые(наблюдения(путь, "punkt")[1])
    без = [н for н in список if not н["метка"]]
    по_классам = {}
    for н in без:
        кл, _ = класс_адреса(н, арка_папка, корень)
        по_классам.setdefault(кл, []).append(н)

    чинится = по_классам.get("дом есть", [])
    отложено = [н for кл, свои in по_классам.items() if кл != "дом есть"
                for н in свои]
    сверх_порога = len(без) > ПОРОГ_ОЧЕРЕДИ
    красное = чинится + (отложено if (закрытие or сверх_порога) else [])

    if красное:
        повод = ("АРКА ЗАКРЫВАЕТСЯ, А ПУНКТЫ ОЧЕРЕДИ НЕ РАЗНЕСЕНЫ" if закрытие
                 else f"ОЧЕРЕДЬ ЗАХОДА ПЕРЕВАЛИЛА ПОРОГ ({len(без)} > "
                      f"{ПОРОГ_ОЧЕРЕДИ}), РАЗНОСИТЬ ПОРА СЕЙЧАС" if сверх_порога
                 else "ПУНКТЫ ОЧЕРЕДИ НЕ ДОСТАВЛЕНЫ, ХОТЯ ДОМ ЕСТЬ")
        print(f"❌ {повод}:\n", file=sys.stderr)
        for н in красное[:12]:
            кл, _ = класс_адреса(н, арка_папка, корень)
            print(f"  {н['номер']:>3}. {_обрез(н['заголовок'], 74)}  [{кл}]",
                  file=sys.stderr)
        if len(красное) > 12:
            print(f"  … и ещё {len(красное) - 12}", file=sys.stderr)
        print(f"\nКрасных {len(красное)} из {len(список)} пунктов файла. "
              f"Что где живёт: --plan {путь}", file=sys.stderr)
        if not закрытие and отложено:
            print(f"Вне гейта до закрытия арки: {len(отложено)} "
                  f"(дома нет / решение за человеком) — они в `--gejt --zakrytie`.",
                  file=sys.stderr)
        return 1

    хвост = (f" Вне гейта до закрытия арки: {len(отложено)}." if отложено else "")
    print(f"✅ Пунктов с живым домом, ждущих доставки, нет "
          f"({len(список) - len(без)} из {len(список)} доставлено).{хвост}")
    return 0


def _gejt_arki(папка, закрытие=False):
    """`--gejt <папка>` — та же проверка, но по ВСЕЙ арке разом.

    🔴 Зачем отдельный вход. Приёмка судит ОДИН заход, и её порог настроен на
    один заход. Но накопление живёт не в заходе, а в арке: 37 честных заходов,
    каждый ниже порога, дают ту самую груду, ради которой канал и строится.
    Здесь она видна одним кодом возврата.
    """
    файлы = sorted(папка.glob("kod_*.md"))
    уроки_файл = папка / "UROKI-FABRIKE.md"
    if уроки_файл.is_file():
        файлы.append(уроки_файл)
    корень = папка.resolve().parent.parent.parent
    все = []
    for f in файлы:
        все += живые(наблюдения(f)[1])
    без = [н for н in все if not н["метка"]]
    по_классам = {}
    for н in без:
        кл, _ = класс_адреса(н, папка.resolve(), корень)
        по_классам.setdefault(кл, []).append(н)
    чинится = по_классам.get("дом есть", [])
    красное = без if закрытие else чинится
    if красное:
        повод = ("АРКА ЗАКРЫВАЕТСЯ, А НАКОПЛЕННОЕ НЕ РАЗНЕСЕНО" if закрытие
                 else "ПО АРКЕ ЕСТЬ НЕДОСТАВЛЕННОЕ, У ЧЕГО ДОМ ЕСТЬ")
        print(f"❌ {повод}: {len(красное)} из {len(все)} наблюдений "
              f"в {len(файлы)} файлах.\n", file=sys.stderr)
        for кл in КЛАССЫ:
            свои = по_классам.get(кл, [])
            if свои:
                метка = "🔴" if (кл == "дом есть" or закрытие) else "  "
                print(f"  {метка} {кл:<22} {len(свои):>4}   {ЧЕМ_ЗАКРЫВАТЬ[кл]}",
                      file=sys.stderr)
        print(f"\nЧто где живёт: --volna {папка}", file=sys.stderr)
        return 1
    print(f"✅ По арке недоставленного с живым домом нет "
          f"({len(все) - len(без)} из {len(все)} доставлено).")
    return 0


