# ── З8: критерий не требует того, что заход сам себе запрещает ────────────────
# Класс, стоивший двух остановок работы за одни сутки (`UROKI-FABRIKE` 12 и 14):
# два обязательных указания, невыполнимых разом. Живой разбор обоих случаев
# показал, что они РАЗНОЙ лексической формы, и одним шаблоном не ловятся:
#   З8a — глагольный: критерий требует «запушь», тело говорит «ветки заходов НЕ
#         пушить», место, где действие разрешено, не названо (marketplace-github);
#   З8b — охватный: критерий требует АБСОЛЮТНОГО нуля от команды, сканирующей
#         всё дерево (`grep -rn … .` → 0 строк), а менять заход разрешает не всё
#         (reshenia-intervyu). Запрет здесь не в слове «НЕ», а в границе зоны;
#         ровно это и есть вердикт урока 12.
#
# 🔴 РАСПОЗНАЁТСЯ РОЛЬ СЛОВА, А НЕ ПРИСУТСТВИЕ СЛОВА. Заход, объясняющий этот
# класс ошибок, ЦИТИРУЕТ и «запушь», и «НЕ пушить» — и обязан молчать. Поэтому
# сторона ТРЕБОВАНИЯ ищется только внутри секции критерия и только в форме
# приказа/инфинитива, а сама цитата под отрицанием требованием не считается.
#
# 🔴 СУДИТСЯ ТОЛЬКО ЗАДАНИЕ — текст ДО `## ПЛАН`. Ниже начинается писанина
# исполнителя (план, вопросы, отчёт), которой в момент выдачи захода ещё нет;
# без этой отсечки отчёт «запушил с разрешения владельца» гасил бы проверку
# задним числом, а принятый заход менял бы вердикт после приёмки.
ZADANIE_KONEC_RE = re.compile(r'^##\s+ПЛАН\b', re.M)

# (имя · как выглядит ТРЕБОВАНИЕ · как выглядит тот же глагол ВООБЩЕ)
#
# 🔴 ГЛАГОЛОВ ДВА, И ЭТО РЕЗУЛЬТАТ КАЛИБРОВКИ, А НЕ ЛЕНЬ. Опорный список
# аналитика был шире (`удали`, `отключи`, `перепиши`, `тронь`), и верификатор
# §3 показал на каждом из четырёх ложное красное на ПРАВДОПОДОБНО ЗДОРОВОМ
# заходе: «Файлы не создавай и не удаляй» ↔ «удали мёртвую ветку `if LEGACY:`»;
# «Гейты отключать нельзя» ↔ «отключи запись байткода»; «Историю переписывать
# нельзя» ↔ «перепиши докстринг». Причина одна и она не чинится словарём: у этих
# глаголов объект бывает РАЗНОГО МАСШТАБА (файл против строки, гейт против
# переменной окружения), и различить масштаб лексически нечем.
# `пуш` и `влить` таким свойством не обладают: пушат и вливают всегда ветку, и
# запрет на них — всегда запрет ровно того действия, которого требует критерий.
# Остальные глаголы объявлены слепой зоной в докстринге: пропуск дешевле
# ложного красного, потому что ложное красное обходят `--no-verify` ЦЕЛИКОМ.
#
# 🔴 «коммит» в таблицу не входит по той же причине, только грубее: «зона
# закоммичена» стоит в каждом критерии фабрики, «сам файл НЕ коммитишь» — в
# каждом контракте зоны; пара дала бы красное на 161 заходе из 161.
#
# Форма СОСТОЯНИЯ («ветка влита», «правка запушена») считается требованием
# наравне с приказом: критерии сплошь и рядом пишутся состоянием, а не приказом
# (находка верификатора A1).
Z8_GLAGOLY = [
    ("пуш",   r'запуш\w*|\bпушни\b|\bgit\s+push\b',                    r'пуш\w*'),
    ("влить", r'\bвлей\b|\bвлить\b|\bвливай\b|\bсмёржи\b|\bвлит[аыоеу]\w*|\bслит[аыоеу]\w*',
                                                                       r'влит\w*|влива\w*|\bвлей\b'),
]
# Форс-пуш — другое действие: запрет на `--force` не запрещает обычный пуш
# своей ветки (находка верификатора B4).
Z8_FORS_RE = re.compile(r'форс|force|-f\b', re.I)
# 🔴 Отрицание/запрет вплотную к глаголу, в пределах одного предложения.
# `\b` у «не» обязателен и оплачен живым прогоном: без него «не» находилось
# ВНУТРИ слова («покраснело», «именно») и превращало git-шаблон `--no-verify …
# --push` в мнимый запрет пуша. Регистр — через re.I: живой текст пишет «Не»
# с большой буквы в начале фразы, и перечисление `(?:НЕ|не)` его не ловит вовсе.
Z8_ZAPRET_SLEVA = r'(?:\bне\b|\bнельзя\b|\bзапрещ\w*|\bзапрет\w*|\bбез\b)'
Z8_ZAPRET_SPRAVA = r'(?:\bзапрещ\w*|\bнельзя\b|\bзапрет\w*)'
Z8_OTRICANIE_SLEVA = re.compile(r'(?:\bне|\bбез)\s+\w*$', re.I)
# Названное разрешённое место — то, что делает гейт полезным, а не назойливым:
# «тестовый коммит делается в `main`», «пушить можно только…».
Z8_RAZRESHENO = re.compile(
    r'разреш\w*|\bможно\b|допуст\w*|допуска\w*|\bдозволен\w*|легитим\w*', re.I)
Z8_OKNO = 45  # символов между отрицанием и глаголом


def _predlozheniya(text):
    """Деление на предложения: точка/;/!/?/перевод строки/тире-врезка.

    🔴 Внутри backtick не делит. Поймано ловушкой 15 фикстуры: имя объекта
    `engine.js` содержит точку, наивный `re.split` разрывал фразу пополам и
    оставлял запрет БЕЗ объекта — а запрет без объекта считается общим, и
    проверка краснела там, где запрет и требование про разное.
    """
    out, buf, vnutri = [], [], False
    for i, ch in enumerate(text):
        if ch == '`':
            vnutri = not vnutri
        elif not vnutri and (ch in '.;!?\n' or (
                ch == '—' and i and text[i - 1].isspace()
                and i + 1 < len(text) and text[i + 1].isspace())):
            out.append(''.join(buf))
            buf = []
            continue
        buf.append(ch)
    out.append(''.join(buf))
    return [s for s in out if s.strip()]


def _v_kavychkah(s, i):
    """Стоит ли позиция `i` внутри «ёлочек» или backtick — то есть цитатой.

    🔴 Роль слова, а не присутствие слова, и на стороне ТРЕБОВАНИЯ тоже. Заход,
    который сам чинит этот класс дефектов, пишет в критерии «фикстура, где
    критерий требует «запушь», даёт красное» — это не требование запушить
    (находка верификатора B5: без этого проверка краснела на заходе, которым её
    же и правят).
    """
    return (s.count('«', 0, i) > s.count('»', 0, i)) or (s.count('`', 0, i) % 2 == 1)


def _obekty(s):
    """Объекты фразы — токены в backtick, приведённые к базовому имени.

    `_generator/tools/check_kartoteka.py` и `check_kartoteka.py` — один объект;
    флаги (`--push`) и плейсхолдеры (`<зона>`) объектами не считаются.
    """
    out = set()
    for tok in re.findall(r'`([^`]+)`', s):
        tok = tok.strip()
        if tok.startswith('-') or tok.startswith('<'):
            continue
        out.add(tok.rstrip('/').split('/')[-1].lower())
    return out


def _citata(s, limit=90, vokrug=None):
    """Цитата стороны. `vokrug` — подстрока, которая ОБЯЗАНА остаться в кадре.

    Без этого длинный пункт критерия обрезался по первым 90 символам и терял
    ровно тот глагол, из-за которого покраснел («…сделай пустяковую правку в…»
    вместо «…закоммить, запушь…»), а сообщение без обеих сторон дословно —
    половина ценности гейта.
    """
    s = ' '.join(s.split()).strip(' *`—-')
    if len(s) <= limit:
        return s
    i = s.find(vokrug) if vokrug else -1
    if i < 0:
        return s[:limit - 1] + '…'
    start = max(0, i + len(vokrug) // 2 - limit // 2)
    hvost = s[start:start + limit]
    return ('…' if start else '') + hvost + ('…' if start + limit < len(s) else '')


# 🔴 Запрет, ОБЛАСТЬ которого — «всё, чего заход не касается», противоречием не
# является: критерий по построению требует работы ВНУТРИ зоны. Ровно так устроен
# здоровый заход — запретов у него больше, а не меньше, и все они про чужие
# объекты («Всё вне — READ-ONLY: не править, не двигать, не удалять»). Без этого
# исключения гейт краснел бы на «пробу удали» в критерии против шаблонной строки
# зоны — замер: 3 ложных из 161 на живом корпусе, все три этой одной формы.
Z8_VNE_ZONY_RE = re.compile(r'READ-ONLY|всё вне|все вне|вне зоны|вне твоей зоны|'
                            r'за пределами зоны|в зону не входит|не входит в зону', re.I)


def _z8a_glagoly(zadanie, kriterij):
    ostalnoe = zadanie.replace(kriterij, ' ') if kriterij else zadanie
    # Заголовки — строительные леса самого документа, а не указания о работе:
    # «## КОНТРАКТ ЗОНЫ (обязателен — не удалять; вписан Cowork)» запрещает
    # трогать СЕКЦИЮ файла-захода, а не объект работы.
    ostalnoe = '\n'.join(l for l in ostalnoe.splitlines() if not l.lstrip().startswith('#'))
    msgs = []
    for imya, trebovanie_re, stem_re in Z8_GLAGOLY:
        # ── сторона ТРЕБОВАНИЯ: приказ/инфинитив внутри критерия, НЕ под отрицанием
        treb = treb_obj = None
        for s in _predlozheniya(kriterij):
            for m in re.finditer(trebovanie_re, s, re.I):
                if Z8_OTRICANIE_SLEVA.search(s[max(0, m.start() - 20):m.start()]):
                    continue  # это цитата запрета, а не требование
                if _v_kavychkah(s, m.start()):
                    continue  # глагол ПРОЦИТИРОВАН, а не потребован
                treb, treb_obj = _citata(s, vokrug=m.group(0)), _obekty(s)
                break
            if treb is not None:
                break
        if treb is None:
            continue
        # ── сторона ЗАПРЕТА: тот же глагол под отрицанием в остальном задании
        zapret = None
        for s in _predlozheniya(ostalnoe):
            if Z8_VNE_ZONY_RE.search(s) or Z8_FORS_RE.search(s):
                continue
            if re.search(rf'{Z8_ZAPRET_SLEVA}[^,]{{0,{Z8_OKNO}}}?(?:{stem_re})', s, re.I) or \
               re.search(rf'(?:{stem_re})[^,]{{0,{Z8_OKNO}}}?{Z8_ZAPRET_SPRAVA}', s, re.I):
                # 🔴 ОБЪЕКТ, А НЕ ТОЛЬКО ГЛАГОЛ. Запрет и требование обязаны
                # говорить об одном и том же, иначе гейт краснеет на каждом
                # заходе фабрики: «пробу удали» в критерии и «КОНТРАКТ ЗОНЫ —
                # не удалять» в шапке — разные объекты и никакого противоречия.
                # Совпадение считается по backtick-токенам; ни у одной стороны
                # объекта в backtick нет — запрет считается общим (запрещён сам
                # глагол, как «ветки заходов НЕ пушить»), и это противоречие.
                zap_obj = _obekty(s)
                if treb_obj and zap_obj and not (treb_obj & zap_obj):
                    continue
                zapret = _citata(s)
                break
        if zapret is None:
            continue
        # ── названо ли МЕСТО, где действие разрешено (тогда противоречия нет)
        if any(re.search(stem_re, s, re.I) and Z8_RAZRESHENO.search(s)
               for s in _predlozheniya(ostalnoe)):
            continue
        msgs.append(("З8", f"критерий требует «{treb}», а текст захода говорит "
                            f"«{zapret}» — назови место, где действие разрешено, "
                            f"либо сними требование"))
    return msgs


# Команда, сканирующая ВСЁ дерево: рекурсивный grep/find с целью `.` или корнем.
Z8_SPLOSHNOJ_RE = re.compile(r'(?:grep|rg|ack)\s+-\w*r\w*\b[^`]*?(?<![\w/.])\.(?=[\s`]|$)|'
                             r'\bfind\s+\.(?=[\s`])')
Z8_ABSOLUT_RE = re.compile(r'(?:→|->|=)\s*\**\s*0\b|\b0\s+строк|ни одного|0\s+вхожден|'
                           r'\bнет ни\b', re.I)
# Исключение сверх `.git` — то, чем составитель признаёт неприкосновенные пути.
Z8_ISKLYUCHENIE_RE = re.compile(r'--exclude(?:-dir)?=(?!\.git\b)|:!|--\s*:\^|'
                                r'кроме|исключ\w*|законн\w*', re.I)


def _z8b_ohvat(zadanie, kriterij):
    if not kriterij:
        return []
    zona = ZONA_RE.search(zadanie)
    # 🔴 Краснеет НЕ на «зона уже репозитория» — узкая зона у каждого захода, и
    # сплошной `grep → 0` при ней совершенно законен: так доказывают, что
    # переименование доведено до конца, а все вхождения лежат внутри зоны
    # (находка верификатора B2). Краснеет на другом: составитель ЯВНО вырезал
    # пути оговоркой «кроме `X`» — то есть сам назвал места, где вхождения
    # чинить нельзя, — и тут же требует нуля по всему дереву. Это уже не риск, а
    # текстуальное противоречие: ровно случай `kod_reshenia-intervyu`.
    if not zona or not re.search(r'\bкроме\b|\bисключ\w*', zona.group(1), re.I):
        return []
    # 🔴 ПО СТРОКАМ, а не по предложениям: деление на предложения рвётся о точки
    # внутри самой команды (`--exclude-dir=.git`, цель `.`), и пункт критерия
    # распадается ровно там, где стоит его доказательство. Пункт критерия —
    # строка.
    for punkt in kriterij.splitlines():
        sploshnoj = Z8_SPLOSHNOJ_RE.search(punkt)
        if not sploshnoj:
            continue
        # 🔴 Ноль обязан относиться К ЭТОЙ КОМАНДЕ — ищем его ПОСЛЕ неё. Иначе
        # первый пункт критерия почти каждого захода («`sh test.sh` → `echo $?`
        # = 0»), в котором рядом упомянут рекурсивный grep, читался как
        # требование нуля от grep (находка верификатора B3).
        absolut = Z8_ABSOLUT_RE.search(punkt, sploshnoj.end())
        if not absolut or Z8_ISKLYUCHENIE_RE.search(punkt):
            continue
        return [("З8", f"критерий требует «{_citata(punkt, 120, absolut.group(0))}» — абсолютный счёт по "
                        f"ВСЕМУ дереву, а зона захода уже репозитория "
                        f"(«{_citata(zona.group(1), 60)}»): вхождения вне зоны "
                        f"исполнителю не починить. Исключи неприкосновенные пути "
                        f"из самой команды либо назови строкой, сколько вхождений "
                        f"законно и почему")]
