# ДО того, как блок стал обязательным, и З10 на них КРАСНЕЕТ. Это не то ложное
# красное, от которого закон защищает: файл действительно не несёт блока, ставшего
# обязательным, — красное ИСТИННО. Закон запрещает линтеру шуметь на здоровом, а
# здесь он называет реальный унаследованный долг, и ровно эти два файла служат
# З10 ПОЛОЖИТЕЛЬНЫМ КОНТРОЛЕМ (ловушка 24 фикстуры) — живым, а не синтетическим.
# Практического шума ноль: каждый будущий заход рождается из генератора уже с
# блоком, а старые заходы никто не линтует повторно.
#
# 🔴 СУДИТСЯ ТОЛЬКО ЗАДАНИЕ — текст ДО `## ПЛАН`, как у З8, и по той же причине:
# ниже начинается писанина исполнителя, и заход, ОБСУЖДАЮЩИЙ маркер пустоты в
# своём плане или отчёте, не должен краснеть из-за цитаты.
# 🔴 ФОРМА БЛОКА ИЗМЕНИЛАСЬ 14.08 (заход `nositeli-gen`, шаг 2): слоты 0, 2 и 3
# уехали в ПРОМПТ СУБАГЕНТА, слот 1 остался в окне исполнителя. Замер: контур
# занимал ~24 строки из ~290 и на содержание задачи не влиял — кроме влития, без
# которого инструмента на диске может не быть вовсе. Клауза следует за
# генератором: она сторожит те же три вещи, но там, где они теперь лежат, —
# иначе линтер красил бы КАЖДЫЙ свежесобранный заход, а генератор с линтером
# разъехались бы молча.
GIT_KONTUR_ZAGOLOVOK = re.compile(r'^###\s+0\.1\s.*ГИТ-КОНТУР', re.M)
GIT_KONTUR_SLOTY = [
    ("ВЛИТЬ ПЕРЕД РАБОТОЙ", re.compile(r'^\*\*1\.\s*ВЛИТЬ\s+ПЕРЕД\s+РАБОТОЙ', re.M)),
    ("ОСТАЛЬНОЙ КОНТУР — В СУБАГЕНТА",
     re.compile(r'^\*\*2\.\s*ОСТАЛЬНОЙ\s+КОНТУР', re.M)),
]
# 🔴 ДВЕРЬ К ОСТАЛЬНОМУ КОНТУРУ. Сам текст пунктов 0/2/3 в файле-заходе больше
# НЕ ЛЕЖИТ — он печатается командой (в этом и был смысл выноса: блок §0.1 иначе
# растёт вместо того, чтобы сокращаться). Значит линтер обязан сторожить не
# текст, а ДВЕРЬ: команду, которой исполнитель этот текст получает. Содержимое
# самого промпта сторожит фикстура `fixtures/zahod/PROGNAT.sh` — это работа над
# инструментом, а не над файлом-заходом, и разделены они намеренно.
SUBAGENT_DVER_RE = re.compile(r'bootstrap_zahod\.py\s+--zadanie-subagentu')
NE_ZAPOLNENO_MARKER = "НЕ ЗАПОЛНЕНО"


def check_z10_git_kontur(text):
    m = ZADANIE_KONEC_RE.search(text)
    zadanie = text[:m.start()] if m else text
    zag = GIT_KONTUR_ZAGOLOVOK.search(zadanie)
    if not zag:
        return [("З10", "нет блока «### 0.1 ГИТ-КОНТУР» в шапке — заход не называет, "
                        "что влить ДО работы, что забрать в git ПО ХОДУ и что погасить "
                        "ПОСЛЕ. Собирается генератором: `bootstrap_zahod.py … "
                        "[--vlit <ветка>] [--kommitit \"<что>\"] [--zakryt \"<что>\"]`")]
    # Блок кончается следующим `## `-заголовком (`## 1. ДИСЦИПЛИНА`) — внутри него
    # живут только три слота, поэтому границу слота задаёт следующий слот, а
    # границу третьего — конец блока.
    hvost = zadanie[zag.end():]
    konec = re.search(r'^##\s', hvost, re.M)
    blok = hvost[:konec.start()] if konec else hvost

    granicy = []
    for imya, pat in GIT_KONTUR_SLOTY:
        mm = pat.search(blok)
        granicy.append((imya, mm))
    msgs = []
    for i, (imya, mm) in enumerate(granicy):
        if mm is None:
            msgs.append(("З10", f"в блоке §0.1 нет слота «{imya}» — блок и генератор "
                                f"разъехались, чинить генератор, а не заход"))
            continue
        sled = next((g[1].start() for g in granicy[i + 1:] if g[1] is not None), len(blok))
        telo = blok[mm.end():sled]
        # Заголовок слота несёт свою пояснительную фразу, поэтому «непусто»
        # считается по строкам НИЖЕ него: это и есть место, куда аналитик пишет.
        soderzhimoe = "\n".join(telo.splitlines()[1:]).strip()
        if not soderzhimoe:
            msgs.append(("З10", f"слот «{imya}» блока §0.1 ПУСТ — нужна конкретика либо "
                                f"явное «нечего, проверено командой …»; молчание "
                                f"неотличимо от «здесь ничего не требуется»"))
    # 🔴 Без двери вынос контура означал бы, что три четверти контура (заявки,
    # коммиты по ходу, гашение) перестали доезжать до исполнителя ВООБЩЕ, а блок
    # §0.1 остался бы зелёным и коротким — то есть выглядел бы как улучшение.
    if not SUBAGENT_DVER_RE.search(blok):
        msgs.append(("З10", "в блоке §0.1 нет команды `bootstrap_zahod.py "
                            "--zadanie-subagentu` — остальной контур (очередь заявок, "
                            "что забрать в git, что погасить) до исполнителя не "
                            "доедет вовсе. Чинить генератор, а не заход"))
    # 🔴 ПОИМЁННО, А НЕ «где-то есть маркер». Слоты 2 и 3 уехали к субагенту, но
    # спрашивают они по-прежнему разное — что ЗАБРАТЬ в git и что ПОГАСИТЬ, — и
    # аналитик забывает их поодиночке. Сообщение «в блоке есть незаполненный
    # слот» заставило бы искать глазами, какой именно.
    for stroka in blok.splitlines():
        if NE_ZAPOLNENO_MARKER not in stroka:
            continue
        if "--kommitit" in stroka:
            imya = "ЗАКОММИТИТЬ ПО ХОДУ"
        elif "--zakryt" in stroka:
            imya = "ЗАКРЫТЬ ПОСЛЕ"
        else:
            imya = "неизвестный (маркер без подсказки флага)"
        msgs.append(("З10", f"слот «{imya}» блока §0.1 не заполнен — стоит маркер "
                            f"генератора «{NE_ZAPOLNENO_MARKER}». Дозаполни при "
                            f"пересборке захода соответствующим флагом"))
    return msgs


