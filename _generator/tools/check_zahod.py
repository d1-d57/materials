# ── З19: греп-критерий с кириллическим диапазоном — ложный ноль ───────────────
# Дом: `zahody` КРТ-033 и КРТ-РАЗН-21. Второе место того же дефекта: диапазон
# живёт не в коде инструмента, а в КОМАНДЕ, которую заход даёт исполнителю как
# КРИТЕРИЙ. Цена этого места оплачена отдельно и она хуже кодовой: критерий,
# заданный кириллическим классом, под `LC_ALL=C` даёт ложный счёт, а ложный
# НОЛЬ в критерии читается как «дефектов нет» — и стоит целого прохода, потому
# что заход при этом выглядит зелёным.
#
# 🔴 РАЗЛИЧЕНИЕ ТО ЖЕ, ЧТО В `check_tool_contract.check_cyrillic_range`:
# краснеет ШЕЛЛ (`grep`/`sed`/`awk`), а строка с `python` не судится вовсе —
# в питоновском `re` тот же диапазон корректен (замер 15.08 в докстринге той
# функции). Сторож, красящий оба случая, зашумит каждый питоновский однострочник
# в критериях, и его отключат вместе с остальным линтером.
#
# 🔴 ОБЪЯВЛЕННОЕ ИСТИННОЕ КРАСНОЕ, А НЕ ЛОЖНОЕ: заход, который САМ чинит этот
# дефект, показывает его строкой замера — и краснеет. Это не сбой калибровки:
# строка в файле-заходе исполнима, и всякий, кто её скопирует, получит ту же
# ложь. Класс тот же, что у З10/З11 на калибровочных заходах (докстринг модуля,
# закон 2), и лечится он так же — переписать замер на python либо на явное
# перечисление букв.
Z19_SHELL_RE = check_tool_contract.SHELL_TOOL_RE
Z19_KIR_RE = check_tool_contract.KIR_RANGE_RE


def check_z19_kirillica_v_grepe(text):
    m = ZADANIE_KONEC_RE.search(text)
    zadanie = text[:m.start()] if m else text
    for n, stroka in enumerate(zadanie.splitlines(), 1):
        if "python" in stroka:
            continue  # питоновский `re` корректен — см. шапку клаузы
        if not Z19_SHELL_RE.search(stroka):
            continue
        km = Z19_KIR_RE.search(stroka)
        if km:
            return [("З19", f"строка {n}: греп-критерий с КИРИЛЛИЧЕСКИМ ДИАПАЗОНОМ "
                            f"«{km.group(0)}» — под `LC_ALL=C` он матчит побайтово и "
                            f"врёт, под UTF-8-локалью GNU grep падает «Invalid "
                            f"collation character». Ложный НОЛЬ в критерии читается "
                            f"как «дефектов нет» и стоит целого прохода: перечисли "
                            f"буквы явно либо считай питоном (`python3 -c \"import "
                            f"re; …\"`)")]
    return []


# ── З20: греп-критерий без ограничивающего пути ────────────────────────────
# Дом: `zahody` Р5-66. Критерий готовности часто формулируют так: «`grep -c
