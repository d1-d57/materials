def judge(text, checks=None):
    """`(жёсткие, мягкие)` — списки `(код, сообщение)`.

    `checks` — подмножество жёстких проверок (по умолчанию все `HARD_CHECKS`);
    мягкие (`SOFT_CHECKS`) в подмножество не входят — это печать для человека,
    не гейт для генератора.

    🔴 Секция-носитель («## СТАРТОВОЕ СООБЩЕНИЕ ВЛАДЕЛЬЦУ») вырезается из
    текста ОДИН раз, здесь, до раздачи клаузам (`_bez_startovogo`) — она
    цитата, а не текст задания (докстринг `_bez_startovogo`). Видят ПОЛНЫЙ
    текст только клаузы из `CHECKS_NA_POLNOM_TEKSTE` — З13 (нужна сама
    вырезаемая секция) и З20 (нужен номер строки на исходный файл, не на
    сдвинутый урезанием, см. её докстринг).
    """
    urezanny = _bez_startovogo(text)
    fns = checks or HARD_CHECKS
    hard = [msg for fn in fns
            for msg in fn(text if fn in CHECKS_NA_POLNOM_TEKSTE else urezanny)]
    soft = [msg for fn in SOFT_CHECKS for msg in fn(urezanny)] if checks is None else []
    return hard, soft


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Линтер входа: судит kod_*.md как задание, до того как его запустили. "
                    "Судит только текст — ничего не исполняет (см. докстринг).")
    ap.add_argument("paths", nargs="+", help="файлы kod_*.md для проверки")
    a = ap.parse_args(argv)

    # 🔴 ТРИ ИСХОДА, А НЕ ДВА (Рычаг 3, `КРТ-061`/`Р5-3`, заход `rychagi-3`):
    # 0 — чисто, 1 — НАШЁЛ ДЕФЕКТ, 2 — ПОЗВАЛИ НЕВЕРНО. До этого нечитаемый файл
    # давал ту же единицу, что и найденный дефект: «линтер отработал и нашёл
    # плохое» и «линтер вообще не посмотрел на файл» выглядели снаружи
    # одинаково, и второе читалось как первое. `argparse` уже отдаёт 2 на
    # отсутствующем аргументе и неизвестном флаге — здесь тот же код доводится
    # до последнего случая неверного вызова, чтобы контракт был сплошным.
    # Неверный вызов ПЕРЕВЕШИВАЕТ найденные дефекты: если хоть один вход не
    # прочитан, охват прогона неизвестен, и «нашёл дефект» о нём не сообщает.
    bad = 0
    nevernyj_vyzov = 0
    for p in a.paths:
        path = Path(p)
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as e:
            print(f"❌ {p}: не читается ({e.__class__.__name__}) — это НЕВЕРНЫЙ ВЫЗОВ (rc=2), "
                  f"а не найденный дефект")
            nevernyj_vyzov += 1
            continue
        hard, soft = judge(text)
        if hard or soft:
            print(f"── {p}")
            for code, msg in hard:
                print(f"❌ {code}: {msg}")
            for code, msg in soft:
                print(f"⚠ {code}: {msg}")
            bad += len(hard)
    if nevernyj_vyzov:
        return 2
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
