    posl = pts[-1]
    if Z15_POLNAYA_RE.search(posl) or Z15_KOROTKAYA_RE.search(posl):
        return [("З15", "последний пункт критерия готовности назван ОБЯЗАТЕЛЬНЫМ — "
                        "исполнитель читает список сверху вниз и решает, что критерий "
                        "выполнен, ДО того как дойдёт до конца (КРТ-041/Р5-10); "
                        "переставь пункт выше или вынеси его отдельной строкой "
                        "перед списком")]
    return []


