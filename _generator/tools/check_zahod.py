# надежда (`KONSTITUCIYA §11`), и вернулось бы к ручному вписыванию за день.
#
# 🔴 ОБЪЯВЛЕННОЕ ОТСТУПЛЕНИЕ ОТ ЗАКОНА КАЛИБРОВКИ (шапка файла, п. 2). Оба
