# калибровочных из докстринга модуля) дал ложное на «Существительное не
# выбрасывается» («существ» — префикс совсем другого слова, не формы глагола
# «существовать») и грозил массово красить стоковую фразу «живой прогон/
# корпус/эталон» (сотни вхождений в корпусе) — «живой» не форма предиката
# «жива», а прилагательное; граница `\b` после необязательной гласной уже
# отсекает её по построению (`жив[аоы]?\b` не матчит «живо**й**», т.к. после
# «о» стоит «й», не граница слова). Итог сужения: ТОЧНЫЙ список словоформ, не
# открытые основы. Замер после сужения на тех же 27 файлах: 10 срабатываний
# предиката в жирных спанах, у ВСЕХ 10 в окне ±300 нашёлся backtick — **ложных
# 0**, гейт молчит на живом корпусе целиком.
#
# 🔴 ЧЕГО КЛАУЗА НЕ ЛОВИТ (объявленные слепые зоны, симметрично докстринговой
# клаузе 4 самого модуля):
# - **рассуждения о будущем** («получишь X», «станет») — предикат стативный,
#   не будущего времени, класс не пересекается по построению;
# - **цитаты правил** — предикат внутри «ёлочек» или backtick-цитаты
#   (`_v_kavychkah`, тот же дозор, что у З8) не считается новым утверждением;
# - **отрицания-запреты** («не делай», «нельзя») — список ловит СТАТИВНЫЕ
#   формы («лежит», «существует», «доступен»), не императивы; не пересекается
#   по построению, как и «рассуждения о будущем»;
# - **текст внутри ```-блоков** — `_v_fense` глушит матч внутри ограждения;
# - **буквальные ПУТИ в backtick** — это предмет С3 (`check_sborki.py`), не
#   дублируется: спан с backtick-путём проходит проверку «есть backtick рядом»
#   и молчит здесь, живёт своей проверкой там.
Z14_PRED_RE = re.compile(
    r'\b('
    r'лежит|лежат|лежала|лежали|'
    r'доступ(?:ен|на|но|ны)|недоступ(?:ен|на|но|ны)|'
    r'на месте|не на месте|'
    r'жив[аоы]?\b|'
    r'существует|существовал[аои]?|перестал[ао]?\s+существовать|'
    r'отсутствует|отсутствуют|отсутствие|'
    r'поставлен[аоы]?|не поставлен[аоы]?|'
    r'выполнен[аоы]?|не выполнен[аоы]?'
    r')\b', re.I)
