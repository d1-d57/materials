# построчный проход по нему. Второе смещение — граница СЕКЦИИ: красное
# годится только внутри «## 2. ЗАДАЧА» (где живёт и **КРИТЕРИЙ ГОТОВНОСТИ**,
# у него нет своего `##`-заголовка — он жирный спан внутри ЗАДАЧИ, ровно как
# у KRITERIJ_RE выше). Строка ГИГИЕНЫ («Г5: `grep -c '<имя файла>' <карта
# своего корня>` → 1») лежит в «## 4.1 ГИГИЕНА», вне этой границы, и красить
# её нечем по построению — она рабочая команда с путём-плейсхолдером, а не
# пример дефекта.
#
# 🔴 ОТСЕЧКА ПО РОЛИ, А НЕ ПО ФОРМЕ — ЗАВЕДОМО ШИРЕ ДВУХ ПРИМЕРОВ-МАРКЕРОВ ИЗ
# ЗАХОДА («пример», «дефект», «было», «нельзя»), ПОТОМУ ЧТО ЖИВОЙ ОТРИЦАТЕЛЬНЫЙ
# КОНТРОЛЬ — ЭТОТ САМЫЙ ФАЙЛ: «### Что ловим» цитирует дефектный греп дословно
# («часто формулируют так: «`grep -c "фраза"`» — она задана строкой этого
# самого докстринга), а «### Механика» п.2 перечисляет три ФОРМЫ греп-вызова
# как фрагменты правила, не как исполнимую инструкцию. Ни то ни другое —
# не команда исполнителю, и клауза, красящая их, наказывала бы здоровый
# заход за то, что он ОБЪЯСНЯЕТ собственный класс дефекта (тот же промах,
# что уже разбирал З9 про «роль слова, а не присутствие слова»).
# Признак роли — ДВА независимых сигнала, срабатывает любой:
#   (а) греп-токен стоит ВНУТРИ «ёлочек» — этот репозиторий уже метит так
#       цитируемую речь. 🔴 НЕ `_v_kavychkah` целиком: та ИЛИ-объединяет « »
#       с backtick-чётностью, а backtick в этом файле — универсальная
#       разметка ЛЮБОЙ команды, и живой, и цитаты («`grep -c "текст"`» —
#       backtick есть у обеих). Взятая целиком, `_v_kavychkah` объявила бы
#       цитатой КАЖДЫЙ греп в backtick и не покрасила бы ни одного —
#       живая находка калибровки (синтетический позитив с `` `grep -c
#       "…"` `` без пути молчал, пока проверка не сузилась до одних « »).
#       Здесь — своя `_v_yolochkah`, только « »-половина того же приёма.
#       Строка «### Что ловим» этого файла оборачивает ВЕСЬ приведённый
#       пример («`grep -c "фраза"`» вместе со словом `grep`) в « », а
#       реальный живой дефектный критерий («grep «шаблон» = пусто», корпус
#       `kod_lekcia1-modeli.md`) держит « » только вокруг ШАБЛОНА ПОИСКА —
#       слово `grep` там снаружи « », сигнал не срабатывает, критерий красится;
#   (б) на той же строке, ДО греп-токена, встречается слово-маркер цитаты —
#       список НАМЕРЕННО ШИРЕ данных заходом четырёх слов: добавлены
#       «формулир» (формулируют/формулировка — ровно то, чем открывается
#       пример в «### Что ловим»), «например» и сам символ `⚠` — этим корпус
#       уже метит «предостережение о прошлой ошибке» ПОВСЮДУ (в том числе
#       этот файл-заход, «⚠ ложное красное здесь вероятнее»), и живая
#       калибровка нашла ровно такую строку: `kod_zamykanie.md` — «⚠ Две
#       ловушки уже сработали: `grep 'тривиально'` ловит `нетривиально`
#       подстрокой…» — предостережение о ПРОШЛОЙ ошибке чужого грепа, не
#       инструкция исполнителю. Пропустить дефект дешевле, чем покрасить
#       здоровый текст (это же правило заход называет прямо, «### Механика»
#       п.3) — отсечка расширяется в эту сторону, не в другую.
# 🔴 СЛЕПАЯ ЗОНА, НАЗВАННАЯ ЯВНО: (а)/(б) — эвристика по ФОРМЕ строки, не по
# грамматике. Реальный дефектный критерий, процитировавший себя маркерным
# словом ВНЕ этого списка («опечатка», «черновик», «было раньше» — есть в
# списке только «было» без «раньше», совпадёт), или обернувший ВЕСЬ вызов в
# « » без слова-маркера рядом, пройдёт МОЛЧА — ложный ПРОПУСК, не ложное
# красное. Это осознанный перекос (см. п.3 выше), а не недосмотр; калибровка
# §2 обязана проверить его поимённым разбором, а не полагаться на регексп.
#
# 🔴 СЛЕПАЯ ЗОНА №2, НАЙДЕНА КАЛИБРОВКОЙ И НЕ ЗАКРЫТА НАМЕРЕННО: РАЗБОР
# СТРОЧНЫЙ (приём З19), А MARKDOWN ПЕРЕНОСИТ ОДНО ПРЕДЛОЖЕНИЕ НА НЕСКОЛЬКО
# ФИЗИЧЕСКИХ СТРОК. Живой ложный случай — `kod_doktrina-v-nastoyashchuyu-
# disciplinu.md`: «`grep -c 'obosnovanie_verstki'` и\n   `grep -c
# 'zagolovok_snyat_namerenno'` по \`SKILL.md\` + \`kartochka-slajda.md\`» —
# путь назван, но на СЛЕДУЮЩЕЙ физической строке того же предложения; строчный
# разбор его не видит и красит здоровый критерий. Не чинится склейкой
# соседних строк В ЛОБ: склейка «текущая+следующая» замаскировала бы РЕАЛЬНЫЙ
# дефект в предыдущем пункте того же нумерованного списка, если следующий
# пункт случайно упомянет путь (риск новой, менее предсказуемой дыры вместо
# старой). Оставлено как есть: пропустить дефект дешевле, чем гнаться за
# регекспом без конца (заход, «### 🔴 КАЛИБРОВКА», «не подгоняй регексп
# бесконечно») — уже третье сужение подряд, и это последний найденный класс.
#
# 🔴 «ПУТЬ» СУДИТСЯ ПО ФОРМЕ СТРОКИ, НЕ ПО ФАЙЛОВОЙ СИСТЕМЕ: `/` (разделитель
# каталога), `--include`, токен «слово.расширение» (латиница, 1-5 букв —
# охватывает `.py`/`.md`/`.sh`/`.txt` и подобные, НЕ охватывает кириллические
# сокращения «т.д.»/«т.е.», которые дали бы ложный «путь найден» на обычной
# прозе), либо `<плейсхолдер>` в угловых скобках — конвенция ЭТОГО корпуса
# для «путь подставит контекст/инструмент» (живой пример — Г5 КОНТРАКТА ЗОНЫ
# этого самого файла: «`grep -c '<имя файла>' <карта своего корня>`» — путь
# не литерален, но ОГРАНИЧИВАЕТ, а не отсутствует). Диапазон СЧИТАЕТСЯ ПО
# ВСЕЙ СТРОКЕ command'ы, а не только по хвосту после греп-токена — «этой же
# команде» из «### Механика» п.2 не обещает порядок аргументов, и живой
# пример `kod_dajdzhesty-i-mit.md:189` («`grep -c '^## \`' VYCHITANO.md`»)
# ставит путь ПОСЛЕ шаблона поиска.
#
# 🔴 СУЖЕНИЕ ПОСЛЕ ПЕРВОЙ КАЛИБРОВКИ (§2 захода) — ГРЕП В ПАЙПЕ НЕ СУДИТСЯ
# ПО ПУТИ ВООБЩЕ. Живой корпус: `git branch | grep -c main`
# (`kod_odna-vetka.md`), `git … status --porcelain | grep "^ D" | wc -l`
# (`kod_chistka-diska.md`) — три из первых пяти разобранных находок были
# РОВНО этого вида. Дерево тут ни при чём: `grep` без `-r` и без файлового
# аргумента читает СТАНДАРТНЫЙ ВВОД, а не CWD — когда токен идёт СРАЗУ ПОСЛЕ
# `|` (не считая пробелов/backtick), его вход уже ограничен ВЫВОДОМ предыдущей
# команды, и «путь» в претензии Р5-66 неприменим по построению, что бы ни
# стояло дальше по строке. Отличать от `\|` — экранированной альтернативы
# ВНУТРИ шаблона поиска (`grep «меняй ленту\|строка меняется» = пусто»`,
# живой дефект `kod_lekcia1-modeli.md`): там `|` стоит ПОСЛЕ греп-токена и
# внутри кавычек шаблона, не «прямо перед» им — `_posle_pajpa` смотрит
# СТРОГО назад от начала токена, этот случай не трогает.
Z20_GREP_TOOL_RE = re.compile(r'\b(?:grep|egrep|fgrep|rg)\b')
Z20_PUT_RE = re.compile(r'--include|/|\b[\w-]+\.[a-zA-Z]{1,5}\b|<[^<>\n]+>')
Z20_CITATA_MARKER_RE = re.compile(r'пример|дефект|\bбыло\b|нельзя|формулир|например|⚠', re.I)
Z20_ZADACHA_ZAGOLOVOK_RE = re.compile(r'^##\s+2\.\s+ЗАДАЧА\b', re.M)


def _posle_pajpa(s, i):
    """Токен на позиции `i` идёт СРАЗУ ПОСЛЕ `|` (не считая пробелов/backtick)?

    Значит команда читает СТАНДАРТНЫЙ ВВОД (вывод предыдущей по конвейеру), а
    не дерево каталогов — «ограничивающий путь» Р5-66 к ней неприменим.
    """
    return s[:i].rstrip(' \t`').endswith('|')


def _v_yolochkah(s, i):
    """Позиция `i` — внутри «ёлочек» («…»)? Только эта половина `_v_kavychkah`

    (см. докстринг клаузы выше про то, почему backtick-половину сюда брать
    нельзя): в разметке команд backtick несёт и живую инструкцию, и цитату
    одинаково, а « » в этом корпусе — маркер именно ЦИТИРУЕМОЙ речи.
    """
    return s.count('«', 0, i) > s.count('»', 0, i)


# 🔴 СУЖЕНИЕ ВТОРОГО РАУНДА (§2 захода, «⚠ ложное красное здесь вероятнее»):
# ГОЛОЕ УПОМИНАНИЕ ТОКЕНА БЕЗ АРГУМЕНТА — НЕ КОМАНДА. Живой корпус:
# «**`grep` по репозиторию на отменённую формулировку**» (`kod_dobivka-
# registracii.md`) и «`grep` по скиллу и по дому находит…» (`kod_kanon-
# put.md`) — в backtick лежит ГОЛОЕ слово `grep` (или «`grep -c`» без
# паттерна), а область поиска названа ПРОЗОЙ СНАРУЖИ backtick («по
# репозиторию», «по скиллу и по дому») — это описание намерения, не
# исполнимая команда, и красить нечем: аргумента для грепа тут не было ДО
# правки, не после неё. Отличие от истинного дефекта («`grep -c
# MISSING-MATH`» → 0, `kod_vizitka-i-oblozhka.md`) — там ПОСЛЕ токена и
# флагов внутри ТОГО ЖЕ backtick-спана стоит аргумент-паттерн (кавычка или
# голый идентификатор); здесь backtick закрывается сразу за флагами.
def _bez_argumenta(s, tm):
    """У греп-токена `tm` нет АРГУМЕНТА в его же backtick-спане — ни

    кавычки, ни голого идентификатора после токена и его `-флагов`, только
    закрывающий backtick или конец строки. Значит это упоминание СЛОВОМ
    («`grep` по репозиторию…»), а не вызов, который можно исполнить как есть.

    🔴 Флаг — `[^\\s\\x60]+` (НЕ `\\S+`): живая находка калибровки на
    `kod_dver-urokov.md` — «(`grep -c` до и после…)» — `\\S+` жадно съедал
    ЗАКРЫВАЮЩИЙ backtick вместе с флагом («-c`» как один токен), после чего
    хвост строки начинался с русской прозы, а не с backtick, и голый вызов
    БЕЗ аргумента ошибочно читался как вызов С аргументом.
    """
    posle = re.sub(r'^(?:\s+-{1,2}[^\s`]+)*', '', s[tm.end():]).lstrip()
    return posle[:1] in ('', '`')


# 🔴 СУЖЕНИЕ ВТОРОГО РАУНДА, ЕЩЁ ОДИН КЛАСС: СОСТАВНОЕ СЛОВО — НЕ ТОКЕН.
# Живой корпус: «grep-паттерн ловит не то, что заявлено» (`kod_rychagi.md`)
# — здесь `grep` вообще не команда, а половина сложного русского
# существительного («грep-паттерн» = «поисковый паттерн»), даже без
# backtick вокруг. Отличать от реального флага («grep -c»): у флага между
# токеном и дефисом ВСЕГДА пробел (эта же форма — единственная, что
# встречает калибровка по всему корпусу), у составного слова дефис
# приклеен вплотную. Проверка ПРЕДШЕСТВУЕТ `_bez_argumenta` по построению:
# составное слово — не команда вовсе, а не команда-без-аргумента.
def _sostavnoe_slovo(s, tm):
    """Сразу после токена (без пробела) идёт `-буква` — сложное слово, не флаг."""
    return bool(re.match(r'-[a-zA-Zа-яА-ЯёЁ]', s[tm.end():tm.end() + 2]))


def _granica_sekcii(text, zagolovok_re):
    """`(start, end)` символьные границы секции — от конца заголовка до

    следующего `## `-заголовка или конца текста. `None`, если заголовка нет.
    Отдельно от `_section()` выше: тому нужно ТЕЛО секции строкой, здесь
    нужны СМЕЩЕНИЯ — чтобы отличить позицию совпадения ВНУТРИ секции от
    позиции СНАРУЖИ на полном тексте `zadanie`, без пересчёта номеров строк.
    """
    m = zagolovok_re.search(text)
    if not m:
        return None
    tail = text[m.end():]
    nxt = re.search(r'^##\s', tail, re.M)
    return m.end(), m.end() + (nxt.start() if nxt else len(tail))


def check_z20_grep_bez_puti(text):
    """🔴 ВИДИТ ПОЛНЫЙ ТЕКСТ (см. `CHECKS_NA_POLNOM_TEKSTE`), не урезанный —

    и это НЕ повторяет свойство З13 «просто по аналогии»: без полного текста
    номер строки в сообщении СИСТЕМАТИЧЕСКИ ВРЁТ. `judge()` в норме режет
    секцию «## СТАРТОВОЕ СООБЩЕНИЕ ВЛАДЕЛЬЦУ» ДО раздачи клаузам
    (`_bez_startovogo`) — она заметно длиннее одной строки (замер на живом
    заходе `kod_kanon-put.md`: 1151 символ), и всё, что лежит НИЖЕ неё —
    то есть «## 2. ЗАДАЧА» ВСЕГДА — сдвигается на эту длину. Подсчёт `\\n`
    от НАЧАЛА урезанного текста называет строку из СЕРЕДИНЫ чужого места
    файла: живая калибровка (§2 захода) поймала это САМА СОБОЙ — три из
    первых находок оказались строками без единого `grep`, потому что номер
    считался по вырезанному тексту, а печатался как будто по исходному.
    Секция-границы и совпадения ищутся на СВОЁМ урезанном срезе (это
    безопасно: «## 2. ЗАДАЧА» лежит после вырезаемого блока, содержимое
    самой секции им не тронуто) — искажён только номер строки, поэтому
    чинится он один, отдельным поиском найденной СТРОКИ в исходном тексте.
    """
    urezanny = _bez_startovogo(text)
    m = ZADANIE_KONEC_RE.search(urezanny)
    zadanie = urezanny[:m.start()] if m else urezanny
    granica = _granica_sekcii(zadanie, Z20_ZADACHA_ZAGOLOVOK_RE)
    if granica is None:
        return []
    start, end = granica
    for lm in re.finditer(r'^([^\n]*)$', zadanie, re.M):
        if lm.start() < start or lm.start() >= end:
            continue
        stroka = lm.group(1)
        for tm in Z20_GREP_TOOL_RE.finditer(stroka):
            if Z20_PUT_RE.search(stroka):
                break  # путь/--include/расширение/плейсхолдер — не дефект
            if _posle_pajpa(stroka, tm.start()):
                continue  # читает вывод предыдущей команды, не дерево
            if _sostavnoe_slovo(stroka, tm):
                continue  # «grep-паттерн» — сложное слово, не вызов
            if _bez_argumenta(stroka, tm):
                continue  # голое упоминание токена, не исполнимая команда
            if _v_yolochkah(stroka, tm.start()):
                continue  # греп-токен ВНУТРИ «ёлочек» целиком — цитата
            if Z20_CITATA_MARKER_RE.search(stroka[:tm.start()]):
                continue  # маркер цитаты раньше по этой же строке
            pozicia_v_originale = text.find(stroka)
            n = (text.count('\n', 0, pozicia_v_originale) + 1
                 if pozicia_v_originale >= 0 else '?')
            return [("З20", f"строка {n}: греп-критерий «{stroka.strip()[:90]}» "
                            f"без ограничивающего пути — идёт по ВСЕМУ дереву "
                            f"репозитория, ложный НОЛЬ читается как «дефектов "
                            f"нет» и стоит целого прохода (Р5-66). Добавь "
                            f"путь/`--include`/ограничение каталогом")]
    return []


# 🔴 Судят ПОЛНЫЙ, а не урезанный ОТ секции-носителя текст. Две клаузы, две
# РАЗНЫЕ причины (см. докстринги `check_z13_startovoe` и
# `check_z20_grep_bez_puti` выше и `judge()` ниже, где текст урезается для
# всех остальных): З13 ищет саму секцию-носитель, которая иначе вырезана;
# З20 ищет содержимое ПОСЛЕ неё, но обязана номером строки на исходный файл,
# а урезание сдвигает всё, что ниже, на длину вырезанного блока.
CHECKS_NA_POLNOM_TEKSTE = {check_z13_startovoe, check_z20_grep_bez_puti}


def _bez_startovogo(text):
    """Текст БЕЗ секции «## СТАРТОВОЕ СООБЩЕНИЕ ВЛАДЕЛЬЦУ» — она ЦИТАТА, не задание.

    🔴 ГЛАВНАЯ ЛОВУШКА, НАЙДЕННАЯ ЖИВЫМ ПРОГОНОМ (заход `nositel`, ## ЗАДАЧА
    шаг 1). Блок канала `app` внутри секции несёт строку `## ПЛАН внутри него —
    до всяких действий` — это литеральный markdown-заголовок второго уровня.
    Секция стоит в НАЧАЛЕ файла, поэтому без вырезания:
    - `ZADANIE_KONEC_RE` (`^##\\s+ПЛАН\\b`) находит ЕЁ раньше настоящего
      `## ПЛАН`, и «задание» (текст, который судят З8/З10/З12) схлопывается до
      нескольких строк шапки — блок §0.1 ГИТ-КОНТУР там не помещается по
      построению, и З10/З12 красят каждый свежесобранный заход ложно;
    - З9 считает заголовки регуляркой `^##\\s+ПЛАН\\b` и находит два.
    Секция — цитата, а не текст задания, и все клаузы обязаны её игнорировать.
    Вырезано ОДИН раз, здесь, а не починкой З9/З10/З12 по отдельности — три
    места разъехались бы при первой же правке формулировки блока.

    🔴 ГРАНИЦА СЕКЦИИ УЧИТЫВАЕТ ```-ОГРАЖДЕНИЕ. Наивный поиск «следующего
    `^##\\s`» ловится на ТОЙ ЖЕ ловушке ещё раз, но внутри себя: канал `app`
    несёт строку `## ПЛАН внутри него — до всяких действий` ВНУТРИ
    ```` ``` ````-блока секции — это тоже `^##\\s`, и наивная граница обрубает
    секцию посреди неё, оставляя хвост блока («## ПЛАН внутри него…\\n```…»)
    в «урезанном» тексте, где он снова читается как настоящий `## ПЛАН`.
    Живой прогон пробного захода поймал это самим собой (`check_zahod.py`
    красил З9/З10/З12 на свежесобранном файле). Границей считается только
    строка `^##\\s`, стоящая ВНЕ ```-ограждения.

    🔴 ГРАНИЦА ТАКЖЕ ОСТАНАВЛИВАЕТСЯ НА `^──` — И ЭТО ВТОРАЯ ПОЛОВИНА ТОЙ ЖЕ
    НАХОДКИ, живым прогоном чужой (но применимой) фикстуры `fixtures/gigiena/
    PROGNAT.sh`. Секция-носитель в `bootstrap_zahod.py` встаёт ПЕРЕД блоком
    «── СЧЁТ НЕЗАКРЫТОГО (печать, не гейт) ──» — тот НЕ является `##`-заголовком,
    и граница только по `##` проезжала мимо него дальше, до `## ЧТО
    ФИНАЛИЗИРОВАНО НА ИНТЕРВЬЮ», вырезая ЧУЖОЙ легитимный текст (сам блок
    СЧЁТ и абзац КОНТЕКСТ.) вместе с секцией — а не только секцию. Итог:
    check_sborki С8 переставала видеть «## 4.1 ГИГИЕНА» на КАЖДОМ свежем
    заходе (она смещалась в «урезанном» тексте, но это уже симптом того же
    промаха дальше по файлу — граница обязана быть точной, а не «примерно
    после секции»).
    """
    m = re.search(STARTOVOE_ZAGOLOVOK_RE, text, re.M)
    if not m:
        return text
    hvost = text[m.end():]
    v_fense, konec = False, len(hvost)
    for lm in re.finditer(r'^([^\n]*)$', hvost, re.M):
        line = lm.group(1)
        if line.strip().startswith('```'):
            v_fense = not v_fense
            continue
        if not v_fense and re.match(r'^(##\s|──)', line):
            konec = lm.start()
            break
    return text[:m.start()] + hvost[konec:]


