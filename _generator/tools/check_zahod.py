    out = []
    for m in re.finditer(r'\d+', span):
        levo = span[:m.start()]
        if re.search(r'[A-ZА-ЯЁ]$', levo):
            continue  # «Г3», «З1» — цифра вплотную к заглавной: идентификатор
        if re.search(r'[A-Za-zА-Яа-яЁё]-$', levo):
            continue  # «Ф-1», «Г-15» — идентификатор через дефис
