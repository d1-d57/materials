def _section(text, heading_re):
    """Текст ПОСЛЕ строки, совпавшей с `heading_re`, до следующего заголовка
    `## …` или конца файла. Возвращает None, если заголовок не найден.

    Используется и для настоящих markdown-заголовков (`## КОНТРАКТ ЗОНЫ`), и
    для инлайн-жирных «заголовков» внутри секции (`**КРИТЕРИЙ ГОТОВНОСТИ…**») —
    в обоих случаях следующий `## ` markdown-заголовок закрывает секцию.
    """
    m = re.search(heading_re, text, re.M)
    if not m:
        return None
    tail = text[m.end():]
    nxt = re.search(r'^##\s', tail, re.M)
    return tail[:nxt.start()] if nxt else tail


