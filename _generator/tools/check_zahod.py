# 🔴 Подмножество для `bootstrap_zahod.py` (только что собранный файл).
# Свежий скелет ещё НЕ содержит критерия/контекста — их дозаполняет Cowork
# ОТДЕЛЬНЫМ ходом ПОСЛЕ генерации (докстринг bootstrap: «Cowork дозаполняет
# `<...>`»). Живой прогон подтвердил: полный `judge()` красит З2 на КАЖДОМ
# свежесобранном файле (плейсхолдер `## 2. ЗАДАЧА` в шаблоне не содержит
# «живой прогон» и не может — это работа Cowork). Гейтить в момент генерации
# можно только то, за что генератор отвечает САМ: зону (З3, из `--zone`),
# точку входа (З5, из `{{КОНТРАКТ_МЕСТО}}`/`{{ПЕРВЫЙ_ХОД}}`), секции-заготовки
# и формат очереди (З7, из анкоров-инъекций). Иначе гейт отказывал бы всегда.
STRUCTURAL_CHECKS = [
    check_z3_zona,
    check_z5_kanal,
    check_z7_sekcii,
]


def judge(text, checks=None):
    """`(жёсткие, мягкие)` — списки `(код, сообщение)`.

    `checks` — подмножество жёстких проверок (по умолчанию все `HARD_CHECKS`);
    мягкие (`SOFT_CHECKS`) в подмножество не входят — это печать для человека,
    не гейт для генератора.
    """
    hard = [msg for fn in (checks or HARD_CHECKS) for msg in fn(text)]
    soft = [msg for fn in SOFT_CHECKS for msg in fn(text)] if checks is None else []
    return hard, soft


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Линтер входа: судит kod_*.md как задание, до того как его запустили. "
                    "Судит только текст — ничего не исполняет (см. докстринг).")
    ap.add_argument("paths", nargs="+", help="файлы kod_*.md для проверки")
    a = ap.parse_args(argv)

    bad = 0
    for p in a.paths:
        path = Path(p)
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as e:
            print(f"❌ {p}: не читается ({e.__class__.__name__})")
            bad += 1
            continue
        hard, soft = judge(text)
        if hard or soft:
            print(f"── {p}")
            for code, msg in hard:
                print(f"❌ {code}: {msg}")
            for code, msg in soft:
                print(f"⚠ {code}: {msg}")
            bad += len(hard)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
