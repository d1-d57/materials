# можно только то, за что генератор отвечает САМ И БЕЗ ИСКЛЮЧЕНИЙ: зону (З3,
# из `--zone`), точку входа (З5, из `{{КОНТРАКТ_МЕСТО}}`/`{{ПЕРВЫЙ_ХОД}}`),
# секции-заготовки и формат очереди (З7, из анкоров-инъекций жёсткого шаблона).
# Иначе гейт отказывал бы всегда.
