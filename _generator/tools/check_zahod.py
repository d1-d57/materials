# единственный способ не потерять настоящие: «**L2, 18 карточек**» начинается с
# идентификатора `L2`, но несёт живое «18 карточек», ради которого клауза и
# существует. Спан краснеет, если в нём есть ХОТЬ ОДНО число вне шести классов.
Z6_LOZHNYJ_KONTEKST = re.compile(
    r'(?:'
    r'модел\w*\s*:?\s*[A-Za-zА-Яа-яЁё]*\s*|'
    r'(?:sonnet|opus|haiku|fable|claude)\s+|'
    r'(?:част[ьияей]|фаз[аыеуи]|шаг[аиу]?|пункт[аеу]?|этап[аеу]?|уровн\w*|уровень|'
    r'слот[аеу]?|лекци[яию]|раздел[аеу]?|верси[яию]|глав[аыеу])\s+|'
    r'(?:потол\w*|порог\w*|максимум|минимум|лимит\w*|не\s+менее|не\s+более)'
    r'[^.;]{0,40}'
    r')$', re.I)


def _z6_chisla_faktov(span):
    """Числа спана, которые ПРЕТЕНДУЮТ быть фактом о состоянии диска.

    Пусто — спан не несёт ни одного посчитанного числа, и требовать рядом
    команду не за что.
    """
    out = []
    for m in re.finditer(r'\d+', span):
        levo = span[:m.start()]
        if re.search(r'[A-ZА-ЯЁ]$', levo):
            continue  # «Г3», «З1» — цифра вплотную к заглавной: идентификатор
        if re.search(r'[A-Za-zА-Яа-яЁё]-$', levo):
            continue  # «Ф-1», «Г-15» — идентификатор через дефис
        if levo.count('$') % 2 == 1 or re.search(r'[\^_]\{?$', levo):
            continue  # внутри $…$ либо степень/индекс — формула, не метрика
        if not levo and Z6_NOMER_PUNKTA_RE.match(span[m.start():]):
            continue  # класс 6: «N. Заглавная…» — заголовок нумерованного пункта
        if Z6_LOZHNYJ_KONTEKST.search(levo):
            continue
        out.append(m.group(0))
    return out
# Окно ПО СИМВОЛАМ, а не по абзацу: команда-источник числа часто стоит в
# СОСЕДНЕМ абзаце (напр. код-блок с замером — отдельным абзацем ДО утверждения).
# Живой калибровочный файл (`kod_ochered-domov.md`) поймал это на себе: абзац
# «Замер канона: 0 из 8…» сам без backtick, а `` `## ПЛАН` `` / `` `## ВОПРОСЫ` ``
# стоят в абзацах прямо до и после — поабзацная проверка их не видела.
RADIUS = 300


def check_z6_chislo(text):
    for m in BOLD_SPAN_RE.finditer(text):
        span = m.group(1)
        if not NUM_IN_SPAN_RE.search(span):
            continue
        chisla = _z6_chisla_faktov(span)
        if not chisla:
            continue  # версия модели / идентификатор / порядковый номер / норматив
        window = text[max(0, m.start() - RADIUS):min(len(text), m.end() + RADIUS)]
        if '`' in window:
            continue  # рядом уже есть backtick-команда/путь — достаточно
