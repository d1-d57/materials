# ── З9: секции, которые скелет заводит один раз, встречаются РОВНО один раз ────
# Класс дефекта: аналитик дозаполняет сгенерированный скелет вставкой своего
# текста ВЫШЕ по файлу вместо замены шаблонного места — второй, шаблонный,
# остаётся ниже (со своим плейсхолдером и второй «КРИТЕРИЙ ГОТОВНОСТИ»). Линтер
# входа его не видел: З7 проверяет НАЛИЧИЕ секций-заготовок, не их ЕДИНСТВЕННОСТЬ.
#
# 🔴 СЧИТАЮТСЯ ТОЛЬКО ЗАГОЛОВКИ В НАЧАЛЕ СТРОКИ (`re.M`, `^##\s+…`), не вхождения
# подстроки. Имена секций упоминаются в прозе задания (в том числе в ЭТОМ самом
# докстринге и в тексте захода, который заводил эту проверку) многократно —
# считающая подстроку версия красила бы КАЖДЫЙ заход, объясняющий сам класс
# дефекта (тот же промах, что был у первой редакции З8 — роль слова, а не
# присутствие слова).
#
# 🔴 Список — из `_TEMPLATE-zahod.md`, не придуман: секции, которые скелет
# заводит один раз. `## ОТЧЁТ` — это ЗАГОЛОВОК СЕКЦИИ (`## ОТЧЁТ — (заполняет
# исполнитель)`), а не инструктивный «## 5. ОТЧЁТ → секция `## ОТЧЁТ` внизу»,
# который в тексте §5, — паттерн `^##\s+ОТЧЁТ\b` их различает: инструктивный
# заголовок начинается с «## 5.», не с «## ОТЧЁТ».
EDINSTVENNYE_SEKCII = [
    ("задача", r'^##\s+2\.\s+ЗАДАЧА\b'),
    ("верификатор", r'^##\s+3\.\s+ВЕРИФИКАТОР\b'),
    ("план", r'^##\s+ПЛАН\b'),
    ("вопросы", r'^##\s+ВОПРОСЫ\b'),
    ("отчёт", r'^##\s+ОТЧЁТ\b'),
    ("уроки фабрике", r'^##\s+УРОКИ\s+ФАБРИКЕ\b'),
]


def _v_backtike(text, i):
    """Позиция `i` — внутри backtick-цитаты (нечётное число ` до неё)?

    🔴 Живая находка на САМОМ ЭТОМ заходе (§2.1): `KRITERIJ_RE` — не заголовок
    с `^`-якорем (у настоящей строки критерия нет фиксированной позиции в
    строке — шаблон ставит её то первой фразой абзаца, то серединой), якорем
    не защититься. Отчёт, ЦИТИРУЮЩИЙ образец («плюс отдельно строка
    `` `**КРИТЕРИЙ ГОТОВНОСТИ…**` `` ») красил бы себя же — ровно тот же класс
    промаха, что уже упомянут докстрингом выше (роль слова, а не присутствие
    слова), только на другом паттерне. Цитата в backtick — не второе
    требование критерия, а разговор О тексте; `_v_kavychkah` (по соседству)
    уже решает эту же задачу для секции-среза З8, здесь нужна версия на
    ПОЛНОМ тексте документа, а не на предложении.
    """
    return text.count('`', 0, i) % 2 == 1


def check_z9_edinstvennost(text):
    msgs = []
    for name, pat in EDINSTVENNYE_SEKCII:
        n = len(re.findall(pat, text, re.M))
        if n > 1:
            msgs.append(("З9", f"секция «{name}» встречается {n} раза — "
                                f"дозаполняли вставкой вместо замены, снимите "
                                f"шаблонный остаток"))
    krit_matches = [m for m in re.finditer(KRITERIJ_RE, text)
                    if not _v_backtike(text, m.start())]
    n_krit = len(krit_matches)
    if n_krit > 1:
        msgs.append(("З9", f"строка «КРИТЕРИЙ ГОТОВНОСТИ» встречается {n_krit} раза — "
                            f"дозаполняли вставкой вместо замены, снимите "
                            f"шаблонный остаток"))
    return msgs


