# 🔴 Подмножество для `bootstrap_zahod.py` (только что собранный файл).
# Свежий скелет ещё НЕ содержит критерия/контекста — их дозаполняет Cowork
# ОТДЕЛЬНЫМ ходом ПОСЛЕ генерации (докстринг bootstrap: «Cowork дозаполняет
# `<...>`»). Живой прогон подтвердил: полный `judge()` красит З2 на КАЖДОМ
