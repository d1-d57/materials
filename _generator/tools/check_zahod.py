# 🔴 З13 СЮДА НЕ ВХОДИТ — ЖИВАЯ НАХОДКА, РЕВЕРС РЕШЕНИЯ ИЗ `## ПЛАН` п.5.
# Первая редакция включала З13 в STRUCTURAL_CHECKS («секцию производит сам
# генератор — та же ответственность, что у З3/З5/З7»), и живой прогон фикстуры
# `fixtures/dvizhok/PROGNAT.sh` (хук pre-commit, чужая, но применимая по
# TOOL-CONTRACT-COVERS фикстура) уронил её целиком: та кормит генератор
# СИНТЕТИЧЕСКИМ мини-шаблоном без анкора `{{ВЛИТИЕ}}`-секции (`\nКОНТЕКСТ.`,
# тот же якорь, на который садится и секция-носитель) — якорь МЯГКИЙ (как у
# ВОПРОСЫ/УРОКИ/ГИГИЕНА/ФИНАЛИЗИРОВАНО, ни один из которых в STRUCTURAL_CHECKS
# не входит НАМЕРЕННО), его отсутствие законно, и секция на такой заготовке
# просто не вставляется. Жёсткий гейт СРАЗУ ПОСЛЕ мягкой вставки — внутреннее
# противоречие: генератор гарантированно падает на КАЖДОМ шаблоне без этого
# анкора, а такие шаблоны у фикстур законны по построению. Значит «против» из
# исходного захода (## ЗАДАЧА, шаг 2) была верна: З13 остаётся ТОЛЬКО в
# HARD_CHECKS полного `judge()` — ловит настоящий баг вставки на РЕАЛЬНОМ
# шаблоне (у него анкор жёсткий по факту, хоть и не по коду), не роняя
# синтетические заготовки, которых секция не касается вовсе.
STRUCTURAL_CHECKS = [
    check_z3_zona,
    check_z5_kanal,
    check_z7_sekcii,
]


def judge(text, checks=None):
    """`(жёсткие, мягкие)` — списки `(код, сообщение)`.

    `checks` — подмножество жёстких проверок (по умолчанию все `HARD_CHECKS`);
    мягкие (`SOFT_CHECKS`) в подмножество не входят — это печать для человека,
    не гейт для генератора.

    🔴 Секция-носитель («## СТАРТОВОЕ СООБЩЕНИЕ ВЛАДЕЛЬЦУ») вырезается из
    текста ОДИН раз, здесь, до раздачи клаузам (`_bez_startovogo`) — она
    цитата, а не текст задания (докстринг `_bez_startovogo`). Видит ПОЛНЫЙ
    текст только З13 (`CHECKS_NA_POLNOM_TEKSTE`) — ей нужна как раз вырезаемая
    секция.
    """
    urezanny = _bez_startovogo(text)
    fns = checks or HARD_CHECKS
    hard = [msg for fn in fns
            for msg in fn(text if fn in CHECKS_NA_POLNOM_TEKSTE else urezanny)]
    soft = [msg for fn in SOFT_CHECKS for msg in fn(urezanny)] if checks is None else []
    return hard, soft


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Линтер входа: судит kod_*.md как задание, до того как его запустили. "
                    "Судит только текст — ничего не исполняет (см. докстринг).")
    ap.add_argument("paths", nargs="+", help="файлы kod_*.md для проверки")
    a = ap.parse_args(argv)

    bad = 0
    for p in a.paths:
        path = Path(p)
        try:
            text = path.read_text(encoding="utf-8")
        except OSError as e:
            print(f"❌ {p}: не читается ({e.__class__.__name__})")
            bad += 1
            continue
        hard, soft = judge(text)
        if hard or soft:
            print(f"── {p}")
            for code, msg in hard:
                print(f"❌ {code}: {msg}")
            for code, msg in soft:
                print(f"⚠ {code}: {msg}")
            bad += len(hard)
    return 1 if bad else 0


