# ── З14: факт о мире без соседней команды/адреса (обобщение З6 на нечисла) ────
# Рычаг 1, дом `zahody §2` (26 записей, самый крупный класс на 14.08): заход
# утверждает факт о мире («файл лежит там-то», «в источнике этого нет»,
# «инструмент доступен», «раздел на месте», «предпосылка жива») — и ни одно
# такое утверждение сегодня не обязано нести рядом команду/путь, которыми оно
# проверено. З6 уже решил ровно эту задачу для ЧИСЕЛ (KONSTITUCIYA §10);
# здесь — тот же механизм («жирный спан без соседнего backtick в окне ±300»),
# перенесённый на нечисловые стативные утверждения.
#
# 🔴 КАЛИБРОВКА 14.08 (заход `rychagi`) — список форм СУЖЕН по живому корпусу,
# а не выдуман за столом. Прогон черновика с открытыми основами (`существ\w*`,
