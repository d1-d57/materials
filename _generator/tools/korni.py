def _норм(путь):
    """Путь к виду `a/b/c.md` — posix. Принимает и `Path`, и строку.

    `Path.as_posix()` заодно снимает ведущее `./` и схлопывает `//`: инструменты
    зовут реестр и относительным путём из индекса git, и собранным через `/`.
    """
    return Path(путь).as_posix()


def корень_пути(rel):
    """Корень, которому принадлежит путь, либо None — если он вне всех корней.

    Сравниваем ПЕРВЫЙ компонент целиком, а не префиксом строки: префикс
    `_studio` совпал бы и с папкой `_studio-arhiv/`, то есть чужая папка
    судилась бы индексом соседа и молча.

    🔴 Корень с именем `"*"` — «весь репозиторий», совпадает с ЛЮБЫМ путём,
    включая файл прямо в корне (у такого «первый компонент» — имя самого файла,
    и под схему «имя папки» он не ложится ни при какой строке таблицы). Такая
    строка есть у `disciplina`, где документы лежат без общей папки-имени;
    таблица выбирается по активному `REPO` (см. `КОРНИ_ПО_РЕПО` выше), поэтому
    звёздочка одного репозитория не может принять путь другого.
    """
    норм = _норм(rel)
    первый = норм.split("/")[0]
    for к in КОРНИ:
        if к.имя in ("*", первый):
            return к
    return None


