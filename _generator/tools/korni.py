#!/usr/bin/env python3
"""РЕЕСТР КОРНЕЙ — единственный дом ответа «какие корни судятся и чем».

    python3 -c "import sys; sys.path.insert(0,'_generator/tools'); import korni; print(korni.описать())"

ЗАЧЕМ. Путь `_studio` был вшит ЛИТЕРАЛОМ в одиннадцать мест шести инструментов
(`check_kartoteka` ×4, `register_doc` ×2, `git_zona` ×3, `bootstrap_arka`,
`bootstrap_zahod`, `check_incidenty`). Пока это так, вынос любой фабрики в
собственную папку даёт не «фабрику без гейтов», а фабрику с гейтами, которые
МОЛЧАТ, — а молчащий гейт неотличим от зелёного и потому опаснее отсутствующего
(`KONSTITUCIYA §11а`, класс, оплаченный месяцем: четыре гейта и хук числились
существующими и не работали).

🔴 ЭТО ДАННЫЕ, А НЕ ЛОГИКА. Добавление пятой фабрики — ОДНА строка в таблице
`КОРНИ` ниже и НОЛЬ правок в инструментах. Если ради нового корня пришлось
править инструмент — сломан реестр, а не корень; чинить надо здесь.

🔴 ПОЧЕМУ РЕЕСТР ОТВЕЧАЕТ НА ТРИ ВОПРОСА, А НЕ ХРАНИТ ОДНО ИМЯ. «Вынесем `_studio`
в константу» — самая вероятная ошибка этой расшивки: она даёт один корень под
новым именем и не даёт МНОГИХ. Корень характеризуется тройкой «судится ли ·
где его индекс · где его журнал», и все три у разных корней разные:
`teorkat-vvedenie` судится воротами, но индекса и журнала не имеет вовсе, а
`obzory` индекс имеет — ЧУЖОЙ, в `_studio/`. Отображение «корень → индекс»
поэтому не тождество, и свести его к имени папки нельзя.
"""
import os
from collections import namedtuple
from pathlib import Path

# GIT_ZONA_REPO — ЕДИНАЯ дверь к одноразовому репозиторию, та же, что была у
# `git_zona.py` и `register_doc.py`. До расшивки корень репо определялся ДВУМЯ
# способами: половина инструментов знала эту переменную, половина нет, и
# фикстуре приходилось выбирать приём под каждый (`RAZDELENIE-issledovanie §2`).
# Здесь способ один на всех.
#
# 🔴 Корень репо — это «на два уровня выше файла инструмента», а НЕ «где лежит
# `.git`». Свойство несущее, а не случайное: фикстуры копируют инструменты в
# `$T/_generator/tools/`, и `parents[2]` честно указывает на `$T` ещё до того,
# как там появится git. Определение через `.git` сломало бы каждую фикстуру,
# которая проверяет инструмент ДО `git init`, и все — которые гоняют его на
# дереве без git вовсе.
REPO = Path(os.environ.get("GIT_ZONA_REPO") or Path(__file__).resolve().parents[2])

# `карта` — индекс, в котором регистрируются документы корня. НЕ «свой индекс»:
#           у `obzory/` он чужой, в `_studio/`. None — корень не индексируется.
# `журнал` — где у корня лежат арки. None — журнала нет.
# `ворота` — судят ли этот корень ворота 1–4 `check_kartoteka.py --gates`.
# `регистрация` — «обязательна» (ворота 5 краснеют на незарегистрированном `.md`)
#                 · «добровольна» (дверь принимает, ворота 5 молчат)
#                 · «нет» (дверь отказывает).
# `рама` — есть ли у корня СВОИ `SPEKA.md`/`DUH.md`/`KOTYOL.md`, по которым
#          ворота 4 судят ссылки вида `SPEKA §Калибровка`. Значение по умолчанию
#          `False`: рама есть у курсов, а не у фабрик.
#
# 🔴 ПОЧЕМУ РАМА — ПОЛЕ РЕЕСТРА, А НЕ ВТОРОЙ СПИСОК. До этого в
# `check_kartoteka.py` жили ДВЕ независимые таблицы корней: одна для индекса,
# вторая (`КОРНИ_РАМЫ`) — для рамы, и вторая осталась литералом. Найдено
# верификатором захода и доказано прогоном на пятом корне: документ нового
# корня либо не получал ворот 4 ВОВСЕ (`if not дома: continue` — молчание), либо
# судился по ЧУЖОЙ раме, и диагноз называл чужой файл. Один вопрос — один дом:
# два списка корней расходятся молча, и расхождение видно только на новом корне.
Корень = namedtuple("Корень", "имя карта журнал ворота регистрация рама",
                    defaults=(False,))

# 🔴 ПОРЯДОК СТРОК НЕСУЩИЙ, а не косметика: в этом порядке `check_kartoteka.файлы()`
# обходит корни, и он же задаёт порядок ❌ в выводе ворот. Перестановка строк
# перетасует вывод гейта и будет прочитана как регрессия при сверке «до/после».
КОРНИ = (
    # Рамка у КАЖДОГО курса СВОЯ, и ссылки на неё относительные (`../SPEKA.md §…`).
    # Живой курс — `teorkat-vvedenie/`, замороженный архив ресёрча —
    # `teoriya-kategoriy/`, и у него собственный `SPEKA.md` с собственными
    # секциями. Сверять всё с одним файлом = объявить мёртвыми 250 живых ссылок
    # архива (поймано первым же прогоном).
    Корень("teoriya-kategoriy", None,                    None,              True,  "нет", True),
    Корень("teorkat-vvedenie",  None,                    None,              True,  "нет", True),
    Корень("_studio",           "_studio/docs/KARTA.md", "_studio/zhurnal", True,  "обязательна"),
    # Добавлен 03.08.2026: `obzory/README.md` велел регистрировать обзор в §6, а
    # дверь такие пути отвергала — инструкция была неисполнима штатно. Ворота 5
    # эту папку не судят, поэтому регистрация добровольная. Настоящий индекс
    # обзоров вычисляемый (`python3 obzory/spisok.py`, `KONSTITUCIYA §10`);
    # строка в §6 — указатель «документ существует», а не список.
    Корень("obzory",            "_studio/docs/KARTA.md", None,              False, "добровольна"),
    # Первая вынесенная фабрика (2026-08-06). Строка ОДНА, правок в инструментах
    # ноль — это и есть проверка расшивки на себе: понадобилась бы вторая правка,
    # значит реестр не единственный дом. Индекс СВОЙ (`_illustracii/docs/KARTA.md`),
    # а не `_studio/`: иначе документы иллюстраций числились бы в чужом §6.
    # Рамы нет — рама у курсов, а не у фабрик.
    Корень("_illustracii",      "_illustracii/docs/KARTA.md", "_illustracii/zhurnal", True, "обязательна"),
)

# Корень, где живёт инфраструктура git: черновик `.commit-plan` и автолог
# `zhurnal/_INFRA-git/`. Один на репозиторий, а не по одному на фабрику:
# индекс git у репозитория ОДИН, и лог срывов коммита у него тоже один.
# Отдельной строкой — чтобы при выносе фабрик его переезд был одной правкой,
# а не поиском литерала в двух файлах.
ИНФРА = "_studio"

ИНФРА_ЖУРНАЛ = f"{ИНФРА}/zhurnal/_INFRA-git"
ПЛАН_REL = f"{ИНФРА}/.commit-plan"
ИНЦИДЕНТЫ_REL = f"{ИНФРА_ЖУРНАЛ}/INCIDENTY.md"
ВЕРДИКТЫ_REL = f"{ИНФРА_ЖУРНАЛ}/VERDIKTY.md"


def _норм(путь):
    """Путь к виду `a/b/c.md` — posix. Принимает и `Path`, и строку.

    `Path.as_posix()` заодно снимает ведущее `./` и схлопывает `//`: инструменты
    зовут реестр и относительным путём из индекса git, и собранным через `/`.
    """
    return Path(путь).as_posix()


def корень_пути(rel):
    """Корень, которому принадлежит путь, либо None — если он вне всех корней.

    Сравниваем ПЕРВЫЙ компонент целиком, а не префиксом строки: префикс
    `_studio` совпал бы и с папкой `_studio-arhiv/`, то есть чужая папка
    судилась бы индексом соседа и молча.
    """
    первый = _норм(rel).split("/")[0]
    for к in КОРНИ:
        if к.имя == первый:
            return к
    return None


def имена_воротами():
    """Имена корней, которые судят ворота — в порядке обхода (порядок несущий)."""
    return tuple(к.имя for к in КОРНИ if к.ворота)


def карта_для(rel):
    """Индекс (`KARTA.md`), в котором регистрируется этот путь; None — негде."""
    к = корень_пути(rel)
    return к.карта if к else None


def все_карты():
    """Все индексы реестра без дублей — их самих ворота 3 не судят."""
    return tuple(sorted({к.карта for к in КОРНИ if к.карта}))


def корни_рамы():
    """Корни, у которых есть СВОЯ рама (`SPEKA`/`DUH`/`KOTYOL`) — в порядке реестра.

    Порядок влияет только на ТЕКСТ диагноза ворот 4 (какой файл рамы назван
    первым): вердикт берётся объединением секций всех найденных рам, а свой
    корень документа подставляется первым независимо от порядка здесь.
    """
    return tuple(к.имя for к in КОРНИ if к.рама)


def все_журналы():
    """Все журналы реестра — где вообще могут лежать арки и заходы."""
    return tuple(к.журнал for к in КОРНИ if к.журнал)


def арка_пути(rel):
    """`<корень>/zhurnal/<арка>/что/угодно.md` → `<корень>/zhurnal/<арка>`; иначе None.

    🔴 Возвращаем ПОЛНЫЙ путь арки, а не одно её имя. До расшивки возвращалось
    имя, и это было безопасно ровно пока журнал был один: две фабрики свободно
    заведут арку `2026-08-05_faza-lenty` каждая, и по одному имени закрытая арка
    одной глушила бы ворота 4 и 5 на одноимённой ЖИВОЙ арке другой — молча.
    Вложенность любая: подпапки арки — та же арка.
    """
    p = _норм(rel)
    ч = p.split("/")
    if len(ч) <= 3:
        return None
    журнал = "/".join(ч[:2])
    return "/".join(ч[:3]) if журнал in все_журналы() else None


def арка_зоны(rel):
    """То же для `git_zona`: путь → зона арки `<корень>/zhurnal/<арка>`, либо None.

    Отдельное имя, потому что вопрос другой: здесь путь может быть и САМОЙ
    папкой арки (`len == 3`), а не только файлом внутри неё.
    """
    ч = _норм(rel).split("/")
    if len(ч) < 3:
        return None
    return "/".join(ч[:3]) if "/".join(ч[:2]) in все_журналы() else None


def регистрация_обязательна(rel):
    """Краснеют ли ворота 5 на этом пути, если он не в индексе."""
    к = корень_пути(rel)
    return bool(к and к.регистрация == "обязательна")


def дверь_принимает(rel):
    """Возьмётся ли `register_doc.py` регистрировать этот путь."""
    к = корень_пути(rel)
    return bool(к and к.регистрация != "нет")


def префиксы_двери():
    """`("_studio/", "obzory/")` — для сообщения об отказе двери, а не для суда."""
    return tuple(f"{к.имя}/" for к in КОРНИ if к.регистрация != "нет")


def шаблон(имя):
    """Путь к шаблону арки/захода внутри журнала ИНФРА-корня.

    Шаблоны лежат в одном месте на репозиторий, а не по копии на фабрику:
    разъехавшиеся копии шаблона — это разъехавшийся контракт зоны у заходов
    разных фабрик, и разъезд не виден, пока не понадобится.
    """
    return REPO / ИНФРА / "zhurnal" / имя


def описать():
    """Читаемая таблица реестра — чтобы состояние спрашивали командой, а не памятью."""
    строки = [f"корень репо: {REPO}", f"инфра-корень: {ИНФРА}", ""]
    for к in КОРНИ:
        строки.append(
            f"  {к.имя:<20} карта={к.карта or '—':<24} журнал={к.журнал or '—':<18}"
            f" ворота={'да' if к.ворота else 'нет':<4} регистрация={к.регистрация}")
    return "\n".join(строки)
