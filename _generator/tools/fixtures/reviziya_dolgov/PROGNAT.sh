#!/usr/bin/env bash
# TOOL-CONTRACT-COVERS: reviziya_dolgov.py
# Фикстуры чекера статусов DOLG.md (reviziya_dolgov.py, 2026-08-08).
# Гонять после каждой правки:  bash _generator/tools/fixtures/reviziya_dolgov/PROGNAT.sh
#
# Кривой вход обязан падать ГРОМКО (rc=1, понятное сообщение), а не молчать
# и не трейсбеком. Плюс: запись без статуса обязана красить rc, здоровая — нет.
set -u

TOOL="$(cd "$(dirname "$0")/../.." && pwd)/reviziya_dolgov.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
OK=0

pusk () {                       # pusk <файл> <ожидаемый-код>
  out=$(python3 "$TOOL" "$1" 2>&1)
  got=$?
  if [ "$got" = "$2" ]; then
    echo "  v $(basename "$1"): код $got"
  else
    echo "  x $(basename "$1"): код $got, ожидался $2"
    echo "$out"
    OK=1
  fi
}

echo "-- ФИКСТУРЫ ЧЕКЕРА СТАТУСОВ DOLG.md --"

# 1. КРИВОЙ ВХОД: путь не существует — обязан упасть громко, rc=1, без трейсбека.
pusk "$TMP/net-takogo-fajla.md" 1

# 2. ЗДОРОВЫЙ ВХОД: у обеих записей (табличной и нарративной) есть и статус,
# и фаза, а сама команда не в белом списке (не перепроверяемо, не красит) — rc=0.
cat > "$TMP/zdorovyj.md" <<'EOF'
| Д1 | долг раз | откуда <br>СТАТУС: ЖИВ · 2026-08-08 · `команда` → вывод · ФАЗА: Ф1 |

## Долг 2 — долг два

текст долга.

СТАТУС: МЁРТВ · 2026-08-08 · `команда` → вывод · ФАЗА: Ф0,Ф6

---
EOF
pusk "$TMP/zdorovyj.md" 0

# 3. КРИВОЙ ВХОД: у табличной записи статуса нет — гейт обязан покраснеть.
cat > "$TMP/bez-statusa.md" <<'EOF'
| Д1 | долг раз | откуда |

## Долг 2 — долг два

текст долга.

СТАТУС: МЁРТВ · 2026-08-08 · `команда` → вывод

---
EOF
pusk "$TMP/bez-statusa.md" 1

# 4. КРИВОЙ ВХОД: статус есть, ФАЗЫ нет — тоже обязан покраснеть (Ф-3).
cat > "$TMP/bez-fazy.md" <<'EOF'
| Д1 | долг раз | откуда <br>СТАТУС: ЖИВ · 2026-08-08 · `команда` → вывод |
EOF
pusk "$TMP/bez-fazy.md" 1

# 5. РЕПРОГОН: метка с командой из белого списка, чей записанный вывод
# заведомо не совпадает с реальным (echo вместо реального числа строк
# фикстурного файла) — обязан дать РАЗОШЛОСЬ и общий rc=1 (критерий Ф-1).
printf 'раз\nдва\nтри\n' > "$TMP/tri-stroki.txt"
cat > "$TMP/razoshlas.md" <<EOF
| Д1 | долг раз | откуда <br>СТАТУС: ЖИВ · 2026-08-08 · \`wc -l $TMP/tri-stroki.txt\` → 999 · ФАЗА: Ф0 |
EOF
pusk "$TMP/razoshlas.md" 1

# 6. БЕЗОПАСНОСТЬ: опасная команда (rm) внутри метки — НЕ должна выполниться
# (иначе tri-stroki.txt пропадёт), долг уходит в «не перепроверяемо», а
# команда — в отдельный список опасных; общий гейт по одной этой причине не
# обязан быть красным (гейт красит только РАЗОШЛОСЬ/без статуса/без фазы).
cat > "$TMP/opasnaya.md" <<EOF
| Д1 | долг раз | откуда <br>СТАТУС: ЖИВ · 2026-08-08 · \`rm $TMP/tri-stroki.txt\` → готово · ФАЗА: Ф0 |
EOF
out=$(python3 "$TOOL" "$TMP/opasnaya.md" 2>&1)
if [ -f "$TMP/tri-stroki.txt" ]; then
  echo "  v opasnaya.md: rm не выполнился, файл на месте"
else
  echo "  x opasnaya.md: файл ИСЧЕЗ — опасная команда была выполнена!"
  OK=1
fi
echo "$out" | grep -q "ОПАСНЫЕ КОМАНДЫ" || { echo "  x opasnaya.md: список опасных команд не напечатан"; OK=1; }

echo
[ "$OK" = 0 ] && echo "ВСЁ ЗЕЛЁНОЕ" || echo "ЕСТЬ ПРОВАЛЫ"
exit "$OK"
