#!/bin/sh
# TOOL-CONTRACT-COVERS: priyomka.py git_zona.py dolg_repozitoriev.py
# ↑ ОХВАТ: ФАЗА ПРИЁМКИ как механизм — гейты Г13 (раздел заполнен, заявки
# сверены с очередью), Г14 (ветка названа и её влитие проверено фактом),
# Г15 (отказ git-операции разобран), плюс две двери, без которых эти гейты
# судили бы пустоту: `zayavka --kak-vlit` (мини-промпт влития) и `otkaz_stop`
# (стоп при неудаче влития/коммита), и счётчик долга по всем репозиториям.
#
# Запуск:  sh _generator/tools/fixtures/faza-priyomki/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# 🔴 ВСЁ ГОНЯЕТСЯ НА ОДНОРАЗОВОМ РЕПОЗИТОРИИ (`GIT_ZONA_REPO`), А НЕ НА ЖИВОМ.
# Гейты читают ЖИВУЮ очередь заявок и ЖИВЫЕ ветки; на настоящем `materials`
# фикстура была бы то зелёной, то красной по причинам, не имеющим отношения к
# коду, а половина ловушек писала бы мусор в рабочую очередь владельца.
#
# ЧТО СТОРОЖИТ КАЖДАЯ ЛОВУШКА (сколько их — печатает сам прогон):
#   1. Г13 краснеет на РАЗДЕЛЕ С ПЛЕЙСХОЛДЕРАМИ — то есть на свежесобранном
#      заходе, которого приёмка не касалась.
#   2. Г13 зеленеет, когда вердикт назван и заявка продублирована ЖИВЫМ id.
#   3. 🔴 СЕРДЦЕ Ч3: Г13 краснеет на ВЫДУМАННОМ id. Без этой ловушки «дубль»
#      неотличим от «намерения», а разница — единственное, ради чего владелец
#      потребовал формулировку «продублируй то, что уже положил».
#   4. Г14 краснеет на невлитой ветке, не названной ни в одной заявке.
#   5. Г14 зеленеет на ВЛИТОЙ ветке (проверка фактом, не словом).
#   6. Г14 зеленеет на невлитой, но НАЗВАННОЙ в заявке — долг виден и адресован.
#   7. Ч6: заявка на влитие БЕЗ `--kak-vlit` отклоняется (rc=1).
#   8. Ч6: та же заявка С инструкцией проходит (rc=0), и текст доезжает в файл.
#   9. 🔴 Ч6 ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: заявка НЕ про влитие без `--kak-vlit`
#      проходит. Иначе требование краснело бы на каждой заявке подряд и его
#      сняли бы вместе с механизмом.
#  10. Ч4: конфликтное влитие даёт rc≠0, печатает СТОП и заводит заявку-отказ.
#  11. 🔴 Ч4 ГРАНИЦА: «нечего вливать» — rc=0 и НИ ОДНОЙ заявки-отказа. Стоп,
#      который срабатывает на здоровом прогоне, — это паралич, а не стоп.
#  12. Г15 краснеет, пока заявка-отказ открыта, и зеленеет после её закрытия.
#  13. Ч5: счётчик долга краснеет на заниженном пороге и печатает вынесенное.
set -e
TOOLS=$(cd "$(dirname "$0")/../.." && pwd)
REPO_ROOT=$(cd "$TOOLS/../.." && pwd)
unset $(git rev-parse --local-env-vars) 2>/dev/null || true

LOVUSHEK=$(grep -c '^echo "── ловушка' "$0" || true)
echo "ловушек в этом прогоне: $LOVUSHEK  ← grep -c '^echo \"── ловушка' $0"

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
G() { git -c user.email=proba@proba -c user.name=proba "$@"; }

R="$T/repo"
mkdir -p "$R/_studio/zhurnal/proba" "$R/_studio/docs" "$R/_generator/tools/dummy-zone"
( cd "$R"
  G -c init.defaultBranch=main init -q
  echo start > f.txt; G add f.txt; G commit -q -m init
  G checkout -q -b zahod/vlitaya; echo v > v.txt; G add v.txt; G commit -q -m v
  G checkout -q main; G merge -q --no-edit zahod/vlitaya
  G checkout -q -b zahod/nevlitaya; echo n > n.txt; G add n.txt; G commit -q -m n
  G checkout -q -b zahod/v-zayavke; echo z > z.txt; G add z.txt; G commit -q -m z
  G checkout -q -b zahod/arhivnaya main; echo a > a.txt; G add a.txt; G commit -q -m a
  G checkout -q -b zahod/konflikt main; echo B > f.txt; G commit -q -am B
  G checkout -q main; echo C > f.txt; G commit -q -am C
  G checkout -q -b zahod/pusto main
  G checkout -q main )

# ── заход-образец: только тот кусок, который читают Г13/Г14 ────────────────────
# Гейты берут раздел `## ФАЗА ПРИЁМКИ` и поля в нём; остальной заход им не нужен,
# и подставлять сюда весь шаблон значило бы сторожить чужие клаузы заодно.
zahod_s_razdelom() {  # <файл> <вердикт-строка> <ветка> <строка-заявки>
  cat > "$1" <<MD
# Канал исполнителя — проба фикстуры

## ОТЧЁТ — (заполняет исполнитель)
Сделано.

## ФАЗА ПРИЁМКИ — (заполняет АНАЛИТИК, не исполнитель)
**ВЕРДИКТ:** $2

**ВЕТКА РАБОТЫ:** \`$3\`

**ЗАЯВКИ, ПОСТАВЛЕННЫЕ ЭТОЙ ПРИЁМКОЙ — ПРОДУБЛИРУЙ СЮДА ТО, ЧТО УЖЕ ЛЕЖИТ В СПИСКЕ:**

$4
MD
}

gejt() {  # <гейт g13|g14|g15> <файл|-> → печатает "OK <msg>" либо "KRASNO <msg>"
  # 🔴 ДВЕ ДВЕРИ, А НЕ ОДНА: `GIT_ZONA_REPO` уводит на синтетический репозиторий
  # очередь заявок, `PRIYOMKA_REPO` — сами git-команды гейтов. Без второй Г14
  # спрашивал про ветки ЖИВОГО `materials`, честно отвечал «ветки нет» и делал
  # ловушку 4 зелёной по неверной причине (поймано первым прогоном фикстуры).
  GIT_ZONA_REPO="$R" PRIYOMKA_REPO="$R" python3 - "$1" "$2" <<'PY'
import sys
sys.path.insert(0, __import__('os').environ.get('FIX_TOOLS'))
import priyomka
imya, put = sys.argv[1], sys.argv[2]
if imya == "g15":
    ok, msg = priyomka.gate_g15()
else:
    tekst = open(put, encoding='utf-8').read()
    ok, msg = getattr(priyomka, "gate_" + imya)(tekst)
print(("OK " if ok else "KRASNO ") + " ".join(str(msg).split()))
PY
}
export FIX_TOOLS="$TOOLS"

echo "── ловушка 1: Г13 краснеет на разделе с плейсхолдерами (приёмка его не касалась)"
zahod_s_razdelom "$T/z1.md" '`<принято | доработка | отклонено>` — `<почему>`' \
    "zahod/vlitaya" '- `<id заявки>` — `<род>` — `<суть>`'
OUT=$(gejt g13 "$T/z1.md")
case "$OUT" in KRASNO*) echo "  ✅ ловушка 1: $OUT" ;;
  *) echo "❌ ЛОВУШКА 1: Г13 принял НЕЗАПОЛНЕННЫЙ раздел — гейт без зубов. $OUT"; exit 1 ;; esac

# Живая заявка в синтетической очереди — её id и будет «тем, что уже лежит в списке».
ZID=$(GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka --rod git-operaciya \
        "проба фикстуры: забрать хвост в git" | sed -n 's/^✅ Заявка создана: //p')
[ -n "$ZID" ] || { echo "❌ ФИКСТУРА: заявка в синтетической очереди не создалась"; exit 1; }

echo "── ловушка 2: Г13 зеленеет на заполненном разделе с ЖИВЫМ id заявки"
zahod_s_razdelom "$T/z2.md" "принято — проверено прогоном фикстуры" \
    "zahod/vlitaya" "- \`$ZID\` — \`git-operaciya\` — забрать хвост в git"
OUT=$(gejt g13 "$T/z2.md")
case "$OUT" in OK*) echo "  ✅ ловушка 2: $OUT" ;;
  *) echo "❌ ЛОВУШКА 2: Г13 покраснел на честно заполненном разделе — ложная тревога, ровно та, из-за которой гейт отключают. $OUT"; exit 1 ;; esac

echo "── ловушка 3: 🔴 Г13 краснеет на ВЫДУМАННОМ id — намерение вместо дубля"
zahod_s_razdelom "$T/z3.md" "принято — проверено прогоном фикстуры" \
    "zahod/vlitaya" "- \`2026-01-01T0000-takoj-zayavki-net\` — \`git-operaciya\` — влитие"
OUT=$(gejt g13 "$T/z3.md")
case "$OUT" in KRASNO*) echo "  ✅ ловушка 3: $OUT" ;;
  *) echo "❌ ЛОВУШКА 3: Г13 принял id, которого в очереди НЕТ. Дубль перестал быть дублем — это и есть та самая разница между копией и намерением. $OUT"; exit 1 ;; esac

echo "── ловушка 4: Г14 краснеет на невлитой ветке, не названной ни в одной заявке"
zahod_s_razdelom "$T/z4.md" "принято — проверено" "zahod/nevlitaya" \
    "- \`$ZID\` — \`git-operaciya\` — забрать хвост в git"
OUT=$(gejt g14 "$T/z4.md")
case "$OUT" in KRASNO*) echo "  ✅ ловушка 4: $OUT" ;;
  *) echo "❌ ЛОВУШКА 4: Г14 принял невлитую и никому не адресованную ветку — ровно тот случай, когда владелец дважды не нашёл работу. $OUT"; exit 1 ;; esac

echo "── ловушка 5: Г14 зеленеет на ВЛИТОЙ ветке (факт, а не слово)"
OUT=$(gejt g14 "$T/z2.md")
case "$OUT" in OK*) echo "  ✅ ловушка 5: $OUT" ;;
  *) echo "❌ ЛОВУШКА 5: Г14 покраснел на реально влитой ветке. $OUT"; exit 1 ;; esac

echo "── ловушка 6: Г14 зеленеет на невлитой, но НАЗВАННОЙ в заявке ветке"
ZID2=$(GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka --rod git-operaciya \
        "влить zahod/v-zayavke в основную" \
        --kak-vlit "ЧТО: одна ветка · ГДЕ ЖДАТЬ КОНФЛИКТА: нигде, файлы не пересекаются · ЧЬЕЙ СТОРОНОЙ: неприменимо · ПОСЛЕ: ничего" \
        | sed -n 's/^✅ Заявка создана: //p')
[ -n "$ZID2" ] || { echo "❌ ФИКСТУРА: вторая заявка не создалась"; exit 1; }
zahod_s_razdelom "$T/z6.md" "принято — проверено" "zahod/v-zayavke" \
    "- \`$ZID2\` — \`git-operaciya\` — влитие"
OUT=$(gejt g14 "$T/z6.md")
case "$OUT" in OK*) echo "  ✅ ловушка 6: $OUT" ;;
  *) echo "❌ ЛОВУШКА 6: Г14 покраснел на ветке, долг по которой НАЗВАН заявкой — тогда гейт требует влить немедленно, а это не то, что решил владелец. $OUT"; exit 1 ;; esac

echo "── ловушка 7: Ч6 — заявка на влитие БЕЗ --kak-vlit отклоняется"
if OUT=$(GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka --rod git-operaciya \
        "влить zahod/nevlitaya в основную" 2>&1); then
  echo "❌ ЛОВУШКА 7: заявка на влитие принята БЕЗ инструкции «как вливать». Вывод:"
  echo "$OUT"; exit 1
fi
echo "$OUT" | grep -q "как вливать" || {
  echo "❌ ЛОВУШКА 7: отказ есть, но не по причине отсутствия инструкции. Вывод:"
  echo "$OUT"; exit 1; }
echo "  ✅ ловушка 7: отклонена, причина названа"

echo "── ловушка 8: Ч6 — та же заявка С инструкцией проходит, текст доезжает в файл"
ZID3=$(GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka --rod git-operaciya \
        "влить zahod/nevlitaya в основную" \
        --kak-vlit "ЧТО: nevlitaya первой · ГДЕ ЖДАТЬ КОНФЛИКТА: f.txt · ЧЬЕЙ СТОРОНОЙ: брать сторону основной · ПОСЛЕ: пересобрать" \
        | sed -n 's/^✅ Заявка создана: //p')
[ -n "$ZID3" ] || { echo "❌ ЛОВУШКА 8: заявка с инструкцией НЕ создалась"; exit 1; }
grep -q "^КАК ВЛИВАТЬ: ЧТО: nevlitaya первой" \
     "$R/_studio/zhurnal/_INFRA-git/zayavki/$ZID3.md" || {
  echo "❌ ЛОВУШКА 8: инструкция не доехала в файл заявки — поле есть только в командной строке"
  cat "$R/_studio/zhurnal/_INFRA-git/zayavki/$ZID3.md"; exit 1; }
echo "  ✅ ловушка 8: заявка создана, блок «КАК ВЛИВАТЬ» на месте"

echo "── ловушка 9: 🔴 отрицательный контроль — заявка НЕ про влитие без --kak-vlit проходит"
GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka --rod pravka-koda \
    "дописать канон двумя подкомандами" > /dev/null || {
  echo "❌ ЛОВУШКА 9: требование «как вливать» краснеет на заявке, которая влития не просит —"
  echo "   так его снимут вместе с механизмом."; exit 1; }
echo "  ✅ ловушка 9: заявка не про влитие проходит без инструкции"

echo "── ловушка 10: Ч4 — конфликтное влитие даёт rc≠0, СТОП и заявку-отказ"
if OUT=$(GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" vlit-v-osnovnuyu zahod/konflikt 2>&1); then
  echo "❌ ЛОВУШКА 10: конфликтное влитие вернуло rc=0 — отказ неотличим от успеха"
  echo "$OUT"; exit 1
fi
echo "$OUT" | grep -q "СТОП. GIT-ОПЕРАЦИЯ НЕ ПРОШЛА" || {
  echo "❌ ЛОВУШКА 10: отказ есть, а СТОПа нет — исполнитель пойдёт работать дальше. Вывод:"
  echo "$OUT" | tail -20; exit 1; }
OTKAZOV=$(ls "$R/_studio/zhurnal/_INFRA-git/zayavki/" | grep -c 'otkaz' || true)
[ "$OTKAZOV" -ge 1 ] || {
  echo "❌ ЛОВУШКА 10: заявка-отказ не заведена — стоп не переживёт конец сессии"; exit 1; }
( cd "$R" && G merge --abort 2>/dev/null || true )
echo "  ✅ ловушка 10: rc≠0, СТОП напечатан, заявок-отказов в очереди: $OTKAZOV"

echo "── ловушка 11: 🔴 ГРАНИЦА Ч4 — «нечего вливать» это НЕ отказ"
DO=$(ls "$R/_studio/zhurnal/_INFRA-git/zayavki/" | grep -c 'otkaz' || true)
GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" vlit-v-osnovnuyu zahod/pusto > "$T/pusto.log" 2>&1 || {
  echo "❌ ЛОВУШКА 11: влитие ветки, в которой нечего вливать, вернуло НЕнулевой код —"
  echo "   стоп превратился в паралич. Вывод:"; cat "$T/pusto.log"; exit 1; }
grep -q "сливать нечего" "$T/pusto.log" || {
  echo "❌ ЛОВУШКА 11: нет строки «сливать нечего» — исход неразличим"; exit 1; }
POSLE=$(ls "$R/_studio/zhurnal/_INFRA-git/zayavki/" | grep -c 'otkaz' || true)
[ "$DO" -eq "$POSLE" ] || {
  echo "❌ ЛОВУШКА 11: здоровый прогон завёл заявку-отказ ($DO → $POSLE)"; exit 1; }
echo "  ✅ ловушка 11: rc=0, заявок-отказов не прибавилось ($DO → $POSLE)"

echo "── ловушка 12: Г15 краснеет при открытом отказе и зеленеет после разбора"
OUT=$(gejt g15 -)
case "$OUT" in KRASNO*) echo "  ✅ ловушка 12а: $OUT" ;;
  *) echo "❌ ЛОВУШКА 12а: Г15 зелен при НЕЗАКРЫТОМ отказе влития — приёмка примет заход, в котором влитие сорвалось. $OUT"; exit 1 ;; esac
OTKAZ_ID=$(ls "$R/_studio/zhurnal/_INFRA-git/zayavki/" | grep 'otkaz' | head -1 | sed 's/\.md$//')
GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka-zakryt "$OTKAZ_ID" \
    --rezultat "разобрано фикстурой: конфликт учебный, ветка отброшена" > /dev/null
OUT=$(gejt g15 -)
case "$OUT" in OK*) echo "  ✅ ловушка 12б: $OUT" ;;
  *) echo "❌ ЛОВУШКА 12б: Г15 остался красным ПОСЛЕ закрытия заявки — разобрать отказ стало невозможно, и гейт отключат. $OUT"; exit 1 ;; esac

echo "── ловушка 13: Ч5 — счётчик долга краснеет на заниженном пороге"
python3 "$TOOLS/dolg_repozitoriev.py" --porog-vetok 1 > "$T/dolg.log" 2>&1 && {
  echo "❌ ЛОВУШКА 13: порог невлитых=1 не покраснел ни на одном репозитории —"
  echo "   счётчик не умеет краснеть вовсе."; cat "$T/dolg.log"; exit 1; }
grep -q "ДОЛГ ОБРАЗОВАЛСЯ" "$T/dolg.log" || {
  echo "❌ ЛОВУШКА 13: код возврата ненулевой, а вердикта в выводе нет"; exit 1; }
python3 "$TOOLS/dolg_repozitoriev.py" --porog-vetok 0 > /dev/null 2>&1 && {
  echo "❌ ЛОВУШКА 13: порог 0 принят — неверный вызов неотличим от найденного долга"; exit 1; }
echo "  ✅ ловушка 13: краснеет на заниженном пороге, отвергает бессмысленный"

echo "── ловушка 14: переадресованная заявка ЗАКРЫВАЕТСЯ (второй дом виден двери)"
# 🔴 До 16.08 `zayavka-zakryt` смотрела только в верхний каталог очереди, а
# `zayavka-peredat` физически переносит файл в `zayavki/na-zahod/`. Заявку,
# уехавшую туда, закрыть было НЕЛЬЗЯ ВООБЩЕ: дверь отвечала «нет такой заявки,
# открытых заявок нет вовсе». Шесть живых заявок оказались незакрываемыми по
# построению — то есть заход-разработчик исполнял их и не мог отметить это ничем.
ZID4=$(GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka --rod pravka-koda \
        "проба второго дома: починить гейт" | sed -n 's/^✅ Заявка создана: //p')
GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka-peredat "$ZID4" \
    --pochemu "род pravka-koda: контур код не редактирует" > /dev/null
[ -f "$R/_studio/zhurnal/_INFRA-git/zayavki/na-zahod/$ZID4.md" ] || {
  echo "❌ ЛОВУШКА 14: заявка не уехала во второй дом — проверять нечего"; exit 1; }
GIT_ZONA_REPO="$R" python3 "$TOOLS/git_zona.py" zayavka-zakryt "$ZID4" \
    --rezultat "исполнено фикстурой: проверка, что второй дом виден двери закрытия" > /dev/null || {
  echo "❌ ЛОВУШКА 14: переадресованную заявку закрыть НЕЛЬЗЯ — механизм переадресации"
  echo "   превращается в тупик: исполнил и отметить нечем."; exit 1; }
[ -f "$R/_studio/zhurnal/_INFRA-git/zayavki/sdelano/$ZID4.md" ] || {
  echo "❌ ЛОВУШКА 14: закрытие прошло, а файл не уехал в sdelano/"; exit 1; }
echo "  ✅ ловушка 14: заявка из na-zahod/ закрыта и уехала в sdelano/"

# ── ловушки 15-19: ОБХОДЫ, НАЙДЕННЫЕ ПОСЛЕ-ВЕРИФИКАТОРОМ ─────────────────────
