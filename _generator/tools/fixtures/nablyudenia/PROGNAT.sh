#!/bin/sh
# TOOL-CONTRACT-COVERS: dostavit_urok.py
# Фикстуры КАНАЛА НАБЛЮДЕНИЙ — вид `punkt` (пункт очереди из `## ВОПРОСЫ`).
# Вид `urok` сторожит соседняя фикстура fixtures/urok/PROGNAT.sh; она же держит
# обратную совместимость двери уроков и после расширения обязана быть зелёной.
#
# Запуск:  sh _generator/tools/fixtures/nablyudenia/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЗАЧЕМ. Канал ПИШЕТ В ЧУЖИЕ ФАЙЛЫ и СХЛОПЫВАЕТ записи, а потерянная при разборе
# находка неотличима от никогда не существовавшей. Гейт, который не умеет
# падать, здесь молча объявляет очередь разнесённой.
#
# 🔴 ГЛАВНЫЕ ЛОВУШКИ — 1, 2, 3: ТРИ ПРИЧИНЫ, ПО КОТОРЫМ РАЗБОР ПО НОМЕРУ ТЕРЯЛ
# 72 ПУНКТА ИЗ 199 НА ЖИВОЙ АРКЕ. Каждая — не гипотеза, а замер по 37 файлам
# `2026-08-05_faza-lenty`: жирный номер (`kod_etap-20-i-perenos.md` — 9 пунктов,
# 0 разобранных), чужое имя секции (`## ВТОРАЯ ПАЧКА ВОПРОСОВ` — 18 пунктов),
# образец формы в blockquote-шапке (72 ложных строки). Снимешь любую — счёт
# очереди снова станет неправдой, и это будет видно только на новом файле.
#
# 🔴 ЛОВУШКА 5 — ПРО ГЕЙТ, КОТОРЫЙ УМЕЕТ СТАТЬ ЗЕЛЁНЫМ. Пунктов `ДОМ: владелец`
# на живой арке больше половины, и доставить их некуда по определению. Гейт,
# красный на любом недоставленном, не станет зелёным никогда — такой отключают
# первым. Ловушка держит два состояния разведёнными: «дом есть» краснеет всегда,
# «дома нет / решение за человеком» — только на `--zakrytie`.
#
# ДВЕНАДЦАТЬ ЛОВУШЕК:
#   1. пункт с жирным номером (`**2. …**`) разобран (иначе теряется молча);
#   2. пункт в секции `## ВТОРАЯ ПАЧКА ВОПРОСОВ` разобран (имя секции — не `ВОПРОСЫ`);
#   3. образец формы в blockquote-шапке пунктом НЕ считается;
#   4. `ДОМ:` с хвостом-пояснением после пути резолвится в дом, а не в «дома нет»;
#   5. `--gejt` КРАСНЫЙ на недоставленном с живым домом;
#   6. `--gejt` ЗЕЛЁНЫЙ, когда остались только «владелец»/«дома нет»…
#   7. …а `--gejt --zakrytie` на том же файле КРАСНЫЙ (два состояния, не одно);
#   8. `--dostavit` кладёт содержание в дом И метку в источник — одним ходом;
#   9. повторный `--dostavit` дубля не заводит (идемпотентность);
#  10. дома нет на диске → rc=2, файл наугад НЕ создан;
#  11. дом — файл-указатель («→ ПЕРЕЕХАЛ») → rc=2, дом не тронут байт-в-байт;
#  12. метка доставки понятна Г7 `priyomka.py` (иначе ложно-красная приёмка);
#  15. адрес `<эта арка>/…` (плейсхолдер шаблона, пишется дословно) резолвится
#      в папку арки, а не объявляется «дома нет»;
#  14. номер пункта не уникален в файле → rc=2 (в двух секциях вопросов
#      нумерация своя, номера сталкиваются; доставить наугад = потерять две);
#  13. дом — исполняемый код (`.py`) → rc=2, скрипт не тронут (доставка markdown
#      в конец `.py` даёт SyntaxError; проверка оплачена сломанным git_zona.py).
cd "$(dirname "$0")/../../../.." || exit 1
TOOL=_generator/tools/dostavit_urok.py
T=$(mktemp -d) || exit 1
A=$T/repo/_studio/zhurnal/test-arka
mkdir -p "$A" || exit 1
fail=0

ok() { echo "  ✅ $1"; }
no() { echo "  ❌ $1"; fail=1; }
je() { [ "$2" = "$3" ] && ok "$1 ($2)" || no "$1: получено «$2», ожидалось «$3»"; }

# ── Файл-заход: живые формы записи пункта, снятые с корпуса ────────────────
cat > "$A/kod_test-zahod.md" <<'EOF'
# Тестовый заход

## ВОПРОСЫ — (заполняет исполнитель)
> Нашёл вещь, которая принадлежит чужому дому? Оформи ПУНКТОМ ОЧЕРЕДИ:
> ```
> N. <текст находки>
>    ДОМ: <путь от корня репозитория | владелец>
>    ДОСТАВЛЕНО: нет
> ```
> Аналитик при переносе меняет `ДОСТАВЛЕНО: нет` на метку.

1. Обычный пункт с живым домом.
   ДОМ: DOM-kanon.md
   ДОСТАВЛЕНО: нет

**2. Пункт, пронумерованный ЖИРНЫМ — разбор по номеру его теряет.**
   ДОМ: DOM-kanon.md
   ДОСТАВЛЕНО: нет

3. Пункт, чей дом назван с пояснением после пути.
   ДОМ: `DOM-kanon.md` (тот же дом, что и у пункта 1)
   ДОСТАВЛЕНО: нет

4. Пункт, чей дом не существует.
   ДОМ: NETU.md
   ДОСТАВЛЕНО: нет

9. Пункт, чей дом записан плейсхолдером шаблона.
   ДОМ: <эта арка>/DOM-kanon.md
   ДОСТАВЛЕНО: нет

5. Пункт, чей дом — файл-указатель.
   ДОМ: UKAZATEL.md
   ДОСТАВЛЕНО: нет

6. Пункт, адресованный человеку.
   ДОМ: владелец
   ДОСТАВЛЕНО: нет

8. Пункт, чей дом — исполняемый скрипт.
   ДОМ: instrument.py
   ДОСТАВЛЕНО: нет

## ВТОРАЯ ПАЧКА ВОПРОСОВ — накоплена по ходу работы

7. Пункт в секции с ДРУГИМ именем — поиск по точному `ВОПРОСЫ` его не видит.
   ДОМ: DOM-kanon.md
   ДОСТАВЛЕНО: нет

6. Пункт с номером, который уже занят в первой секции — коллизия адреса.
   ДОМ: владелец
   ДОСТАВЛЕНО: нет

Проза ВНУТРИ секции вопросов, обсуждающая саму форму: поле ДОСТАВЛЕНО тут
упомянуто, но своего ДОМ у него нет — это не пункт, а разговор о пунктах.
   ДОСТАВЛЕНО: нет
EOF

printf '# Дом-канон\n\nЖивой документ.\n' > "$A/DOM-kanon.md"
printf '#!/usr/bin/env python3\nprint("живой инструмент")\n' > "$A/instrument.py"
cp "$A/instrument.py" "$T/instrument.etalon"
printf '# UKAZATEL.md \xe2\x86\x92 \xd0\x9f\xd0\x95\xd0\xa0\xd0\x95\xd0\x95\xd0\xa5\xd0\x90\xd0\x9b\n\nСодержание уехало.\n' > "$A/UKAZATEL.md"
cp "$A/UKAZATEL.md" "$T/ukazatel.etalon"

Z=$A/kod_test-zahod.md

python3 $TOOL --plan "$Z" > "$T/plan.txt" 2>&1
je "план отработал" "$?" "0"

# 1 — жирный номер
je "1. пункт с ЖИРНЫМ номером разобран" \
   "$(grep -c 'пронумерованный ЖИРНЫМ' "$T/plan.txt")" "1"
# 2 — чужое имя секции
je "2. пункт из «ВТОРОЙ ПАЧКИ ВОПРОСОВ» разобран" \
   "$(grep -c 'секции с ДРУГИМ именем' "$T/plan.txt")" "1"
# 3 — образец в шапке не считается; всего пунктов ровно 7
je "3. образец формы в blockquote-шапке пунктом не считается" \
   "$(grep -c 'пунктов очереди: 10' "$T/plan.txt")" "1"
je "3б. поле ДОСТАВЛЕНО без своего ДОМ посчитано прозой, а не пунктом" \
   "$(grep -c 'без своего' "$T/plan.txt")" "1"
# 4 — хвост-пояснение в адресе
je "4. дом с пояснением после пути резолвится (класс «дом есть» — пункты 1,2,3,7)" \
   "$(grep -cE 'дом есть +5 ' "$T/plan.txt")" "1"

# 5 — гейт красный, пока есть недоставленное с живым домом
python3 $TOOL --gejt "$Z" > "$T/gejt1.txt" 2>&1
je "5. --gejt КРАСНЫЙ на недоставленном с живым домом" "$?" "1"

# 8 — доставка: содержание в дом И метка в источник
python3 $TOOL --dostavit 1 "$Z" > "$T/dost1.txt" 2>&1
je "8. --dostavit отработал" "$?" "0"
je "8а. содержание уехало в дом дословно" \
   "$(grep -c 'Обычный пункт с живым домом' "$A/DOM-kanon.md")" "1"
je "8б. метка встала в источник" \
   "$(grep -c 'ДОСТАВЛЕНО: test-zahod#1' "$Z")" "1"
je "8в. метка встала и в доме (её ищет Г7)" \
   "$(grep -c 'ДОСТАВЛЕНО: test-zahod#1' "$A/DOM-kanon.md")" "1"

# 9 — идемпотентность
do_kol=$(grep -c 'Обычный пункт с живым домом' "$A/DOM-kanon.md")
python3 $TOOL --dostavit 1 "$Z" > "$T/dost1b.txt" 2>&1
je "9. повторный --dostavit кода 0, дубля нет" "$?" "0"
je "9а. в доме по-прежнему один экземпляр" \
   "$(grep -c 'Обычный пункт с живым домом' "$A/DOM-kanon.md")" "$do_kol"

# 10 — дома нет
python3 $TOOL --dostavit 4 "$Z" > "$T/dost4.txt" 2>&1
je "10. дома нет на диске → rc=2" "$?" "2"
je "10а. файл наугад НЕ создан" "$([ -e "$A/NETU.md" ] && echo да || echo нет)" "нет"

# 11 — файл-указатель
python3 $TOOL --dostavit 5 "$Z" > "$T/dost5.txt" 2>&1
je "11. дом — файл-указатель → rc=2" "$?" "2"
je "11а. указатель не тронут байт-в-байт" \
   "$(cmp -s "$A/UKAZATEL.md" "$T/ukazatel.etalon" && echo цел || echo тронут)" "цел"

# 15 — плейсхолдер `<эта арка>`
python3 $TOOL --dostavit 9 "$Z" > "$T/placeholder.txt" 2>&1
je "15. адрес с плейсхолдером <эта арка> резолвится и доставка проходит" "$?" "0"
je "15а. содержание доехало" \
   "$(grep -c 'дом записан плейсхолдером' "$A/DOM-kanon.md")" "1"

# 14 — коллизия номера
python3 $TOOL --dostavit 6 "$Z" > "$T/kol.txt" 2>&1
je "14. номер, занятый дважды → rc=2" "$?" "2"
je "14а. отказ называет обе строки" "$(grep -c 'не уникален' "$T/kol.txt")" "1"

# 13 — дом-скрипт
python3 $TOOL --dostavit 8 "$Z" > "$T/dost8.txt" 2>&1
je "13. дом — исполняемый код → rc=2" "$?" "2"
je "13а. скрипт не тронут байт-в-байт" \
   "$(cmp -s "$A/instrument.py" "$T/instrument.etalon" && echo цел || echo тронут)" "цел"
je "13б. скрипт остался валидным Python" \
   "$(python3 -c "import ast,pathlib;ast.parse(pathlib.Path('$A/instrument.py').read_text())" 2>&1 && echo ок)" "ок"

# 6/7 — два состояния гейта: доставляем всё, у чего дом ЕСТЬ
python3 $TOOL --dostavit 2 "$Z" >/dev/null 2>&1
python3 $TOOL --dostavit 3 "$Z" >/dev/null 2>&1
python3 $TOOL --dostavit 7 "$Z" >/dev/null 2>&1
python3 $TOOL --gejt "$Z" > "$T/gejt2.txt" 2>&1
je "6. --gejt ЗЕЛЁНЫЙ, когда остались только «владелец» и «дома нет»" "$?" "0"
python3 $TOOL --gejt --zakrytie "$Z" > "$T/gejt3.txt" 2>&1
je "7. --gejt --zakrytie на том же файле КРАСНЫЙ" "$?" "1"
je "7а. и он называет, сколько именно осталось" \
   "$(grep -c 'Красных 5 из 10' "$T/gejt3.txt")" "1"

# 12 — метка понятна Г7 priyomka.py: значение поля ДОСТАВЛЕНО обязано
#      встречаться в файле-доме подстрокой (иначе приёмка краснеет на верной
#      доставке — ровно тот ложно-красный, из-за которого гейты отключают).
znachenie=$(grep -m1 'ДОСТАВЛЕНО: test-zahod#1' "$Z" | sed 's/.*ДОСТАВЛЕНО: //' | tr -d ' \r')
je "12. Г7: значение метки найдено в доме подстрокой" \
   "$(grep -qF "$znachenie" "$A/DOM-kanon.md" && echo найдено || echo НЕТ)" "найдено"

# --volna по папке
python3 $TOOL --volna "$A" > "$T/volna.txt" 2>&1
je "волна отработала на папке" "$?" "0"
je "волна отделяет «решение за человеком» своей группой" \
   "$(grep -c 'решение за человеком' "$T/volna.txt")" "2"

echo
if [ "$fail" = "0" ]; then
  echo "ФИКСТУРЫ ЗЕЛЁНЫЕ"
  rm -rf "$T"
  exit 0
fi
echo "ФИКСТУРЫ КРАСНЫЕ — разбор в $T"
exit 1
