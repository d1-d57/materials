#!/bin/sh
# TOOL-CONTRACT-COVERS: dostavit_urok.py
# Фикстуры ДВЕРИ УРОКОВ. Гоняй ПОСЛЕ любой правки dostavit_urok.py.
# Строка COVERS выше — не украшение: по ней хук решает, поднимать ли фикстуру.
#
# Запуск:  sh _generator/tools/fixtures/urok/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЗАЧЕМ. Дверь ПИШЕТ В ЧУЖИЕ ФАЙЛЫ — в канон, который читают все будущие
# проекты. Гейт, который не умеет падать, здесь не просто театр: он молча
# объявляет арку разнесённой, и уроки умирают вместе с ней.
#
# 🔴 ГЛАВНАЯ ЛОВУШКА — 7, И ОНА ПРО ЛОЖНО-ЗЕЛЁНОЕ. В живом файле арки 37 уроков
# из 60 уже несут строку `ДОСТАВЛЕНО: <заход>#<N>`, и она значит ПРИХОД записи
# сюда, а не уход её в дом. Возьми гейт тот же ключ — и он промолчит на 37
# уроках, ни один из которых в канон не доставлен. Ловушка 7 держит ключи
# разведёнными: урок со старой меткой обязан считаться НЕ доставленным.
#
# СЕМЬ ЛОВУШЕК:
#   1. образец формы внутри ```-забора не считается уроком (иначе охват никогда
#      не досчитает до 100 %, а три грепа шапки сойдутся, не видя, что считают);
#   2. `--gejt` КРАСНЫЙ, пока есть недоставленные (гейт умеет падать);
#   3. `--dostavit` кладёт содержание в дом И метку в урок — одним ходом;
#   4. повторный `--dostavit` дубля не заводит (grep -c до и после одинаков);
#   5. дома нет на диске → rc=2, и файл наугад НЕ создан;
#   6. дом — файл-указатель («→ ПЕРЕЕХАЛ») → rc=2, дом не тронут байт-в-байт;
#   7. старая метка `ДОСТАВЛЕНО:` за доставку НЕ засчитывается;
#   8. `--gejt` ЗЕЛЁНЫЙ, когда доставлены все (иначе он краснеет по другой причине).
cd "$(dirname "$0")/../../../.." || exit 1
TOOL=_generator/tools/dostavit_urok.py
T=$(mktemp -d) || exit 1
A=$T/repo/_studio/zhurnal/test-arka
mkdir -p "$A" || exit 1
fail=0

ok() { echo "  ✅ $1"; }
no() { echo "  ❌ $1"; fail=1; }
je() { [ "$2" = "$3" ] && ok "$1 ($2)" || no "$1: получено «$2», ожидалось «$3»"; }

cat > "$A/UROKI-FABRIKE.md" <<'EOF'
# УРОКИ ФАБРИКЕ — арка «test-arka»

```
### N. <что произошло — одной фразой, без морали>
ЦЕНА: <что сломалось и сколько стоило>
ВЕРДИКТ: <пусто до закрытия арки>
```

---

### 1. Первый урок с живым домом
ЦЕНА: сломалось то-то, один ход разбора.
ВЕРДИКТ: чинится так-то. Дом — `DOM-kanon.md`.

### 2. Урок, у которого уже стоит СТАРАЯ метка прихода
ЦЕНА: цена названа, два хода.
ВЕРДИКТ: чинится сяк-то. Дом — `DOM-kanon.md`.
ДОСТАВЛЕНО: chuzhoj-zahod#3

### 3. Урок, чей дом не существует
ЦЕНА: цена есть, один ход.
ВЕРДИКТ: чинится этак. Дом — `NETU.md`.

### 4. Урок, чей дом — файл-указатель
ЦЕНА: цена есть, полхода.
ВЕРДИКТ: чинится вот так. Дом — `UKAZATEL.md`.
EOF

printf '# Дом-канон\n\nЖивой документ.\n' > "$A/DOM-kanon.md"
printf '# UKAZATEL.md \xe2\x86\x92 \xd0\x9f\xd0\x95\xd0\xa0\xd0\x95\xd0\x95\xd0\xa5\xd0\x90\xd0\x9b\n\nСодержание уехало в другой файл.\n' > "$A/UKAZATEL.md"
cp "$A/UKAZATEL.md" "$T/ukazatel.etalon"

U=$A/UROKI-FABRIKE.md

# 1 — забор
python3 $TOOL --plan "$U" > "$T/plan.txt" 2>&1
je "1. plan отработал" "$?" "0"
je "1. образец формы внутри забора не посчитан уроком" \
   "$(grep -c 'настоящих уроков: 4' "$T/plan.txt")" "1"
je "1. заголовков в файле при этом пять" \
   "$(grep -c '^### ' "$U")" "5"

# 2 — гейт умеет падать
python3 $TOOL --gejt "$U" >/dev/null 2>&1
je "2. гейт КРАСНЫЙ, пока есть недоставленные" "$?" "1"

# 7 — старая метка прихода за доставку не считается
python3 $TOOL --gejt "$U" 2>&1 | grep -q '2\. Урок, у которого уже стоит СТАРАЯ метка' \
  && ok "7. урок со старой меткой ДОСТАВЛЕНО: числится НЕ доставленным" \
  || no "7. старая метка засчитана за доставку — это ложно-зелёный гейт"

# 3 — содержание и метка одним ходом
python3 $TOOL --dostavit 1 "$U" >/dev/null 2>&1
je "3. dostavit отработал" "$?" "0"
je "3. содержание легло в дом" "$(grep -c '^ЦЕНА: сломалось то-то' "$A/DOM-kanon.md")" "1"
je "3. метка встала в уроке" "$(grep -c '^ДОСТАВЛЕНО-В-ДОМ:' "$U")" "1"

# 4 — идемпотентность
do_=$(grep -c 'ДОСТАВЛЕНО-В-ДОМ: test-arka#1' "$A/DOM-kanon.md")
python3 $TOOL --dostavit 1 "$U" >/dev/null 2>&1
je "4. повтор отработал без ошибки" "$?" "0"
je "4. повтор дубля не завёл" "$(grep -c 'ДОСТАВЛЕНО-В-ДОМ: test-arka#1' "$A/DOM-kanon.md")" "$do_"

# 5 — дома нет
python3 $TOOL --dostavit 3 "$U" >/dev/null 2>&1
je "5. дома нет → отказ" "$?" "2"
[ -e "$A/NETU.md" ] && no "5. дом создан наугад — это выглядит доставкой" \
                    || ok "5. файл наугад НЕ создан"

# 6 — дом-указатель
python3 $TOOL --dostavit 4 "$U" >/dev/null 2>&1
je "6. дом-указатель → отказ" "$?" "2"
cmp -s "$A/UKAZATEL.md" "$T/ukazatel.etalon" && ok "6. указатель не тронут байт-в-байт" \
                                             || no "6. в указатель что-то дописано"

# 8 — зелёный гейт достижим
V=$T/repo/_studio/zhurnal/test-arka2
mkdir -p "$V"
cat > "$V/UROKI-FABRIKE.md" <<'EOF'
# УРОКИ ФАБРИКЕ — арка «test-arka2»

### 1. Единственный урок, уже доставленный
ЦЕНА: цена названа, один ход.
ВЕРДИКТ: чинится так. Дом — `DOM.md`.
ДОСТАВЛЕНО-В-ДОМ: 2026-08-06 → DOM.md
EOF
python3 $TOOL --gejt "$V/UROKI-FABRIKE.md" >/dev/null 2>&1
je "8. гейт ЗЕЛЁНЫЙ, когда доставлены все" "$?" "0"

rm -rf "$T"
[ $fail = 0 ] && echo "ФИКСТУРЫ ЗЕЛЁНЫЕ" || echo "ФИКСТУРЫ КРАСНЫЕ — дверь уроков сломана правкой"
exit $fail
