print(najti_transcript(None))
" 2>/dev/null)
case "$NAJDEN" in
  */mnt/.claude/projects/proj-x/aaaa1111.jsonl) ;;
  *) echo "❌ ЛОВУШКА 2: транскрипт в песочнице НЕ найден. najti_transcript вернул: '$NAJDEN'"
     exit 1 ;;
esac
echo "  ✅ ловушка 2: транскрипт по пути песочницы найден"

# Дневник арки: пока БЕЗ номеров реплик.
cat > "$T/arka2/SESSIYA.md" <<'MD'
# СЕССИЯ — дневник тестовой арки

## 2026-08-03 — запись, в которой номеров реплик нет
Аналитик что-то записал, но реплики владельца не разнёс.
MD

# ── ЛОВУШКА 3. НЕПОКРЫТАЯ РЕПЛИКА ВАЛИТ `proverit`.
# ЧТО ЛОМАЕТСЯ: сам вердикт гейта. Если непокрытая реплика даёт exit 0, гейт
# не гейт: он подтверждает полноту дневника, которой нет.
# ЧЕГО ЭТО СТОИЛО: независимая вычитка 03.08 нашла СЕМЬ потерь за одну сессию
# при том, что дневник вёлся по ходу и считался полным. Этот exit-код —
# единственное, что отличает «сверено» от «понадеялись».
OUT3=$(python3 "$D" proverit "$T/arka2" --transcript "$T/aaaa1111.jsonl" 2>&1) && {
  echo "❌ ЛОВУШКА 3: дневник без номеров реплик дал exit 0"; exit 1; }
echo "$OUT3" | grep -q "Saaaa-В001" || {
  echo "❌ ЛОВУШКА 3: в выводе нет номера непокрытой реплики. Вывод:"; echo "$OUT3"; exit 1; }
echo "$OUT3" | grep -q "покрыто 0 из 3" || {
  echo "❌ ЛОВУШКА 3: нет ОХВАТА «покрыто N из M». Вывод:"; echo "$OUT3"; exit 1; }
echo "  ✅ ловушка 3: непокрытая реплика валит проверку, номер и охват напечатаны"

# ── ЛОВУШКА 4. ПОЛНОЕ ПОКРЫТИЕ — exit 0 И МОЛЧАНИЕ.
# ЧТО ЛОМАЕТСЯ: `KONSTITUCIYA` Р31. Гейт, который шумит при зелёном, отключат,
# и вместе с шумом уедет вся польза. Проверяется именно ПУСТОТА вывода, а не
# только код возврата: «зелёный, но болтливый» — это отключённый гейт завтра.
printf '\n<!-- РЕПЛИКИ РАЗНЕСЕНЫ: Saaaa-В001 · Saaaa-В002 · Saaaa-В003 -->\n' >> "$T/arka2/SESSIYA.md"
OUT4=$(python3 "$D" proverit "$T/arka2" --transcript "$T/aaaa1111.jsonl" 2>&1) || {
  echo "❌ ЛОВУШКА 4: полное покрытие дало ненулевой код. Вывод:"; echo "$OUT4"; exit 1; }
[ -z "$OUT4" ] || { echo "❌ ЛОВУШКА 4: при полном покрытии гейт шумит:"; echo "$OUT4"; exit 1; }
echo "  ✅ ловушка 4: полное покрытие — exit 0 и молчание"

# ── ЛОВУШКА 5. 🔴 СТОЛКНОВЕНИЕ СЕССИЙ.
# ЧТО ЛОМАЕТСЯ: идентификатор сессии внутри номера реплики. Без него номера
# второй сессии — те же `В001`, `В002`, и они «покрывают» реплики первой.
# ЧЕГО ЭТО СТОИЛО: это тихая поломка ровно того вида, против которого инструмент
# и построен, — гейт зеленеет, а реплики второй сессии не разнесены ни одной.
# Дневник уже содержит `Saaaa-В001/В002`; транскрипт `bbbb2222` даёт `Sbbbb-…`,
# и покрыть его старыми номерами нельзя.
sed 's/гейт полноты дневника/реестр направлений и дерево гейтов/' \
    "$T/aaaa1111.jsonl" > "$T/bbbb2222.jsonl"
OUT5=$(python3 "$D" proverit "$T/arka2" --transcript "$T/bbbb2222.jsonl" 2>&1) && {
  echo "❌ ЛОВУШКА 5: реплики ЧУЖОЙ сессии засчитаны покрытыми — идентификатор сессии не работает"
  exit 1; }
echo "$OUT5" | grep -q "Sbbbb-В001" || {
  echo "❌ ЛОВУШКА 5: в выводе нет номера реплики второй сессии. Вывод:"; echo "$OUT5"; exit 1; }
echo "  ✅ ловушка 5: номера разных сессий не покрывают друг друга"

# ── ЛОВУШКА 6. ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: `zapis` пишет, и после неё `proverit` зеленеет.
# ЧТО ЛОМАЕТСЯ: без этого «краснеет всегда» неотличимо от «краснеет верно» —
# сломанный `zapis` (не дописал маркер, переписал файл) выглядел бы как честный
# красный гейт. Проверяется ещё и то, что старый текст дневника НА МЕСТЕ:
# `zapis` дописывает, а не переформатирует — в дневнике лежит знание, которое
# никуда больше не уехало.
python3 "$D" zapis "$T/arka2" \
  --tekst "Владелец потребовал реестр направлений и дерево гейтов вместо разовой починки." \
  --repliki "Sbbbb-В001,Sbbbb-В002,Sbbbb-В003" >/dev/null || {
  echo "❌ ЛОВУШКА 6: zapis не отработал"; exit 1; }
grep -q "запись, в которой номеров реплик нет" "$T/arka2/SESSIYA.md" || {
  echo "❌ ЛОВУШКА 6: zapis затёр существующий текст дневника"; exit 1; }
grep -q "реестр направлений и дерево гейтов" "$T/arka2/SESSIYA.md" || {
  echo "❌ ЛОВУШКА 6: текст записи не попал в дневник"; exit 1; }
OUT6=$(python3 "$D" proverit "$T/arka2" --transcript "$T/bbbb2222.jsonl" 2>&1) || {
  echo "❌ ЛОВУШКА 6: после zapis гейт всё равно красный. Вывод:"; echo "$OUT6"; exit 1; }
[ -z "$OUT6" ] || { echo "❌ ЛОВУШКА 6: после zapis гейт зелёный, но шумит:"; echo "$OUT6"; exit 1; }
echo "  ✅ ловушка 6: zapis дописал запись с маркером, старый текст цел, proverit позеленел"

