#!/bin/sh
# TOOL-CONTRACT-COVERS: zakryt_sessiyu.py sdelat_handoff.py dnevnik.py
# ↑ ОХВАТ: три инструмента дисциплины сессии — выгрузка транскрипта, сборка
# хэндоффа и гейт полноты дневника. Один механизм: закрытие сессии так, чтобы
# знание не терялось. `dnevnik.py` тут не гость: он ИМПОРТИРУЕТ разбор из
# `zakryt_sessiyu.py`, поэтому правка разбора обязана поднимать обе половины
# сразу — иначе сверка начнёт считать не те реплики, которые выгружены.
#
# Запуск:  sh _generator/tools/fixtures/sessiya/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЗАЧЕМ. Оба инструмента заведены 03.08 после того, как независимый субагент
# вычитал транскрипт сессии и нашёл СЕМЬ потерь при том, что дневник вёлся по
# ходу и считался полным. Инструменты лечат потерю знания — и потому их
# собственная тихая поломка страшнее обычной: пустая выгрузка и пустой хэндофф
# выглядят ровно как «ничего важного не было».
#
# ЛОВУШКИ ВЫГРУЗКИ И ХЭНДОФФА (ниже отдельным блоком — шесть ловушек дневника):
#   1. НЕТ ПАПКИ АРКИ. Выгрузка обязана отказать, а не писать в никуда.
#   2. НЕТ ТРАНСКРИПТА по явному пути. Отказать, а не искать «похожий»: молчаливая
#      подмена источника даст выгрузку ЧУЖОЙ сессии, и это худший исход.
#   3. 🔴 ТРАНСКРИПТ БЕЗ РЕПЛИК ВЛАДЕЛЬЦА (формат изменился). Обязан упасть с
#      объяснением. Именно здесь инструмент опаснее всего: он отработает «успешно»,
#      выдаст пустой файл, и аналитик решит, что сессия была бессодержательной.
#   4. ХЭНДОФФ БЕЗ ОБЯЗАТЕЛЬНОГО ПОЛЯ. `--gde` пропущено — сборки быть не должно.
#      Цена: хэндофф 03.08 не назвал, где запускать работу, и владелец спрашивал
#      это голосом.
#   5. ХЭНДОФФ ПОВЕРХ СУЩЕСТВУЮЩЕГО. Не перезаписывать: в старом файле может
#      лежать не перенесённое знание.
#   6. ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ. На здоровом входе оба обязаны отработать и
#      создать файлы — иначе «краснеет всегда» неотличимо от «краснеет верно».
set -e
TOOLS=$(cd "$(dirname "$0")/../.." && pwd)

# Вычистить окружение git — та же строка и та же причина, что в fixtures/register_doc:
# внутри хука git экспортирует GIT_DIR/GIT_INDEX_FILE на БОЕВОЙ репозиторий.
unset $(git rev-parse --local-env-vars) 2>/dev/null || true

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
mkdir -p "$T/arka"

Z="$TOOLS/zakryt_sessiyu.py"
H="$TOOLS/sdelat_handoff.py"
D="$TOOLS/dnevnik.py"

krasnet() {  # <описание> <команда...>
  OPIS="$1"; shift
  if "$@" >/dev/null 2>&1; then
    echo "❌ ЛОВУШКА НЕ СРАБОТАЛА: $OPIS — инструмент принял кривой вход"
    exit 1
  fi
  echo "  ✅ $OPIS — отвергнуто"
}

echo "── ловушка 0: синтаксис, которого нет на старом питоне"
# 🔴 ЦЕНА, оплачено 03.08. В `zakryt_sessiyu.py` стояла аннотация `str | None`
# (PEP 604, Python 3.10+). В песочнице аналитика питон новее, чем на машине
# владельца, поэтому проверка прошла у одного и упала у другого:
# `TypeError: unsupported operand type(s) for |` — и уронила коммит.
# Проверяется грепом, а не запуском: на новом питоне такой код исполняется
# нормально, и никакой прогон его не поймает.
# ⚠ Первая редакция этой ловушки НЕ КРАСНЕЛА на подсунутом дефекте: в шаблоне
# стоял класс символов с `\[\]`, а в POSIX ERE обратный слэш внутри класса
# трактуется буквально и ломает его. Отрицательный контроль это поймал —
# и он тут не для красоты: ловушка, которая не краснеет, хуже отсутствующей.
# Проверка ниже нарочно тупая: `|` в строке `def ...` или в аннотации переменной.
proverit_604() {
  grep -nE '^[[:space:]]*def .*\|' "$1" && return 0
  grep -nE '^[[:space:]]*[a-z_]+[[:space:]]*:[^=]*\|' "$1" && return 0
  return 1
}
for F in "$Z" "$H" "$D"; do
  if proverit_604 "$F" >/dev/null 2>&1; then
    echo "❌ $F: в сигнатуре или аннотации есть '|' — это PEP 604, Python 3.10+,"
    echo "   на машине владельца упадёт TypeError. Писать без него."
    exit 1
  fi
done
echo "  ✅ 3.10-синтаксиса в аннотациях нет"

# Отрицательный контроль САМОЙ ловушки: на заведомо дефектном файле она обязана
# краснеть. Без этого «ловушка не сработала» и «дефекта нет» неотличимы.
printf 'def f(x: str | None):\n    pass\n' > "$T/defekt.py"
if ! proverit_604 "$T/defekt.py" >/dev/null 2>&1; then
  echo "❌ ЛОВУШКА 0 СЛЕПА: не видит 'str | None' в заведомо дефектном файле"
  exit 1
fi
echo "  ✅ ловушка 0 проверена на дефектном образце — краснеет"

echo "── ловушки zakryt_sessiyu.py"

# 1. нет папки арки
krasnet "нет папки арки" python3 "$Z" "$T/net-takoj-papki"

# 2. нет транскрипта по явному пути
krasnet "явный транскрипт не существует" python3 "$Z" "$T/arka" --transcript "$T/net.jsonl"

# 3. 🔴 транскрипт без реплик владельца — формат изменился
printf '%s\n' '{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"только ассистент и ничего больше в этом файле"}]}}' > "$T/pusto.jsonl"
krasnet "транскрипт без реплик владельца" python3 "$Z" "$T/arka" --transcript "$T/pusto.jsonl"

echo "── ловушки sdelat_handoff.py"

# 4. пропущено обязательное поле --gde
krasnet "хэндофф без --gde" python3 "$H" "$T/arka" \
  --chto-delaem "x" --pervyj-hod "y" --gotovo "z"

# 5. поверх существующего файла
ZAVTRA=$(python3 -c "import datetime;print((datetime.date.today()+datetime.timedelta(days=1)).isoformat())")
: > "$T/arka/HANDOFF-$ZAVTRA.md"
krasnet "хэндофф поверх существующего" python3 "$H" "$T/arka" \
  --chto-delaem "x" --gde "g" --pervyj-hod "y" --gotovo "z"
rm -f "$T/arka/HANDOFF-$ZAVTRA.md"

echo "── положительный контроль: здоровый вход обязан пройти"

# ⚠ У реплики владельца тут стоит `origin.kind = human`, и это НЕ украшение.
# Первая редакция этой строки была `content` списком БЕЗ `origin` — форма, которой
# у владельца не бывает: замер по всем транскриптам обеих сред дал 18 822 записи
# роли `user` вида «список без origin», и все до единой — результаты инструментов
# и служебный текст хоста (`[Image: …]`, `Continue from where you left off`,
# загрузка скилла). Синтетика, которой не бывает в природе, увела разбор в
# ложное правило и стоила пяти ложных реплик на живом транскрипте.
# Настоящих форм ровно три, и все три покрыты: строка (владелец набрал),
# список + `origin=human` (владелец с вложением), `tool_result` с маркером
# виджета в позиции 0 (ответ на интервью).
cat > "$T/norma.jsonl" <<'JSONL'
{"type":"user","origin":{"kind":"human"},"message":{"role":"user","content":[{"type":"text","text":"Давай сделаем так, чтобы заход начинался с интервью. Бюджет 40 долларов. А что ты имеешь в виду под этим?"}]}}
{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Понял, сделаю линтер и починю счётчик."}]}}
JSONL
# `zakryt_sessiyu.py` теперь несёт наружу код возврата `dnevnik.py proverit`
# СВОИМ последним ходом (часть A.1) — чтобы позитивный контроль ниже остался
# позитивным, дневник арки заранее покрывает единственную реплику norma.jsonl
# (идентификатор сессии — первые 4 символа имени файла: "norm").
printf '%s\n' '<!-- РЕПЛИКИ РАЗНЕСЕНЫ: Snorm-В001 -->' > "$T/arka/SESSIYA.md"
python3 "$Z" "$T/arka" --transcript "$T/norma.jsonl" >/dev/null
VYG=$(ls "$T/arka"/VYGRUZKA-*.md 2>/dev/null | head -1)
[ -n "$VYG" ] || { echo "❌ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: выгрузка не создана"; exit 1; }
grep -q "интервью" "$VYG" || { echo "❌ реплика владельца не попала в выгрузку"; exit 1; }
grep -q "ВОПРОСЫ ВЛАДЕЛЬЦА" "$VYG" || { echo "❌ раздел вопросов не собран"; exit 1; }
grep -q "ОБЕЩАНИЯ АНАЛИТИКА" "$VYG" || { echo "❌ раздел обещаний не собран"; exit 1; }
grep -q "число" "$VYG" || { echo "❌ метка «число» не проставлена на «40 долларов»"; exit 1; }
echo "  ✅ выгрузка собрана, реплика владельца на месте, вопросы и обещания выделены"

python3 "$H" "$T/arka" --chto-delaem "задача" --gde "Cowork" \
  --pervyj-hod "интервью" --gotovo "критерий" >/dev/null
HAN=$(ls "$T/arka"/HANDOFF-*.md 2>/dev/null | head -1)
[ -n "$HAN" ] || { echo "❌ ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: хэндофф не создан"; exit 1; }
grep -q "ГДЕ ЭТО ЗАПУСКАТЬ" "$HAN" || { echo "❌ в хэндоффе нет раздела «где запускать»"; exit 1; }
grep -q "ИНТЕРВЬЮ, а не работа" "$HAN" || { echo "❌ в хэндоффе нет вшитого интервью"; exit 1; }
grep -q "СТАРТОВАЯ СТРОКА" "$HAN" || { echo "❌ в хэндоффе нет стартовой строки для нового чата"; exit 1; }
grep -q "Открой файл" "$HAN" || { echo "❌ стартовая строка не называет файл входа"; exit 1; }
echo "  ✅ хэндофф собран: «где запускать», интервью и стартовая строка на месте"

# 7. РУКОПИСНЫЙ ФАЙЛ НЕ ПЕРЕЗАПИСЫВАЕТСЯ ДАЖЕ С --zamenit.
# Цена: в рукописном хэндоффе может лежать знание, которое никуда больше не уехало.
printf '%s\n' "# написан руками, маркера генератора нет" > "$T/arka/RUCHNOJ.md"
krasnet "--zamenit поверх рукописного файла" python3 "$H" "$T/arka" --imya RUCHNOJ.md \
  --chto-delaem "x" --gde "g" --pervyj-hod "y" --gotovo "z" --zamenit

# ═══════════════════════════════════════════════════════════════════════════
# ЛОВУШКИ dnevnik.py — гейт полноты дневника
#
# Инструмент строится против ТИХОЙ потери: реплика владельца сказана, но в
# дневник не разнесена. Его собственная тихая поломка потому и страшна, что
# «непокрытых нет» и «я ничего не проверил» печатаются одинаково.
# ═══════════════════════════════════════════════════════════════════════════
echo "── ловушки dnevnik.py"

mkdir -p "$T/arka2"

# Дневник арки2 заранее покрывает три реплики aaaa1111.jsonl (Saaaa-В001..003) —
# иначе `zakryt_sessiyu.py` ниже (ловушка 1 и «второе закрытие» ) красным кодом
# сверки дневника завалит `set -e`, хотя цель этих строк — проверить саму
# ВЫГРУЗКУ, не дневник. Ловушки 3-6 ниже перезапишут этот файл СВОИМ контентом,
# когда придёт их черёд проверять именно дневник.
printf '%s\n' '<!-- РЕПЛИКИ РАЗНЕСЕНЫ: Saaaa-В001 · Saaaa-В002 · Saaaa-В003 -->' > "$T/arka2/SESSIYA.md"

# Свой транскрипт с ОПОЗНАВАЕМЫМ именем: первые 4 символа имени уходят в номер
# реплики (`Saaaa-В001`), и на этом держится ловушка 5.
cat > "$T/aaaa1111.jsonl" <<'JSONL'
{"type":"user","message":{"role":"user","content":"Давай сделаем гейт полноты дневника, иначе разнос держится на внимательности аналитика."}}
{"type":"user","message":{"role":"user","content":[{"tool_use_id":"toolu_01","type":"tool_result","content":"The user answered: нужен предохранитель и база инцидентов, чтобы потери не повторялись из сессии в сессию."}]}}
{"type":"user","message":{"role":"user","content":[{"tool_use_id":"toolu_02","type":"tool_result","content":"1\t# Заголовок прочитанного файла\n2\tсодержимое чужого результата инструмента, владелец этого не говорил\n3\tа в этой строке файл лишь ЦИТИРУЕТ маркер The user answered: и репликой от этого не становится"}]}}
{"type":"user","message":{"role":"user","content":[{"type":"text","text":"Continue from where you left off. Это текстовый блок, но породил его ХОСТ, а не владелец."}]}}
{"type":"user","origin":{"kind":"human"},"message":{"role":"user","content":[{"type":"text","text":"Опять упал"},{"type":"image","source":{"type":"base64"}}]}}
{"type":"user","origin":"task-notification","message":{"role":"user","content":"Фоновая задача завершилась — это служебная запись хоста, а не реплика владельца."}}
JSONL

# ── ЛОВУШКА 1. 🔴 ОТВЕТ ВЛАДЕЛЬЦА ЧЕРЕЗ ВИДЖЕТ ОБЯЗАН ПОПАСТЬ В ВЫГРУЗКУ.
# ЧТО ЛОМАЕТСЯ: опознание реплики владельца в `razobrat`. Прямая регрессия на
# дыру, найденную 03.08 на живом файле: ответы на интервью через AskUserQuestion
# приходят как `tool_result` с текстом «The user answered: …», и греп
# `"tool_result" not in line` выбрасывал ЦЕЛЫЙ КЛАСС реплик — ровно тот, который
# породила новая дисциплина «интервью первым ходом».
# ЧЕГО ЭТО СТОИЛО: в сессии 03.08 в виджет продиктованы три развёрнутых ответа,
# включая всю идею предохранителя и базы инцидентов. Выгрузка потеряла бы их
# молча, и результат читался бы как «владелец ничего не говорил».
# И ОБРАТНАЯ ПОЛОВИНА: ЧУЖОЙ `tool_result` (результат `Read`) репликой НЕ
# считается — иначе гейт утонет в тысячах результатов инструментов, и аналитик
# отключит его в первый же день.
python3 "$Z" "$T/arka2" --transcript "$T/aaaa1111.jsonl" >/dev/null
V2=$(ls "$T/arka2"/VYGRUZKA-*.md 2>/dev/null | head -1)
[ -n "$V2" ] || { echo "❌ ловушка 1: выгрузка не создана"; exit 1; }
grep -q "реплик владельца 3 " "$V2" || {
  echo "❌ ЛОВУШКА 1: реплик владельца не 3 — вот что насчитано:"
  grep -o "реплик владельца [0-9]*" "$V2"; exit 1; }
grep -q "предохранитель" "$V2" || {
  echo "❌ ЛОВУШКА 1: ответ виджета («The user answered») НЕ попал в выгрузку"; exit 1; }
if grep -q "содержимое чужого результата" "$V2"; then
  echo "❌ ЛОВУШКА 1: чужой tool_result засчитан как реплика владельца"; exit 1
fi
# Чужой tool_result, ЦИТИРУЮЩИЙ маркер виджета в середине текста, репликой не является:
# иначе любой `Read` файла-захода или самого инструмента давал бы ложную реплику.
if grep -q "репликой от этого не становится" "$V2"; then
  echo "❌ ЛОВУШКА 1: tool_result, лишь цитирующий «The user answered», засчитан репликой"; exit 1
fi
# Текстовый блок, порождённый ХОСТОМ (нет origin=human), — не владелец.
if grep -q "породил его ХОСТ" "$V2"; then
  echo "❌ ЛОВУШКА 1: служебный текстовый блок хоста засчитан репликой владельца"; exit 1
fi
# `content` строкой, но origin служебный, — тоже не владелец.
if grep -q "Фоновая задача завершилась" "$V2"; then
  echo "❌ ЛОВУШКА 1: запись с origin=task-notification засчитана репликой владельца"; exit 1
fi
# 🔴 И ОБРАТНОЕ: КОРОТКАЯ реплика владельца (origin=human, 10 символов, со скриншотом)
# обязана уцелеть. Цена: общий порог `len(t) < 25` съел на живом транскрипте
# реплику «Опять упал, вот» — владелец сообщал о падении коммита, и это ушло молча.
grep -q "Опять упал" "$V2" || {
  echo "❌ ЛОВУШКА 1: короткая реплика владельца (origin=human) отброшена порогом длины"; exit 1; }
echo "  ✅ ловушка 1: реплик ровно 3 — виджет и короткая внутри, чужое и служебное снаружи"

# Довесок к ловушке 1 — ВТОРОЕ ЗАКРЫТИЕ В ТОТ ЖЕ ДЕНЬ НЕ ЗАТИРАЕТ ПЕРВОЕ.
# ЧТО ЛОМАЕТСЯ: имя `VYGRUZKA-<дата>.md` несёт только дату, и вторая сессия дня
# молча перезаписывала выгрузку первой. ЧЕГО СТОИЛО: длинные дни с двумя
# сессиями у этого проекта норма, а пропажа не видна — файл на месте и свежий.
python3 "$Z" "$T/arka2" --transcript "$T/aaaa1111.jsonl" >/dev/null
[ "$(ls "$T/arka2"/VYGRUZKA-*.md | wc -l)" -eq 2 ] || {
  echo "❌ второе закрытие в тот же день затёрло первую выгрузку"; exit 1; }
echo "  ✅ второе закрытие в тот же день не затирает первое"

# ── ЛОВУШКА 2. ТРАНСКРИПТ ЛЕЖИТ ПО ПУТИ ПЕСОЧНИЦЫ.
# ЧТО ЛОМАЕТСЯ: список шаблонов в `najti_transcript`. В песочнице Cowork `~` —
# это `/sessions/<имя>/`, а папка транскриптов смонтирована уровнем ниже, в
# `<mnt>/.claude/projects/`, так что `~/.claude/projects` мимо.
# ЧЕГО ЭТО СТОИЛО: 03.08 аналитик запустил скрипт из песочницы, ничего не нашёл
# и объявил владельцу, что инструмент в этой среде не работает В ПРИНЦИПЕ, —
# и начал строить обходной путь. Владелец не поверил и оказался прав.
# Дата в будущем — чтобы `max(mtime)` выбрал именно наш файл, а не настоящий
# транскрипт машины, который тоже может попасть под абсолютные шаблоны.
mkdir -p "$T/mnt/.claude/projects/proj-x"
cp "$T/aaaa1111.jsonl" "$T/mnt/.claude/projects/proj-x/aaaa1111.jsonl"
touch -t 203001010000 "$T/mnt/.claude/projects/proj-x/aaaa1111.jsonl"
NAJDEN=$(HOME="$T" python3 -c "
import sys
sys.path.insert(0, '$TOOLS')
