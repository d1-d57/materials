#!/bin/sh
# TOOL-CONTRACT-COVERS: schet_blokov.py
# Фикстура СЧЁТЧИКА БЛОКОВ. Гоняй ПОСЛЕ любой правки schet_blokov.py.
# Строка COVERS выше — не украшение: по ней хук решает, поднимать ли фикстуру.
#
# Зачем именно эти случаи. У счётчика код возврата несёт РОВНО ОДИН смысл, и
# спутать его дороже всего: 0 — инструмент отработал (сколько бы бесхозных
# абзацев он ни нашёл), 2 — инструмент НЕ отработал, вход кривой. Счётчик
# намеренно не гейт (заход `yadro-blokov`, §ЧТО ФИНАЛИЗИРОВАНО п.4: требование
# «каждый абзац принадлежит блоку» до контракта Ф4 только считается и
# печатается), поэтому «нашёл 278 бесхозных абзацев» ОБЯЗАНО быть нулём. День,
# когда находки начнут ронять код возврата, — это день, когда сборка встанет у
# всего репозитория, а причина будет выглядеть как поломка гейта.
#
# Та же мина оплачена 23.07 на bootstrap_arka.py: `--help` проглотили как имя
# арки и завели папку-сироту, которую потом каждый `plan` тянул в коммит.
#
# Проверяем ТОЛЬКО разбор входа и смысл кода возврата — сканирование живых
# папок сюда не входит, поэтому фикстура быстрая и не зависит от того, что
# сейчас лежит в obzory/.
cd "$(dirname "$0")/../../../.." || exit 1
G=_generator/tools/schet_blokov.py
fail=0

# кривой вход → ровно 2, и ни в коем случае не 0
for krivoj in "net-takoj-papki" "_generator/tools/schet_blokov.py" ""; do
  # shellcheck disable=SC2086
  python3 "$G" $krivoj >/dev/null 2>&1
  got=$?
  if [ "$got" = "2" ]; then
    echo "  ✅ «$krivoj»: exit 2 (отвергнут громко)"
  else
    echo "  ❌ «$krivoj»: exit $got, ожидался 2"
    fail=1
  fi
done

# кривой вход обязан НАЗВАТЬ себя, а не просто упасть
if python3 "$G" net-takoj-papki 2>&1 | grep -q "net-takoj-papki"; then
  echo "  ✅ сообщение называет сам аргумент"
else
  echo "  ❌ упал молча: в сообщении нет самого аргумента"
  fail=1
fi

# --help не проглатывается как путь и не падает трейсбеком
python3 "$G" --help >/dev/null 2>&1
if [ "$?" = "0" ]; then
  echo "  ✅ --help: exit 0"
else
  echo "  ❌ --help: exit $?, ожидался 0"
  fail=1
fi

# 🔴 ГЛАВНОЕ. Находки НЕ меняют код возврата: на папке, где бесхозные абзацы
# заведомо есть, выход обязан быть 0. Папка собирается здесь же, одноразовая, —
# фикстура не адресует боевые obzory/ и ничего в дереве не трогает.
TMP="${TMPDIR:-/tmp}/schet_blokov_fixture_$$"
mkdir -p "$TMP" || exit 1
cat > "$TMP/proba.md" <<'MD'
# Заголовок

Это бесхозный абзац: он не принадлежит ни одному блоку.

**Определение 1 (проба).** Тело определения.

И ещё один бесхозный абзац следом.
MD
python3 "$G" "$TMP" >"$TMP/out.txt" 2>&1
got=$?
if [ "$got" = "0" ]; then
  echo "  ✅ находки не роняют код возврата: exit 0"
else
  echo "  ❌ находки уронили код возврата: exit $got, ожидался 0 (счётчик не гейт)"
  fail=1
fi
# и при этом бесхозные абзацы реально СОСЧИТАНЫ, а не пропущены молча
if grep -q "абзацев вне блоков: 2" "$TMP/out.txt"; then
  echo "  ✅ бесхозные абзацы сосчитаны (2)"
else
  echo "  ❌ бесхозные абзацы не сосчитаны:"
  sed 's/^/      /' "$TMP/out.txt"
  fail=1
fi
if grep -q "Определение 1" "$TMP/out.txt"; then
  echo "  ✅ род блока распознан ядром (Определение)"
else
  echo "  ❌ род блока не распознан — счётчик разошёлся с ядром sborka/bloki.py"
  fail=1
fi
rm -rf "$TMP"

[ "$fail" = "0" ] && echo "✅ фикстура schet_blokov: чисто" || echo "❌ фикстура schet_blokov: есть провалы"
exit $fail
