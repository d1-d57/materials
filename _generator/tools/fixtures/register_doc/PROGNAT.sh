#!/bin/sh
# TOOL-CONTRACT-COVERS: register_doc.py bootstrap_zahod.py bootstrap_arka.py check_kartoteka.py
# ↑ ОХВАТ, а не список авторства. Четыре имени, потому что механизм «регистрация
# исполнима» размазан по четырём файлам: дверь (register_doc), два генератора,
# зовущих ту же дверь (bootstrap_zahod — заход, bootstrap_arka — арка на все
# пять файлов), и ворота 5 (check_kartoteka — там живёт предикат
# «зарегистрирован», общий для двери и гейта). Правка ЛЮБОГО из четырёх
# может рассинхронизировать «дверь вписала» и «хук засчитал», и тогда обход
# `--no-verify` вернётся штатным ходом. Пока охват жил в голове автора, хук
# поднимал фикстуру git_zona только на правку git_zona.py — у гейта триггер был
# уже его собственного покрытия (ZHURNAL §4.4).
#
# Запуск:  sh _generator/tools/fixtures/register_doc/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЗАЧЕМ. Два обязательных указания репозитория нельзя было выполнить разом: хук
# требовал строку в `KARTA.md §6` у каждого нового `.md` в `_studio/`, а
# контракт зоны отдавал исполнителю `_studio/docs/` только на чтение. ЦЕНА по
# автологу `_INFRA-git/INCIDENTY.md`: из 56 срывов коммита 28 — обходы
# `--no-verify`, и 27 из этих 28 — ровно эта причина, то есть 48 % всей боли.
# Лечение — дверь `register_doc.py`. Но дверь без того, что покраснеет при её
# поломке, — надежда, а не правило (`KONSTITUCIYA §11`). Здесь краснеет.
#
# ПЯТЬ ЛОВУШЕК, каждая проверена МУТАЦИЕЙ (гейт, который не умеет падать, — театр):
#   1. новый `.md` в `_studio/` без регистрации → ворота 5 краснеют;
#   2. после `register_doc.py` → ворота 5 зелёные;
#   3. повторный `register_doc.py` не плодит дубль;
#   4. путь вне `_studio/` → отказ, и `KARTA.md` не тронут ни байтом;
#   5. `bootstrap_zahod.py` создал заход → ворота 5 про него молчат СРАЗУ.
#
# ПОЧЕМУ ИНСТРУМЕНТЫ КОПИРУЮТСЯ, А НЕ ЗОВУТСЯ НА МЕСТЕ. `check_kartoteka.py`
# берёт корень репозитория из `Path(__file__).resolve().parents[2]` и своей
# переменной среды не имеет. Символическая ссылка не годится: `resolve()`
# развернёт её в боевой путь, и фикстура начнёт судить настоящий репозиторий.
# Копия в `$T/_generator/tools/` делает `parents[2]` честным адресом /tmp.

set -e
TOOLS=$(cd "$(dirname "$0")/../.." && pwd)

# 🔴 ОБЯЗАТЕЛЬНО ПЕРВЫМ ХОДОМ: вычистить окружение git — та же строка и та же
# причина, что в fixtures/git_zona/PROGNAT.sh. Внутри хука git экспортирует
# GIT_DIR/GIT_INDEX_FILE АБСОЛЮТНЫМИ путями на БОЕВОЙ репозиторий, и без
# вычистки `git add` фикстуры уходит в боевой индекс. Цена 21.07: фикстура,
# поднятая хуком, СОЗДАЛА КОММИТ В БОЕВОМ РЕПОЗИТОРИИ.
# Форма каноническая, из документации githooks: список даёт сам git.
unset $(git rev-parse --local-env-vars)

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT

ARKA=_studio/zhurnal/2026-07-30_proba
mkdir -p "$T/_generator/tools" "$T/_studio/docs" "$T/_studio/zhurnal" \
         "$T/$ARKA" "$T/teoriya-kategoriy/kartoteka" "$T/proekt"
cp "$TOOLS/check_kartoteka.py" "$TOOLS/register_doc.py" "$TOOLS/check_zahod.py" \
   "$TOOLS/bootstrap_zahod.py" "$TOOLS/bootstrap_arka.py" "$TOOLS/korni.py" \
   "$TOOLS/check_sborki.py" "$T/_generator/tools/"
cp "$TOOLS/../../_studio/zhurnal/_TEMPLATE-zahod.md" "$T/_studio/zhurnal/"
cp -r "$TOOLS/../../_studio/zhurnal/_TEMPLATE-arka" "$T/_studio/zhurnal/_TEMPLATE-arka"

# Индекс-двойник: два раздела вокруг §6 — чтобы было видно, если вставка
# заедет к соседям. Строка арки есть, значит проверяется и ветка «раздел
# нашёлся», а не только «завожу новую строку».
cat > "$T/_studio/docs/KARTA.md" <<'KARTA'
# КАРТА (фикстурная)

## §5. Раздел ДО — обязан остаться нетронутым
Соседний текст сверху.

## §6. Карта документов (все `.md`)
**`docs/`:** `KARTA.md` (этот индекс).
**Арка `../zhurnal/2026-07-30_proba/`** (фикстурная арка): `PLAN.md` — план.
**Приманка `../../_generator/skeleton/src/`** (чужой раздел с однокомпонентным хвостом `src/` — сюда запись уезжать НЕ должна).

## §7. Раздел ПОСЛЕ — обязан остаться нетронутым
Соседний текст снизу.
KARTA

cat > "$T/teoriya-kategoriy/kartoteka/KARTA-OBLASTI.md" <<'KART'
# Картотека (фикстурная)

## Индекс по роду

## Нити
KART

cd "$T"
git init -q .
git config user.email fixture@test
git config user.name fixture
git add -A
git commit -qm baseline

GATE="python3 $T/_generator/tools/check_kartoteka.py teoriya-kategoriy/kartoteka/KARTA-OBLASTI.md --staged"
DOOR="python3 $T/_generator/tools/register_doc.py"
FAIL=0

# ── ЛОВУШКА 1: новый .md в _studio/ без регистрации → ворота 5 КРАСНЫЕ ──
# Ворота не ослабляются ни на йоту: сироты реальны, документ без строки в
# индексе действительно не существует для следующей сессии. Ловушка сторожит
# именно это — «дверь появилась» не должно означать «ворота подобрели».
echo "артефакт захода" > "$T/$ARKA/ARTEFAKT.md"
git add "$ARKA/ARTEFAKT.md"
if $GATE > /dev/null 2>&1
then echo "  ❌ ВОРОТА 5 ПРОМОЛЧАЛИ на незарегистрированном .md — защита снята"; FAIL=1
else echo "  ✅ незарегистрированный .md в _studio/ краснеет (ворота 5 живы)"
fi

# ── ЛОВУШКА 2: после register_doc.py → ворота 5 ЗЕЛЁНЫЕ ──
# Половина, ради которой всё затевалось: дверь обязана удовлетворять ТОТ САМЫЙ
# предикат, которым судит хук. Разойдись они — дверь печатала бы «готово», а
# коммит вставал, и обход вернулся бы штатным ходом.
$DOOR "$ARKA/ARTEFAKT.md" "артефакт фикстуры: проба двери" > /dev/null 2>&1 || true
if $GATE > /dev/null 2>&1
then echo "  ✅ после register_doc.py ворота 5 зелёные (дверь и гейт согласны)"
else echo "  ❌ ДВЕРЬ ВПИСАЛА, А ХУК НЕ ЗАСЧИТАЛ — предикаты разъехались"; FAIL=1
fi

# ── ЛОВУШКА 3: повторный вызов не плодит дубль ──
# Идемпотентность не косметика: генератор захода зовёт ту же дверь, и пересборка
# захода не должна оставлять в индексе вторую строку про один документ. Дубль в
# индексе — это два описания одного файла, расходящиеся молча.
#
# ⚠ Считаем ВХОЖДЕНИЯ (`grep -o | wc -l`), а НЕ строки (`grep -c`). Разница тут
# решает: раздел §6 — это абзац-СТРОКА, и обе записи легли бы в неё же. С
# `grep -c` ловушка осталась ЗЕЛЁНОЙ на снятой идемпотентности — поймано
# мутацией при сборке этой самой фикстуры. Ловушка, не краснеющая на своей
# поломке, не существует.
$DOOR "$ARKA/ARTEFAKT.md" "второе описание того же" > /dev/null 2>&1 || true
V=$(grep -o 'ARTEFAKT.md' "$T/_studio/docs/KARTA.md" | wc -l | tr -d ' ')
[ "$V" = "1" ] && echo "  ✅ повторный register_doc.py не завёл вторую строку" \
               || { echo "  ❌ ДУБЛЬ В ИНДЕКСЕ (вхождений: $V) — идемпотентность мертва"; FAIL=1; }

# ── ЛОВУШКА 4: путь вне _studio/ → отказ, KARTA.md не тронут ──
# Ворота 5 судят только `_studio/`. Дверь, регистрирующая что угодно, засоряет
# индекс фабрики документами проектов, у которых свои индексы, — и делает это
# тихо. Проверяем ОБЕ половины: и код возврата, и что файл не изменился.
echo "чужой документ" > "$T/proekt/CHUZHOJ.md"
H0=$(git hash-object "$T/_studio/docs/KARTA.md")
if $DOOR "proekt/CHUZHOJ.md" "описание есть, а путь чужой" > /dev/null 2>&1
then echo "  ❌ ДВЕРЬ ЗАРЕГИСТРИРОВАЛА ПУТЬ ВНЕ _studio/ — индекс фабрики засоряется"; FAIL=1
else echo "  ✅ путь вне _studio/ отвергнут (rc≠0)"
fi
H1=$(git hash-object "$T/_studio/docs/KARTA.md")
[ "$H0" = "$H1" ] && echo "  ✅ при отказе KARTA.md не тронут ни байтом" \
                  || { echo "  ❌ ОТКАЗ ВСЁ РАВНО ПРАВИЛ KARTA.md — отказ лоссовый"; FAIL=1; }

# Те же две половины на пустом описании: строка без описания выглядит как
# выполненная регистрация, а несёт ноль — это хуже отсутствия строки.
if $DOOR "$ARKA/PUSTOE.md" "" > /dev/null 2>&1
then echo "  ❌ ДВЕРЬ ПРИНЯЛА ПУСТОЕ ОПИСАНИЕ — индекс наполняется пустышками"; FAIL=1
else echo "  ✅ пустое описание отвергнуто (rc≠0)"
fi

# ── ЛОВУШКА 5: bootstrap_zahod.py — заход рождается зарегистрированным ──
# Ворота 5 обязаны молчать про него СРАЗУ, без отдельного вызова двери. Это и
# есть шаг A: регистрирует тот ход, у которого `docs/` открыт by construction.
python3 "$T/_generator/tools/bootstrap_zahod.py" "$ARKA" proba \
    --branch fixture-branch --zone "moya-zona/" --kanal terminal \
    --opisanie "фикстурный заход: проверка регистрации тем же ходом" \
    > /dev/null 2>&1 || true
if [ -f "$T/$ARKA/kod_proba.md" ]; then
    git add "$ARKA/kod_proba.md"
    if $GATE > /dev/null 2>&1
    then echo "  ✅ заход от bootstrap_zahod.py зарегистрирован тем же ходом"
    else echo "  ❌ ЗАХОД РОДИЛСЯ СИРОТОЙ — шаг A мёртв, исполнителю снова нечем коммитить"; FAIL=1
    fi
else
    echo "  ❌ bootstrap_zahod.py не создал заход — проверить нечего"; FAIL=1
fi

# Описание не задано — строка обязана уйти С ЯВНОЙ ПОМЕТКОЙ, а не тихой
# заглушкой: тихая выглядит как выполненная регистрация (прямой запрет задания).
python3 "$T/_generator/tools/bootstrap_zahod.py" "$ARKA" bezopisania \
    --branch fixture-branch --zone "moya-zona/" --kanal terminal > /dev/null 2>&1 || true
V=$(grep -o 'описание не задано' "$T/_studio/docs/KARTA.md" | wc -l | tr -d ' ')
[ "$V" = "1" ] && echo "  ✅ без --opisanie в индекс ушла ЯВНАЯ пометка, а не тишина" \
               || { echo "  ❌ ТИХАЯ ЗАГЛУШКА (вхождений пометки: $V) — пустая регистрация выглядит выполненной"; FAIL=1; }

# ── ЦЕЛОСТНОСТЬ ИНДЕКСА: вставка ЛОКАЛЬНА, соседние разделы не переписаны ──
# `KARTA.md` — 210 КБ, отдельные строки-разделы под 45 000 знаков. Программная
# правка такого файла — самый вероятный способ незаметно снести чужой раздел.
V=$(grep -c '^## §' "$T/_studio/docs/KARTA.md" || true)
[ "$V" = "3" ] && echo "  ✅ разделов ## §N по-прежнему 3 (структура цела)" \
               || { echo "  ❌ ЧИСЛО РАЗДЕЛОВ ИЗМЕНИЛОСЬ ($V вместо 3) — вставка заехала в структуру"; FAIL=1; }
V=$(grep -c 'Соседний текст' "$T/_studio/docs/KARTA.md" || true)
[ "$V" = "2" ] && echo "  ✅ соседние разделы §5 и §7 нетронуты" \
               || { echo "  ❌ СОСЕДНИЕ РАЗДЕЛЫ ПОСТРАДАЛИ ($V из 2) — правка не локальна"; FAIL=1; }
V=$(grep -o 'ARTEFAKT.md' "$T/_studio/docs/KARTA.md" | wc -l | tr -d ' ')
[ "$V" = "1" ] && echo "  ✅ запись ушла в строку арки, а не размножилась" \
               || { echo "  ❌ записей про ARTEFAKT.md: $V"; FAIL=1; }

# ══ ЛОВУШКИ 6–10: дыры, найденные АТАКОЙ верификатора 2026-07-30 ══
# Все пять нашлись за один прогон свежего субагента, сформулированный как
# «сломай», а не «проверь». Каждая закрыта кодом — и каждая обязана краснеть
# здесь, иначе починка держится только на памяти автора.

# ── ЛОВУШКА 6 (Д1): подстрочный предикат не должен глушить ДВЕРЬ ──
# Ворота 5 судят подстрокой (`имя in раздел`) — это их давнее поведение, и
# заход запрещает его менять. Но дверь обязана быть строже: имя `PLAN.md` уже
# стоит в §6 у соседней арки, и на `PLAN.md` НОВОЙ арки дверь печатала бы
# «уже зарегистрирован», rc=0, не написав НИЧЕГО. Исполнитель получал бы
# успех и пустой индекс — то есть дверь плодила бы сирот, ради которых
# заводилась. Так молчали все пять файлов, что создаёт bootstrap_arka.py.
mkdir -p "$T/_studio/zhurnal/2026-08-01_novaya"
echo "план новой арки" > "$T/_studio/zhurnal/2026-08-01_novaya/PLAN.md"
$DOOR "_studio/zhurnal/2026-08-01_novaya/PLAN.md" "план новой арки" > /dev/null 2>&1 || true
V=$(grep -o '2026-08-01_novaya' "$T/_studio/docs/KARTA.md" | wc -l | tr -d ' ')
[ "$V" = "1" ] && echo "  ✅ имя-подстрока (PLAN.md) всё равно зарегистрировано по-настоящему" \
               || { echo "  ❌ ДВЕРЬ ПРОГЛОТИЛА ИМЯ-ПОДСТРОКУ (записей: $V) — успех при пустом индексе"; FAIL=1; }

# ── ЛОВУШКА 7 (Д5): второй `## §6.` не должен ссорить дверь с воротами ──
# Ворота режут §6 от ПЕРВОГО заголовка, самодельный поиск границы брал
# ПОСЛЕДНИЙ. Хватало строки `## §6.` в примере формата внутри самого индекса:
# дверь писала в настоящий раздел с rc=0, хук краснел на том же файле, повтор
# печатал «уже зарегистрирован» — легального хода не оставалось, и
# `--no-verify` возвращался штатным ходом. Это самый дорогой класс дефекта.
cp "$T/_studio/docs/KARTA.md" "$T/KARTA.rezerv"
python3 - "$T/_studio/docs/KARTA.md" <<'PY'
import sys, pathlib
p = pathlib.Path(sys.argv[1]); t = p.read_text(encoding="utf-8")
p.write_text(t.replace("## §7.", "## §6. двойник-ловушка\nмусор\n\n## §7.", 1),
             encoding="utf-8")
PY
echo "документ при двойнике" > "$T/$ARKA/DVOJNIK.md"
$DOOR "$ARKA/DVOJNIK.md" "документ при двойнике заголовка" > /dev/null 2>&1 || true
git add "$ARKA/DVOJNIK.md"
if $GATE > /dev/null 2>&1
then echo "  ✅ при втором заголовке §6 дверь и ворота остались согласны"
else echo "  ❌ СГОВОР СЛОМАН: дверь вписала, ворота краснеют — обход возвращается"; FAIL=1
fi
git rm -q --cached "$ARKA/DVOJNIK.md" > /dev/null 2>&1 || true
rm -f "$T/$ARKA/DVOJNIK.md"
cp "$T/KARTA.rezerv" "$T/_studio/docs/KARTA.md"

# ── ЛОВУШКА 8 (Д3): не-ASCII путь виден воротам В РЕЖИМЕ ХУКА ──
# При дефолтном core.quotePath=true git отдаёт кириллический путь в
# C-экранировке, он не оканчивается на `.md` и ВЫПАДАЛ из всех пяти ворот.
# В боевом `_studio/` такие файлы есть; полный прогон их видел, хук — никогда.
echo "кириллический документ" > "$T/$ARKA/ЗАХОД-проба.md"
git add "$ARKA/ЗАХОД-проба.md"
if $GATE > /dev/null 2>&1
then echo "  ❌ НЕ-ASCII ПУТЬ НЕВИДИМ ВОРОТАМ — сирота уезжает при зелёном хуке"; FAIL=1
else echo "  ✅ не-ASCII путь виден воротам (quotePath не глушит гейт)"
fi
$DOOR "$ARKA/ЗАХОД-проба.md" "кириллический документ" > /dev/null 2>&1 || true
if $GATE > /dev/null 2>&1
then echo "  ✅ и дверь его регистрирует (легальный ход есть)"
else echo "  ❌ не-ASCII путь виден воротам, но дверь его не чинит — тупик"; FAIL=1
fi

# ── ЛОВУШКА 9 (Д4): переименование не должно быть невидимым ──
# `git mv` даёт статус R100, а фильтр стоял `ACM`: новое имя без строки в §6
# уезжало зелёным, а старая строка §6 начинала указывать на пустоту.
git commit -qm "перед переименованием" -- "$ARKA/ЗАХОД-проба.md" "$ARKA/ARTEFAKT.md" > /dev/null 2>&1 || true
git mv "$ARKA/ARTEFAKT.md" "$ARKA/PEREIMENOVAN.md"
if $GATE > /dev/null 2>&1
then echo "  ❌ ПЕРЕИМЕНОВАНИЕ НЕВИДИМО ВОРОТАМ — новое имя уезжает сиротой"; FAIL=1
else echo "  ✅ переименованный документ судится воротами (фильтр видит R)"
fi
git mv "$ARKA/PEREIMENOVAN.md" "$ARKA/ARTEFAKT.md"

# ── ЛОВУШКА 10 (Д7): запись не должна уезжать в чужой раздел ──
# Однокомпонентный хвост папки (`src/`, `content/`) совпадал с чужими токенами
# §6, и документ из `<арка>/src/` ложился записью в строку про другой проект.
# Индекс при этом не молчал, а ВРАЛ о месте — это хуже сироты.
mkdir -p "$T/$ARKA/src"
echo "документ в подпапке" > "$T/$ARKA/src/VLOZHENNYJ.md"
$DOOR "$ARKA/src/VLOZHENNYJ.md" "документ в подпапке арки" > /dev/null 2>&1 || true
V=$(grep -c 'VLOZHENNYJ.md' "$T/_studio/docs/KARTA.md" || true)
[ "$V" = "1" ] && echo "  ✅ вложенный документ получил СВОЮ строку, а не чужой раздел" \
               || { echo "  ❌ МИСФАЙЛИНГ: строк с VLOZHENNYJ.md — $V"; FAIL=1; }
V=$(grep -c 'skeleton.*VLOZHENNYJ' "$T/_studio/docs/KARTA.md" || true)
[ "$V" = "0" ] && echo "  ✅ строка-приманка с хвостом src/ записи НЕ получила" \
