#!/usr/bin/env bash
# TOOL-CONTRACT-COVERS: check_termin.py
# Фикстуры гейта порядка введения (check_termin.py, 2026-07-30).
# Гонять после каждой правки check_termin.py:  bash _generator/tools/fixtures/termin/PROGNAT.sh
#
# Гейт может ПРОЙТИ — значит обязана быть фикстура, на которой он ПАДАЕТ.
# Здесь четыре: реальная поломка (та самая, из обзора про Гудстейна) · её починка
# перестановкой · законное «назвал в прозе, не определив» · пустой вход.
set -u

GATE="$(cd "$(dirname "$0")/../.." && pwd)/check_termin.py"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
OK=0

pusk () {                       # pusk <имя> <ожидаемый-код>
  python3 "$GATE" "$TMP/$1" --tiho
  got=$?
  if [ "$got" = "$2" ]; then
    echo "  ✓ $1: код $got"
  else
    echo "  ✗ $1: код $got, ожидался $2"
    OK=1
  fi
}

echo "── ФИКСТУРЫ ГЕЙТА ПОРЯДКА ВВЕДЕНИЯ ──"

# 1. РЕАЛЬНАЯ ПОЛОМКА: теорема пользуется словом, определение ниже.
mkdir -p "$TMP/slomannyj"
cat > "$TMP/slomannyj/a.md" <<'EOF'
# Проба

**Теорема 2 (о представлении).** Всякое вполне упорядоченное множество изоморфно одному ординалу.

**Определение 3 (ординал; фон Нейман).** Ординал — транзитивное множество, на котором принадлежность есть вполне упорядочение.
EOF
pusk "slomannyj" 1

# 2. ПОЧИНКА ПЕРЕСТАНОВКОЙ: то же содержание, определение поднято.
mkdir -p "$TMP/pochinennyj"
cat > "$TMP/pochinennyj/a.md" <<'EOF'
# Проба

**Определение 2 (ординал; фон Нейман).** Ординал — транзитивное множество, на котором принадлежность есть вполне упорядочение.

**Теорема 3 (о представлении).** Всякое вполне упорядоченное множество изоморфно одному ординалу.
EOF
pusk "pochinennyj" 0

# 3. ЗАКОННЫЙ СЛУЧАЙ: слово названо в ПРОЗЕ до определения (приём «назвал, но не работает»).
#    Гейт обязан молчать — иначе он запретит вводную часть и его начнут обходить.
mkdir -p "$TMP/nazval-v-proze"
cat > "$TMP/nazval-v-proze/a.md" <<'EOF'
# Проба

Дальше всё держится на том, что объекту сопоставляется ординал, и этот ординал убывает.

**Определение 1 (ординал; фон Нейман).** Ординал — транзитивное множество, на котором принадлежность есть вполне упорядочение.

**Теорема 2 (о представлении).** Всякое вполне упорядоченное множество изоморфно одному ординалу.
EOF
pusk "nazval-v-proze" 0

# 4. Пустой вход — не падать.
mkdir -p "$TMP/pustoj"
printf '# Ничего\n\nПросто текст без врезок.\n' > "$TMP/pustoj/a.md"
pusk "pustoj" 0

echo
[ "$OK" = 0 ] && echo "ВСЁ ЗЕЛЁНОЕ" || echo "ЕСТЬ ПРОВАЛЫ"
exit "$OK"
