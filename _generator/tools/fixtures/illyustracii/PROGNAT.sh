#!/bin/sh
# TOOL-CONTRACT-COVERS: gejt_illyustracij.py
# Фикстуры ГЕЙТА ЗАКАЗА ИЛЛЮСТРАЦИЙ. Гоняй ПОСЛЕ любой правки gejt_illyustracij.py.
# Строка COVERS выше — не украшение: по ней хук решает, поднимать ли фикстуру
# (класс ошибки — «триггер уже охвата», см. check_tool_contract.py:212-215).
#
# Запуск:  sh _generator/tools/fixtures/illyustracii/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЗАЧЕМ. Класс отказа «заказ и приёмка иллюстрации» — 112 записей на пяти фазах
# картотеки фабрики (заход `provod-illyustracij`); `zakaz.md` был выходом фазы 2 /
# входом фазы 5, которого не читала НИ ОДНА команда. Пять фикстур ниже — ровно
# критерий готовности того захода: три обязаны падать красным, две — зелёным,
# плюс кривой вход (путь мимо, без флагов) не должен тихо превращаться в зелёный.
cd "$(dirname "$0")/../../../.." || exit 1
TOOL=_generator/tools/gejt_illyustracij.py
FIX=_generator/tools/fixtures/illyustracii
fail=0

ok() { echo "  ✅ $1"; }
no() { echo "  ❌ $1"; fail=1; }
je() { [ "$2" = "$3" ] && ok "$1 (rc=$2)" || no "$1: rc=$2, ожидался $3"; }

# 1 — слайд ссылается на имя без zakaz.md в пуле
python3 $TOOL "$FIX/bez-zakaza" --tiho
je "1. слайд без заказа" "$?" "1"
python3 $TOOL "$FIX/bez-zakaza" 2>&1 | grep -q "primer-a" \
  && ok "1. имя картинки названо в тексте ошибки" \
  || no "1. имя картинки в ошибке не найдено"

# 2 — заказ без одного из пяти полей (заглушка «заполнить»)
python3 $TOOL "$FIX/nepolnyj-zakaz" --tiho
je "2. неполный заказ" "$?" "1"

# 3 — заказ-сирота
python3 $TOOL "$FIX/sirota" --tiho
je "3. заказ-сирота" "$?" "1"

# 4a — всё на местах
python3 $TOOL "$FIX/zdorovyj" --tiho
je "4a. здоровый провод" "$?" "0"

# 4b — иллюстраций нет вовсе (обратная совместимость)
python3 $TOOL "$FIX/bez-illyustracij" --tiho
je "4b. лекция без иллюстраций" "$?" "0"

# 4c — карточка нового формата, с lifecycle-блоком «что дальше» перед шапкой
python3 $TOOL "$FIX/s-lifecycle-blokom" --tiho
je "4c. карточка с lifecycle-блоком" "$?" "0"

# 4d — картинка заказана ТОЛЬКО шапкой brief.md (служебный слайд-обложка, папки слайда
# нет вовсе). До правки захода `zakrytie-l2` гейт видел здесь ложную сироту.
python3 $TOOL "$FIX/brief-oblozhka" --tiho
je "4d. картинка только на обложке (brief.md)" "$?" "0"
python3 $TOOL "$FIX/brief-oblozhka" 2>&1 | grep -q "из brief.md: 1" \
  && ok "4d. ссылка из brief.md посчитана в сводке" \
  || no "4d. в сводке нет ссылки из brief.md"

# 7 — 🔴 СТОРОЖ ПРАВКИ: brief.md читается, но сирота ловится по-прежнему.
# Гейт, научившийся видеть шапку и ослепший на сирот, хуже прежнего — этот пункт
# краснеет ровно на такой «починке».
#
# 🔴 ПОЧЕМУ ЭТА ФИКСТУРА СТРОИТСЯ ПРОГОНОМ, а соседние лежат на диске. Она обязана
# быть КРАСНОЙ, а `.githooks/pre-commit` берёт «лекции» из staged-путей по маске
# `slajdy/*/slaid.md` — и не отличает фикстуру от живой лекции. Красная фикстура,
# положенная на диск, останавливала бы КАЖДЫЙ коммит, который её касается (поймано
# на живом коммите захода `zakrytie-l2`). В mktemp она невидима для хука, а сторожем
# быть не перестаёт. Идиома не новая: так устроен 21 прогон из 26.
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
S="$T/brief-sirota"
mkdir -p "$S/slajdy/s01" "$S/illustracii/kartinka-oblozhki" "$S/illustracii/zabytyj"
cat > "$S/brief.md" <<'EOF'
---
id: FIX-SIR
title: Живой brief.md рядом с настоящей сиротой
oblozhka_zagolovok: Заголовок обложки
oblozhka_illustracii: kartinka-oblozhki
---
Шапка ссылается на `kartinka-oblozhki`, а в пуле рядом лежит `zabytyj` — на него не
ссылается НИКТО. Гейт обязан остаться на нём красным.
EOF
cat > "$S/slajdy/s01/slaid.md" <<'EOF'
---
imya: s01
nazvanie: Слайд без картинок
illustracii: []
---
Картинок на слайде нет — сирота в пуле от этого сиротой быть не перестаёт.
EOF
cat > "$S/illustracii/kartinka-oblozhki/zakaz.md" <<'EOF'
что изображено: пустой квадрат с тонкой рамкой по центру кадра
сколько объектов и как подписаны: 1 квадрат, без подписей
что происходит: ничего не происходит, это заставка обложки
чего рисовать НЕ надо: не рисовать заливку, тень и подписи по углам
размер: четверть высоты кадра
EOF
cat > "$S/illustracii/zabytyj/zakaz.md" <<'EOF'
что изображено: ломаная из трёх звеньев, идущая слева направо
сколько объектов и как подписаны: 3 звена, подписаны a, b, c
что происходит: показывает путь, собранный из трёх шагов
чего рисовать НЕ надо: не рисовать стрелки на концах звеньев
размер: половина ширины слайда
EOF
python3 $TOOL "$S" --tiho
je "7. сирота при живом brief.md" "$?" "1"
python3 $TOOL "$S" 2>&1 | grep -q "zabytyj" \
  && ok "7. имя сироты названо в тексте ошибки" \
  || no "7. имя сироты в ошибке не найдено"
python3 $TOOL "$S" 2>&1 | grep -q "kartinka-oblozhki.*сирота" \
  && no "7. картинка из brief.md ошибочно названа сиротой" \
  || ok "7. картинка из brief.md сиротой не названа"

# кривой вход — без аргументов
python3 $TOOL >/dev/null 2>&1
je "5. без аргументов" "$?" "2"

# кривой вход — путь не существует (НЕ то же самое, что «иллюстраций нет»:
# тихий зелёный здесь замаскировал бы опечатку в пути лекции)
python3 $TOOL "$FIX/net-takoj-papki" >/dev/null 2>&1
je "6. несуществующий путь лекции" "$?" "2"

[ $fail = 0 ] && echo "ФИКСТУРЫ ЗЕЛЁНЫЕ" || echo "ФИКСТУРЫ КРАСНЫЕ — гейт заказа иллюстраций сломан правкой"
exit $fail
