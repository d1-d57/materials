#!/bin/sh
# TOOL-CONTRACT-COVERS: gejt_illyustracij.py
# Фикстуры ГЕЙТА ЗАКАЗА ИЛЛЮСТРАЦИЙ. Гоняй ПОСЛЕ любой правки gejt_illyustracij.py.
# Строка COVERS выше — не украшение: по ней хук решает, поднимать ли фикстуру
# (класс ошибки — «триггер уже охвата», см. check_tool_contract.py:212-215).
#
# Запуск:  sh _generator/tools/fixtures/illyustracii/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЗАЧЕМ. Класс отказа «заказ и приёмка иллюстрации» — 112 записей на пяти фазах
# картотеки фабрики (заход `provod-illyustracij`); `zakaz.md` был выходом фазы 2 /
# входом фазы 5, которого не читала НИ ОДНА команда. Пять фикстур ниже — ровно
# критерий готовности того захода: три обязаны падать красным, две — зелёным,
# плюс кривой вход (путь мимо, без флагов) не должен тихо превращаться в зелёный.
cd "$(dirname "$0")/../../../.." || exit 1
TOOL=_generator/tools/gejt_illyustracij.py
FIX=_generator/tools/fixtures/illyustracii
fail=0

ok() { echo "  ✅ $1"; }
no() { echo "  ❌ $1"; fail=1; }
je() { [ "$2" = "$3" ] && ok "$1 (rc=$2)" || no "$1: rc=$2, ожидался $3"; }

# 1 — слайд ссылается на имя без zakaz.md в пуле
python3 $TOOL "$FIX/bez-zakaza" --tiho
je "1. слайд без заказа" "$?" "1"
python3 $TOOL "$FIX/bez-zakaza" 2>&1 | grep -q "primer-a" \
  && ok "1. имя картинки названо в тексте ошибки" \
  || no "1. имя картинки в ошибке не найдено"

# 2 — заказ без одного из пяти полей (заглушка «заполнить»)
python3 $TOOL "$FIX/nepolnyj-zakaz" --tiho
je "2. неполный заказ" "$?" "1"

# 3 — заказ-сирота
python3 $TOOL "$FIX/sirota" --tiho
je "3. заказ-сирота" "$?" "1"

# 4a — всё на местах
python3 $TOOL "$FIX/zdorovyj" --tiho
je "4a. здоровый провод" "$?" "0"

# 4b — иллюстраций нет вовсе (обратная совместимость)
python3 $TOOL "$FIX/bez-illyustracij" --tiho
je "4b. лекция без иллюстраций" "$?" "0"

# 4c — карточка нового формата, с lifecycle-блоком «что дальше» перед шапкой
python3 $TOOL "$FIX/s-lifecycle-blokom" --tiho
je "4c. карточка с lifecycle-блоком" "$?" "0"

# кривой вход — без аргументов
python3 $TOOL >/dev/null 2>&1
je "5. без аргументов" "$?" "2"

# кривой вход — путь не существует (НЕ то же самое, что «иллюстраций нет»:
# тихий зелёный здесь замаскировал бы опечатку в пути лекции)
python3 $TOOL "$FIX/net-takoj-papki" >/dev/null 2>&1
je "6. несуществующий путь лекции" "$?" "2"

[ $fail = 0 ] && echo "ФИКСТУРЫ ЗЕЛЁНЫЕ" || echo "ФИКСТУРЫ КРАСНЫЕ — гейт заказа иллюстраций сломан правкой"
exit $fail
