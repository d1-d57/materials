  echo "❌ ЛОВУШКА 8: предупреждение З6 не напечатано. Вывод:"; echo "$OUT8"; exit 1; }
echo "  ✅ ловушка 8: З6 напечатано предупреждением, rc=0 (не гейт)"

echo "── ловушка 9: З7а — нет секции-заготовки (## УРОКИ ФАБРИКЕ)"
