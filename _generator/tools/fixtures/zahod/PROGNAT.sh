#!/bin/sh
# TOOL-CONTRACT-COVERS: check_zahod.py
# ↑ ОХВАТ: линтер входа как механизм — девять проверок (З1-З9) над текстом
# kod_*.md, плюс интеграция с bootstrap_zahod.py (структурный гейт при сборке).
#
# Запуск:  sh _generator/tools/fixtures/zahod/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЛОВУШЕК ДВАДЦАТЬ ШЕСТЬ (задание требовало не менее девяти):
#   1. 🔴 ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НА ЖИВЫХ ФАЙЛАХ — главная ловушка фикстуры:
#      она сторожит не поломку, а излишнюю строгость, от которой линтер отключат.
#      ⚠ С 08.08 — с одним ОБЪЯВЛЕННЫМ вычетом: З10 (см. ловушку 24 и докстринг
#      `check_zahod.py`, закон 2). Молчание требуется по всем ОСТАЛЬНЫМ проверкам.
#   2. Положительный контроль на синтетическом здоровом заходе — rc=0.
#   3. З1: критерий без backtick/числа — красный, поимённо.
#   4. З2: критерий без «живого прогона» — красный, поимённо.
#   5. З3: ЗОНА без backtick-путей — красный, поимённо.
#   6. З4: КОНТРАКТ ЗОНЫ без слова «файл»+локации — красный, поимённо.
#   7. З5: нет однозначной точки входа — красный, поимённо.
#   8. З6 (печать, не гейт): число без соседней команды — предупреждение, rc=0.
#   9. З7а: нет секции-заготовки — красный, поимённо.
#  10. З7б: в ВОПРОСЫ нет формата ДОМ:/ДОСТАВЛЕНО: — красный, поимённо.
#  11. `bootstrap_zahod.py` без `--kanal` — заход НЕ собирается.
#  12. 🔴 РЕГРЕССИЯ (верификатор §3): ЗОНА = только `materials/` (имя корня
#      репозитория, содержит «/», но не сужает ничего) — обязана краснеть.
#  13. 🔴 РЕГРЕССИЯ (верификатор §3): критерий, перефразирующий «живой прогон»
#      без буквальной словоформы («реальном объекте», «не пересказ») — обязан
#      МОЛЧАТЬ (лексическая проверка расширена, не только точная фраза).
#  14. З8 отрицательная: критерий требует «запушь», тело говорит «НЕ пушить»,
#      разрешённое место не названо — красный, поимённо.
#  15. З8 положительная: тот же глагол под запретом и в требовании, но объекты
#      РАЗНЫЕ — обязана МОЛЧАТЬ (иначе гейт краснеет на каждом здоровом заходе:
#      запретов у здорового больше, а не меньше). Несёт собственный контроль:
#      тот же файл со СМЕНЁННЫМ объектом запрета обязан покраснеть, иначе
#      «молчит» неотличимо от «проверка вообще не про этот глагол».
#  16. 🔴 З8 РЕГРЕССИОННАЯ, САМАЯ ВАЖНАЯ: тот же глагол под запретом И в
#      требовании, но заход ЯВНО называет разрешённое место («тестовый коммит
#      делается в `main`») — обязана МОЛЧАТЬ. Ровно этот случай отличает
#      полезный гейт от назойливого, который обойдут вместе со всеми.
#  17. `--vlit ВЕТКА` — в собранном заходе есть блок `§0.1` с `merge` и
#      проверкой фактом на диске.
#  18. Без `--vlit` при нуле невлитых `zahod/*`-веток — файл явно говорит
#      «вливать нечего, проверено», а не молчит.
#  19. Невлитая `zahod/*`-ветка есть, `--vlit` не задан — генератор
#      ПРЕДУПРЕЖДАЕТ поимённо в консоль и ВСЁ РАВНО собирает (rc=0, файл на
#      диске) — сторож не отказывает на чужом законном состоянии (§2.3).
#  20. Заход, собранный с `--vlit`, не будит ложный `З8` («влей» из блока
#      влития против «не вливай» из контракта зоны — про РАЗНЫЕ ветки).
#  21. З9: заход с задвоенной секцией `## 2. ЗАДАЧА` — красный, поимённо.
#  22. З9: здоровый заход, каждая секция по разу — молчит.
#  23. 🔴 З9 ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: свежесобранный `bootstrap_zahod.py`-скелет
#      молчит — покраснел бы, чинится проверка, а не генератор.
#  24. 🔴 З10 ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НА ЖИВЫХ: заход без блока §0.1 ГИТ-КОНТУР
#      краснеет поимённо. Живой, а не синтетический: без него «ловушка 1 молчит»
#      неотличимо от «З10 не работает вовсе».
#  25. З10: генератор с тремя слотами (`--vlit`+`--kommitit`+`--zakryt`) даёт
#      заход, на котором З10 МОЛЧИТ — иначе гейт краснел бы на своём же выходе.
#  26. 🔴 З10, сердце механизма: слот без флага получает МАРКЕР в файле и
#      предупреждение в консоли, а линтер краснеет на нём ПОИМЁННО. До 08.08 в
#      этом случае в файл не уходило ничего, и молчание было неотличимо от
#      «здесь ничего не требуется» — цена — три потерянных хода за сутки
#      (`UROKI-FABRIKE.md` арки `2026-08-07_arhitektura-slajdov`, урок 11).
set -e
TOOLS=$(cd "$(dirname "$0")/../.." && pwd)
REPO_ROOT=$(cd "$TOOLS/../.." && pwd)
unset $(git rev-parse --local-env-vars) 2>/dev/null || true

P="$TOOLS/check_zahod.py"

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT

krasnet() {  # <описание> <ожидаемый_код> <файл>
  OPIS="$1"; KOD="$2"; FILE="$3"
  OUT=$(python3 "$P" "$FILE" 2>&1) && {
    echo "❌ ЛОВУШКА НЕ СРАБОТАЛА: $OPIS — линтер принял дефектный вход"
    exit 1
  }
  echo "$OUT" | grep -q "❌ $KOD" || {
    echo "❌ ЛОВУШКА: красное есть, но НЕ от $KOD поимённо. Вывод:"
    echo "$OUT"; exit 1
  }
  echo "  ✅ $OPIS — $KOD покраснел поимённо"
}

# ── эталон здорового захода: все семь проверок обязаны молчать ────────────────
sobrat_zdorovyj() {  # <путь>
  cat > "$1" <<'MD'
# Канал исполнителя — test (проба фикстуры)

## КОНТРАКТ ЗОНЫ (обязателен)
- **МЕСТО РАБОТЫ:** worktree захода; проверить, что на месте — `git branch --show-current` обязано дать `test-branch`.
- **ЗОНА (можно менять):** `_generator/tools/dummy.py`. Всё вне — READ-ONLY.
- Отчёт пишется в файл ОСНОВНОЙ папки репозитория, по абсолютному пути — сам файл не коммитится.

## 0. ПЕРВЫЙ ХОД
### 0.1 🔴 ГИТ-КОНТУР — ДО ВСЕГО ОСТАЛЬНОГО (три слота, пустых быть не должно)

**1. ВЛИТЬ ПЕРЕД РАБОТОЙ.** Пояснение слота.

вливать нечего, проверено командой `git branch --no-merged` при сборке: невлитых веток 0.

**2. ЗАКОММИТИТЬ ПО ХОДУ.** Пояснение слота.

- зона `_generator/tools/dummy.py`

**3. ЗАКРЫТЬ ПОСЛЕ.** Пояснение слота.

- гасить нечего: ветка захода закрывается приёмкой

## 2. ЗАДАЧА
Сделать X, ровно по шагам.

**КРИТЕРИЙ ГОТОВНОСТИ (может ПРОВАЛИТЬСЯ):**
1. `sh test.sh` → `echo $?` = 0.
2. 🔴 Живой прогон на реальном файле репозитория, не только фикстура.

## 3. ВЕРИФИКАТОР
Свежий субагент проверяет результат.

## ПЛАН — (заполняет исполнитель)
План: сделать X.

## ВОПРОСЫ — (заполняет исполнитель)
1. Находка, принадлежащая чужому дому — оформи пунктом очереди:
```
N. <текст находки>
   ДОМ: <путь от корня репозитория | владелец>
   ДОСТАВЛЕНО: нет
```

## ОТЧЁТ — (заполняет исполнитель)
Сделано X, проверено прогоном.

## УРОКИ ФАБРИКЕ — (заполняет исполнитель; пусто — нормальный исход)
MD
}

echo "── ловушка 1: 🔴 ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НА ЖИВЫХ ФАЙЛАХ — rc=0 И пустой вывод"
LIVE1="$REPO_ROOT/_studio/zhurnal/2026-07-30_dovodka-fabriki/kod_tirazh-ocheredi.md"
LIVE2="$REPO_ROOT/_studio/zhurnal/2026-07-30_dovodka-fabriki/kod_ochered-domov.md"
# 🔴 ОДНО ОБЪЯВЛЕННОЕ ИСКЛЮЧЕНИЕ — З10 (08.08.2026). Оба калибровочных захода
# написаны ДО того, как блок §0.1 ГИТ-КОНТУР стал обязательным, и он у них
# действительно отсутствует: красное З10 на них ИСТИННОЕ, а закон калибровки
# запрещает ЛОЖНОЕ. Поэтому здесь проверяется молчание по всем проверкам КРОМЕ
# З10, а сами эти файлы служат З10 живым положительным контролем (ловушка 24).
# Строки-шапки `── <путь>` линтер печатает при любом выводе, они не находка.
for LIVE in "$LIVE1" "$LIVE2"; do
  [ -f "$LIVE" ] || { echo "❌ ЛОВУШКА 1: живой файл не найден — $LIVE"; exit 1; }
  OUT=$(python3 "$P" "$LIVE" 2>&1) || true
  KROME=$(echo "$OUT" | grep -v '^── ' | grep -v 'З10' | grep -v '^[[:space:]]*$' || true)
  [ -z "$KROME" ] || {
    echo "❌ ЛОВУШКА 1: линтер НЕ МОЛЧИТ (сверх объявленного З10) на признанном хорошим живом заходе — $LIVE. Вывод:"
    echo "$KROME"; exit 1; }
done
echo "  ✅ ловушка 1: оба живых калибровочных захода — молчат по всем проверкам, кроме объявленной З10"

