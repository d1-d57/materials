  echo "❌ ЛОВУШКА 2: синтетический здоровый заход дал красный. Вывод:"; echo "$OUT2"; exit 1; }
echo "  ✅ ловушка 2: синтетический здоровый заход — rc=0"

echo "── ловушка 3: З1 — критерий без backtick/числа"
sobrat_zdorovyj "$T/kod_z1.md"
python3 -c "
p = '$T/kod_z1.md'
t = open(p, encoding='utf-8').read()
t = t.replace(
    '1. \`sh test.sh\` → \`echo \$?\` = 0.\n2. 🔴 Живой прогон на реальном файле репозитория, не только фикстура.',
    'Я закончу, когда всё будет готово, и проверю внимательно.')
open(p, 'w', encoding='utf-8').write(t)
"
krasnet "критерий без backtick/числа" "З1" "$T/kod_z1.md"

echo "── ловушка 4: З2 — критерий без «живого прогона»"
