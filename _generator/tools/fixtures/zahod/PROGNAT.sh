filler = 'Отдельный абзац без единого backtick, нужен только чтобы отодвинуть ' \
         'следующее числовое утверждение дальше трёхсот символов от ближайшей ' \
         'команды или пути в этом синтетическом эталоне — иначе окно проверки ' \
         'находит код-блок очереди ВОПРОСЫ по соседству и не даёт ловушке ' \
         'сработать на самом деле изолированном утверждении ниже, что и есть ' \
         'смысл этой конкретной ловушки восемь.'
assert len(filler) > 300, len(filler)
t += '\n\n' + filler + '\n\n**Замерено: 128 инцидентов за сессию, свежая метрика, без ссылки на команду.**\n'
open(p, 'w', encoding='utf-8').write(t)
"
