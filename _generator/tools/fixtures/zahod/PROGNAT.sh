set -e
TOOLS=$(cd "$(dirname "$0")/../.." && pwd)
REPO_ROOT=$(cd "$TOOLS/../.." && pwd)
unset $(git rev-parse --local-env-vars) 2>/dev/null || true

P="$TOOLS/check_zahod.py"

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT

krasnet() {  # <описание> <ожидаемый_код> <файл>
  OPIS="$1"; KOD="$2"; FILE="$3"
  OUT=$(python3 "$P" "$FILE" 2>&1) && {
    echo "❌ ЛОВУШКА НЕ СРАБОТАЛА: $OPIS — линтер принял дефектный вход"
    exit 1
  }
  echo "$OUT" | grep -q "❌ $KOD" || {
    echo "❌ ЛОВУШКА: красное есть, но НЕ от $KOD поимённо. Вывод:"
    echo "$OUT"; exit 1
  }
  echo "  ✅ $OPIS — $KOD покраснел поимённо"
}

# ── эталон здорового захода: все проверки обязаны молчать ─────────────────────
# 🔴 Секция «## СТАРТОВОЕ СООБЩЕНИЕ ВЛАДЕЛЬЦУ» — обязательная часть эталона
# (заход `nositel`, ## ЗАДАЧА шаг 1): секцию заводит З13, и без неё
# ВСЕ существующие «здоровый заход молчит»-ловушки этого файла посыпались бы
# ложно на новом HARD_CHECK. Тело несёт РЕАЛЬНУЮ строку `## ПЛАН внутри него`
# канала `app` — тот же текст, которым живой прогон при сборке ЭТОГО захода
# поймал главную ловушку (см. `check_zahod._bez_startovogo`): регресс на
# фикстуре здорового захода ловит его тем же ходом, а не отдельной пробой.
sobrat_zdorovyj() {  # <путь>
  cat > "$1" <<'MD'
# Канал исполнителя — test (проба фикстуры)

## СТАРТОВОЕ СООБЩЕНИЕ ВЛАДЕЛЬЦУ

> Это блок для владельца — то, чем тебя запустили. Исполнителю здесь делать нечего, твоё задание ниже.

```
Модель: Sonnet 5 — проба фикстуры.

Ты исполнитель в репозитории /tmp/proba.

Твой единственный вход — файл-заход:
/tmp/proba/kod_test.md

Первым ходом: git branch --show-current, затем чтение захода, затем секция
## ПЛАН внутри него — до всяких действий.
```

## ЧТО ФИНАЛИЗИРОВАНО НА ИНТЕРВЬЮ

1. Владелец подтвердил: делаем X, ровно тем способом, что описан ниже.
2. Владелец подтвердил: живой прогон обязателен, фикстуры одной не хватит.

## КОНТРАКТ ЗОНЫ (обязателен)
- **МЕСТО РАБОТЫ:** worktree захода; проверить, что на месте — `git branch --show-current` обязано дать `test-branch`.
- **ЗОНА (можно менять):** `_generator/tools/dummy.py`. Всё вне — READ-ONLY.
- Отчёт пишется в файл ОСНОВНОЙ папки репозитория, по абсолютному пути — сам файл не коммитится.

## 0. ПЕРВЫЙ ХОД
### 0.1 🔴 ГИТ-КОНТУР — ДО ВСЕГО ОСТАЛЬНОГО

🔴 «ничего сверх задачи» относится к СОДЕРЖАНИЮ работы; git-контур §0.1 — законное исключение, он про состояние репозитория и исполняется целиком.

**1. ВЛИТЬ ПЕРЕД РАБОТОЙ — САМ, В ЭТОМ ОКНЕ.** Пояснение слота.

вливать нечего, проверено командой `git branch --no-merged` при сборке: невлитых веток 0.

**2. ОСТАЛЬНОЙ КОНТУР — В СУБАГЕНТА, ОДНИМ ХОДОМ.** Очередь заявок (`git_zona.py zayavki`), что забрать в git и что погасить. Полный текст задания печатает команда:
```
python3 _generator/tools/bootstrap_zahod.py --zadanie-subagentu --kommitit 'зона' --zakryt 'ветку'
```

## 2. ЗАДАЧА
Сделать X, ровно по шагам.

**КРИТЕРИЙ ГОТОВНОСТИ (может ПРОВАЛИТЬСЯ):**
1. `sh test.sh` → `echo $?` = 0.
2. 🔴 Живой прогон на реальном файле репозитория, не только фикстура.

## 3. ВЕРИФИКАТОР
Свежий субагент проверяет результат.

## ПЛАН — (заполняет исполнитель)
План: сделать X.

## ВОПРОСЫ — (заполняет исполнитель)
1. Находка, принадлежащая чужому дому — оформи пунктом очереди:
```
N. <текст находки>
   ДОМ: <путь от корня репозитория | владелец>
   ДОСТАВЛЕНО: нет
```

## ОТЧЁТ — (заполняет исполнитель)
Сделано X, проверено прогоном.

## УРОКИ ФАБРИКЕ — (заполняет исполнитель; пусто — нормальный исход)
MD
}

echo "── ловушка 1: 🔴 ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ НА ЖИВЫХ ФАЙЛАХ — rc=0 И пустой вывод"
LIVE1="$REPO_ROOT/_studio/zhurnal/2026-07-30_dovodka-fabriki/kod_tirazh-ocheredi.md"
LIVE2="$REPO_ROOT/_studio/zhurnal/2026-07-30_dovodka-fabriki/kod_ochered-domov.md"
# 🔴 ТРИ ОБЪЯВЛЕННЫХ ИСКЛЮЧЕНИЯ — З10 (08.08.2026), З11 (11.08.2026) и З13
# (13.08.2026). Все калибровочные заходы написаны ДО того, как блок §0.1
# ГИТ-КОНТУР, секция ЧТО ФИНАЛИЗИРОВАНО НА ИНТЕРВЬЮ и секция СТАРТОВОЕ
# СООБЩЕНИЕ ВЛАДЕЛЬЦУ стали обязательными, и они у них действительно
