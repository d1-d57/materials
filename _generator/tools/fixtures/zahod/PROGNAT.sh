python3 -c "
p = '$T/kod_z5.md'
t = open(p, encoding='utf-8').read()
t = t.replace(
    '- **МЕСТО РАБОТЫ:** worktree захода; проверить, что на месте — \`git branch --show-current\` обязано дать \`test-branch\`.',
    '- **МЕСТО РАБОТЫ:** там, где удобнее исполнителю.')
open(p, 'w', encoding='utf-8').write(t)
"
krasnet "нет однозначной точки входа" "З5" "$T/kod_z5.md"

echo "── ловушка 8: З6 (печать, не гейт) — число без соседней команды/адреса"
sobrat_zdorovyj "$T/kod_z6.md"
python3 -c "
p = '$T/kod_z6.md'
t = open(p, encoding='utf-8').read()
# Синтетический эталон короткий (весь документ < 300 символов от любого места
# до любого) — окно З6 (±300) достаёт до ближайшего backtick ВСЕГДА, если не
