python3 -c "
p = '$T/kod_z4.md'
t = open(p, encoding='utf-8').read()
t = t.replace('- Отчёт пишется в файл ОСНОВНОЙ папки репозитория, по абсолютному пути — сам файл не коммитится.\n',
              '')
open(p, 'w', encoding='utf-8').write(t)
