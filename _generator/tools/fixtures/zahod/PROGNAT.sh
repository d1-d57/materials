  OUT=$(python3 "$P" "$LIVE" 2>&1) || true
  KROME=$(echo "$OUT" | grep -v '^── ' | grep -v 'З10' | grep -v 'З11' | grep -v 'З12' | grep -v 'З13' | grep -v '^[[:space:]]*$' || true)
  [ -z "$KROME" ] || {
    echo "❌ ЛОВУШКА 1: линтер НЕ МОЛЧИТ (сверх объявленных З10/З11/З12/З13) на признанном хорошим живом заходе — $LIVE. Вывод:"
    echo "$KROME"; exit 1; }
done
echo "  ✅ ловушка 1: оба живых калибровочных захода — молчат по всем проверкам, кроме объявленных З10/З11/З12/З13"

echo "── ловушка 2: положительный контроль на синтетическом здоровом заходе"
