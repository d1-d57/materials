new = '## ВОПРОСЫ — (заполняет исполнитель)\nВопросов нет.\n'
assert old in t, 'шаблон ВОПРОСЫ разъехался с фикстурой'
t = t.replace(old, new)
open(p, 'w', encoding='utf-8').write(t)
