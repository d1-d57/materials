# запрещает ЛОЖНОЕ. Поэтому здесь проверяется молчание по всем проверкам КРОМЕ
# З10, З11, З12 и З13, а сами эти файлы служат живым положительным контролем
# всех четырёх (ловушки 24, 28, позитивный контроль З12, позитивный контроль
# З13). Строки-шапки `── <путь>` линтер печатает при любом выводе, они не находка.
