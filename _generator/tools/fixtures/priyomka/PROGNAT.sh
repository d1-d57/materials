# 🔴 ПАРАМИ, И ПОЛОЖИТЕЛЬНЫХ ЗДЕСЬ БОЛЬШЕ, ЧЕМ ОТРИЦАТЕЛЬНЫХ, — НАМЕРЕННО.
# Опасность этой клаузы не в том, что она пропустит усечение, а в том, что она
# покраснеет на отчётах БЕЗ субагентов (таких большинство). Красное на здоровом —
# это гейт, который отключат вместе со всей защитой (Р31). Поэтому 25 ловит
# настоящую болезнь, а 26/27/28 сторожат ровно молчание на здоровом.
# `subagent_stroku()` вставляет строки в тело `## ОТЧЁТ`, не трогая **АРТЕФАКТ:**
# и **КОММИТ:** — иначе покраснели бы Г1/Г2 и ловушка перестала бы изолировать Г9.
subagent_stroku() {  # <файл-заход> <строка...>
  FILE="$1"; shift
  python3 - "$FILE" "$@" <<'PY'
import sys, pathlib
p = pathlib.Path(sys.argv[1])
t = p.read_text(encoding="utf-8")
yakor = "Сделано: собран инструмент X, прогнан на живом файле, числа воспроизведены."
assert yakor in t, "якорь тела ## ОТЧЁТ не найден — шаблон sobrat_zdorovyj разъехался"
p.write_text(t.replace(yakor, yakor + "\n" + "\n".join(sys.argv[2:])), encoding="utf-8")
PY
}

# 🔴 ОТМЕТКА ВРЕМЕНИ ПРАВИЛА — без неё Г9 неприменима по построению (см. gate_g9).
# Фраза «ОТВЕТ ЛЮБОГО …» уезжает в §0.1 из bootstrap_zahod.git_kontur_blok(), и
# ловушки Г9 обязаны собирать заход ИМЕННО с ней: иначе они проверяют случай,
# которого в жизни не бывает, и зеленеют по неправильной причине.
marker_pravila() {  # <файл захода>
  python3 -c "
from pathlib import Path
p = Path('$1')
t = p.read_text(encoding='utf-8')
y = '## ПЛАН'
assert y in t, 'якорь ## ПЛАН не найден'
m = '🔴 ОТВЕТ ЛЮБОГО субагента, которого ты запускаешь (не только этого), обязан КОНЧАТЬСЯ строкой охвата.'
p.write_text(t.replace(y, m + chr(10) + chr(10) + y, 1), encoding='utf-8')
"
}

