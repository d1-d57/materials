#!/bin/sh
# TOOL-CONTRACT-COVERS: priyomka.py
# ↑ ОХВАТ: приёмка отчёта как механизм — машинные гейты Г0-Г6 плюс печать для
# рук (вопросы/уроки/числа/чек-лист). Инструмент отбирает у аналитика
# возможность забыть пять из шести шагов приёмки, для которых носителя не
# было вовсе (см. докстринг `priyomka.py`).
#
# Запуск:  sh _generator/tools/fixtures/priyomka/PROGNAT.sh
# Ожидание: ФИКСТУРЫ ЗЕЛЁНЫЕ, exit 0.
#
# ЛОВУШЕК ДВАДЦАТЬ ВОСЕМЬ (задание требовало не менее семи):
#   1. АРТЕФАКТ — плейсхолдер в угловых скобках (Г2) — красное.
#   2. Артефакт старше источника (Г3) — красное.
#   3. Хэш коммита, которого нет в репозитории (Г1) — красное.
#   4. Урок без ЦЕНА: (Г5) — красное.
#   5. 🔴 Урок в дневнике «Урок фабрике» с ЗАГЛАВНОЙ (Г6) — обязан быть найден;
#      прямая регрессия на форму грепа, дававшую ложное зелёное (RUKOVODSTVO
#      §Хук «→ фабрика»).
#   6. ## ВОПРОСЫ печатаются ДАЖЕ при полностью зелёном прогоне.
#   7. Положительный контроль: здоровый отчёт → exit 0 + блок печати для рук.
#   8. Пустые ## ОТЧЁТ / ## ПЛАН (Г4) — красное.
#   9. Ф1/часть B — пункт очереди помечен ДОСТАВЛЕНО, а метки по адресу ДОМ
#      нет (Г7) — красное.
#  10. Ф1/часть B — пункт очереди НЕ помечен (ДОСТАВЛЕНО: нет) — печатается
#      в списке недоставленных, но НЕ красный.
#  11. Часть A — транскрипт недоступен (изолированный HOME) — печатается
#      честная причина, прогон НЕ падает.
#  12. Часть C4 — Г6 после отсечки `<!-- РАЗНЕСЕНО ДО СЮДА -->` не видит
#      упоминания «урок» ДО неё и видит упоминание ПОСЛЕ.
#  13. 🔴 Часть B (тираж) — артефакт ВНУТРИ зоны, старше .md по mtime, но в ТОМ
#      ЖЕ коммите, что назван в §4 — Г3 НЕ красный (регрессия на ложное красное
#      из самоссылки, см. `kod_ochered-domov.md`).
#  14. Часть B — артефакт ВНУТРИ зоны, но НЕ входит в названный коммит — Г3 красный.
#  15. Часть B — артефакт ВНЕ зоны (но отслеживается в репо), старше по
#      коммит-времени — Г3 красный (ветка «вне зоны» через коммит-время, а не
#      только через mtime-вне-репо, как в ловушке 2).
#  16. Часть C — доля пунктов «ДОМ: владелец» печатается при ОДНОМ пункте (1 из N).
#  17. Часть C — доля пунктов «ДОМ: владелец» печатается при НУЛЕ пунктов (0 из 0).
#  18. 🔴 «АРТЕФАКТ: артефакта нет: <причина>» (форма разрешена шаблоном отчёта
#      для инфраструктурных заходов) — Г3 НЕ красный, причина Г2 и Г3 не спорят.
#  19. Путь к реально существующему файлу — Г3 по-прежнему зелёный (regression
#      guard: новая ветка «артефакта нет» не глотает обычные пути).
#  20. Путь к несуществующему файлу — Г3 остаётся красным (способность краснеть
#      на настоящей пропаже артефакта не потеряна правкой ловушки 18).
#  21. 🔴 Л1 (задание Ш3 этого захода) — заявка возрастом 30 ч → приёмка красная.
#  22. Л1 — заявка возрастом 1 ч → зелёная.
#  23. Л1 — очередь пуста → зелёная, с охватом «проверено 0 заявок».
#  24. 🔴 Л1 — постоянное исключение (`СРОЧНОСТЬ: postoyannaya`) ЛЮБОГО возраста
#      возрастом не судится вовсе (§4 PROEKT.md: иначе гейт красил бы КАЖДУЮ
#      приёмку арки с намеренно долгоживущей заявкой, и его отключили бы первым).
#  25. 🔴 Г9 (Р5-6, КРТ-020a) — отчёт называет субагента, строки охвата «выдано N
#      позиций из M найденных» нет → красное поимённо, остальные гейты зелёные.
#  26. Г9 — тот же отчёт СО строкой охвата → зелёное.
#  27. 🔴 Г9 — отчёт БЕЗ субагентов вовсе, и отчёт с явным «субагентов не
#      запускал» → Г9 молчит (отчётов без субагентов большинство; красное на них
#      снесло бы защиту целиком).
#  28. 🔴 Г9 — заход ПРЕДПИСЫВАЕТ субагента (§0.1), а отчёт его не называет →
#      зелёное с подсказкой для рук, а не красное: блок §0.1 печатается в КАЖДЫЙ
#      свежий заход, и безусловное красное покрасило бы их все.
#
# 🔴 Г0 («зона доехала в git») сознательно НЕ параметризован реальной грязью
# рабочего дерева разработчика — фикстура использует несуществующий префикс
# зоны (`git_zona.py check --zone <несуществующий путь>` вернул ✅ живым
# прогоном: несуществующий путь трактуется как «вне git ничего нет»), чтобы
# зелёный прогон фикстуры не зависел от того, закоммичена ли ИМЕННО СЕЙЧАС
# рабочая зона исполнителя, который её запускает.
set -e
TOOLS=$(cd "$(dirname "$0")/../.." && pwd)
REPO_ROOT=$(cd "$TOOLS/../.." && pwd)

# Вычистить окружение git — та же строка и та же причина, что в других
# фикстурах: внутри хука git экспортирует GIT_DIR/GIT_INDEX_FILE на БОЕВОЙ
# репозиторий, и дочерние git-вызовы фикстуры должны их не видеть.
unset $(git rev-parse --local-env-vars) 2>/dev/null || true

P="$TOOLS/priyomka.py"
HASH=$(git -C "$REPO_ROOT" --no-optional-locks rev-parse HEAD)
ZONA_CHISTAYA="_studio/zhurnal/_never-existing-zone-priyomka-fixture"

T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT

krasnet() {  # <описание> <arka-file...>
  OPIS="$1"; shift
  if python3 "$P" "$@" >/dev/null 2>&1; then
    echo "❌ ЛОВУШКА НЕ СРАБОТАЛА: $OPIS — приёмка приняла кривой вход"
    exit 1
  fi
  echo "  ✅ $OPIS — покраснело"
}

# ── общий шаблон здорового отчёта: КОММИТ существует, АРТЕФАКТ заполнен и
# свежее источника, секции ОТЧЁТ/ПЛАН/ВОПРОСЫ/УРОКИ ФАБРИКЕ заполнены, урок
# несёт ЦЕНА:. ─────────────────────────────────────────────────────────────
sobrat_zdorovyj() {  # <папка> <имя файла-захода>
  ARKA="$1"; IMYA="$2"
  mkdir -p "$ARKA"
  cat > "$ARKA/$IMYA" <<MD
## КОНТРАКТ ЗОНЫ (обязателен — не удалять)
- ЗОНА (можно менять): \`fixtures/priyomka/dummy.py\`

## ПЛАН — (заполняет исполнитель)
Собрать инструмент X, прогнать на фикстуре Y, отчитаться.

## ВОПРОСЫ — (заполняет исполнитель)
1. Нужен ли этому гейту порог эскалации из предупреждения в ошибку?

## УРОКИ ФАБРИКЕ — (заполняет исполнитель)
### Гейт оказался хрупким на кривом входе
ЦЕНА: чинили дважды, час потерян на живом прогоне.

## ОТЧЁТ — (заполняет исполнитель)
Сделано: собран инструмент X, прогнан на живом файле, числа воспроизведены.
**АРТЕФАКТ:** \`$ARKA/artefakt.txt\` — открывать текстом
**КОММИТ:** \`$HASH\` — тестовый коммит фикстуры · git_zona.py check --zone $ZONA_CHISTAYA → ✅
MD
  echo "содержимое артефакта" > "$ARKA/artefakt.txt"
}

echo "── ловушка 1: АРТЕФАКТ — плейсхолдер в угловых скобках (Г2)"
# 🔴 Не просто «упало» — проверяем, что упало ИМЕННО Г2, а не Г3 случайно
# (несуществующий путь-плейсхолдер тоже не найдётся на диске, и Г3 замаскирует
# дыру в Г2, если её мутацией сломать: слепой exit-код тут недостаточен).
sobrat_zdorovyj "$T/a1" "kod_test.md"
python3 -c "
import re
p = '$T/a1/kod_test.md'
t = open(p, encoding='utf-8').read()
t = re.sub(r'\*\*АРТЕФАКТ:\*\* \`.*\` —', '**АРТЕФАКТ:** \`<АБСОЛЮТНЫЙ путь к собранному файлу>\` —', t)
open(p, 'w', encoding='utf-8').write(t)
"
# Перезапись .md И ПОЭТОМУ ДВИГАЕТ ЕГО mtime ВПЕРЁД — без этого
# touch артефакт мог бы оказаться «старше источника» и Г3 замаскировал бы
# именно то расхождение, которое проверяет эта ловушка (Г2).
touch "$T/a1/artefakt.txt"
OUT1=$(python3 "$P" "$T/a1/kod_test.md" 2>&1) && {
  echo "❌ ЛОВУШКА 1: АРТЕФАКТ-плейсхолдер дал exit 0"; exit 1; }
echo "$OUT1" | grep -q "❌ Г2 .*плейсхолдер" || {
  echo "❌ ЛОВУШКА 1: красное есть, но НЕ от Г2 (плейсхолдер не пойман по имени). Вывод:"
  echo "$OUT1"; exit 1; }
echo "  ✅ ловушка 1: Г2 поимённо поймал плейсхолдер в АРТЕФАКТ"

echo "── ловушка 2: артефакт СТАРШЕ источника (Г3)"
sobrat_zdorovyj "$T/a2" "kod_test.md"
# `sobrat_zdorovyj` кладёт artefakt.txt ПОСЛЕ .md (то есть заведомо не старше
# источника) — чтобы получить обратный случай, откатываем mtime артефакта
# далеко в прошлое, не трогая остальное.
touch -t 202001010000 "$T/a2/artefakt.txt"
krasnet "артефакт старше источника" "$T/a2/kod_test.md"

echo "── ловушка 3: хэш коммита, которого нет в репозитории (Г1)"
sobrat_zdorovyj "$T/a3" "kod_test.md"
python3 -c "
import re
p = '$T/a3/kod_test.md'
t = open(p, encoding='utf-8').read()
t = re.sub(r'\*\*КОММИТ:\*\* \`[0-9a-f]*\`', '**КОММИТ:** \`0000000000000000000000000000000000000000\`', t)
open(p, 'w', encoding='utf-8').write(t)
"
touch "$T/a3/artefakt.txt"   # см. комментарий у ловушки 1 — sed двигает mtime .md
OUT3=$(python3 "$P" "$T/a3/kod_test.md" 2>&1) && {
  echo "❌ ЛОВУШКА 3: хэш коммита не в репозитории дал exit 0"; exit 1; }
echo "$OUT3" | grep -q "❌ Г1 .*не найден в репозитории" || {
  echo "❌ ЛОВУШКА 3: красное есть, но НЕ от Г1 поимённо. Вывод:"; echo "$OUT3"; exit 1; }
echo "  ✅ ловушка 3: Г1 поимённо поймал хэш, которого нет в репозитории"

echo "── ловушка 4: урок без ЦЕНА: (Г5)"
sobrat_zdorovyj "$T/a4" "kod_test.md"
python3 -c "
p = '$T/a4/kod_test.md'
t = open(p, encoding='utf-8').read()
t = '\n'.join(l for l in t.split('\n') if not l.startswith('ЦЕНА:'))
open(p, 'w', encoding='utf-8').write(t)
"
touch "$T/a4/artefakt.txt"   # см. комментарий у ловушки 1
OUT4=$(python3 "$P" "$T/a4/kod_test.md" 2>&1) && {
  echo "❌ ЛОВУШКА 4: урок без ЦЕНА: дал exit 0"; exit 1; }
echo "$OUT4" | grep -q "❌ Г5 .*без \`ЦЕНА:\`" || {
  echo "❌ ЛОВУШКА 4: красное есть, но НЕ от Г5 поимённо. Вывод:"; echo "$OUT4"; exit 1; }
echo "  ✅ ловушка 4: Г5 поимённо поймал урок без ЦЕНА:"

echo "── ловушка 5: 🔴 «Урок фабрике» с ЗАГЛАВНОЙ в дневнике (Г6)"
# ЧТО ЛОМАЕТСЯ: та же болезнь, что канон описывает дословно — форма грепа
# `"урок фабрике\|УРОК ФАБРИКЕ"` не ловит «Урок фабрике» (заглавная «У» при
# строчном «фабрике»), и гейт даёт ЛОЖНОЕ ЗЕЛЁНОЕ, при том что урок с ценой
# остался ненайденным домом уроков. `priyomka.py` обязан ловить это терпимой
# формой `урок` регистронезависимо по одному слову.
sobrat_zdorovyj "$T/a5" "kod_test.md"
printf '%s\n' '# СЕССИЯ' 'Урок фабрике: гейт про склейку не работал неделю.' > "$T/a5/SESSIYA.md"
# UROKI-FABRIKE.md намеренно ОТСУТСТВУЕТ — паре взяться неоткуда.
OUT5=$(python3 "$P" "$T/a5/kod_test.md" 2>&1) && {
  echo "❌ ЛОВУШКА 5: урок без пары в доме уроков дал exit 0"; exit 1; }
echo "$OUT5" | grep -q "Урок фабрике: гейт про склейку" || {
  echo "❌ ЛОВУШКА 5: упоминание «Урок фабрике» (с заглавной) НЕ найдено в выводе. Вывод:"
  echo "$OUT5"; exit 1; }
echo "$OUT5" | grep -q "❌ Г6" || {
  echo "❌ ЛОВУШКА 5: Г6 не покраснел при уроке без дома. Вывод:"; echo "$OUT5"; exit 1; }
echo "  ✅ ловушка 5: «Урок фабрике» с заглавной найден регистронезависимо, Г6 покраснел"

echo "── ловушка 6: ВОПРОСЫ печатаются ДАЖЕ при полностью зелёном прогоне"
sobrat_zdorovyj "$T/a6" "kod_test.md"
OUT6=$(python3 "$P" "$T/a6/kod_test.md" 2>&1) || {
  echo "❌ ЛОВУШКА 6/7: здоровый отчёт дал ненулевой код. Вывод:"; echo "$OUT6"; exit 1; }
echo "$OUT6" | grep -q "Нужен ли этому гейту порог эскалации" || {
  echo "❌ ЛОВУШКА 6: ВОПРОСЫ исполнителя не напечатаны при зелёном прогоне. Вывод:"
  echo "$OUT6"; exit 1; }
echo "  ✅ ловушка 6: вопросы исполнителя напечатаны, хотя все гейты зелёные"

echo "── ловушка 7: положительный контроль — здоровый отчёт → exit 0 + печать для рук"
echo "$OUT6" | grep -q "✅ ПРИЁМКА" || {
  echo "❌ ЛОВУШКА 7: нет положительного вердикта приёмки. Вывод:"; echo "$OUT6"; exit 1; }
echo "$OUT6" | grep -q "ПЕЧАТЬ ДЛЯ РУК" || {
  echo "❌ ЛОВУШКА 7: блока печати для рук нет. Вывод:"; echo "$OUT6"; exit 1; }
echo "$OUT6" | grep -q "Чек-лист оставшихся шагов канона" || {
  echo "❌ ЛОВУШКА 7: чек-лист оставшихся шагов канона не напечатан. Вывод:"; echo "$OUT6"; exit 1; }
echo "  ✅ ловушка 7: здоровый отчёт — exit 0, печать для рук на месте"

echo "── ловушка 8: пустая ## ПЛАН при заполненном остальном (Г4)"
# 🔴 Стираем ИМЕННО тело `## ПЛАН`, оставляя `## ОТЧЁТ` (а с ним КОММИТ и
# АРТЕФАКТ) нетронутым — иначе пустой ОТЧЁТ снёс бы заодно Г1/Г2, и ловушка
# перестала бы изолированно проверять именно Г4.
sobrat_zdorovyj "$T/a8" "kod_test.md"
python3 -c "
import re
p = '$T/a8/kod_test.md'
t = open(p, encoding='utf-8').read()
t = re.sub(r'(^## ПЛАН[^\n]*\n)(.*?)(?=^## )', r'\1', t, flags=re.M | re.S)
open(p, 'w', encoding='utf-8').write(t)
"
touch "$T/a8/artefakt.txt"   # см. комментарий у ловушки 1 — переписывание .md двигает mtime
OUT8=$(python3 "$P" "$T/a8/kod_test.md" 2>&1) && {
  echo "❌ ЛОВУШКА 8: пустая ПЛАН дала exit 0"; exit 1; }
echo "$OUT8" | grep -q "❌ Г4 .*ПЛАН пуста" || {
  echo "❌ ЛОВУШКА 8: красное есть, но Г4 не назвал пустую ПЛАН поимённо. Вывод:"
  echo "$OUT8"; exit 1; }
echo "$OUT8" | grep -q "❌ Г1\|❌ Г2\|❌ Г3" && {
  echo "❌ ЛОВУШКА 8: другой гейт тоже покраснел — ловушка перестала изолировать Г4. Вывод:"
  echo "$OUT8"; exit 1; }
echo "  ✅ ловушка 8: Г4 поимённо поймал пустую ПЛАН, Г1/Г2 остались зелёными"

echo "── ловушка 9: 🔴 Ф1/часть B — пункт очереди «доставлен», а метки по адресу нет (Г7)"
sobrat_zdorovyj "$T/a9" "kod_test.md"
echo "не найдёт себе метку" > "$T/a9/dom.txt"
python3 -c "
p = '$T/a9/kod_test.md'
t = open(p, encoding='utf-8').read()
t = t.replace('## ВОПРОСЫ — (заполняет исполнитель)\n1. Нужен ли этому гейту порог эскалации из предупреждения в ошибку?',
              '## ВОПРОСЫ — (заполняет исполнитель)\n1. Нужен ли этому гейту порог эскалации из предупреждения в ошибку?\n'
              '2. Термин из разведки принадлежит глоссарию курса\n'
              '   ДОМ: $T/a9/dom.txt\n'
              '   ДОСТАВЛЕНО: kod_test#2')
open(p, 'w', encoding='utf-8').write(t)
"
touch "$T/a9/artefakt.txt"   # см. комментарий у ловушки 1 — переписывание .md двигает mtime
OUT9=$(python3 "$P" "$T/a9/kod_test.md" 2>&1) && {
  echo "❌ ЛОВУШКА 9: ложная доставка (Г7) дала exit 0"; exit 1; }
echo "$OUT9" | grep -q "❌ Г7 .*помечен доставленным.*дом.*не найден\|❌ Г7 .*помечен доставленным.*метки.*нет" || {
  echo "❌ ЛОВУШКА 9: красное есть, но НЕ от Г7 поимённо. Вывод:"; echo "$OUT9"; exit 1; }
echo "  ✅ ловушка 9: Г7 поимённо поймал пункт очереди без метки по адресу"

echo "── ловушка 10: Ф1/часть B — недоставленный пункт очереди печатается, но НЕ красный"
sobrat_zdorovyj "$T/a10" "kod_test.md"
python3 -c "
p = '$T/a10/kod_test.md'
t = open(p, encoding='utf-8').read()
t = t.replace('## ВОПРОСЫ — (заполняет исполнитель)\n1. Нужен ли этому гейту порог эскалации из предупреждения в ошибку?',
              '## ВОПРОСЫ — (заполняет исполнитель)\n1. Нужен ли этому гейту порог эскалации из предупреждения в ошибку?\n'
              '2. Источник найден, но не влит в манифест\n'
