#!/bin/sh
# TOOL-CONTRACT-COVERS: schet_nezakrytogo.py
#
# Фикстура «кривого входа» для schet_nezakrytogo.py (Ш4, заход
# `instrument-podklyuchen`, 2026-08-08). Инструмент только ФИЛЬТРУЕТ строкой —
# у него нет формата, который можно сломать, но `check_tool_contract.py`
# требует ДОКАЗАТЕЛЬСТВА, а не обещания: без вызова аргумент-разбора никто не
# проверял, что ОБЛАСТЬ-мусор не роняет инструмент трейсбеком.
#
# Запуск: sh _generator/tools/fixtures/nezakrytogo/PROGNAT.sh
# Ожидание: exit 0.

set -u
TOOLS="$(cd "$(dirname "$0")/../.." && pwd)"
GATE="$TOOLS/schet_nezakrytogo.py"
OK=0

# 1. Без аргумента — сегодняшнее (глобальное) поведение, обязано остаться.
OUT1=$(python3 "$GATE" 2>&1); RC1=$?
if [ "$RC1" = "0" ] && echo "$OUT1" | grep -q "СЧЁТ НЕЗАКРЫТОГО"; then
    echo "  ✓ без области: rc=0, заголовок на месте"
else
    echo "  ✗ без области: rc=$RC1 или сломан вывод"
    echo "$OUT1"
    OK=1
fi

# 2. Область-мусор (заведомо ничего не матчит) — НЕ трейсбек, а честный ноль
#    по пунктам 1/3/4, и пункт 2 (долги) остаётся тем же числом, что и без
#    области — область НЕ должна тихо просочиться в глобальную метрику.
OUT2=$(python3 "$GATE" "оч-е-нь-редкая-строка-которой-нигде-нет-XYZ" 2>&1); RC2=$?
if [ "$RC2" != "0" ]; then
    echo "  ✗ область-мусор: rc=$RC2 (ожидался 0 — фильтр не крашится)"
    echo "$OUT2"
    OK=1
elif echo "$OUT2" | grep -q "Traceback"; then
    echo "  ✗ область-мусор: трейсбек вместо честного нуля"
    echo "$OUT2"
    OK=1
else
    D1=$(echo "$OUT1" | grep "долгов СТАТУС" | grep -oE '[0-9]+$')
    D2=$(echo "$OUT2" | grep "долгов СТАТУС" | grep -oE '[0-9]+$')
    U2=$(echo "$OUT2" | grep "уроков фабрике" | grep -oE '[0-9]+$')
    if [ "$D1" = "$D2" ] && [ "$U2" = "0" ]; then
        echo "  ✓ область-мусор: rc=0, долги (2) не сузились ($D2 = $D1), уроки (3) = 0"
    else
        echo "  ✗ область-мусор: долги разъехались ($D1 vs $D2) или уроки не обнулились ($U2)"
        OK=1
    fi
fi

# 3. Область непустая, но структурно ОСМЫСЛЕННАЯ (подстрока пути реестра) —
#    подмножество обязано быть НЕ БОЛЬШЕ общего (критерий Ш4: «печатает
#    подмножество, меньшее общего»), а не случайно бо́льшим при опечатке.
OUT3=$(python3 "$GATE" "2026-08-07_arhitektura-slajdov" 2>&1); RC3=$?
if [ "$RC3" = "0" ]; then
    U0=$(echo "$OUT1" | grep "уроков фабрике" | grep -oE '[0-9]+$')
    U3=$(echo "$OUT3" | grep "уроков фабрике" | grep -oE '[0-9]+$')
    Q0=$(echo "$OUT1" | grep "пунктов очереди" | grep -oE '[0-9]+$')
    Q3=$(echo "$OUT3" | grep "пунктов очереди" | grep -oE '[0-9]+$')
    if [ "$U3" -le "$U0" ] && [ "$Q3" -le "$Q0" ]; then
        echo "  ✓ область «эта арка»: подмножество не больше общего (уроки $U3≤$U0, очередь $Q3≤$Q0)"
    else
        echo "  ✗ область «эта арка»: подмножество БОЛЬШЕ общего — фильтр сломан"
        OK=1
    fi
else
    echo "  ✗ область «эта арка»: rc=$RC3, ожидался 0"
    echo "$OUT3"
    OK=1
fi

echo
[ "$OK" = 0 ] && echo "ФИКСТУРЫ ЗЕЛЁНЫЕ" || echo "ФИКСТУРЫ КРАСНЫЕ"
exit "$OK"
