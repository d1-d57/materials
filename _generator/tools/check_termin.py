#!/usr/bin/env python3
"""ГЕЙТ ПОРЯДКА ВВЕДЕНИЯ: термин не употребляется раньше, чем определён.

    python3 _generator/tools/check_termin.py <src-dir-или-файл>
    python3 _generator/tools/check_termin.py <путь> --tiho     # только код возврата

Код возврата: 0 — чисто, 1 — есть нарушения. Годится в ворота.

ЗАЧЕМ (правило 11 в `_studio/docs/kak-delat/STANDART-teksta.md`).
Правило 3 «необъяснённых понятий нет» держится ровно до тех пор, пока автор
пишет линейно. Стоит переставить куски — и определение уезжает НИЖЕ теоремы,
которая этим словом пользуется. Глазами это не ловится: автор-то знает, что
определение в тексте ЕСТЬ, и проверка «есть ли определение» проходит зелёной.
Ломается не наличие, а ПОРЯДОК.

ЦЕНА (2026-07-30, обзор про Гудстейна, поймал владелец, гейты пропустили).
Теорема «о представлении» стояла ВЫШЕ определения ординала и им пользовалась;
над ней вдобавок было написано «вот что делает слово ординал осмысленным» —
про слово, которое ещё не определено. Вердикт владельца: «ты говоришь, вот что
делает слово ординал осмысленным, а ты это слово не определил. Так нельзя в
математическом тексте делать». Раздел переписан целиком вторым заходом; первый
круг правок (введение арифметики, класса Ord, канторовой формы) этой поломки
не увидел, потому что искал недостающие определения, а не их порядок.

ЧТО ИМЕННО ПРОВЕРЯЕТ. Для каждой врезки `**Определение N (термин).**` берётся
ключевое слово термина и ищется его первое вхождение в тексте. Если оно попало
ВНУТРЬ врезки с номером меньше N — красный. Прозаический текст между врезками
(введение, мотивировка, «о чём это») нарушением НЕ считается: там слово может
быть названо до определения, это законный приём «назвал, но не работает»
(STANDART-teksta §Э). Красным становится только рабочее употребление — то есть
внутри утверждения, определения или примера.
"""
import re
import sys
from pathlib import Path

VREZKA = re.compile(
    r"^\*\*(Определение|Теорема|Лемма|Предложение|Утверждение|Пример|Задача|Замечание)"
    r"\s+(\d+)\s*\(([^)]*)\)", re.M)

# слова, по которым искать бессмысленно: слишком общие либо служебные
STOP = {"это", "как", "что", "для", "при", "или", "все", "тот", "три", "два",
        "первые", "основные", "порядок", "форма", "запись", "шаг", "где", "why"}
MIN_LEN = 5          # ключ короче — не ищем, слишком шумно
KOREN = 7            # сколько букв берём под корень (грубая замена стеммингу)


def slova(termin):
    """Термин из скобок → значимые слова (без формул, авторов и годов)."""
    t = re.sub(r"\$[^$]*\$", " ", termin)          # формулы выкидываем
    t = t.split(";")[0].split(",")[0]              # «ординал; фон Нейман, 1923» → «ординал»
    return [w.lower() for w in re.findall(r"[А-Яа-яЁёA-Za-z]+", t)
            if len(w) >= MIN_LEN and w.lower() not in STOP]


def obrazec(termin):
    """Термин → регулярка ФРАЗЫ целиком, а не отдельного слова.

    Ищем «сопоставленный ординал» как словосочетание. Искать по одному слову
    нельзя: голова словосочетания («ординал») уже определена выше и законно
    встречается всюду — гейт зашумится и его начнут обходить."""
    ws = slova(termin)
    if not ws:
        return None
    return re.compile(r"\W+".join(re.escape(w[:KOREN]) + r"[А-Яа-яЁёA-Za-z]*" for w in ws))


def razobrat(text):
    """Текст → список врезок (номер, тип, термин, начало, конец).

    Врезка кончается на ПУСТОЙ СТРОКЕ, а не на следующей врезке: в этом диалекте
    типизированный блок пишется слитно, а между блоками идёт обычная проза —
    и она врезке не принадлежит. Если считать иначе, каждый заголовок раздела
    и каждый абзац-связка попадут «внутрь» предыдущего утверждения."""
    vr = []
    for m in VREZKA.finditer(text):
        konec = text.find("\n\n", m.start())
        vr.append({"num": int(m.group(2)), "tip": m.group(1), "termin": m.group(3),
                   "start": m.start(), "end": konec if konec != -1 else len(text)})
    return vr


def vnutri_kakoy(vr, poz):
    """В какой врезке лежит позиция; 0 — в прозе между врезками."""
    for v in vr:
        if v["start"] <= poz < v["end"]:
            return v["num"]
    return 0


def proverit_text(text, imya):
    vr = razobrat(text)
    bad = []
    odnoslovnye = set()                              # уже определённые односложные термины
    for v in sorted(vr, key=lambda x: x["num"]):
        if v["tip"] != "Определение":
            continue
        ws = slova(v["termin"])
        # «ординал $\varepsilon_0$» после снятия формулы схлопывается в «ординал»,
        # который определён выше. Это не новый термин, а его частный случай,
        # названный формулой, — проверять нечего.
        if len(ws) == 1 and ws[0][:KOREN] in odnoslovnye:
            continue
        if len(ws) == 1:
            odnoslovnye.add(ws[0][:KOREN])
        rx = obrazec(v["termin"])
        if rx is None:
            continue
        for m in rx.finditer(text.lower()):
            gde = vnutri_kakoy(vr, m.start())
            if gde and gde < v["num"]:
                stroka = text[:m.start()].count("\n") + 1
                bad.append((imya, stroka, v["num"], v["termin"], gde))
                break                                # по одному сигналу на термин
    return bad


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    tiho = "--tiho" in sys.argv
    if not args:
        print(__doc__.strip().splitlines()[0])
        sys.exit(2)
    p = Path(args[0])
    files = sorted(p.glob("*.md")) if p.is_dir() else [p]
    bad = []
    for f in files:
        bad += proverit_text(f.read_text(encoding="utf-8"), f.name)

    if not tiho:
        print("── ГЕЙТ ПОРЯДКА ВВЕДЕНИЯ (check_termin) ──")
    if bad:
        if not tiho:
            print("  ✗ КРАСНЫЙ — %d" % len(bad))
            for imya, stroka, num, termin, gde in bad:
                print("     %s:%d — «%s» (определение %d) работает раньше, "
                      "во врезке %d" % (imya, stroka, termin, num, gde))
            print("  Чинится ПЕРЕСТАНОВКОЙ: определение поднимается выше "
                  "первого рабочего употребления.")
        sys.exit(1)
    if not tiho:
        print("  ✓ ЗЕЛЁНЫЙ: ни один термин не работает раньше своего определения")
    sys.exit(0)


if __name__ == "__main__":
    main()
