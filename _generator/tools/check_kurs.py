"""Гейты КУРСА (не лекции) — курс «Теория категорий».

ЗАЧЕМ ЭТОТ ФАЙЛ (не удалять причину — она дороже кода).

Владелец прочитал Л4 вслух: «не понял, какой центральный объект, примеры,
применения». Все семь ЛЕКЦИОННЫХ гейтов на Л4 были зелёные. Диагноз владельца:
«все семь гейтов — по лекции. Ни один — по курсу». Идеально загейченная девятка
может быть неправильной девяткой.

Этот скрипт — попытка перенести машинерию отбора на КУРС ЦЕЛИКОМ из донора
`kurs leto 2026` (научпоп «может ли машина мыслить», где ворота набора развиты
сильно дальше нашего). Попунктный разбор, что переносится, — в
`_studio/zhurnal/2026-07-16_teorkat-programma-dizajn/VERDIKT-gejty-kursa.md`.
Здесь — только МЕХАНИЧЕСКИ проверяемые выжившие. Судящее (Г4-полный, квота-числа)
НЕ подделано под скрипт — см. секцию «ЧЕГО Я НЕ ПРОВЕРЯЮ» в выводе.

⚠ ГЛАВНЫЙ УРОК ЗАХОДА: гейт, построенный в лоб, врёт в ОБЕ стороны. Поэтому у
каждого гейта ниже в докстринге назван раздел «о чём соврёт», и набор
откалиброван так, чтобы красить РОВНО известно-слабые места (Л4 — нет объекта,
Л5 — нет якоря LCCC) и НЕ трогать те, что внешняя мерка зовёт сильными (Л6 —
`{izomorfizm}`-ядро, «самое сильное совпадение курса»). Красит сильную —
сигнал о ГЕЙТЕ, не о лекции.

Идиома репо (как `check_kartoteka.py`): stdlib, детерминизм, без исполнения
чужого кода, вывод таблицей. ЧИТАЕТ SPEKA.md + KARTA-OBLASTI.md, НИЧЕГО НЕ ПИШЕТ.

Запуск:
    python3 _generator/tools/check_kurs.py teoriya-kategoriy
    # мета-чек покрытия донора вердиктом (критерий 2.2.1 захода):
    python3 _generator/tools/check_kurs.py --audit-donor \\
        "kurs leto 2026/1-START-HERE/sistema-ocenki.md" \\
        _studio/zhurnal/2026-07-16_teorkat-programma-dizajn/VERDIKT-gejty-kursa.md
Код возврата: 0 — чисто, 1 — есть что показать (годится в ворота).
"""
import re
import sys
from pathlib import Path

# --- Якоря ТЗ (SPEKA §Темп/§Слой2, 🔒): концепт → замко́вая лекция → стемы id ---
# Стем 'omega' у топоса — ОСОЗНАННЫЙ алиас: топос вводится как Ω (omega-opredelenie),
# карточки с именем «topos» рода `понятие` нет. Без алиаса гейт ложно покрасил бы Л9.
ЯКОРЯ = [("CCC", "Л3", ("ccc",)),
         ("LCCC", "Л5", ("lccc",)),
         ("топос", "Л9", ("topos", "omega"))]

# --- G-D: токены «вердикт о ПРОЕКТЕ» (STANDART §5: утверждение=факт математики,
#     находка=факт о курсе/материале). Эвристика, флагует подозреваемых. ---
ТОКЕНЫ_ПОДЛОГА = ("вердикт", "следствие для л", "смет", "не сглаж")


def _текст(путь):
    return Path(путь).read_text(encoding="utf-8")


def карточки(корень):
    """KARTA-OBLASTI.md → {id: {род, суть, находка, статус, прибор}}.
    Режем СТРОГО по ```-границам (как check_kartoteka): иначе поля текут между
    карточками (известная ошибка — lazy-квантор прыгает в следующую)."""
    текст = _текст(Path(корень) / "kartoteka" / "KARTA-OBLASTI.md")
    out = {}
    for m in re.finditer(r"```\n(id: (\S+)\n(?:(?!```).*\n)*)```", текст):
        блок = m.group(1)
        поле = lambda f: (re.search(rf"^{f}: (.*)$", блок, re.M) or [None, ""])[1].strip()
        out[m.group(2)] = {
            "род": поле("род"),
            "суть": поле("суть"),
            "находка": поле("находка"),
            "статус": поле("статус"),
            "прибор": "проверено-на-приборе" in блок,
        }
    return out


def карта_лекций(корень):
    """SPEKA §Слой 2 → {'Л5': [ids]} — единственный дом связи лекция↔карточка."""
    текст = _текст(Path(корень) / "SPEKA.md")
    return {m.group(1): m.group(2).split()
            for m in re.finditer(r"^(Л[1-9]): (.+)$", текст, re.M)}


def _секция(текст, старт, стоп):
    m = re.search(старт + r"(.*?)(?=" + стоп + r")", текст, re.S)
    return m.group(1) if m else ""


def нити(корень):
    """KARTA-OBLASTI §Нити «НИТИ — сквозные» → {id: {тип, лекции:[...]}}."""
    текст = _текст(Path(корень) / "kartoteka" / "KARTA-OBLASTI.md")
    блок = _секция(текст, r"### НИТИ — сквозные", r"### РЁБРА|\Z")
    out = {}
    for m in re.finditer(r"\{([^}]+)\}[^|]*\|\s*тип:([^|]+)\|\s*лекции:\[([^\]]+)\]", блок):
        лекс = re.findall(r"Л[1-9]", m.group(3))
        out[m.group(1).strip()] = {"тип": m.group(2).strip(), "лекции": лекс}
    return out


def рёбра(корень):
    """KARTA-OBLASTI §Нити «РЁБРА — парные» → [(a, знак, b)] (~ ненапр., -> напр.)."""
    текст = _текст(Path(корень) / "kartoteka" / "KARTA-OBLASTI.md")
    блок = _секция(текст, r"### РЁБРА — парные", r"\n## |\n### 🔴|\Z")
    return [(m.group(1), m.group(2), m.group(3))
            for m in re.finditer(r"^-\s*(Л[1-9])\s*(~|->)\s*(Л[1-9])\s*\|", блок, re.M)]


ЛЕКЦИИ = [f"Л{n}" for n in range(1, 10)]


# ============================ ГЕЙТЫ КУРСА ============================

def g_a_yakorya(карты, карта):
    """G-A. Якоря ТЗ на их лекциях (тень A5/Н3/§3.4.1 «вписанность в имя-центр»).
    О ЧЁМ СОВРЁТ: ключит поверхностный стем; требует род=понятие (потому НЕ
    обманывается подлогом verdict-rifma-lccc — тот утверждение); НЕ проверяет,
    что концепт развёрнут. Л4/Л5 переписываются."""
    print("\n=== G-A. Якоря ТЗ (CCC→Л3 · LCCC→Л5 · топос→Л9) ===")
    провал = []
    for имя, лек, стемы in ЯКОРЯ:
        ids = карта.get(лек, [])
        нашёл = [i for i in ids if карты.get(i, {}).get("род") == "понятие"
                 and any(s in i.lower() for s in стемы)]
        ок = bool(нашёл)
        print(f"  {'✅' if ок else '❌'} {имя:6} в {лек}: "
              + (f"понятие {нашёл}" if ок else f"НЕТ карточки рода `понятие` под {стемы}"))
        if not ок:
            провал.append((имя, лек))
    return провал


def g_b_obekt(карты, карта):
    """G-B. Центральный объект: у каждой лекции ≥1 карточка рода `понятие`
    (механизируемая половина Г4; ровно жалоба владельца на Л4).
    О ЧЁМ СОВРЁТ: наличие ≠ содержательность; ловит ОБЪЕКТ, не примеры/применения
    (владелец назвал три); концепт как утверждение/пример дал бы ложный красный."""
    print("\n=== G-B. Центральный объект (≥1 карточка рода `понятие` у лекции) ===")
    провал = []
    for лек in ЛЕКЦИИ:
        pon = [i for i in карта.get(лек, []) if карты.get(i, {}).get("род") == "понятие"]
        ок = bool(pon)
        if not ок:
            провал.append(лек)
        print(f"  {'✅' if ок else '❌'} {лек}: понятий {len(pon)}"
              + ("" if ок else "  — ЦЕНТРАЛЬНОГО ОБЪЕКТА НЕТ"))
    return провал


def g_c_siroty(карта, нит):
    """G-C. Сироты нитей: каждая лекция в ≥1 нити; каждая нить ≥2 лекций; ID
    лекций в нитях резолвятся (несущее ядро Н4/§3.4.3 БЕЗ квот-чисел).
    О ЧЁМ СОВРЁТ: НЕ навязывает донорское «≥5 нитей/лекцию» (сознательно — это
    калибровка N=6 под 8 исторических типов, красит Л6-ядро). «На нити» ≠
    «центральна для неё»."""
    print("\n=== G-C. Сироты нитей / целостность графа нитей ===")
    порог = -(-9 * 7 // 10)  # ⌈0.7·N⌉, N=9 → 7 (правило масштабирования G2)
    беды = []
    # висячие ссылки на лекции в нитях
    for tid, t in нит.items():
        плохие = [l for l in t["лекции"] if l not in ЛЕКЦИИ]
        if плохие:
            беды.append(f"нить {{{tid}}}: несуществующие лекции {плохие}")
        if len(t["лекции"]) < 2:
            беды.append(f"нить {{{tid}}}: <2 лекций ({t['лекции']})")
    счёт = {лек: sum(1 for t in нит.values() if лек in t["лекции"]) for лек in ЛЕКЦИИ}
    сироты = [лек for лек, n in счёт.items() if n == 0]
    if сироты:
        беды.append(f"ЛЕКЦИИ-СИРОТЫ (0 нитей): {сироты}")
    сквозные = [tid for tid, t in нит.items() if len(t["лекции"]) >= порог]
    print(f"  Нитей: {len(нит)} · типы: {sorted({t['тип'] for t in нит.values()})} "
          f"({len({t['тип'] for t in нит.values()})} — донор просит ≥4)")
    print(f"  Нитей на лекцию: " + " · ".join(f"{l}={счёт[l]}" for l in ЛЕКЦИИ))
    print(f"  Сквозные (≥{порог} из 9, правило G2): {сквозные or 'НЕТ'}  "
          f"[справочно; «≥5/лекцию» и «≥3 сквозных» НЕ импортированы — см. докстринг]")
    if беды:
        for b in беды:
            print(f"  ❌ {b}")
    else:
        print("  ✅ сирот нет, все нити ≥2 лекций, все ID резолвятся")
    return беды


def g_d_podlog(карты, карта):
    """G-D. Род-подлог: карточки рода `утверждение`, читающиеся как вердикт о
    ПРОЕКТЕ (STANDART §5). Тень ловушки 2/случай 1 (ложно-зелёный «≥1 утверждение»).
    О ЧЁМ СОВРЁТ: ЭВРИСТИКА — может флагнуть реальное мат-утверждение, случайно
    сославшееся на лекцию, и пропустить тонко-подложную карточку без токена.
    Флагует ПОДОЗРЕВАЕМЫХ на ручное подтверждение, НЕ доказывает подлог."""
    print("\n=== G-D. Род-подлог: `утверждение`, читающееся как вердикт о проекте ===")
    где = {i: [l for l, ids in карта.items() if i in ids] for i in карты}
    флаг = []
    for i, c in карты.items():
        if c["род"] != "утверждение":
            continue
        текст = (c["суть"] + " " + c["находка"]).lower()
        токены = [t for t in ТОКЕНЫ_ПОДЛОГА if t in текст]
        if токены:
            флаг.append((i, где.get(i, []), токены))
    if not флаг:
        print("  ✅ подозреваемых нет")
    for i, лекс, ток in флаг:
        print(f"  ⚠ {i}  [лекции {лекс or '—'}]  токены {ток}")
        print(f"      суть: «{карты[i]['суть'][:90]}»")
    if флаг:
        print("  ⇒ ПОДОЗРЕВАЕМЫЕ, не приговор: род сверяет человек по STANDART §5.\n"
              "    Механическое следствие: гейт «у лекции ≥1 утверждение» на этих\n"
              "    лекциях ложно-зелёный (утверждение — вердикт о курсе, не о математике).")
    return флаг


def g_e_svyaznost(карта, нит, ребра):
    """G-E. Связность-отчёт — ДИАГНОСТИКА, НЕ пасс/фейл.
    О ЧЁМ СОВРЁТ (если читать как вердикт): низкая входящая степень ≠ дефект —
    рёбра суть КУРИРОВАННЫЕ находки, не полный граф; «получает/отдаёт» как гейт
    ложно покрасил бы Л3 (плотнейшую, щедрейшую) и Л8. Потому диагностика."""
    print("\n=== G-E. Связность (ДИАГНОСТИКА, не гейт) ===")
    нитей = {лек: sum(1 for t in нит.values() if лек in t["лекции"]) for лек in ЛЕКЦИИ}
    вх = {лек: 0 for лек in ЛЕКЦИИ}
    исх = {лек: 0 for лек in ЛЕКЦИИ}
    for a, знак, b in ребра:
        исх[a] += 1
        вх[b] += 1
        if знак == "~":
            исх[b] += 1
            вх[a] += 1
    print(f"  {'ЛЕК':4} {'нитей':>6} {'вх':>4} {'исх':>4}")
    for лек in ЛЕКЦИИ:
        print(f"  {лек:4} {нитей[лек]:>6} {вх[лек]:>4} {исх[лек]:>4}")
    слаб = min(ЛЕКЦИИ, key=lambda l: (нитей[l], вх[l] + исх[l]))
    связн = max(ЛЕКЦИИ, key=lambda l: вх[l] + исх[l])
    print(f"  ⇒ слабейшая: {слаб} · связнейшая: {связн}  "
          f"(рёбер всего {len(ребра)}; курированные находки, не полный граф)")


def проверить(корень):
    карты = карточки(корень)
    карта = карта_лекций(корень)
    нит = нити(корень)
    ребра = рёбра(корень)

    print(f"=== Гейты КУРСА: {корень} ===")
    print(f"Карточек: {len(карты)} · лекций в карте: {len(карта)} · "
          f"нитей: {len(нит)} · рёбер: {len(ребра)}")
    if not карта:
        print("❌ Не нашёл карту `Лn: id id` в SPEKA §Слой 2. Формат сломан?")
        return 1

    a = g_a_yakorya(карты, карта)
    b = g_b_obekt(карты, карта)
    c = g_c_siroty(карта, нит)
    d = g_d_podlog(карты, карта)
    g_e_svyaznost(карта, нит, ребра)

    print("\n=== ИТОГ (гейты курса; лекционные — в check_kartoteka/sostoyanie) ===")
    print(f"  G-A якоря:          {'❌ ' + str([f'{n}/{l}' for n, l in a]) if a else '✅'}")
    print(f"  G-B центр.объект:   {'❌ ' + str(b) if b else '✅'}")
    print(f"  G-C сироты нитей:   {'❌ ' + str(len(c)) + ' бед' if c else '✅'}")
    print(f"  G-D род-подлог:     {'⚠ ' + str([i for i, _, _ in d]) if d else '✅'}")

    print("\n=== ⚠ ЧЕГО Я НЕ ПРОВЕРЯЮ (судящее — держат аналитик и прибор) ===")
    print("  · Г4-полный — одна 2-мин ось, тест пересказом. Механизируема лишь\n"
          "    ПОЛОВИНА (G-B: есть ли центральный объект).")
    print("  · Квота-числа §3.4.3 (≥5 нитей/лекцию · ≥3 сквозных · ≥10 парных) — НЕ\n"
          "    импортированы: калибровка антологии N=6 под ИСТОРИЧЕСКИЕ типы нитей;\n"
          "    красят Л6 (`{izomorfizm}`-ядро, «самое сильное совпадение») и Л9-финал.")
    print("  · §5.2 РЕАЛЬНОСТЬ связей нитей — судит изолированный верификатор (иная\n"
          "    модель), не скрипт (см. VERDIKT §Верификатор).")
    print("  · Лекционные гейты 3/4/5 (замкнутый сюжет · зал изобретает · 40-я мин) —\n"
          "    суждение; честно объявлены в check_kartoteka.py / sostoyanie_lekcii.py.")
    print("  · Содержательность (объект развёрнут? ось сильна? удивление настоящее?) —\n"
          "    прибор (владелец-лектор). Зелёный гейт ≠ хорошая лекция.")

    краснит = bool(a or b or c or d)
    print(f"\n  Что покраснело — то покраснело; курс НЕ чиню (заход: чинит владелец).")
    return 1 if краснит else 0


# ======================= МЕТА: покрытие донора =======================

def audit_donor(путь_донор, путь_вердикт):
    """Критерий 2.2.1: сколько пунктов донора разобрано в VERDIKT. M считается
    ПРОГРАММНО: кодовые — регекспом из донора, секционные — объявленный реестр.
    Кросс-чек НЕ циклический: ищем каждый ожидаемый ID в вердикте по `бэктикам`."""
    донор = _текст(путь_донор)
    вердикт = _текст(путь_вердикт)

    кодовые = set()
    for pat in (r"Г(?:1[01]|[1-9])", r"К(?:1[01]|[1-9])", r"Н[1-4]",
                r"Н-[αβγδεζη]", r"A[1-6]", r"B[1-6]", r"G[1-7]"):
        кодовые |= set(re.findall(r"\b" + pat + r"\b", донор))
    # у греческих Н- нет \b перед α — добираем отдельно
    кодовые |= set(re.findall(r"Н-[αβγδεζη]", донор))

    реестр = (["движок-квиз", "движок-обыденное", "движок-двойная", "движок-DF",
               "§2.4-анатомия", "§2.4-вертикаль"]
              + [f"§2.5.{i}" for i in range(0, 11)]
              + ["§3.3"] + [f"§3.4.{i}" for i in range(1, 6)]
              + ["§3.5", "§5.2", "§6.1", "§6.2", "§6.3"])

    ожид = sorted(кодовые) + реестр
    непокрыто = [i for i in ожид if f"`{i}`" not in вердикт]
    N = len(ожид) - len(непокрыто)
    M = len(ожид)

    print(f"=== Покрытие донора вердиктом (критерий 2.2.1) ===")
    print(f"Донор:   {путь_донор}")
    print(f"Вердикт: {путь_вердикт}")
    print(f"Кодовых пунктов (регексп из донора): {len(кодовые)}")
    print(f"Секционных (объявленный реестр):     {len(реестр)}")
    print(f"M (всего пунктов):                   {M}")
    print(f"N (разобрано в вердикте):            {N}")
    print(f"\n>>> РАЗОБРАНО {N} ПУНКТОВ ИЗ {M} <<<")
    if непокрыто:
        print(f"❌ НЕ ПОКРЫТО ({len(непокрыто)}): {непокрыто}")
    else:
        print("✅ покрыты все пункты донора")
    return 1 if непокрыто else 0


if __name__ == "__main__":
    argv = sys.argv[1:]
    if argv and argv[0] == "--audit-donor":
        if len(argv) != 3:
            sys.exit("--audit-donor требует <донор> <вердикт>")
        sys.exit(audit_donor(argv[1], argv[2]))
    if len(argv) != 1:
        sys.exit(__doc__)
    sys.exit(проверить(argv[0]))
