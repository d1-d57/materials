def набор_индекса(текст):
    """id, перечисленные в «## Индекс по роду» — единственном месте регистрации."""
    m = re.search(r"^## Индекс по роду$(.*?)^## ", текст, re.M | re.S)
    return set(re.findall(r"`([^`]+)`", m.group(1))) if m else set()


def номера_карточек(текст):
    """[(id, номер строки)] — для сообщений с адресом, а не «где-то в файле»."""
    return [(m.group(1), текст[:m.start()].count("\n") + 1)
            for m in re.finditer(r"^id: (\S+)$", текст, re.M)]


