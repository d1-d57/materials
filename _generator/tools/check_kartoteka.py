def staged_md():
    """Пути .md из индекса коммита. Пусто — не в git-контексте, это не ошибка.

    🔴 `-z` ОБЯЗАТЕЛЕН, а не аккуратность. При дефолтном `core.quotePath=true`
    git отдаёт не-ASCII путь в C-экранировке —
    `"_studio/…/\\320\\227\\320\\220\\320\\245\\320\\236\\320\\224-x.md"`, —
    и он не оканчивается на `.md`, то есть ВЫПАДАЕТ из всех пяти ворот. В
    `_studio/` такие файлы есть прямо сейчас (`_SHTAB-…/zahody/ЗАХОД-*.md`):
    полный прогон `--gates` их видел, хук — никогда. `-z` отдаёт сырые байты
    через NUL, экранирования нет вовсе. (`git_zona.py` квотинг уже декодировал —
    значит это было упущение, а не решение.)

    🔴 `R` в фильтре — по той же причине. `git mv` даёт статус `R100`, и при
    `ACM` переименованный документ невидим: новое имя без строки в §6 уезжало
    в коммит зелёным, а старая строка §6 начинала указывать на пустоту.
    Соседний `check_tool_contract.staged_paths()` фильтрует `ACMR` — расхождение
    было внутри одной кодовой базы. При `--name-only` переименование отдаёт
    ровно НОВЫЙ путь, что и требуется (проверено на живом git).
    """
    try:
        out = subprocess.run(
            ["git", "--no-optional-locks", "diff", "--cached", "--name-only",
             "-z", "--diff-filter=ACMR"],
            cwd=REPO, capture_output=True, text=True, check=True).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    return [l for l in out.split("\0") if l.endswith(".md")]


def файлы(staged=None):
    """Какие .md судим: весь курс+фабрика, либо только staged-пути (режим хука)."""
    if staged is not None:
        пути = [p for p in staged if p.split("/")[0] in КОРНИ]
    else:
        пути = []
        for корень in КОРНИ:
            пути += [str(p.relative_to(REPO)) for p in sorted((REPO / корень).rglob("*.md"))]
    return [p for p in пути if not any(x in "/" + p for x in НЕ_СУДИМ)
            and (REPO / p).is_file()]


def карточные_блоки(текст):
    """[(id, номер строки)] — блоки, у которых есть И `id:`, И `род:`.

    Требование `род:` — не придирка: без него сюда попадали бы блоки `id: L1`
    из `KARTA-LEKCIY.md` (карта лекций, законный дом другой сущности).
    """
    out = []
    for m in re.finditer(r"```\n(id: (\S+)\n(?:(?!```).*\n)*)```", текст):
        if re.search(r"^род: \S", m.group(1), re.M):
            out.append((m.group(2), текст[:m.start()].count("\n") + 2))
    return out


def похоже_на_id(x):
    """Форма slug'а картотеки: латиница со строчным дефисом, от 6 знаков.

    Порог намеренно грубый и он ОТСЕИВАЕТ, а не ловит: `A1`, `G7`, `git` — не id,
    и без порога они дают ложную тревогу из колонок с теми же именами. Короткие
    настоящие id (`chl`, `nno`) от этого не страдают: они В картотеке, значит
    резолвятся и без проверки. Цена ошибки здесь несимметрична (урок №3).
    """
    return bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{5,}", x)) and "-" in x


def ссылки_на_id(текст):
    """[(id, строка)] из ИМЕНОВАННЫХ мест — полей и колонок, а не из всего текста."""
    out = []
    колонки = []
    for n, line in enumerate(текст.splitlines(), 1):
        m = re.match(r"^(\w[\w -]*): (.+)$", line)
        if m and m.group(1).strip().lower() in ПОЛЯ_ID:
            for x in re.split(r"[,·]", m.group(2)):
                x = x.strip().strip("`")
                if похоже_на_id(x):
                    out.append((x, n))
            continue
        if not line.startswith("|"):
            колонки = []
            continue
        ячейки = [c.strip() for c in line.strip().strip("|").split("|")]
        if all(re.fullmatch(r":?-{2,}:?", c) for c in ячейки) and ячейки:
            continue                                   # разделитель шапки
        if not колонки:                                # это шапка таблицы
            колонки = [i for i, c in enumerate(ячейки)
                       if c.strip("* `").lower() in КОЛОНКИ_ID]
            continue
        for i in колонки:
            if i < len(ячейки):
                for x in re.findall(r"`([^`]+)`", ячейки[i]):
                    if похоже_на_id(x):
                        out.append((x, n))
    return out


def _норм(s):
    """Имя секции без оформления: эмодзи и знаки спереди, регистр, пробелы.

    Заголовки живут как `### 🎯 КАЛИБРОВКА УРОВНЯ — рабочий прибор`, а ссылки —
    как `SPEKA §Калибровка` и `§Возврат≠узнавание`. Сравнивать надо суть.
    """
    s = re.sub(r"^[^\wА-Яа-яЁё]+", "", s.strip().strip("*")).lower()
    return re.sub(r"\s+", "", s.rstrip(".,"))


def секции_рамы(путь):
    """Нормализованные имена секций файла рамы — заголовок и его «голова» до тире."""
    имена = set()
    for h in re.findall(r"^#{1,4} +(.+)$", Path(путь).read_text(encoding="utf-8"), re.M):
        for вариант in (h, h.split("—")[0], re.sub(r"^\s*(\d+)\..*", r"\1", h)):
            if _норм(вариант):
                имена.add(_норм(вариант))
    return имена


def рамы_для(путь):
    """Какие файлы рамки видит этот документ: сначала СВОЙ проект, потом соседний."""
    свой = путь.split("/")[0]
    корни = ([свой] if свой in КОРНИ_РАМЫ else []) + list(КОРНИ_РАМЫ)
    out = {}
    for имя in ФАЙЛЫ_РАМЫ:
        out[имя] = [f"{k}/{имя}.md" for k in dict.fromkeys(корни)
                    if (REPO / f"{k}/{имя}.md").exists()]
    return out


def ссылки_на_ramu(текст):
    """[(файл, имя, строка)] — `SPEKA §Калибровка`, `DUH §3`, `KOTYOL §…`."""
    out = []
    for n, line in enumerate(текст.splitlines(), 1):
        for m in re.finditer(r"\b(SPEKA|DUH|KOTYOL)(?:\.md)?[`\s]*§ ?([^`\n]{1,60})", line):
            # `/` и `+` рвут ссылку так же, как запятая: `§Темп/§Калибровка/§Охват`
            # и `§Визуал + wikipedia` — это перечисления, а не имена секций.
            хвост = re.split(r"[`»,;:)\]*\n/+]|\s—\s", m.group(2))[0].strip()
            слова = хвост.split()
            if not слова or not слова[0][0].isalnum():
                continue                               # `SPEKA §…` — плейсхолдер, не ссылка
            out.append((m.group(1), слова[:3], n))
    return out


def вырезать_раздел_6(текст):
    """Текст `§6` из УЖЕ ПРОЧИТАННОГО `KARTA.md` — от `## §6.` до следующей `## §N`.

    Отделено от чтения файла нарочно: ту же границу обязана видеть дверь
    регистрации (`register_doc.py`), а она правит файл, который ещё не на диске
    в финальном виде. Две реализации одной границы разъехались бы молча.
    """
    m = re.search(r"^## §6\..*?(?=^## §\d)", текст, re.M | re.S)
    return m.group(0) if m else ""


def зарегистрирован(p, раздел):
    """Считают ли ворота 5 путь `p` зарегистрированным в тексте `раздел`.

    🔴 ЕДИНСТВЕННЫЙ ДОМ ЭТОГО ПРЕДИКАТА. Его зовут ворота 5 (ниже) И
    `register_doc.py`, который эту строку вписывает. Разойдись они на йоту —
    дверь печатала бы «зарегистрировано», а хук останавливал коммит, и обход
    `--no-verify` вернулся бы штатным ходом (28 обходов из 56 срывов, 27 из них
    по одной этой причине — автолог `_INFRA-git/INCIDENTY.md`).
    Условие грубое (подстрока) — таким оно и было; здесь оно НЕ меняется,
    а только переезжает в функцию.
    """
    имя = Path(p).name
    return имя in раздел or имя[:-3] in раздел or p in раздел


def раздел_karta_6(карта_rel):
    """Текст `§6` ИМЕННО ТОГО индекса, которым судится корень пути.

    🔴 Индекс стал параметром, а не константой: у каждого корня реестра свой дом
    регистрации (у `obzory/` он вообще чужой — в `_studio/`). Пока индекс был
    один и вшитый, документ второй фабрики сверялся бы с индексом ПЕРВОЙ и
    молча числился сиротой либо, наоборот, зачитывался по чужой строке.
    """
    return вырезать_раздел_6((REPO / карта_rel).read_text(encoding="utf-8"))


