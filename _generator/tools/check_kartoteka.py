# «Понятие без привязанной карточки-мотивации в курс не идёт. Это гейт, не
# пожелание» — STANDART-uzla.md.
ОБЯЗАТЕЛЬНЫЕ_РОДЫ = ("мотивация", "сцена")


def карточки(текст):
    """Режем СТРОГО по границам блока ```…``` — иначе поля текут между карточками
    (ошибка №2 из шапки: lazy-квантор радостно перепрыгивает в следующую)."""
    out = {}
    for m in re.finditer(r"```\n(id: (\S+)\n(?:(?!```).*\n)*)```", текст):
        блок = m.group(1)
        поле = lambda f: (re.search(rf"^{f}: (.*)$", блок, re.M) or [None, ""])[1].strip()
        out[m.group(2)] = {
            "род": поле("род"),
            "статус": поле("статус"),
            "связи": [s.strip() for s in поле("связи").split(",") if s.strip()],
            "прибор": "проверено-на-приборе" in блок,
        }
    return out


def карта_лекций(путь_speka):
    """Читаем `Лn: id id id` из SPEKA §Слой 2. Единственный дом соответствия."""
    текст = Path(путь_speka).read_text(encoding="utf-8")
    return {m.group(1): m.group(2).split() for m in re.finditer(r"^(Л\d+): (.+)$", текст, re.M)}


def гейты_лекций(карты, карта):
    """Гейт-таблица по лекциям. СТАТУС ВЫЧИСЛЯЕТСЯ, а не поддерживается руками —
    в этом весь смысл. Гейты 1/2/6 механические; 3/4/5 (сюжет, изобретение зала,
    40-я минута) — суждение, скриптом не проверяются и здесь честно не притворяются."""
    print("\n=== Гейты по лекциям (механические 1/2/6; см. SPEKA §Слой 2) ===")
    print(f"{'ЛЕК':4} {'карт':>4}  {'мотив':>5} {'сцена':>5}  {'seed':>4} {'приб':>4}  вердикт")
    провал = []
    for лек, ids in карта.items():
        нет = [i for i in ids if i not in карты]
        есть = [карты[i] for i in ids if i in карты]
        мот = [c for c in есть if c["род"] == "мотивация"]
        сц = [c for c in есть if c["род"] == "сцена"]
        seed_нес = [i for i in ids if i in карты and карты[i]["статус"] == "seed"
                    and карты[i]["род"] in ОБЯЗАТЕЛЬНЫЕ_РОДЫ]
        приб = [i for i in ids if i in карты and карты[i]["прибор"]]
        беды = []
        if not мот:
            беды.append("гейт1: НЕТ МОТИВАЦИИ")
        if not сц:
            беды.append("гейт2: НЕТ СЦЕНЫ")
        if нет:
            беды.append(f"нет карточек: {нет}")
        # здоровая мотивация может быть seed, если её поднял прибор
        живые_seed = [i for i in seed_нес if not карты[i]["прибор"]]
        if живые_seed and len(живые_seed) == len([c for c in мот if c["статус"] == "seed"]) and not [
                c for c in мот if c["статус"] != "seed"]:
            беды.append(f"гейт6: вся мотивация seed {живые_seed}")
        вердикт = " · ".join(беды) if беды else "✅"
        if беды:
            провал.append(лек)
        print(f"{лек:4} {len(есть):>4}  {len(мот):>5} {len(сц):>5}  {len(seed_нес):>4} {len(приб):>4}  {вердикт}")
    print(f"\nПрошли механические гейты: {len(карта)-len(провал)}/{len(карта)}"
          + (f" · не прошли: {провал}" if провал else " ✅"))
    print("⚠ Гейты 3/4/5 (замкнутый сюжет · зал изобретает · 40-я минута) — суждение,\n"
          "  не скрипт. Их держит аналитик и прибор; здесь они НЕ проверены.")
    return провал


def проверить(путь, путь_speka=None):
    текст = Path(путь).read_text(encoding="utf-8")
    шапка = текст.split("## Нити")[0]
    карты = карточки(текст)
    # ошибка №1: id бывают короткие (`nno`) и с заглавными (`motivation-EM`)
    индекс = set(re.findall(r"`([A-Za-z0-9_-]{2,})`", шапка))

    рёбра = {t for c in карты.values() for t in c["связи"]}
    висячие = sorted(рёбра - set(карты))
    сироты = sorted(set(карты) - индекс)
    дубли = [i for i in карты if len(re.findall(rf"^id: {re.escape(i)}$", текст, re.M)) > 1]

    print(f"=== Гейт картотеки: {путь} ===")
    print(f"Карточек: {len(карты)} · уникальных id: {len(set(карты))} · в индексе: {len(индекс & set(карты))}")
    print(f"A. Висячие рёбра (target не резолвится):  {висячие or 'НЕТ ✅'}")
    print(f"B. Карточки не в индексе (сироты):        {сироты or 'НЕТ ✅'}")
    print(f"C. Дубликаты id:                          {дубли or 'НЕТ ✅'}")

    seed = sorted(i for i, c in карты.items() if c["статус"] == "seed")
    seed_несущие = sorted(i for i in seed if карты[i]["род"] in ОБЯЗАТЕЛЬНЫЕ_РОДЫ)
    прибор = sorted(i for i, c in карты.items() if c["прибор"])
    print(f"D. `seed` в несущем роде {ОБЯЗАТЕЛЬНЫЕ_РОДЫ}: {seed_несущие or 'НЕТ ✅'}")
    print(f"   (всего seed: {len(seed)} · прошло живой прибор: {len(прибор)})")

    по_роду = {}
    for c in карты.values():
        по_роду[c["род"]] = по_роду.get(c["род"], 0) + 1
    print("\nПо роду: " + " · ".join(f"{r} {n}" for r, n in sorted(по_роду.items(), key=lambda x: -x[1])))

    плохо = bool(висячие or сироты or дубли)
    print(f"\nИТОГ по графу: {'❌ ЕСТЬ НАРУШЕНИЯ' if плохо else '✅ граф замкнут, индекс полон'}")
    if seed_несущие:
        print("⚠ seed в несущем роде — не блокер сам по себе, но лекция с таким "
              "не проходит гейт 6 (SPEKA §Слой 2). Поднять может источник ИЛИ прибор,\n"
              "  но НЕ согласие аналитика: он лицо заинтересованное (STANDART §7).")

    if путь_speka:
        карта = карта_лекций(путь_speka)
        if not карта:
            print(f"\n❌ В {путь_speka} не нашёл карту `Лn: id id`. Формат сломан?")
            return 1
        не_в_карте = sorted(set(карты) - {i for ids in карта.values() for i in ids})
        гейты_лекций(карты, карта)
        if не_в_карте:
            print(f"\nКарточек вне карты лекций: {len(не_в_карте)} "
                  f"(норма для инструментов и находок о методе) — {не_в_карте}")
    return 1 if плохо else 0


