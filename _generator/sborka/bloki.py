# Сцены раньше проставлял разметчик руками — тегом `{@N}` в начале абзаца/списка
# (см. докстроку модуля выше: этот файл тег не разбирает, он живёт в `telo` как
# обычный текст и уходит в `build_deck.render_md`/`_attrs_from_tag` без изменений).
# Владелец после лекции 2: «разбиение на сцены совпало с разбиением на блоки — и
# самое простое решение — так и делать всегда». Отсюда — новое поведение
# `render_section_markdown` ниже: сцена ПОРОЖДАЕТСЯ границей блока по умолчанию,
# разметчик тег не пишет вовсе (Э1). Ручной `{@N}` остаётся законным ИСКЛЮЧЕНИЕМ
# (Э2) — но раз он живёт как исключение, а не как второй параллельный слой, его
# присутствие ПЕРЕБИВАЕТ автоматику для ВСЕЙ карточки целиком: смешивать в одной
# карточке порождённые и ручные номера сцен значило бы завести два источника
# истины разом (порождённый {@3} на блоке 3 и ручной {@2} на абзаце внутри него —
# что из них правда?). Гейт (`gejt_kartochki.py`) требует поле-обоснование
# `sceny_vruchnuyu` у любой карточки, где авто выключилась этим путём.
_LEADING_TAG_RE = re.compile(r"^\{([^}|]*)\}(.*)$", re.S)


def _tag_tokens(first_line):
    """Первая строка абзаца → список токенов ведущего тега `{...}` (та же позиция,
    что `build_deck.SCENE_PREFIX`), или None — абзац тега не несёт."""
    m = _LEADING_TAG_RE.match(first_line)
    return m.group(1).split() if m else None


def _has_scene_token(tokens):
    return any(t.startswith("@") for t in (tokens or ()))


def _live_paragraphs(telo):
    """Тело блока → его абзацы ТЕМ ЖЕ приёмом, что `build_deck.render_md` делит
    текст на markdown-блоки (пустая строка — разделитель) — иначе смещение тега
    на абзаце разойдётся с тем, что реально увидит рендер."""
    return [p for p in re.split(r"\n\s*\n", telo.strip("\n")) if p.strip()]


def block_has_manual_scene(block):
    """Блок несёт РУЧНОЙ тег сцены (ведущий, с `@`-токеном) хотя бы в одном своём
    абзаце. `{fill@N|…}`/`{blur@N|…}`/инлайн `{@N|текст}` сюда не попадают — это
    другая, инлайн-форма (не ведущий тег абзаца), она уживается с автоматикой."""
    for para in _live_paragraphs(block.telo):
        first_line = para.split("\n", 1)[0].strip()
        if _has_scene_token(_tag_tokens(first_line)):
            return True
    return False


def has_manual_scenes(blocks):
    """Хоть один блок раздела несёт ручной тег сцены — Э2: автоматика для ВСЕЙ
    карточки выключается целиком, `render_section_markdown` возвращает тела
    блоков дословно (ручная разметка работает, как и раньше)."""
    return any(block_has_manual_scene(b) for b in blocks if b.telo.strip())


def _inject_scene(paragraph, scene_num):
    """Вставить `@scene_num` в ведущий тег абзаца — если тег уже есть (например,
    `{.formula}`), сцена ДОБАВЛЯЕТСЯ первым токеном, а не заменяет чужой; если
    тега нет вовсе — заводится новый `{@N}`."""
    lines = paragraph.split("\n")
    first = lines[0]
    m = _LEADING_TAG_RE.match(first)
    if m:
        tokens = m.group(1).split()
        rest = m.group(2)
        lines[0] = "{%s}%s" % (" ".join(["@%d" % scene_num] + tokens), rest)
    else:
        lines[0] = ("{@%d} %s" % (scene_num, first)) if first else "{@%d}" % scene_num
    return "\n".join(lines)


def _auto_tag_block(block, scene_num):
    """Тело блока → то же тело, где КАЖДЫЙ абзац получил `{@scene_num}` — не
    только первый: иначе абзацы 2+ того же блока остались бы видны с первой сцены
    (тег в build_deck.py — свойство абзаца, не всего блока сразу)."""
    return "\n\n".join(_inject_scene(p, scene_num) for p in _live_paragraphs(block.telo))


def block_start_scenes(blocks):
    """[Block] (живые, telo непуст) → [int] сцена ПОЯВЛЕНИЯ каждого блока —
    Э3 гейту нужна ровно эта величина (сравнить сцену `dokazatelstvo` со сценой
    более раннего несущего блока), не полная раскладка тегов внутри блока.

    Автоматический режим (нет ручных тегов): сцена блока = его порядковый номер
    (1-индексация, ровно то же соответствие, что порождает `render_section_markdown`
    ниже) — считать этот случай отдельно от чтения тегов дешевле и не ошибается
    никогда, раз это и есть источник истины для авто-режима.
    Ручной режим: сцена блока = тег ПЕРВОГО абзаца (абзац без тега виден с первой
    сцены — как и блок вовсе без разметки), более поздние теги того же блока на
    его СОБСТВЕННУЮ сцену появления не влияют."""
    live = [b for b in blocks if b.telo.strip()]
    if not has_manual_scenes(live):
        return list(range(1, len(live) + 1))
    scenes = []
    for b in live:
        paras = _live_paragraphs(b.telo)
        scene = 1
        tokens = _tag_tokens(paras[0].split("\n", 1)[0].strip()) if paras else None
        for t in (tokens or ()):
            if t.startswith("@"):
                num = t[1:].split("-", 1)[0]
                if num:
                    scene = int(num)
                break
        scenes.append(scene)
    return scenes


def render_section_markdown(blocks):
    """[Block] → плоский markdown (тела блоков через пустую строку) — то, что
    компилятор (`formaty.render_body`) скармливает `render_md`. Заголовки блоков
    (`### [tip] мысль`) на экран НИКОГДА не выводятся (Я1 §2, §4) — только текст.

    Заход `sceny-iz-blokov` (Э1): по умолчанию КАЖДЫЙ блок начиная со ВТОРОГО
    получает автоматический тег `{@K}` (K — порядковый номер блока, 1-индексация)
    на каждом своём абзаце — новый блок и есть новая сцена, разметчик тег не
    пишет вовсе. Первый блок тега не несёт: он и так виден с первой сцены
    (`build_deck.scene_cascade_css` — тег на сцене 1 нужен только чтобы блок потом
    УШЁЛ по `data-scene-until`, не чтобы появиться). Раздел несёт ХОТЯ БЫ ОДИН
    ручной тег (Э2, `has_manual_scenes`) — автоматика выключается для ВСЕЙ
    карточки, тела блоков возвращаются дословно, как до этого захода.

    🔴 САМА РАЗМЕТКА СЧИТАЕТСЯ НЕ ЗДЕСЬ, а в `blocks_for_render` — эта функция
    ровно склеивает её результат (дочистка-2 захода pravila-kadra, Д4). Пока
    каждая из двух несла собственную копию одного правила, копии разошлись
    молча: рендер дека ушёл на вторую, автоматика осталась в первой, и сцены
    пропали на 14 слайдах из 26 при зелёных гейтах. Одно правило — один дом."""
    return "\n\n".join(b.telo for b in blocks_for_render(blocks))


def fakticheskie_sceny(blocks):
    """[Block] → сколько сцен слайд получит НА САМОМ ДЕЛЕ: максимум по номерам
    сцен в тегах ТОГО текста, который `blocks_for_render` отдаёт рендеру.

    🔴 ЧИТАЕТ ВЫХОД, А НЕ НАМЕРЕНИЕ — в этом весь смысл (Д6 дочистки-2 захода
    pravila-kadra). `block_start_scenes` рядом отвечает на вопрос «на какой сцене
    ДОЛЖЕН появиться блок» и в авто-режиме возвращает `1..len(live)` НЕ ГЛЯДЯ на
    теги — она и была бы зелёной во время регрессии Д4, когда рендер получал тела
    без единого тега. Эта функция берёт ровно тот объект, что уходит в
    `formaty.render_slide_blocks`, и пересчитывает теги обратно: пропадут теги —
    упадёт число, и упадёт ЗДЕСЬ, а не на проекторе у владельца.

    Форму тега разбираем ту же, что `build_deck._attrs_from_tag`: `@N`, `@N-K`
    (от N до K) и `@-K` (только до K) — берём максимум по всем числам, тем же
    приёмом, что `build_deck.max_scenes` (он считает по трём атрибутам сразу,
    а не по одному `data-scenes`)."""
    n = 1
    for b in blocks_for_render(blocks):
        for para in _live_paragraphs(b.telo):
            for t in (_tag_tokens(para.split("\n", 1)[0].strip()) or ()):
                if not t.startswith("@"):
                    continue
                for chast in t[1:].split("-"):
                    if chast.isdigit():
                        n = max(n, int(chast))
    return n


def render_section_for_word_count(blocks):
    """[Block] → плоский markdown БЕЗ автоматических тегов сцен — то, что считает
    словами `gejt_kartochki` (`byudzhet_slov`).

    🔴 ПОЧЕМУ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ФЛАГ К `render_section_markdown`.
    У склейки блоков два потребителя с ПРОТИВОПОЛОЖНОЙ нуждой: вёрстке
    (`formaty.render_body`) автотеги нужны — они и есть раскладка по сценам;
    счёту слов они мусор — лектор их не произносит. Пока потребитель был один,
    функция была одна; заход `sceny-iz-blokov` завёл автоматику, и счёт слов
    молча начал считать разметку.

    🔴 ЭТА ЖЕ ФУНКЦИЯ И ЕСТЬ РАЗРЕШЕНИЕ КОНФЛИКТА `sceny-iz-blokov` ×
    `vid-blokov-vnedrenie` (заход konflikty, 2026-08-14). Ветка ставила на
    `render_section_markdown` предупреждение «НЕ ТРОГАТЬ — её зовёт
    `gejt_kartochki.py` для счёта слов», и предупреждение было ВЕРНО: оно
    описывало ровно то раздвоение потребителей, которое снято здесь.

    ЦЕНА, снятая живым прогоном 2026-08-14 на `teorkat-vvedenie/L2` (23 карточки):
    автотеги дают лишние слова на 16 карточках из 23, всего +53 слова, и на
    `fundamentalnaya-gruppa` ПЕРЕВОРАЧИВАЮТ вердикт гейта — бюджет 58, с тегами 59
    («превышен»), без тегов 56 (в норме). То есть гейт краснел на здоровой
    карточке, и починка автора состояла бы в вырезании живого текста.

    Ручную разметку (`{@2}`, `{.formula}`) функция НЕ трогает намеренно: она была
    в счёте и до автоматики, бюджеты карточек откалиброваны с ней, и её вычитание
    — отдельное решение владельца, а не починка этого дефекта."""
    return "\n\n".join(b.telo for b in blocks if b.telo.strip())


def blocks_for_render(blocks):
    """[Block] → [Block] с непустым `telo`, в порядке появления — тот же отбор
    И ТА ЖЕ РАЗМЕТКА СЦЕН, что у `render_section_markdown` (пустые блоки на
    экран не идут ни в каком виде), но БЕЗ склейки в один markdown: каждый блок
    остаётся структурой (тип + мысль + тело) — заход `vid-blokov-vnedrenie`,
    §5 итога п.1, «вторая функция, отдающая блоки СТРУКТУРОЙ». Вызывающая
    сторона (`formaty.py`) оборачивает КАЖДЫЙ блок отдельно, вокруг результата
    `render_body`.

    🔴 АВТО-ТЕГИРОВАНИЕ СЦЕН ЗДЕСЬ — ПОЧИНКА РЕГРЕССИИ Д4 (заход pravila-kadra,
    дочистка-2 2026-08-14), а не новое поведение. Функция родилась «отдающей
    блоки как есть» и этим МОЛЧА выключила автоматику `sceny-iz-blokov`: сцена
    порождается границей блока в `render_section_markdown` (ниже/выше по файлу),
    а рендер дека с захода `vid-blokov-vnedrenie` ходит сюда и ту функцию не
    зовёт вовсе. Ни один гейт не покраснел — обе половины по отдельности были
    зелёные.

    ЦЕНА, измеренная приёмкой на собранной деке `teorkat-vvedenie/L2`: сумма
    `data-scenes` 50 → 28, элементов `data-scene-from` 100 → 31, схлопнулись в
    ОДНУ сцену 14 слайдов из 26. Уцелел ровно тот слайд, где теги проставлены
    руками (`inyekcii`, поле `sceny_vruchnuyu`) — то есть сломалось именно то,
    что здесь и чинится.

    ПОЧЕМУ РЕГРЕССИЮ НЕ ВИДНО БЫЛО РАНЬШЕ: ветка `polya-i-uzor`, чей замер брали
    за «до», отпочкована ПОСЛЕ `vid-blokov-vnedrenie`, но ДО `sceny-iz-blokov` —
    её 50 сцен были РУЧНЫМИ тегами карточек, которые `sceny-iz-blokov` потом снял
    с 14 карточек (коммит 765912a), положившись на автоматику. Регрессия — не
    правка, а пересечение двух веток: одна убрала ручные теги, другая увела
    рендер с функции, где автоматика живёт.

    Разметка ОБЯЗАНА совпадать с `render_section_markdown` дословно — иначе
    `block_start_scenes` (её зовёт гейт) считает одно, а рендер делает другое."""
    live = [b for b in blocks if b.telo.strip()]
    if has_manual_scenes(live):
        return live
    return [b if i == 1 else b._replace(telo=_auto_tag_block(b, i))
            for i, b in enumerate(live, start=1)]
