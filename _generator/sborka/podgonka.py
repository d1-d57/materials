def kegl_dlya_znakov(chars):
    """Кегль тела текста под объём (по образцу `sverstat.py:kegl`, PRIMERY.md §2:
    «выбор под объём, не патч переполнения»). Пол 35px — та же граница, что в
    оригинале (`audit.py FLOOR_PX` там); пороги 430/560 знаков — оттуда же."""
    if chars <= 430:
        return 40
    if chars <= 560:
        return 38
    return 35


def vpisat_v_boks(fig_w, fig_h, box_w, box_h, pad=0):
    """Размер иллюстрации (по образцу `sverstat.py:panel_box`): фигура с
    пропорцией `fig_w:fig_h` вписывается в бокс `box_w×box_h` без растяжения,
    с полями `pad` по каждой стороне. Возвращает (w, h) — итоговый размер,
    всегда ⩽ доступной области (box − 2·pad) по обеим осям.

    Раньше (в оригинале) — подложка-паспарту под фигурой; здесь её тоже нет
    (см. докстроку `sverstat.panel_box`: «владелец 31.07 снял подложку»),
    `pad` — воздух до края доски, не паспарту."""
    aw, ah = box_w - 2 * pad, box_h - 2 * pad
    if aw <= 0 or ah <= 0 or fig_w <= 0 or fig_h <= 0:
        return max(aw, 0), max(ah, 0)
    scale = min(aw / fig_w, ah / fig_h)
    return fig_w * scale, fig_h * scale
