import sys,re
p=sys.argv[1]; s=open(p).read()
def rep(a,b):
    global s
    rx=re.escape(a).replace(re.escape(" — "),"[  ]— ")
    m=list(re.finditer(rx,s))
    if len(m)!=1: raise SystemExit("НЕТ (%d): %s"%(len(m),a[:80]))
    s=s[:m[0].start()]+b.replace(" — "," — ")+s[m[0].end():]
rep("Дальше в виджетах слово рисуется рядом клеток: единица — закрашенная клетка, ноль — пустая.","В виджетах ниже слово изображено рядом клеток: единица — закрашенная клетка, ноль — пустая.")
rep("Понадобится правило произведения:","Нам понадобится правило произведения:")
rep("Дальше в тексте этим приёмом мы будем пользоваться постоянно.","Этим приёмом мы будем пользоваться постоянно.")
rep("Деления здесь нет: мы только умножаем, и каждое умножение видно, откуда берётся, — из правила произведения.","Деления здесь нет: мы только умножаем, а каждое умножение — это правило произведения.")
open(p,"w").write(s); print("ok")
