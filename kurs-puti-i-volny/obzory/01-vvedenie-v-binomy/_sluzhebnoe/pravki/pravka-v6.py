import sys,re
p=sys.argv[1]; s=open(p).read()
NB=" "
def norm(t): return t.replace(NB+"— "," — ")
def rep(a,b):
    global s
    rx=re.escape(a).replace(re.escape(" — "),"[  ]— ")
    m=list(re.finditer(rx,s))
    if len(m)!=1: raise SystemExit("НЕТ (%d): %s"%(len(m),a[:80]))
    s=s[:m[0].start()]+b+s[m[0].end():]
# В32: X -> binom(8,3)
rep("Обозначим неизвестный ответ буквой $X$. Решим другую задачу:","Ответ — число $\\binom83$; его мы и учимся считать. Решим другую задачу:")
rep("можно сначала выбрать тройку — $X$ способами,","можно сначала выбрать тройку — $\\binom83$ способами,")
rep("Всего $X\\cdot3\\cdot2$. Это одно и то же количество, поэтому\n$$X\\cdot3\\cdot2=8\\cdot7\\cdot6,$$\nто есть $6X=336$ и $X=56$. Так и получилось у Веры: $\\binom83=56$.",
    "Всего $\\binom83\\cdot3\\cdot2$. Это одно и то же количество, поэтому\n$$\\binom83\\cdot3\\cdot2=8\\cdot7\\cdot6,$$\nто есть $6\\binom83=336$ и $\\binom83=56$. Так и получилось у Веры.")
# В33: вынуть раздел «Сумма строки» и поставить перед «Ответом»
i=s.index("## Сумма строки\n"); j=s.index("## Формула\n")
sec=s[i:j]; s=s[:i]+s[j:]
k=s.index("## Ответ\n")
# В34: наблюдение по первым строкам + виджет c8 + удвоение по правилу Паскаля
a="Столько их и насчитано у Чараки. Вместе с пустой смесью получается $64=2^6$. Для четырёх предметов в таблице всех слов $1+4+6+4+1=16=2^4$. Это не совпадение."
assert norm(sec).count(a)==1, 'нет абзаца суммы'
b=("Столько их и насчитано у Чараки. Вместе с пустой смесью получается 64.\n\n"
   "Сложим так же числа в первых строках треугольника. Получится 1, 2, 4, 8, 16, 32, 64: каждая сумма вдвое больше предыдущей.\n\n"
   "{{S:c8}}\n\n"
   "Почему так, видно из правила Паскаля. Каждое число строки входит ровно в два числа следующей строки — в то, что под ним слева, и в то, что под ним справа. Поэтому в следующей строке каждое число предыдущей посчитано дважды: для строки 4 это $2\\cdot16=32=1+5+10+10+5+1$. Сумма строки $n$ получается из единицы удвоением $n$ раз, то есть равна $2^n$.")
sec=norm(sec).replace(a,b)
s=s[:k]+sec+s[k:]
# Паскаль: седьмое следствие и «после следствий»
rep("Это одно из первых явных таких доказательств. Сразу после следствий Паскаль ставит задачу",
    "Это одно из первых явных таких доказательств. Седьмое следствие трактата — ровно наше наблюдение о суммах: сумма клеток каждого основания вдвое больше суммы предыдущего. В конце, после следствий, Паскаль ставит задачу")
# перенумерация врезок по порядку появления
lab=re.compile(r"^\*\*(Определение|Утверждение|Теорема|Задача) (\d+) \(",re.M)
old=[int(m.group(2)) for m in lab.finditer(s)]
mp={o:i+1 for i,o in enumerate(old)}
assert len(set(old))==len(old)
s=lab.sub(lambda m:"**%s %d ("%(m.group(1),mp[int(m.group(2))]),s)
ref=re.compile(r"(?<![\w*])((?:[Уу]тверждени|[Тт]еорем|[Зз]адач|[Оо]пределени)\w*) (\d+)\b(?!\s*\()")
s=ref.sub(lambda m:"%s %d"%(m.group(1),mp.get(int(m.group(2)),int(m.group(2)))),s)
# списки ссылок «Утверждения 4, 6 и 7» — числа до 9 не сдвигались; проверка ниже
# NBSP-проход
out=[]
for line in s.split("\n"):
    if not line.startswith("$$") and not line.startswith("|") and not line.startswith("{{"):
        parts=line.split("$")
        for q in range(0,len(parts),2): parts[q]=parts[q].replace(" — ",NB+"— ")
        line="$".join(parts)
    if line.startswith("*"):
        head,sep,rest=line.partition(".*")
        if sep: line=head.replace(NB+"— "," — ")+sep+rest
    out.append(line)
s="\n".join(out)
open(p,"w").write(s); print("ok", mp)
