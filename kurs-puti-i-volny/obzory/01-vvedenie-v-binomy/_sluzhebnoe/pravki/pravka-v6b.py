import sys,re
p=sys.argv[1]; s=open(p).read()
NB=" "
def rep(a,b):
    global s
    rx=re.escape(a).replace(re.escape(" — "),"[  ]— ")
    m=list(re.finditer(rx,s))
    if len(m)!=1: raise SystemExit("НЕТ (%d): %s"%(len(m),a[:80]))
    s=s[:m[0].start()]+b+s[m[0].end():]
rep("в виджете она отражается под диагональ, и две лесенки складываются в прямоугольник из $n-1$ ряда по $n$ клеток.",
    "в виджете она отражается под диагональ, а после сдвига на клетку вверх две лесенки складываются в прямоугольник из $n-1$ ряда по $n$ клеток.")
rep("*Доказательство — любой из трёх способов выше.* В каждом из них получилось $2\\binom n2=n(n-1)$.",
    "*Доказательство — способ 2 или 3.* В каждом из них получилось $2\\binom n2=n(n-1)$, и оба рассуждения годятся при любом $n$.")
rep("В частности, $\\binom n{n-1}=\\binom n1=n$:","В частности, при $n\\ge1$ выполняется $\\binom n{n-1}=\\binom n1=n$:")
rep("Каждое число строки входит ровно в два числа следующей строки — в то, что под ним слева, и в то, что под ним справа.",
    "Каждое число строки входит ровно в два числа следующей строки — в то, что под ним слева, и в то, что под ним справа; крайние единицы следующей строки получают по одному такому вкладу.")
rep("**Определение 13 (факториал). Статус: пишем с нуля.**","**Определение 13 (факториал). Статус: выверено, SKELET опр. 10.**")
rep("**Утверждение 17 (сумма строки). Статус: пишем с нуля.**","**Утверждение 17 (сумма строки). Статус: выверено, SKELET утв. 12.**")
rep("Здесь видно, зачем наверху треугольника нужна единица $\\binom00=1$: строка 1 получается из строки 0, $\\binom11=\\binom00+\\binom01=1+0$. Без этой единицы правило не дало бы ни одной строки.",
    "Единица $\\binom00=1$ наверху треугольника с правилом согласована: строка 1 получается из строки 0, $\\binom11=\\binom00+\\binom01=1+0$.")
out=[]
for line in s.split("\n"):
    if not line.startswith("$$") and not line.startswith("|") and not line.startswith("{{"):
        parts=line.split("$")
        for q in range(0,len(parts),2): parts[q]=parts[q].replace(" — ",NB+"— ")
        line="$".join(parts)
    if line.startswith("*"):
        head,sep,rest=line.partition(".*")
        if sep: line=head.replace(NB+"— "," — ")+sep+rest
    out.append(line)
s="\n".join(out); open(p,"w").write(s); print("ok")
