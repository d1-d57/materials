#!/usr/bin/env python3
"""ИНДЕКС ЗНАНИЯ курса «Пути и волны» — собирается из файлов, не ведётся руками.

ЗАЧЕМ. Оглавление, которое дописывают руками, рассинхронизируется — это не
гипотеза, а факт этого проекта: картотека курса прожила три недели, не будучи
упомянутой ни в одном индексе, и из-за этого два уже решённых вопроса были
заново выданы владельцу как открытые. Здесь описание живёт В ФАЙЛЕ, а индекс
есть ВЫХОД генератора. Рассинхрон становится невозможен структурно, а не по
дисциплине.

ЧТО СЧИТАЕТСЯ УЗЛОМ ГРАФА ЗНАНИЯ. Две вещи, обе адресуются одинаково — по `id`:
  * КАРТОЧКА — файл картотеки, первая строка вида `id: X · род: Y · суть: Z`;
  * ЯКОРЬ — раздел внутри документа, помеченный `<!--id: X-->`. Так уже устроен
    SKELET.md, и это ровно ответ на «ссылаться не на весь документ, а на часть».

ССЫЛКА — `[[X]]` в любом файле, либо перечисление в поле `связи:` карточки,
либо `опирается: ... (n)` в скелете.

ЧТО ГЕЙТ ЛОВИТ (rc=1):
  1. НОВЫЙ .md без поля `opisanie:` в шапке — новый значит «не записан в долге»;
  2. ссылка на `id`, которого нет нигде;
  3. два узла с одинаковым `id`.
Унаследованный долг (файлы без описания, перечисленные в DOLG-bez-opisaniya.txt)
печатается числом и НЕ валит прогон. Это сознательно: гейт, красный от
рождения, обесценивает красный цвет и его начинают обходить.

ЗАПУСК
    python3 tools/indeks.py            # собрать INDEKS.md и проверить
    python3 tools/indeks.py --proverit # только проверить, ничего не писать
    python3 tools/indeks.py --dolg     # переписать базу долга по факту (осознанно!)
"""

import os
import re
import sys

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATERIALS = os.path.dirname(КОРЕНЬ)

# Дома знания курса. Третий лежит в соседнем проекте — это не ошибка, а история:
# курс вырос из catalan и унёс оттуда память ресёрча.
ДОМА = [
    ("курс", "kurs-puti-i-volny"),
    ("обзор и лекция", "obzory/funkciya-putey-i-ee-uravneniya"),
    ("картотека", "catalan/kartoteka"),
]

ПРОПУСК = {".git", "__pycache__", "node_modules", "snapshots", "SBORKA"}

ФАЙЛ_ДОЛГА = os.path.join(КОРЕНЬ, "tools", "DOLG-bez-opisaniya.txt")
ФАЙЛ_ИНДЕКСА = os.path.join(КОРЕНЬ, "INDEKS.md")

RE_ШАПКА = re.compile(r"\A---\n(.*?)\n---\n", re.S)
RE_БЛОК_КОДА = re.compile(r"```.*?```", re.S)
RE_СТРОЧНЫЙ_КОД = re.compile(r"`[^`\n]*`")
RE_ЯКОРЬ = re.compile(r"<!--\s*id:\s*([a-zA-Z0-9_\-]+)\s*-->")
RE_КАРТОЧКА = re.compile(r"^id:\s*([a-zA-Z0-9_\-]+)\s*·\s*род:\s*([^·]+?)\s*·\s*суть:\s*(.+)$", re.M)
RE_ССЫЛКА = re.compile(r"\[\[([a-zA-Z0-9_\-]+)\]\]")
RE_СВЯЗИ = re.compile(r"^связи:\s*\[?(.+?)\]?\s*$", re.M)
RE_ID_В_СВЯЗЯХ = re.compile(r"\b(kart-[a-zA-Z0-9_\-]+)\b")


def обойти():
    """Все .md в домах знания, путями от materials/."""
    для_всех = []
    for имя_дома, отн in ДОМА:
        база = os.path.join(MATERIALS, отн)
        if not os.path.isdir(база):
            print(f"⚠ дом не найден: {отн}")
            continue
        for путь, папки, файлы in os.walk(база):
            папки[:] = [p for p in папки if p not in ПРОПУСК and not p.startswith(".")]
            for f in sorted(файлы):
                if f.endswith(".md"):
                    полный = os.path.join(путь, f)
                    для_всех.append((имя_дома, os.path.relpath(полный, MATERIALS), полный))
    return для_всех


def шапка(текст):
    m = RE_ШАПКА.match(текст)
    if not m:
        return {}
    поля = {}
    for строка in m.group(1).split("\n"):
        if ":" in строка:
            k, v = строка.split(":", 1)
            поля[k.strip()] = v.strip()
    return поля


def без_кода(текст):
    """Убрать код — и блочный, и строчный.

    🔴 Почему это обязано быть. Гейт, тянущий токены из ВСЕГО текста, краснеет
    на живом тексте, где предмет просто упомянут. Первый же прогон 18.09 назвал
    дублем `chebyshev`: в SKELET.md он стоит один раз якорем и один раз внутри
    обратных кавычек — в абзаце, ОБЪЯСНЯЮЩЕМ синтаксис якорей. Такой гейт учит
    прятать токены, а не чинить ссылки, то есть работает против правды, которую
    сторожит. Разделитель дешёвый и точный: настоящий якорь голый, разговор о
    якоре — в кавычках.
    """
    return RE_СТРОЧНЫЙ_КОД.sub(" ", RE_БЛОК_КОДА.sub(" ", текст))


def первый_заголовок(текст):
    for строка in текст.split("\n"):
        if строка.startswith("# "):
            return строка[2:].strip()
    return ""


def собрать():
    узлы = {}          # id -> (вид, где, суть)
    ссылки = []        # (id, откуда)
    файлы = []         # (дом, отн, описание, статус, число узлов)
    дубли = []

    for дом, отн, полный in обойти():
        with open(полный, encoding="utf-8") as fh:
            текст = fh.read()
        ш = шапка(текст)
        описание = ш.get("opisanie") or ш.get("описание") or ""
        статус = ш.get("status", "")

        # Узлы и ссылки ищем в тексте БЕЗ кода: см. `без_кода`.
        чистый = без_кода(текст)

        свои = 0
        for id_, род, суть in RE_КАРТОЧКА.findall(чистый):
            свои += 1
            if id_ in узлы:
                дубли.append((id_, узлы[id_][1], отн))
            узлы[id_] = ("карточка", отн, суть.strip(), род.strip())
        for id_ in RE_ЯКОРЬ.findall(чистый):
            свои += 1
            if id_ in узлы:
                дубли.append((id_, узлы[id_][1], отн))
            узлы[id_] = ("якорь", отн, "", "")

        for id_ in RE_ССЫЛКА.findall(чистый):
            ссылки.append((id_, отн))
        for кусок in RE_СВЯЗИ.findall(чистый):
            for id_ in RE_ID_В_СВЯЗЯХ.findall(кусок):
                ссылки.append((id_, отн))

        файлы.append((дом, отн, описание or первый_заголовок(текст), статус, свои, bool(описание)))

    return файлы, узлы, ссылки, дубли


def прочитать_долг():
    if not os.path.exists(ФАЙЛ_ДОЛГА):
        return set()
    with open(ФАЙЛ_ДОЛГА, encoding="utf-8") as fh:
        return {s.strip() for s in fh if s.strip() and not s.startswith("#")}


def написать_индекс(файлы, узлы):
    строки = [
        "<!-- 🤖 СОБРАН ГЕНЕРАТОРОМ `tools/indeks.py`. РУКАМИ НЕ ПРАВИТЬ: правка",
        "     будет стёрта следующим прогоном. Описание файла живёт в ЕГО шапке,",
        "     поле `opisanie:`. Нет описания — правь файл, не этот индекс. -->",
        "",
        "# ИНДЕКС ЗНАНИЯ — курс «Пути и волны»",
        "",
        "Собран из шапок самих файлов и якорей внутри них. Пересобрать и проверить:",
        "`python3 tools/indeks.py`",
        "",
    ]

    по_домам = {}
    for дом, отн, опис, статус, сколько, есть in файлы:
        по_домам.setdefault(дом, []).append((отн, опис, статус, сколько, есть))

    строки.append("## Документы")
    for дом in [d for d, _ in ДОМА]:
        if дом not in по_домам:
            continue
        строки += ["", f"### {дом}", "", "| файл | о чём | статус | узлов |", "|---|---|---|---|"]
        for отн, опис, статус, сколько, есть in sorted(по_домам[дом]):
            метка = опис if есть else f"⚠ {опис} *(описания в шапке нет)*"
            строки.append(f"| `{отн}` | {метка} | {статус or '—'} | {сколько or ''} |")

    карточки = {i: v for i, v in узлы.items() if v[0] == "карточка"}
    якоря = {i: v for i, v in узлы.items() if v[0] == "якорь"}

    строки += ["", f"## Узлы графа — карточки ({len(карточки)})", "",
               "| id | род | суть | файл |", "|---|---|---|---|"]
    for id_, (_, отн, суть, род) in sorted(карточки.items()):
        строки.append(f"| `{id_}` | {род} | {суть} | `{отн}` |")

    строки += ["", f"## Узлы графа — якоря в документах ({len(якоря)})", "",
               "Ссылаться на часть документа, а не на документ целиком.", "",
               "| id | файл |", "|---|---|"]
    for id_, (_, отн, _, _) in sorted(якоря.items()):
        строки.append(f"| `{id_}` | `{отн}` |")

    строки += ["", "---", "*Выход генератора. Источник — шапки файлов и метки `<!--id:-->` внутри них.*", ""]

    with open(ФАЙЛ_ИНДЕКСА, "w", encoding="utf-8") as fh:
        fh.write("\n".join(строки))


def main():
    только_проверить = "--proverit" in sys.argv
    переписать_долг = "--dolg" in sys.argv

    файлы, узлы, ссылки, дубли = собрать()
    долг = прочитать_долг()

    без_описания = [отн for _, отн, _, _, _, есть in файлы if not есть]
    новые_без_описания = sorted(set(без_описания) - долг)
    унаследованные = sorted(set(без_описания) & долг)

    висячие = sorted({(i, откуда) for i, откуда in ссылки if i not in узлы})

    if переписать_долг:
        with open(ФАЙЛ_ДОЛГА, "w", encoding="utf-8") as fh:
            fh.write("# Файлы без поля `opisanie:` в шапке — унаследованный долг.\n")
            fh.write("# Гейт их не валит, только считает. Новый файл в этом списке\n")
            fh.write("# появляться НЕ должен: если появился, значит долг растёт.\n")
            for отн in sorted(без_описания):
                fh.write(отн + "\n")
        print(f"база долга переписана: {len(без_описания)} файлов")
        return 0

    if not только_проверить:
        написать_индекс(файлы, узлы)
        print(f"✍ INDEKS.md собран: {len(файлы)} файлов, {len(узлы)} узлов")

    print()
    print(f"документов:          {len(файлы)}")
    print(f"узлов графа:         {len(узлы)}  "
          f"(карточек {sum(1 for v in узлы.values() if v[0]=='карточка')}, "
          f"якорей {sum(1 for v in узлы.values() if v[0]=='якорь')})")
    print(f"ссылок:              {len(ссылки)}")
    print(f"без описания:        {len(без_описания)}  "
          f"(унаследованных {len(унаследованные)}, новых {len(новые_без_описания)})")
    print()

    красно = False

    if новые_без_описания:
        красно = True
        print("❌ НОВЫЙ файл без `opisanie:` в шапке — так документ теряется из индекса:")
        for о in новые_без_описания:
            print(f"     {о}")
        print()

    if висячие:
        красно = True
        print("❌ ссылка на несуществующий id:")
        for i, откуда in висячие:
            print(f"     [[{i}]] ← {откуда}")
        print()

    if дубли:
        красно = True
        print("❌ один id у двух узлов:")
        for i, a, b in дубли:
            print(f"     {i}: {a} и {b}")
        print()

    if унаследованные:
        print(f"⚠ унаследованный долг: {len(унаследованные)} файлов без описания. "
              f"Список — tools/DOLG-bez-opisaniya.txt")
        print()

    print("🔴 ГЕЙТ КРАСНЫЙ" if красно else "✅ гейт зелёный")
    return 1 if красно else 0


if __name__ == "__main__":
    sys.exit(main())
