"""ДУБЛИ — что в корпусе курса написано дважды.

ЗАЧЕМ. За год ресёрча главная опасность не в том, что чего-то не найдём, а в
том, что напишем вторую статью о том же. Это уже случалось в фабрике: две ветки
месяц вели одну картотеку врозь и разошлись на 25 карточек, из которых ПЯТЬ ПАР
описывали одно и то же разными словами. Человеческая внимательность эту задачу
не решает — нужен прибор.

ЧТО МЕРЯЕТ. Похожесть текстов по посимвольным n-граммам (TF-IDF + косинус).
Метод грубый, но для русского работает и не требует ни сети, ни моделей: ловит
пересказ того же своими словами, а не только копипасту.

⚠ ЧЕСТНАЯ ГРАНИЦА МЕТОДА. n-граммы видят СЛОВА, а не СМЫСЛ. «Метод изображений»
и «принцип отражения» — про одно, но текстово далеки, и прибор их не сведёт.
Правильный инструмент для этого — эмбеддинги (sentence-transformers, любая
многоязычная модель; для английского эталон all-MiniLM-L6-v2, для русского
нужна многоязычная — проверить отдельно). Их сегодня нет в песочнице: ни
`sklearn`, ни сети для `pip`. Заменяется ровно одна функция — `векторизовать`.
До тех пор прибор ловит верхние 80 %, и это честно сказано, а не умолчано.

ЗАПУСК
    python3 tools/dubli.py                  # пары похожих документов и узлов
    python3 tools/dubli.py --porog 0.35     # свой порог
    python3 tools/dubli.py --na ФАЙЛ        # на что похож ЭТОТ текст — главный режим:
                                            # спросить ПЕРЕД тем, как писать новое
"""

import os
import re
import sys
import math
from collections import Counter

import numpy as np

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MATERIALS = os.path.dirname(КОРЕНЬ)

ДОМА = ["kurs-puti-i-volny", "obzory/funkciya-putey-i-ee-uravneniya", "catalan/kartoteka"]
ПРОПУСК = {".git", "__pycache__", "node_modules", "snapshots"}
ИМЕНА_МИМО = {"INDEKS.md"}          # выход генератора, не содержание

N = 4          # длина символьной n-граммы

# ПОРОГ откалиброван по ЭТОМУ корпусу прогоном 2026-09-18, а не взят из головы:
#   0.30 → 190 пар (шум: весь корпус про одно, базовая похожесть высокая)
#   0.40 →  26 пар
#   0.45 →   6 пар  ← рабочий: столько человек реально посмотрит
#   0.50 →   4 пары
# Корпус тематически однороден — всё про пути, — поэтому порог выше обычного.
# Перекалибровать той же командой, когда корпус вырастет вдвое.
ПОРОГ = 0.45

RE_ШАПКА = re.compile(r"\A---\n.*?\n---\n", re.S)
RE_КОД = re.compile(r"```.*?```", re.S)
RE_РАЗМЕТКА = re.compile(r"[#*_`>\[\]()|·—–\-…:;,.!?\"'«»%$\\{}<>=+/]+")
RE_ПРОБЕЛЫ = re.compile(r"\s+")
RE_КАРТОЧКА = re.compile(r"^id:\s*([a-zA-Z0-9_\-]+)\s*·", re.M)


def очистить(текст):
    """Оставить только смысловые буквы: без шапки, кода, разметки и регистра."""
    текст = RE_ШАПКА.sub(" ", текст)
    текст = RE_КОД.sub(" ", текст)
    текст = RE_РАЗМЕТКА.sub(" ", текст)
    return RE_ПРОБЕЛЫ.sub(" ", текст).lower().strip()


def нграммы(текст):
    if len(текст) < N:
        return Counter()
    return Counter(текст[i:i + N] for i in range(len(текст) - N + 1))


def собрать_корпус():
    единицы = []
    for дом in ДОМА:
        база = os.path.join(MATERIALS, дом)
        if not os.path.isdir(база):
            continue
        for путь, папки, файлы in os.walk(база):
            папки[:] = [p for p in папки if p not in ПРОПУСК and not p.startswith(".")]
            for f in sorted(файлы):
                if not f.endswith(".md") or f in ИМЕНА_МИМО:
                    continue
                полный = os.path.join(путь, f)
                with open(полный, encoding="utf-8") as fh:
                    сырое = fh.read()
                чистое = очистить(сырое)
                if len(чистое) < 200:      # огрызки не сравниваем
                    continue
                карточка = RE_КАРТОЧКА.search(сырое)
                имя = карточка.group(1) if карточка else os.path.relpath(полный, MATERIALS)
                единицы.append((имя, чистое))
    return единицы


def векторизовать(тексты):
    """TF-IDF по символьным n-граммам, L2-нормировка. Косинус = скалярное произведение.

    ⚠ ТОЧКА ЗАМЕНЫ. Захочешь эмбеддинги — переписывается только эта функция:
    вернуть матрицу (число текстов × размерность), строки L2-нормированы. Всё
    остальное — сбор корпуса, пороги, вывод — не меняется ни строкой.
    """
    словари = [нграммы(t) for t in тексты]
    словарь = {}
    for d in словари:
        for g in d:
            if g not in словарь:
                словарь[g] = len(словарь)

    M = np.zeros((len(тексты), len(словарь)), dtype=np.float32)
    for i, d in enumerate(словари):
        for g, c in d.items():
            M[i, словарь[g]] = 1.0 + math.log(c)

    df = (M > 0).sum(axis=0)
    idf = np.log((1 + len(тексты)) / (1 + df)) + 1.0
    M *= idf

    нормы = np.linalg.norm(M, axis=1, keepdims=True)
    нормы[нормы == 0] = 1.0
    return M / нормы


def полоска(x, ширина=22):
    n = int(round(x * ширина))
    return "█" * n + "·" * (ширина - n)


def main():
    порог = ПОРОГ
    if "--porog" in sys.argv:
        порог = float(sys.argv[sys.argv.index("--porog") + 1])

    единицы = собрать_корпус()
    имена = [и for и, _ in единицы]
    тексты = [t for _, t in единицы]

    if "--na" in sys.argv:
        цель = sys.argv[sys.argv.index("--na") + 1]
        with open(цель, encoding="utf-8") as fh:
            свой = очистить(fh.read())
        M = векторизовать(тексты + [свой])
        похожесть = M[:-1] @ M[-1]
        порядок = np.argsort(-похожесть)
        print(f"На что похож {os.path.basename(цель)} — топ-12 корпуса:\n")
        for i in порядок[:12]:
            метка = "  ← СМОТРЕТЬ" if похожесть[i] >= порог else ""
            print(f"  {похожесть[i]:.3f} {полоска(похожесть[i])}  {имена[i]}{метка}")
        print()
        сколько = int((похожесть >= порог).sum())
        print(f"выше порога {порог}: {сколько}")
        if сколько:
            print("\n⚠ Прежде чем писать новое — прочти помеченные. Возможно, это уже написано.")
        return 0

    M = векторизовать(тексты)
    S = M @ M.T
    np.fill_diagonal(S, 0.0)

    пары = []
    for i in range(len(имена)):
        for j in range(i + 1, len(имена)):
            if S[i, j] >= порог:
                пары.append((S[i, j], имена[i], имена[j]))
    пары.sort(reverse=True)

    print(f"единиц в корпусе: {len(имена)}   порог: {порог}   n-грамма: {N}\n")
    if not пары:
        print("✅ пар выше порога нет")
    else:
        print(f"пар выше порога: {len(пары)}\n")
        for s, a, b in пары:
            print(f"  {s:.3f} {полоска(s)}")
            print(f"        {a}")
            print(f"        {b}\n")
        print("⚠ Похожесть — не приговор. Прибор мерит СЛОВА, а решает человек:")
        print("   бывает законный повтор (сжатие с адресом), бывает настоящий дубль.")

    # самые изолированные — обратная сторона того же прибора
    макс = S.max(axis=1)
    порядок = np.argsort(макс)
    print("\nСамые НИ НА ЧТО не похожие — кандидаты в сироты по смыслу:")
    for i in порядок[:6]:
        print(f"  {макс[i]:.3f}  {имена[i]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
