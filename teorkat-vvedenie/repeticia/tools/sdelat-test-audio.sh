#!/bin/zsh
# Тестовое аудио для холостой проверки конвейера — без настоящей записи.
# Голос Milena (ru_RU) + настоящие паузы между кусками: без паузы
# ffmpeg silencedetect не находит точек, и путь --rezat нечем проверить.
#
# Запуск: zsh tools/sdelat-test-audio.sh
# Выход:  audio/test-30s.aiff (короткий) и audio/test-dlinnyj.wav (~4 мин)
set -e
R="${0:A:h:h}"
cd "$R"
mkdir -p audio .rabota

echo "== короткий (один «стоп» с возвратом) =="
say -v Milena -o audio/test-30s.aiff \
"Итак, зачем нужны категории. Мы говорим, что функтор из категории Групп в категорию Сет забывает структуру. Жуайаль придумал вид, а Маклейн и Эйленберг придумали естественное преобразование. Стоп. Здесь на слайде заголовок золотой, он мне не нравится, слишком мелко и не читается. Продолжаем. Ретракт даёт первый запрет, а кобордизм и тангл живут в категории Коб."

echo "== длинный (шесть кусков через паузу, три «стоп») =="
# ФРАЗЫ подобраны так, чтобы у каждого куска была своя лексика: если стык
# склеится неверно, это видно по тому, чей термин попал не в свой таймкод.
FRAZY=(
"Первый кусок. Тождества на доске выглядят красиво, но требование красоты ломается, когда мы меняем не биекцию, а арену. Вид по Жуайалю живёт именно здесь, и галерея видов это показывает."
"Второй кусок. Стоп. Вот на этом слайде иллюстрация мелкая, непонятно, что изображено, нужна другая картинка. Продолжаем. Две оси обобщения дают категорию, функтор и естественное преобразование."
"Третий кусок. Зоопарк стрелок: стрелка как следование и стрелка как шаг. Морфизм, композиция, тождество. Категории Сет, Групп, Вект, Топ, а также Рел и Пос."
"Четвёртый кусок. Стоп. Здесь золотые заголовки везде мелкие, это системная беда, а не про один слайд. Продолжаем. Ретракт даёт первый запрет, и Брауэр тут появляется не случайно."
"Пятый кусок. Долг из введения и второй запрет: естественность. Ответ снова ни одного, и приём получает имя. Центр и степени, граф как функтор, Фробениус и Маклейн."
"Шестой кусок. Стоп. Вёрстка на этом слайде разъезжается, воздуха мало, кегль велик. Продолжаем. Категория занумерованных множеств, строгий и полный функтор, Стоун и соответствие Галуа."
)
i=0
CHASTI=()
for f in "${FRAZY[@]}"; do
  i=$((i+1))
  say -v Milena -o ".rabota/fraza-$i.aiff" "$f"
  ffmpeg -y -loglevel error -i ".rabota/fraza-$i.aiff" -ac 1 -ar 16000 -c:a pcm_s16le ".rabota/fraza-$i.wav"
  CHASTI+=(".rabota/fraza-$i.wav")
done
# пауза 1,4 с — длиннее порога silencedetect (d=0.45), точка разреза найдётся
ffmpeg -y -loglevel error -f lavfi -i anullsrc=r=16000:cl=mono -t 1.4 -c:a pcm_s16le .rabota/pauza.wav

: > .rabota/spisok.txt
for c in "${CHASTI[@]}"; do
  echo "file '$R/$c'" >> .rabota/spisok.txt
  echo "file '$R/.rabota/pauza.wav'" >> .rabota/spisok.txt
done
ffmpeg -y -loglevel error -f concat -safe 0 -i .rabota/spisok.txt -c copy audio/test-dlinnyj.wav

for f in audio/test-30s.aiff audio/test-dlinnyj.wav; do
  printf "%s — %s с\n" "$f" "$(ffprobe -v error -show_entries format=duration -of default=nw=1:nk=1 "$f")"
done
