OPASNYE = set("<>&%#_^~\\{}") - set("\\{}")   # \ { } приходят только из ZAMENY


def v_tex(t):
    for chto, chem in ZAMENY:
        t = re.sub(chto, chem, t)
    hvost = OPASNYE & set(t)
    if hvost:
        raise SystemExit("❌ символы без правила замены: %s — в строке: %.60s"
                         % (" ".join(sorted(hvost)), t))
    return t


def nayti_shrift():
    """Первый из SHRIFTY, который система реально отдаёт для кириллицы.
    Проверяем именно по букве «а» (U+0430): fc-match без charset вернёт
    подстановку и соврёт, что шрифт есть."""
    for imya in SHRIFTY:
        r = subprocess.run(["fc-match", "%s:charset=0430" % imya, "family"],
                           capture_output=True, text=True, errors="replace")
        if r.stdout.strip() == imya:
            return imya
    raise SystemExit("❌ ни один из шрифтов %s не отдаёт кириллицу" % SHRIFTY)


def zadacha(nomer, imya, pismenno, uslovie, punkty, hvost, v_stroku=()):
    """Имя задачи в вид НЕ выводится — оно живёт в данных для автора.
    v_stroku — по флагу на КАЖДЫЙ пункт: слить его с предыдущей строкой
    или начать им новую."""
    v_stroku = tuple(v_stroku) + (False,) * len(punkty)
    # Знак уровня один на задачу. \star, а не *: в архиве 179 уровень всегда
    # $^{\star}$. Кинжал ЗАМЕНЯЕТ кружок, а не приписывается рядом (решение
    # владельца 03.09): задача и обязательная, и письменная — это один знак.
    uroven = r"\star" if imya in ZVEZDOCHKI else (r"\dag" if pismenno else r"\circ")
    # samepage: без него задача рвётся между страницами по пунктам, и указание
    # уезжает от своего пункта на следующую полосу (проверено рендером).
    stroki = [r"\begin{samepage}"]
    if nomer == RAZDELITEL_POSLE + 1:
        stroki.insert(0, r"\zvezdy")
    # Окно для плюса стоит там, где плюс ставится: у задачи без пунктов —
    # у самой задачи, у задачи с пунктами — у каждого пункта. Номер ВСЕГДА
    # первым в левой колонке (владелец 03.09: «верхний прямоугольник
    # с нижним не сходится»).
    okno = r"\okno\hspace{\zazor}"
    nom = r"\nomer{%d}{%s}\hspace{\zazor}" % (nomer, uroven)
    abzacy = []

    if imya in BULLETY:
        # Не пункты, а маркированный список внутри одного условия: точки подряд
        # в строку, без букв, без окон, окно у задачи одно.
        telo = nom + okno + v_tex(uslovie)
        for p in punkty:
            telo += r"\ \textbullet\ " + v_tex(p)
        abzacy.append(telo)
    else:
        if uslovie:
            abzacy.append(nom + ("" if punkty else okno) + v_tex(uslovie))
        elif punkty:
            # Условия нет — первый пункт садится на строку номера: иначе номер
            # повисает один в пустой строке.
            abzacy.append(nom + okno + r"\textbf{а)} %s" % v_tex(punkty[0]))
            punkty = punkty[1:]
        else:
            abzacy.append(nom + okno)
        # v_stroku приходит ИЗВНЕ: какие пункты слить в строку, решает не длина
        # текста, а замер — какой вариант занял меньше строк (см. podobrat).
        pervaya = 0 if uslovie else 1     # без условия пункт «а» уже напечатан
        for i, p in enumerate(punkty):
            kusok = okno + r"\textbf{%s)} %s" % (BUKVY[pervaya + i], v_tex(p))
            # Решение принимается ПО КАЖДОМУ пункту отдельно: один пункт может
            # экономить строку, а следующий уже нет (владелец 03.09 про 7в).
            if v_stroku[i]:
                abzacy[-1] += r"\hspace{\zazor}" + kusok
            else:
                abzacy.append(kusok)
    if hvost:
        abzacy.append(v_tex(hvost))
    for telo in abzacy:
        stroki.append(r"\blok{%s}" % telo)
    # Интервал подобран под одну полосу: листок обязан быть одностраничным.
    stroki.append(r"\end{samepage}\par\vspace{7pt}")
    return "\n".join(stroki)


def kombinacii(z):
    """Все способы слить пункты задачи в строку — по флагу на пункт.
    У буллетов выбора нет: они и так идут в строку. Первый пункт задачи
    без условия тоже не в счёт — он всегда садится на строку номера."""
    imya, _, uslovie, punkty, _ = z
    n = 0 if imya in BULLETY else max(0, len(punkty) - (0 if uslovie else 1))
    return list(itertools.product((False, True), repeat=n))


def zamerit(zdes):
    """Замеряет ОБА варианта каждой задачи и возвращает {имя: слить?}.

    Правило «пункт в строку» нельзя записать через длину текста: подтянуть
    короткий пункт наверх иногда экономит строку, а иногда только съедает
    воздух, и от чего это зависит, знает верстальщик, а не автор. Поэтому
    решает ЗАМЕР: собираем служебный документ, где каждая задача набрана
    ВСЕМИ комбинациями слияний в настоящую ширину полосы, и печатаем высоту
    каждой. Комбинациями, а не двумя крайними вариантами: один пункт может
    экономить строку, а следующий уже нет (владелец 03.09 про 7в).
    При равном числе строк выигрывает вариант с наименьшим числом слияний —
    там, где выигрыша нет, листку лучше дышать, а отдельная строка на пункт
    показывает, сколько в задаче пунктов.
    """
    kuski = [PREAMBULA, r"\begin{document}",
             # Эталон одной строки: высота vbox не кратна baselineskip, и без
             # него число строк не восстановить — 7.57 и 7.40 это одни и те же
             # восемь строк, а не восемь и семь.
             r"\setbox0=\vbox{\hsize=\linewidth \blok{М}}"
             r"\typeout{BAZA \the\ht0\space\the\dp0\space\the\baselineskip}"]
    for n, z in enumerate(ZADACHI, 1):
        for variant in kombinacii(z):
            kuski.append(
                r"\setbox0=\vbox{\hsize=\linewidth %s}"
                # \space обязателен: пробел после размерности TeX съедает,
                # и три числа склеиваются в одно слово.
                r"\typeout{MERA %d %s \the\ht0\space\the\dp0\space"
                r"\the\baselineskip}"
                % (zadacha(n, *z, v_stroku=variant), n,
                   "".join("1" if v else "0" for v in variant) or "-"))
    kuski.append(r"\end{document}")
    # Служебный файл — во временную папку, а не в проект: замер это черновик,
    # в репозитории ему делать нечего, а удалять из смонтированной папки
    # песочнице не дают прав.
    proba = Path(tempfile.mkdtemp()) / "_zamer.tex"
    proba.write_text("\n".join(kuski), encoding="utf-8")
    stroki, baza = {}, None
    for dvizhok in ("lualatex", "xelatex"):
        # cwd=zdes, чтобы нашлась папка shrifty/; сам файл — по абсолютному пути.
        r = subprocess.run([dvizhok, "-interaction=nonstopmode",
                            "-output-directory=%s" % proba.parent, str(proba)],
                           cwd=zdes, capture_output=True, text=True,
                           errors="replace", env=sreda())
        for s in r.stdout.splitlines():
            if not s.startswith(("MERA ", "BAZA ")):
                continue
            ht, dp, bl = (float(x) for x in re.findall(r"([0-9.]+)pt", s))
            if s.startswith("BAZA "):
                baza, shag = ht + dp, bl
            else:
                _, n, variant = s.split()[:3]
                # СТРОКИ, а не пункты: сравнивать надо то, чем платим. По высоте
                # слитый вариант выигрывает и там, где строк столько же, — и
                # перенос выходит лишним (владелец 03.09).
                stroki[(int(n), variant)] = round((ht + dp - baza) / shag) + 1
        if stroki:
            break
    shutil.rmtree(proba.parent, ignore_errors=True)
    if baza is None or not stroki:
        raise SystemExit("❌ замер не дал строк MERA/BAZA — выбирать переносы нечем")
    reshenie, sekonomleno = {}, 0
    for n, z in enumerate(ZADACHI, 1):
        varianty = kombinacii(z)
        kod = lambda v: "".join("1" if x else "0" for x in v) or "-"
        # Меньше строк, при равенстве — меньше слияний: воздух даром не отдаём.
        luchshiy = min(varianty, key=lambda v: (stroki[(n, kod(v))], sum(v)))
        reshenie[z[0]] = luchshiy
        sekonomleno += stroki[(n, kod(varianty[0]))] - stroki[(n, kod(luchshiy))]
    return reshenie, sekonomleno


def sobrat(slit=None):
    slit = slit or {}
    if RAZDELITEL_POSLE >= len(ZADACHI):
        raise SystemExit("❌ разделитель после задачи %d, а задач всего %d"
                         % (RAZDELITEL_POSLE, len(ZADACHI)))
    # Не %-форматирование: в преамбуле полно знаков % — это комментарии TeX.
    telo = [PREAMBULA, r"\begin{document}",
            # Полосу НЕ подрезаем (решение владельца 03.09): не влезло —
            # значит листок на две страницы, а не с обрезанным полем.
            r"\centerline{\textit{%s}}" % SHAPKA,
            r"\par\medskip\centerline{\rule{0.62\linewidth}{0.4pt}}\par\smallskip",
            # Прописными, а не \textsc: капители для кириллицы у запасных
            # шрифтов нет, и \textsc молча отдаёт строчные.
            r"\centerline{\textbf{%s%s. \MakeUppercase{%s}}}\par\smallskip"
            % (NOMER_LISTKA, BUKVA_UROVNYA, ZAGOLOVOK),
            *([r"\centerline{\small\textit{%s}}\par\medskip" % UROVEN]
              if UROVEN else [])]
    for n, z in enumerate(ZADACHI, 1):
        telo.append(zadacha(n, *z, v_stroku=slit.get(z[0], ())))
    # Легенды знаков внизу нет намеренно (решение владельца 03.09): в листках
    # 179 школы её тоже нет, знаки объясняются устно на занятии.
    telo.append(r"\end{document}")
    return "\n".join(telo)


if __name__ == "__main__":
    zdes = Path(__file__).parent
    tex = zdes / "listok-1.tex"
    slit, sekonomleno = zamerit(zdes)
    tex.write_text(sobrat(slit), encoding="utf-8")
    print("  задач: %d, со звёздочкой %d, разделитель после %d-й"
          % (len(ZADACHI), len(ZVEZDOCHKI), RAZDELITEL_POSLE))
    slityh = [i for i, v in slit.items() if any(v)]
    print("  замер переносов: слито %d из %d (%s); сэкономлено строк: %d"
          % (len(slityh), len(slit), ", ".join(slityh) or "нет", sekonomleno))
    print("  → %s" % tex.name)
    # errors="replace": pdflatex подмешивает в лог байты в кодировке шрифтовых
    # файлов, и strict-декодирование падает раньше, чем мы увидим саму ошибку.
    # Целевой компилятор — lualatex; xelatex это запасной путь для среды,
    # где luatex неисправен. Печатаем, чем собралось: PDF от них отличается
    # (в lua работает растяжение глифов), и знать это надо.
    for dvizhok in ("lualatex", "xelatex"):
        r = subprocess.run([dvizhok, "-interaction=nonstopmode", tex.name],
                           cwd=zdes, capture_output=True, text=True,
                           errors="replace", env=sreda())
        if not r.returncode:
            print("  собрано: %s" % dvizhok)
            break
    if r.returncode:
        # Показываем ТОЛЬКО строки ошибок: полный лог pdflatex — тысячи строк,
        # и настоящая причина в них тонет.
        oshibki = [s for s in r.stdout.splitlines() if s.startswith("!")]
        raise SystemExit("❌ %s rc=%d\n%s" % (dvizhok, r.returncode,
                                                  "\n".join(oshibki[:12])))
    print("  → listok-1.pdf")
