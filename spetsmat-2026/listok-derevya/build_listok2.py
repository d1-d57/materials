# HTML-разметка данных → LaTeX. Список закрытый: что не перечислено здесь,
# до .tex не доедет и упадёт проверкой ниже — молча кривой символ хуже ошибки.
ZAMENY = [
    # <t> — термин: единственный способ выделить слово со специальным смыслом.
    # Как он выглядит, решает \term в преамбуле, а не автор условия.
    (r"<t>(.+?)</t>", r"\\term{\1}"),
    # \textit, а не \emph: у запасных шрифтов \emph подтягивает жирный курсив.
    (r"<i>(.+?)</i>", r"\\textit{\1}"),
    ("×", r"$\\times$"),
    ("⇒", r"$\\Rightarrow$"),
    ("≥", r"$\\geqslant$"),
]
OPASNYE = set("<>&%#_^~\\{}") - set("\\{}")   # \ { } приходят только из ZAMENY


def v_tex(t):
    for chto, chem in ZAMENY:
        t = re.sub(chto, chem, t)
    hvost = OPASNYE & set(t)
    if hvost:
        raise SystemExit("❌ символы без правила замены: %s — в строке: %.60s"
                         % (" ".join(sorted(hvost)), t))
    return t


