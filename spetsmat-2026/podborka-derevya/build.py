SHAPKA = "---\ntab: {tab}\nstatus: chernovik\nporyadok: {p}\nregistr: читаемый\nnomera: da\nzhanr: podborka\n---\n\n# {zag}\n\n{podzag}\n\n"


def nomera(otbor):
    """{имя: номер} для текущей вкладки. Ссылка «задача N» не пишется руками:
    выкинул задачу выше — номер ниже уехал, и ссылка стала бы врать молча."""
    d, n = {}, 0
    for kod, _, _ in BLOKI:
        for z in ZADACHI:
            if z[0] == kod and (otbor is None or otbor in z[2]):
                n += 1
                d[z[1]] = n
    return d


def podstavit(tekst, nom):
    """{N:имя|запасной текст} → «задачи 5» либо запасной текст, если задачи
    на этой вкладке нет. Без запасного варианта — падаем: висячая ссылка
    в листке хуже отсутствующей, её никто не заметит."""
    def zamena(m):
        imya, _, zapas = m.group(1).partition("|")
        if imya in nom:
            return "задачи %d" % nom[imya]
        if zapas:
            return zapas
        raise SystemExit("❌ ссылка на «%s», которой нет на этой вкладке, и нет запасного текста" % imya)
    return re.sub(r"\{N:([^}]+)\}", zamena, tekst)


def sobrat(tab, poryadok, zagolovok, podzagolovok, otbor, tegi):
    """otbor — какой листок ('1'/'2'/'3') или None для общей вкладки."""
    out = [SHAPKA.format(tab=tab, p=poryadok, zag=zagolovok, podzag=podzagolovok)]
    n = 0
    nom = nomera(otbor)
    for kod, imya_bloka, mn in BLOKI:
        vnutri = [z for z in ZADACHI if z[0] == kod and (otbor is None or otbor in z[2])]
        if not vnutri:
            continue
        out.append("## %s\n" % imya_bloka)
        for _, imya, teg, uslovie in vnutri:
            n += 1
            chipy = (" ".join("`Л%s`" % t for t in teg) + "\n") if tegi else ""
            out.append("**Задача %d (%s).** %s%s\n" % (n, imya.lower(), chipy, podstavit(uslovie, nom)))
    return "\n".join(out), n


